function step08_check_amica_quality()
% GOAL
%   Perform a focused final structural QC of the ICA outputs produced by
%   Step 07 before manual cortical IC review.
%
% INPUT
%   Updated subject_level_EEG_table.csv from Step 07.
%   preprocessed_and_ICA.set for each completed subject.
%
% APPROACH
%   1. Automatically select Step 07 datasets with completed and verified
%      AMICA outputs.
%   2. Load only the canonical preprocessed_and_ICA.set metadata/ICA
%      structures used by Step 09.
%   3. Confirm that ICA matrices are present, dimensionally consistent,
%      and finite.
%   4. Confirm that ICLabel classifications are present, finite, and
%      compatible with the ICA decomposition.
%   5. Confirm that DIPFIT models are present and compatible with the ICA
%      decomposition, with valid RV and dipole positions for every IC.
%   6. Write the final structural ICA-QC result to the processing table.
%
% OUTPUT
%   Updated subject_level_EEG_table.csv
%   output_data/amica_ica_quality_summary.csv
%
% USED BY
%   step09_update_manual_ic_review.m

clear; clc; close all;

try

    set(0, 'DefaultFigureVisible', 'off');
    set(groot, 'DefaultFigureVisible', 'off');

    %  LOAD PATHS

    thisFile = mfilename('fullpath');

    if isempty(thisFile)
        error('Could not resolve the current Step file path.');
    end

    scriptsRoot = fileparts(fileparts(thisFile));

    addpath(scriptsRoot, '-begin');
    addpath(fullfile(scriptsRoot, 'config'), '-begin');

    P = project_paths();

    mappingFile = ...
        P.subjectLevelEEGTableFile;

    outputFolder = ...
        P.outputFolder;

    if ~exist(mappingFile, 'file')

        error([ ...
            'Subject-level processing table not found:\n%s\n' ...
            'Run step07_run_amica_dipfit_iclabel.m first.'], ...
            mappingFile);

    end

    %  INITIALIZE EEGLAB

    if ~exist('pop_loadset', 'file')
        eeglab nogui;
    end

    hide_all_figures_local();

    %  READ SUBJECT-LEVEL TABLE

    optsImport = detectImportOptions( ...
        mappingFile, ...
        'FileType', 'text', ...
        'Delimiter', ',', ...
        'VariableNamingRule', 'preserve');

    sourceMap = readtable( ...
        mappingFile, ...
        optsImport);

    fprintf('\nLoaded processing table:\n%s\n', mappingFile);
    fprintf('Rows in processing table: %d\n', height(sourceMap));

    %  REQUIRED STEP 07 COLUMNS

    requiredColumns = { ...
        'FileName', ...
        'BidsSubject', ...
        'BidsSession', ...
        'AMICAStatus', ...
        'AMICAOutputStatus', ...
        'PreprocessedICASetPath' ...
    };

    for c = 1:numel(requiredColumns)

        if ~ismember( ...
                requiredColumns{c}, ...
                sourceMap.Properties.VariableNames)

            error([ ...
                'Subject-level table is missing required column: %s\n' ...
                'Run the latest Step 07 first.'], ...
                requiredColumns{c});

        end

    end

    %  NORMALIZE TABLE COLUMNS

    sourceMap = ensure_numeric_column_local( ...
        sourceMap, ...
        'BidsSubject');

    stringColumns = { ...
        'FileName', ...
        'BidsSession', ...
        'AMICAStatus', ...
        'AMICAOutputStatus', ...
        'PreprocessedICASetPath' ...
    };

    for c = 1:numel(stringColumns)

        sourceMap = ensure_string_column_local( ...
            sourceMap, ...
            stringColumns{c});

    end

    %  AUTOMATIC DOICAQC GATE

    readyForICAQC = ...
        sourceMap.AMICAStatus == "completed" & ...
        sourceMap.AMICAOutputStatus == ...
            "complete_outputs_verified" & ...
        strlength( ...
            strtrim( ...
                sourceMap.PreprocessedICASetPath)) > 0;

    sourceMap.DoICAQC = ...
        double(readyForICAQC);

    fprintf( ...
        '\nDoICAQC automatically updated from current Step 07 status.\n');

    fprintf( ...
        'Rows ready for ICA QC: %d\n', ...
        sum(sourceMap.DoICAQC == 1));

    %  REMOVE REDUNDANT OLD ICA-QC COLUMNS

    redundantColumns = { ...
        'ICAQCChannels', ...
        'ICAQCSrate', ...
        'ICAQCSamples', ...
        'ICAQCDurationSec', ...
        'ICAQCRankEstimate', ...
        'ICAQCHasAMICASet', ...
        'ICAQCHasDipfittedSet', ...
        'ICAQCHasPreprocessedICASet', ...
        'ICAQCHasCleanedICASet', ...
        'ICAQCHasICAWeights', ...
        'ICAQCHasICLabel', ...
        'ICAQCHasDIPFIT', ...
        'ICAQCDipfittedHasDIPFIT', ...
        'ICAQCPreprocessedCleanedCompatible', ...
        'ICAQCAMICAPreprocessedEquivalent', ...
        'ICAQCDipfittedPreprocessedEquivalent', ...
        'ICAQCHasAMICAMetadata', ...
        'ICAQCAMICAInputSignatureOK', ...
        'ICAQCHasBadSampleMask', ...
        'ICAQCBadSamples', ...
        'ICAQCBadSamplesPercent', ...
        'ICAQCBrainICs', ...
        'ICAQCBrainICsP050', ...
        'ICAQCBrainICsP070', ...
        'ICAQCBrainICsP075', ...
        'ICAQCEyeICs', ...
        'ICAQCMuscleICs', ...
        'ICAQCHeartICs', ...
        'ICAQCLineNoiseICs', ...
        'ICAQCChannelNoiseICs', ...
        'ICAQCOtherICs', ...
        'ICAQCDipfitRVMedian', ...
        'ICAQCDipfitRVBelow15', ...
        'ICAQCDipfitRVBelow20' ...
    };

    columnsToRemove = intersect( ...
        redundantColumns, ...
        sourceMap.Properties.VariableNames, ...
        'stable');

    if ~isempty(columnsToRemove)

        sourceMap = removevars( ...
            sourceMap, ...
            columnsToRemove);

        fprintf( ...
            'Removed redundant ICA-QC columns: %s\n', ...
            strjoin(columnsToRemove, ', '));

    end

    %  PREPARE ICA-QC OUTPUT COLUMNS

    sourceMap = ensure_string_column_local( ...
        sourceMap, ...
        'ICAQCStatus');

    sourceMap = ensure_string_column_local( ...
        sourceMap, ...
        'ICAQCNotes');

    sourceMap = ensure_string_column_local( ...
        sourceMap, ...
        'ICAQCDate');

    sourceMap = ensure_string_column_local( ...
        sourceMap, ...
        'ICAQCSetPath');

    sourceMap = ensure_string_column_local( ...
        sourceMap, ...
        'ExpertICReviewStatus');

    sourceMap = ensure_numeric_nan_column_local( ...
        sourceMap, ...
        'AnalysisReady');

    numericColumns = { ...
        'ICAQCNICs', ...
        'ICAQCICAMatrixDimOK', ...
        'ICAQCICAValuesFinite', ...
        'ICAQCICLabelDimOK', ...
        'ICAQCDIPFITDimOK' ...
    };

    for c = 1:numel(numericColumns)

        sourceMap = ensure_numeric_nan_column_local( ...
            sourceMap, ...
            numericColumns{c});

    end

    writetable( ...
        sourceMap, ...
        mappingFile);

    %  SELECT DATASETS

    candidateRows = ...
        find(sourceMap.DoICAQC == 1);

    if isempty(candidateRows)

        error([ ...
            'No rows are eligible for ICA QC.\n' ...
            'Step 07 must first finish successfully.']);

    end

    preprocessedICAPaths = ...
        sourceMap.PreprocessedICASetPath(candidateRows);

    [~, uniqueIdx] = unique( ...
        preprocessedICAPaths, ...
        'stable');

    rowsToCheck = ...
        candidateRows(uniqueIdx);
rowsToCheck = rowsToCheck(hipexo.subject_is_selected(sourceMap.BidsSubject(rowsToCheck)));

    fprintf('\n============================================================\n');
    fprintf('FINAL ICA STRUCTURAL QC STARTED\n');
    fprintf('============================================================\n');

    fprintf( ...
        'Rows with DoICAQC = 1: %d\n', ...
        numel(candidateRows));

    fprintf( ...
        'Unique preprocessed_and_ICA datasets: %d\n', ...
        numel(rowsToCheck));

    fprintf('Processing table:\n%s\n', mappingFile);

    fprintf('============================================================\n\n');

    disp(sourceMap( ...
        rowsToCheck, ...
        intersect( ...
            { ...
                'FileName', ...
                'BidsSubject', ...
                'BidsSession', ...
                'AMICAStatus', ...
                'AMICAOutputStatus', ...
                'PreprocessedICASetPath' ...
            }, ...
            sourceMap.Properties.VariableNames, ...
            'stable')));

    %  QC LOOP

    for rr = 1:numel(rowsToCheck)

        hide_all_figures_local();

        rowIdx = ...
            rowsToCheck(rr);

        sessionRows = ...
            session_peer_rows_local( ...
                sourceMap, ...
                rowIdx);

        preprocessedICASetPath = ...
            char( ...
                sourceMap.PreprocessedICASetPath(rowIdx));

        fprintf('\n\n============================================================\n');

        fprintf( ...
            'ICA QC DATASET %d / %d\n', ...
            rr, ...
            numel(rowsToCheck));

        fprintf( ...
            'FileName: %s\n', ...
            string(sourceMap.FileName(rowIdx)));

        fprintf( ...
            'BidsSubject: %g\n', ...
            sourceMap.BidsSubject(rowIdx));

        fprintf( ...
            'BidsSession: %s\n', ...
            string(sourceMap.BidsSession(rowIdx)));

        fprintf( ...
            'Dataset:\n%s\n', ...
            preprocessedICASetPath);

        [status, notes, metrics] = ...
            check_one_ica_output_local( ...
                preprocessedICASetPath);

        %  WRITE QC RESULT

        sourceMap.ICAQCStatus(rowIdx) = ...
            string(status);

        sourceMap.ICAQCNotes(rowIdx) = ...
            string(notes);

        sourceMap.ICAQCDate(rowIdx) = ...
            string(datetime( ...
                'now', ...
                'Format', ...
                'yyyy-MM-dd HH:mm:ss'));

        sourceMap.ICAQCSetPath(rowIdx) = ...
            string(preprocessedICASetPath);

        sourceMap.ICAQCNICs(rowIdx) = ...
            metrics.nICs;

        sourceMap.ICAQCICAMatrixDimOK(rowIdx) = ...
            double(metrics.icaMatrixDimOK);

        sourceMap.ICAQCICAValuesFinite(rowIdx) = ...
            double(metrics.icaValuesFinite);

        sourceMap.ICAQCICLabelDimOK(rowIdx) = ...
            double(metrics.icLabelDimOK);

        sourceMap.ICAQCDIPFITDimOK(rowIdx) = ...
            double(metrics.dipfitDimOK);

        %  MIRROR SESSION-LEVEL RESULT

        resultColumns = { ...
            'ICAQCStatus', ...
            'ICAQCNotes', ...
            'ICAQCDate', ...
            'ICAQCSetPath', ...
            'ICAQCNICs', ...
            'ICAQCICAMatrixDimOK', ...
            'ICAQCICAValuesFinite', ...
            'ICAQCICLabelDimOK', ...
            'ICAQCDIPFITDimOK' ...
        };

        sourceMap = copy_row_to_rows_local( ...
            sourceMap, ...
            rowIdx, ...
            sessionRows, ...
            resultColumns);

        %  MANUAL REVIEW STATE

        if status == "passed_ica_quality_basic_checks"

            emptyExpertRows = ...
                sessionRows( ...
                    strlength( ...
                        strtrim( ...
                            sourceMap.ExpertICReviewStatus( ...
                                sessionRows))) == 0);

            sourceMap.ExpertICReviewStatus( ...
                emptyExpertRows) = ...
                "pending_manual_cortical_IC_review";

        end

        % Manual cortical IC review is still required before analysis.
        sourceMap.AnalysisReady(sessionRows) = 0;

        %  REPORT CURRENT DATASET

        fprintf('\nICAQCStatus: %s\n', status);
        fprintf('ICAQCNotes: %s\n', notes);

        fprintf( ...
            ['ICs: %g | ICA dimensions OK: %d | ' ...
             'ICA values finite: %d\n'], ...
            metrics.nICs, ...
            metrics.icaMatrixDimOK, ...
            metrics.icaValuesFinite);

        fprintf( ...
            ['ICLabel dimensions OK: %d | ' ...
             'DIPFIT dimensions OK: %d\n'], ...
            metrics.icLabelDimOK, ...
            metrics.dipfitDimOK);

        writetable( ...
            sourceMap, ...
            mappingFile);

    end

    %  FINAL SUMMARY

    fprintf('\n============================================================\n');
    fprintf('FINAL ICA STRUCTURAL QC FINISHED\n');
    fprintf('============================================================\n');

    summaryColumns = { ...
        'FileName', ...
        'BidsSubject', ...
        'BidsSession', ...
        'ICAQCStatus', ...
        'ICAQCNotes', ...
        'ICAQCNICs', ...
        'ICAQCICAMatrixDimOK', ...
        'ICAQCICAValuesFinite', ...
        'ICAQCICLabelDimOK', ...
        'ICAQCDIPFITDimOK', ...
        'ExpertICReviewStatus', ...
        'AnalysisReady' ...
    };

    summaryTable = ...
        sourceMap( ...
            rowsToCheck, ...
            intersect( ...
                summaryColumns, ...
                sourceMap.Properties.VariableNames, ...
                'stable'));

    disp(summaryTable);

    summaryFile = fullfile( ...
        outputFolder, ...
        'amica_ica_quality_summary.csv');

    writetable( ...
        summaryTable, ...
        summaryFile);

    fprintf( ...
        '\nICA QC summary saved to:\n%s\n', ...
        summaryFile);

    fprintf( ...
        'Processing table updated:\n%s\n', ...
        mappingFile);

    fprintf('\nDone.\n');

    restore_figure_visibility_local();

catch ME

    restore_figure_visibility_local();

    rethrow(ME);

end

%% END OF STEP
end

% STEP-LOCAL FUNCTIONS

function [status, notes, metrics] = ...
        check_one_ica_output_local( ...
            preprocessedICASetPath)

    metrics = ...
        empty_ica_metrics_local();

    failures = ...
        strings(0, 1);

    %  LOAD CANONICAL PREPROCESSED_AND_ICA DATASET

    if exist(preprocessedICASetPath, 'file') ~= 2

        status = ...
            "failed_ica_quality_basic_checks";

        notes = ...
            "Failures: preprocessed_and_ICA_set_missing";

        return;

    end

    try

        EEG = ...
            load_set_info_local( ...
                preprocessedICASetPath);

    catch ME

        status = ...
            "failed_ica_quality_basic_checks";

        notes = ...
            "Failures: failed_load_preprocessed_and_ICA_set; " + ...
            "Reason: " + string(ME.message);

        return;

    end

    %  ICA MATRICES

    hasWeights = ...
        isfield(EEG, 'icaweights') && ...
        ~isempty(EEG.icaweights);

    hasSphere = ...
        isfield(EEG, 'icasphere') && ...
        ~isempty(EEG.icasphere);

    hasWinv = ...
        isfield(EEG, 'icawinv') && ...
        ~isempty(EEG.icawinv);

    hasChanInd = ...
        isfield(EEG, 'icachansind') && ...
        ~isempty(EEG.icachansind);

    if ~hasWeights

        failures(end+1, 1) = ...
            "missing_ICA_weights";

    else

        metrics.nICs = ...
            size(EEG.icaweights, 1);

    end

    if ~hasSphere
        failures(end+1, 1) = ...
            "missing_ICA_sphere";
    end

    if ~hasWinv
        failures(end+1, 1) = ...
            "missing_ICA_inverse_weights";
    end

    if ~hasChanInd
        failures(end+1, 1) = ...
            "missing_ICA_channel_indices";
    end

    if hasWeights && ...
            hasSphere && ...
            hasWinv && ...
            hasChanInd

        chanInd = ...
            double(EEG.icachansind(:));

        metrics.icaMatrixDimOK = ...
            metrics.nICs >= 1 && ...
            size(EEG.icaweights, 2) == ...
                size(EEG.icasphere, 1) && ...
            size(EEG.icasphere, 2) == ...
                numel(chanInd) && ...
            size(EEG.icawinv, 1) == ...
                numel(chanInd) && ...
            size(EEG.icawinv, 2) == ...
                metrics.nICs && ...
            all(isfinite(chanInd)) && ...
            all(chanInd >= 1) && ...
            all(chanInd <= EEG.nbchan) && ...
            all(abs(chanInd - round(chanInd)) < 1e-6);

        metrics.icaValuesFinite = ...
            all(isfinite( ...
                double( ...
                    EEG.icaweights(:)))) && ...
            all(isfinite( ...
                double( ...
                    EEG.icasphere(:)))) && ...
            all(isfinite( ...
                double( ...
                    EEG.icawinv(:))));

        if ~metrics.icaMatrixDimOK

            failures(end+1, 1) = ...
                "ICA_matrix_dimensions_are_inconsistent";

        end

        if ~metrics.icaValuesFinite

            failures(end+1, 1) = ...
                "ICA_matrices_contain_NaN_or_Inf";

        end

    end

    %  ICLABEL

    hasICLabel = ...
        isfield(EEG, 'etc') && ...
        isfield(EEG.etc, 'ic_classification') && ...
        isfield( ...
            EEG.etc.ic_classification, ...
            'ICLabel') && ...
        isfield( ...
            EEG.etc.ic_classification.ICLabel, ...
            'classifications');

    if ~hasICLabel

        failures(end+1, 1) = ...
            "missing_ICLabel_classification";

    else

        probs = ...
            EEG.etc.ic_classification.ICLabel.classifications;

        if ~isnumeric(probs) || ...
                isempty(probs)

            failures(end+1, 1) = ...
                "invalid_ICLabel_classification";

        else

            % ICLabel has seven standard output classes.
            metrics.icLabelDimOK = ...
                isfinite(metrics.nICs) && ...
                size(probs, 1) == metrics.nICs && ...
                size(probs, 2) == 7;

            if ~metrics.icLabelDimOK

                failures(end+1, 1) = ...
                    "ICLabel_dimensions_do_not_match_ICA";

            end

            if any(~isfinite(double(probs(:))))

                failures(end+1, 1) = ...
                    "ICLabel_contains_NaN_or_Inf";

            end

        end

    end

    %  DIPFIT

    hasDIPFIT = ...
        isfield(EEG, 'dipfit') && ...
        isfield(EEG.dipfit, 'model') && ...
        ~isempty(EEG.dipfit.model);

    if ~hasDIPFIT

        failures(end+1, 1) = ...
            "missing_DIPFIT_model";

    else

        models = ...
            EEG.dipfit.model;

        metrics.dipfitDimOK = ...
            isfinite(metrics.nICs) && ...
            numel(models) == metrics.nICs;

        if ~metrics.dipfitDimOK

            failures(end+1, 1) = ...
                "DIPFIT_model_count_does_not_match_ICA";

        else

            validRV = true;
            validPosition = true;

            for ic = 1:numel(models)

                if ~isfield(models(ic), 'rv') || ...
                        isempty(models(ic).rv) || ...
                        ~isnumeric(models(ic).rv) || ...
                        ~isfinite(double(models(ic).rv(1)))

                    validRV = false;

                end

                if ~isfield(models(ic), 'posxyz') || ...
                        isempty(models(ic).posxyz) || ...
                        ~isnumeric(models(ic).posxyz)

                    validPosition = false;

                else

                    posxyz = ...
                        double(models(ic).posxyz);

                    if size(posxyz, 2) ~= 3 || ...
                            any(~isfinite(posxyz(:)))

                        validPosition = false;

                    end

                end

            end

            if ~validRV

                failures(end+1, 1) = ...
                    "DIPFIT_RV_missing_or_nonfinite";

            end

            if ~validPosition

                failures(end+1, 1) = ...
                    "DIPFIT_position_missing_or_nonfinite";

            end

        end

    end

    %  FINAL STATUS

    if isempty(failures)

        status = ...
            "passed_ica_quality_basic_checks";

        % Keep this as ONE scalar string because ICAQCNotes contains one
        % table element per dataset.
        notes = ...
            "Required ICA, ICLabel, and DIPFIT structures are present and internally consistent. Manual cortical IC review is still required.";

    else

        status = ...
            "failed_ica_quality_basic_checks";

        notes = ...
            "Failures: " + ...
            join( ...
                unique(failures, 'stable'), ...
                "; ");

    end

end

function metrics = empty_ica_metrics_local()

    metrics = struct();

    metrics.nICs = NaN;

    metrics.icaMatrixDimOK = false;
    metrics.icaValuesFinite = false;

    metrics.icLabelDimOK = false;
    metrics.dipfitDimOK = false;

end

function EEG = load_set_info_local(setPath)

    [folderPath, fileNameNoExt, fileExt] = ...
        fileparts(setPath);

    EEG = ...
        pop_loadset( ...
            'filename', ...
            [fileNameNoExt fileExt], ...
            'filepath', ...
            folderPath, ...
            'loadmode', ...
            'info');

end

function T = ensure_numeric_column_local( ...
        T, ...
        columnName)

    if ~ismember( ...
            columnName, ...
            T.Properties.VariableNames)

        error( ...
            'Missing required numeric column: %s', ...
            columnName);

    end

    if isnumeric(T.(columnName))

        T.(columnName) = ...
            double(T.(columnName));

    elseif islogical(T.(columnName))

        T.(columnName) = ...
            double(T.(columnName));

    else

        T.(columnName) = ...
            str2double( ...
                string( ...
                    T.(columnName)));

    end

end

function T = ensure_numeric_nan_column_local( ...
        T, ...
        columnName)

    if ~ismember( ...
            columnName, ...
            T.Properties.VariableNames)

        T.(columnName) = ...
            nan( ...
                height(T), ...
                1);

        return;

    end

    if isnumeric(T.(columnName))

        T.(columnName) = ...
            double(T.(columnName));

    elseif islogical(T.(columnName))

        T.(columnName) = ...
            double(T.(columnName));

    else

        T.(columnName) = ...
            str2double( ...
                string( ...
                    T.(columnName)));

    end

end

function T = ensure_string_column_local( ...
        T, ...
        columnName)

    if ~ismember( ...
            columnName, ...
            T.Properties.VariableNames)

        T.(columnName) = ...
            strings( ...
                height(T), ...
                1);

        return;

    end

    if ~isstring(T.(columnName))

        T.(columnName) = ...
            string( ...
                T.(columnName));

    end

    T.(columnName)( ...
        ismissing( ...
            T.(columnName))) = "";

end

function T = copy_row_to_rows_local( ...
        T, ...
        rowIdx, ...
        rows, ...
        columnNames)

    for k = 1:numel(columnNames)

        name = ...
            columnNames{k};

        if ~ismember( ...
                name, ...
                T.Properties.VariableNames)

            continue;

        end

        value = ...
            T.(name)(rowIdx, :);

        T.(name)(rows, :) = ...
            repmat( ...
                value, ...
                numel(rows), ...
                1);

    end

end

function rows = session_peer_rows_local( ...
        T, ...
        rowIdx)

    rows = ...
        rowIdx;

    required = { ...
        'BidsSubject', ...
        'BidsSession' ...
    };

    if ~all( ...
            ismember( ...
                required, ...
                T.Properties.VariableNames))

        return;

    end

    subjectValues = ...
        T.BidsSubject;

    if ~isnumeric(subjectValues)

        subjectValues = ...
            str2double( ...
                string(subjectValues));

    end

    sessionValues = ...
        string(T.BidsSession);

    sessionValues( ...
        ismissing(sessionValues)) = "";

    subjectValue = ...
        subjectValues(rowIdx);

    sessionValue = ...
        sessionValues(rowIdx);

    if isnan(subjectValue) || ...
            strlength( ...
                strtrim(sessionValue)) == 0

        return;

    end

    mask = ...
        subjectValues == subjectValue & ...
        sessionValues == sessionValue;

    if ismember( ...
            'DoImport', ...
            T.Properties.VariableNames)

        doImport = ...
            T.DoImport;

        if ~isnumeric(doImport)

            doImport = ...
                str2double( ...
                    string(doImport));

        end

        mask = ...
            mask & ...
            doImport == 1;

    end

    matchedRows = ...
        find(mask);

    if ~isempty(matchedRows)

        rows = ...
            matchedRows;

    end

end

function hide_all_figures_local()

    try

        set( ...
            0, ...
            'DefaultFigureVisible', ...
            'off');

        set( ...
            groot, ...
            'DefaultFigureVisible', ...
            'off');

        close all hidden;

    catch
    end

end

function restore_figure_visibility_local()

    try

        set( ...
            0, ...
            'ShowHiddenHandles', ...
            'off');

        set( ...
            0, ...
            'DefaultFigureVisible', ...
            'on');

        set( ...
            groot, ...
            'DefaultFigureVisible', ...
            'on');

    catch
    end

end