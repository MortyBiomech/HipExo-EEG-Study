            '%s has invalid Parent/Outlier best-fitting cluster %g.', ...
            solutionField, ...
            clusterIndex);


        solutionKeys = ...
            component_keys_from_cluster_local( ...
                STUDY, ...
                solutionClusters(clusterIndex));


        topJaccard(topIndex) = ...
            jaccard_local( ...
                selectedKeys, ...
                solutionKeys);


        inclusionCounts = ...
            inclusionCounts + ...
            double( ...
                ismember(selectedKeys, solutionKeys));

    end


    inclusionRate = ...
        inclusionCounts ./ ...
        max(numel(topSolutions), 1);

end


function value = jaccard_local(firstKeys, secondKeys)

    firstKeys = ...
        unique(firstKeys);


    secondKeys = ...
        unique(secondKeys);


    unionCount = ...
        numel( ...
            union(firstKeys, secondKeys));


    if unionCount == 0

        value = NaN;

    else

        value = ...
            numel( ...
                intersect(firstKeys, secondKeys)) / ...
            unionCount;

    end

end


