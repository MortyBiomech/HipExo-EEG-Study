function [alignedMaps, meanMap, correlations, status] = ...
        align_scalp_maps_local(scalpMaps, channelLabelSets)

    componentCount = ...
        numel(scalpMaps);


    alignedMaps = [];
    meanMap = [];
    correlations = nan(componentCount,1);
    status = "OK";


    if componentCount == 0

        status = "NO_MAPS";
        return;

    end


    referenceLabels = ...
        string(channelLabelSets{1}(:));


    channelCount = ...
        numel(referenceLabels);


    maps = ...
        nan(channelCount, componentCount);


    for componentIndex = 1:componentCount

        labels = ...
            string(channelLabelSets{componentIndex}(:));


        map = ...
            double(scalpMaps{componentIndex}(:));


        if ~isequal(labels, referenceLabels) || ...
                numel(map) ~= channelCount || ...
                any(~isfinite(map))

            status = "INCOMPATIBLE_CHANNELS_OR_MAP";
            return;

        end


        map = ...
            map - ...
            mean(map);


        mapScale = ...
            sqrt( ...
                mean(map.^2));


        if ~isfinite(mapScale) || mapScale == 0

            status = "ZERO_OR_INVALID_MAP";
            return;

        end


        maps(:,componentIndex) = ...
            map ./ mapScale;

    end


    [~, anchorChannel] = ...
        max( ...
            abs(maps(:,1)));


    if maps(anchorChannel,1) < 0

        maps(:,1) = ...
            -maps(:,1);

    end


    referenceMap = ...
        maps(:,1);


    for iteration = 1:3

        for componentIndex = 1:componentCount

            if dot( ...
                    maps(:,componentIndex), ...
                    referenceMap) < 0

                maps(:,componentIndex) = ...
                    -maps(:,componentIndex);

            end

        end


        referenceMap = ...
            mean(maps, 2);


        referenceScale = ...
            sqrt( ...
                mean(referenceMap.^2));


        if referenceScale > 0

            referenceMap = ...
                referenceMap ./ referenceScale;

        end

    end


    meanMap = ...
        mean(maps, 2);


    for componentIndex = 1:componentCount

        correlationMatrix = ...
            corrcoef( ...
                maps(:,componentIndex), ...
                meanMap, ...
                'Rows', ...
                'complete');


        if all(size(correlationMatrix) == [2 2])

            correlations(componentIndex) = ...
                correlationMatrix(1,2);

        end

    end


    alignedMaps = ...
        maps;

end


