function shorten_spectrum_axes_titles_local(figureHandle, STUDY)

    if isempty(figureHandle) || ...
            ~isgraphics(figureHandle) || ...
            ~isfield(STUDY, 'datasetinfo') || ...
            isempty(STUDY.datasetinfo)

        return;

    end


    conditionNames = ...
        strings( ...
            numel(STUDY.datasetinfo), ...
            1);


    for datasetIndex = 1:numel(STUDY.datasetinfo)

        if isfield(STUDY.datasetinfo(datasetIndex), 'condition') && ...
                ~isempty(STUDY.datasetinfo(datasetIndex).condition)

            conditionNames(datasetIndex) = ...
                string( ...
                    STUDY.datasetinfo(datasetIndex).condition);

        end

    end


    conditionNames = ...
        unique( ...
            conditionNames(strlength(conditionNames) > 0), ...
            'stable');


    if isempty(conditionNames)

        return;

    end


    [~, conditionOrder] = ...
        sort( ...
            strlength(conditionNames), ...
            'descend');


    conditionNames = ...
        conditionNames(conditionOrder);


    normalizedConditions = ...
        lower( ...
            regexprep( ...
                conditionNames, ...
                '[^a-zA-Z0-9]', ...
                ''));


    axisHandles = ...
        findall( ...
            figureHandle, ...
            'Type', ...
            'axes');


    for axisIndex = 1:numel(axisHandles)

        axisHandle = ...
            axisHandles(axisIndex);


        titleHandle = ...
            get( ...
                axisHandle, ...
                'Title');


        titleText = ...
            string( ...
                get( ...
                    titleHandle, ...
                    'String'));


        normalizedTitle = ...
            lower( ...
                regexprep( ...
                    join(titleText(:), " "), ...
                    '[^a-zA-Z0-9]', ...
                    ''));


        matchedCondition = ...
            "";


        for conditionIndex = 1:numel(conditionNames)

            if contains( ...
                    normalizedTitle, ...
                    normalizedConditions(conditionIndex))

                matchedCondition = ...
                    conditionNames(conditionIndex);

                break;

            end

        end


        if strlength(matchedCondition) > 0

            title( ...
                axisHandle, ...
                matchedCondition, ...
                'Interpreter', ...
                'none', ...
                'FontSize', ...
                8);

        else

            set( ...
                titleHandle, ...
                'FontSize', ...
                7);

        end


        set( ...
            axisHandle, ...
            'FontSize', ...
            8);

    end

end


function pointCount = ...
        spectrum_point_count_local(figureHandle, frequencyRangeHz)

    pointCount = ...
        0;


    if isempty(figureHandle) || ...
            ~isgraphics(figureHandle)

        return;

    end


    lineHandles = ...
        findall( ...
            figureHandle, ...
            'Type', ...
            'line');


    for lineIndex = 1:numel(lineHandles)

        xData = ...
            double( ...
                get( ...
                    lineHandles(lineIndex), ...
                    'XData'));


        yData = ...
            double( ...
                get( ...
                    lineHandles(lineIndex), ...
                    'YData'));


        validMask = ...
            isfinite(xData) & ...
            isfinite(yData) & ...
            xData >= frequencyRangeHz(1) & ...
            xData <= frequencyRangeHz(2);


        pointCount = ...
            pointCount + ...
            sum(validMask(:));

    end

end


