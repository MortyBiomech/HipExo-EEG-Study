        configuredROIs.ROIID(configuredRow);


    outputTable.OriginalClusterID = ...
        configuredROIs.OriginalClusterID(configuredRow);


    outputTable.ROIName = ...
        configuredROIs.ROIName(configuredRow);


    outputTable = ...
        movevars( ...
            outputTable, ...
            {'ROIID','OriginalClusterID','ROIName'}, ...
            'Before', ...
            1);

end


