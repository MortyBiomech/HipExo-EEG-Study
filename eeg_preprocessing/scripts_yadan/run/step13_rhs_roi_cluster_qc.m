function outputTable = add_posthoc_issue_local( ...
        inputTable, rowIndex, severity, issueText)

    outputTable = ...
        inputTable;


    existingIssues = ...
        string( ...
            outputTable.ClusterAutomaticIssues(rowIndex));


    if existingIssues == "None from deterministic automatic checks"

        existingIssues = "";

    end


    newIssue = ...
        severity + ...
        ": " + ...
        string(issueText);


    if strlength(existingIssues) == 0

        outputTable.ClusterAutomaticIssues(rowIndex) = ...
            newIssue;

    else

        outputTable.ClusterAutomaticIssues(rowIndex) = ...
            existingIssues + ...
            " | " + ...
            newIssue;

    end


    currentStatus = ...
        string( ...
            outputTable.ClusterAutomaticStatus(rowIndex));


    if severity == "BLOCK"

        outputTable.ClusterAutomaticStatus(rowIndex) = ...
            "BLOCK";

    elseif severity == "REVIEW" && ...
            currentStatus ~= "BLOCK"

        outputTable.ClusterAutomaticStatus(rowIndex) = ...
            "REVIEW";

    else

        assert( ...
            ismember(severity, ["BLOCK", "REVIEW"]), ...
            'Unsupported automatic issue severity: %s', ...
            char(severity));

    end

end


