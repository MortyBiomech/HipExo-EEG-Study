function [exportAudit, bids2setLog] = step02b_standardize_xdf_to_bids(P, cfg)
% GOAL
%   Convert structural gait-analysis candidate XDF recordings into
%   canonical BIDS and run-separated EEGLAB files.
%
% INPUT
%   output_data/bemobil_import_table.csv rows enabled by the synchronized
%   structural candidate gate DoBIDSImport.
%
% APPROACH
%   1. Validate enabled recording identities and BIDS keys.
%   2. Reuse unchanged BIDS recordings when their source and saved
%      provenance signatures still match.
%   3. Export only new or changed XDF recordings and audit the result.
%   4. Reuse unchanged run-separated EEGLAB files or convert only the
%      recordings that require an update, without resampling.
%   5. Store conversion status, signatures, and paths in the import table.
%   6. Create the configured BeMoBIL reference mirror when requested.
%
% OUTPUT
%   Canonical BIDS recordings, run-separated EEGLAB files, export audits,
%   conversion logs, and the updated import-control table.
%
% USED BY
%   step03_check_grf_gait_cycles.m and later EEG processing steps.

% Bootstrap project

thisFile = mfilename('fullpath');

if isempty(thisFile)
    error('Could not resolve the current Step file path.');
end

scriptsRoot = fileparts(fileparts(thisFile));

addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

if nargin < 1 || isempty(P)
    P = project_paths();
end

if nargin < 2 || isempty(cfg)
    cfg = config_bids_standardization();
end

% Required paths

requiredPaths = { ...
    'importTableFile', ...
    'bidsDataFolder', ...
    'bidsRawEEGLABFolder', ...
    'bidsExportAuditFile', ...
    'bids2setLogFile', ...
    'outputFolder'};

for iField = 1:numel(requiredPaths)

    assert( ...
        isfield(P, requiredPaths{iField}), ...
        'project_paths is missing field %s.', ...
        requiredPaths{iField});

end

assert( ...
    isfile(P.importTableFile), ...
    ['Import table not found:\n%s\n' ...
     'Run Step 02 first.'], ...
    P.importTableFile);

assert( ...
    exist('bemobil_xdf2bids', 'file') == 2, ...
    ['bemobil_xdf2bids was not found. Check the BeMoBIL ' ...
     'installation/path configuration.']);

% Initialize EEGLAB before plugin checks

if cfg.createRunSeparatedEEGLAB

    initialize_eeglab_local();

    hasBvaIo = ...
        exist('pop_loadbv', 'file') == 2;

    hasFileIO = ...
        exist('pop_fileio', 'file') == 2 && ...
        exist('ft_read_header', 'file') == 2 && ...
        exist('ft_read_data', 'file') == 2;

    assert( ...
        hasBvaIo || hasFileIO, ...
        ['No BrainVision reader is available after EEGLAB startup.\n' ...
         'Supported readers:\n' ...
         '  1) pop_loadbv (EEGLAB bva-io)\n' ...
         '  2) pop_fileio + FieldTrip/FileIO']);

    assert( ...
        exist('pop_saveset', 'file') == 2, ...
        'pop_saveset was not found after EEGLAB startup.');

end

if cfg.createBemobilMergedMirror

    assert( ...
        exist('bemobil_bids2set', 'file') == 2, ...
        'bemobil_bids2set was not found.');

end

% Output folders

ensure_folder_local(P.bidsDataFolder);
ensure_folder_local(P.bidsRawEEGLABFolder);

startingFolder = pwd;
folderCleanup = onCleanup(@() cd(startingFolder)); %#ok<NASGU>

cd(P.outputFolder);

% Header

fprintf( ...
    '\nStep 02B: XDF -> BIDS -> run-separated EEGLAB (%s)\n', ...
    string(cfg.processingVersion));

warn_placeholder_metadata_local(cfg);

% Read import table

opts = detectImportOptions( ...
    P.importTableFile, ...
    'FileType', 'text', ...
    'Delimiter', ',', ...
    'VariableNamingRule', 'preserve');

importTable = readtable( ...
    P.importTableFile, ...
    opts);

assert_file_writable_local( ...
    P.importTableFile);

requiredColumns = { ...
    'DoBIDSImport', ...
    'XdfPath', ...
    'OriginalSubjectID', ...
    'SubjectID', ...
    'BidsSubject', ...
    'BidsSubjectLabel', ...
    'BidsSession', ...
    'Task', ...
    'RunNumber', ...
    'EEGStreamName', ...
    'NominalSrate'};

missingColumns = ...
    requiredColumns( ...
        ~ismember( ...
            requiredColumns, ...
            importTable.Properties.VariableNames));

assert( ...
    isempty(missingColumns), ...
    ['Import table is missing required Step 02B columns:\n%s\n\n' ...
     'Re-run step02_build_import_table.m first.'], ...
    strjoin(missingColumns, ', '));

% Normalize numeric gates / identifiers

importTable.DoBIDSImport = ...
    numeric_column_local( ...
        importTable.DoBIDSImport);

importTable.BidsSubject = ...
    numeric_column_local( ...
        importTable.BidsSubject);

importTable.RunNumber = ...
    numeric_column_local( ...
        importTable.RunNumber);

% Normalize text columns

stringColumns = { ...
    'XdfPath', ...
    'OriginalSubjectID', ...
    'SubjectID', ...
    'BidsSubjectLabel', ...
    'BidsSession', ...
    'Task', ...
    'EEGStreamName'};

for iColumn = 1:numel(stringColumns)

    columnName = ...
        stringColumns{iColumn};

    importTable.(columnName) = ...
        string( ...
            importTable.(columnName));

end

% Reconstruct canonical zero-padded subject labels
%
% CSV import may convert "01" -> 1.
% Reconstruct from numeric BidsSubject every time.

for r = 1:height(importTable)

    if isfinite(importTable.BidsSubject(r))

        importTable.BidsSubjectLabel(r) = ...
            string( ...
                sprintf( ...
                    '%0*d', ...
                    cfg.subjectLabelWidth, ...
                    round(importTable.BidsSubject(r))));

    end

end

% BIDS export gate
%
% Step 02 keeps DoBIDSImport synchronized with DoGaitAnalysis, so the
% canonical BIDS/EEGLAB inputs contain only structural gait candidates.

rowsToExport = ...
    find( ...
        importTable.DoBIDSImport == 1);

assert( ...
    ~isempty(rowsToExport), ...
    ['No rows have DoBIDSImport = 1.\n' ...
     'Run Step 02 with the current structural gait-candidate gate.']);

validate_identity_table_local( ...
    importTable, ...
    rowsToExport, ...
    cfg);

validate_duplicate_bids_keys_local( ...
    importTable, ...
    rowsToExport);

rebuiltSubjects = ...
    clean_stale_subject_outputs_local( ...
        importTable, ...
        P);

fprintf( ...
    'Rows enabled for canonical BIDS export: %d\n', ...
    numel(rowsToExport));

if isempty(rebuiltSubjects)

    fprintf( ...
        'Subjects with obsolete session outputs removed: 0\n');

else

    fprintf( ...
        'Subjects with obsolete session outputs removed: %d (%s)\n', ...
        numel(rebuiltSubjects), ...
        strjoin(rebuiltSubjects, ', '));

end

% BIDS metadata

generalInfo = ...
    build_general_metadata_local(cfg);

eegInfo = ...
    build_eeg_metadata_local( ...
        cfg, ...
        importTable, ...
        rowsToExport);

subjectInfo = ...
    build_participant_metadata_local( ...
        importTable, ...
        rowsToExport, ...
        cfg);

% PART 1
% XDF -> BIDS

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsExportStatus');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsExportMessage');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsEEGHeader');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsSourceSignature');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsRecordingSignature');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsExportConfigSignature');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsExportedAt');

bidsExportConfigSignature = ...
    bids_export_config_signature_local(cfg);

% Each changed recording is overwritten by its own export below.
% A new run must not delete the other recordings of the same subject.

exportAudit = table();
exportWasReused = false(height(importTable), 1);

nBidsReused = 0;
nBidsExported = 0;

for iExport = 1:numel(rowsToExport)

    rowIndex = ...
        rowsToExport(iExport);

    xdfPath = ...
        char(importTable.XdfPath(rowIndex));

    originalSubjectID = ...
        string(importTable.OriginalSubjectID(rowIndex));

    subjectID = ...
        string(importTable.SubjectID(rowIndex));

    bidsSubject = ...
        importTable.BidsSubject(rowIndex);

    bidsSubjectLabel = ...
        string(importTable.BidsSubjectLabel(rowIndex));

    bidsSession = ...
        string(importTable.BidsSession(rowIndex));

    taskLabel = ...
        string(importTable.Task(rowIndex));

    eegStreamName = ...
        string(importTable.EEGStreamName(rowIndex));

    runNumber = ...
        importTable.RunNumber(rowIndex);

    success = false;
    message = "";

    detectedHeader = "";
    structureOK = false;

    sourceSignature = "";
    bidsRecordingSignature = "";
    exportedAt = "";

    if ~isfile(xdfPath)

        message = ...
            "Source XDF does not exist.";

    else

        sourceSignature = ...
            hipexo.file_metadata_signature(xdfPath);

        try

            [ ...
                canReuse, ...
                detectedHeader, ...
                bidsRecordingSignature ...
            ] = ...
                can_reuse_bids_export_local( ...
                    importTable, ...
                    rowIndex, ...
                    P.bidsDataFolder, ...
                    bidsSubjectLabel, ...
                    bidsSession, ...
                    taskLabel, ...
                    runNumber, ...
                    sourceSignature, ...
                    bidsExportConfigSignature);

            if canReuse

                success = true;
                structureOK = true;
                message = "REUSED";
                exportedAt = ...
                    string(importTable.BidsExportedAt(rowIndex));

                exportWasReused(rowIndex) = true;
                nBidsReused = nBidsReused + 1;

            else

                fprintf( ...
                    '\nExporting BIDS %d/%d: %s | ses-%s | task-%s', ...
                    iExport, ...
                    numel(rowsToExport), ...
                    subjectID, ...
                    bidsSession, ...
                    taskLabel);

                if isfinite(runNumber)
                    fprintf(' | run-%03d', round(runNumber));
                end

                fprintf('\n');

                importCfg = [];

                importCfg.bids_target_folder = ...
                    P.bidsDataFolder;

                importCfg.filename = ...
                    xdfPath;

                importCfg.task = ...
                    char(taskLabel);

                importCfg.subject = ...
                    bidsSubject;

                importCfg.session = ...
                    char(bidsSession);

                importCfg.overwrite = ...
                    cfg.overwrite;

                importCfg.eeg.stream_name = ...
                    char(eegStreamName);

                importCfg.eeg.chanloc = [];

                if isfinite(runNumber)

                    importCfg.run = ...
                        round(runNumber);

                end

                % If this exact recording already has an old events.tsv,
                % remove it before re-export so bemobil_xdf2bids does not
                % concatenate incompatible old/new `value` column types.
                if isfinite(runNumber)
                    oldEventsFile = fullfile( ...
                        P.bidsDataFolder, ...
                        ['sub-' char(bidsSubjectLabel)], ...
                        ['ses-' char(bidsSession)], ...
                        'eeg', ...
                        sprintf('sub-%s_ses-%s_task-%s_run-%d_events.tsv', ...
                            char(bidsSubjectLabel), char(bidsSession), ...
                            char(taskLabel), round(runNumber)));
                    if isfile(oldEventsFile)
                        delete(oldEventsFile);
                        fprintf('Removed stale events.tsv before re-export: %s\n', oldEventsFile);
                    end
                end

                bemobil_xdf2bids( ...
                    importCfg, ...
                    'general_metadata', ...
                    generalInfo, ...
                    'participant_metadata', ...
                    subjectInfo, ...
                    'eeg_metadata', ...
                    eegInfo);

                [ ...
                    structureOK, ...
                    detectedHeader, ...
                    structureMessage ...
                ] = ...
                    audit_one_bids_eeg_local( ...
                        P.bidsDataFolder, ...
                        bidsSubjectLabel, ...
                        bidsSession, ...
                        taskLabel, ...
                        runNumber);

                success = ...
                    structureOK;

                if structureOK

                    bidsRecordingSignature = ...
                        hipexo.bids_recording_signature( ...
                            char(detectedHeader));

                    message = ...
                        "OK";

                    exportedAt = ...
                        string(datetime( ...
                            'now', ...
                            'Format', ...
                            'yyyy-MM-dd HH:mm:ss'));

                    nBidsExported = nBidsExported + 1;

                else

                    message = ...
                        "BIDS structure audit failed: " + ...
                        structureMessage;

                end

            end

        catch ME

            message = ...
                string(ME.message);

            warning( ...
                'HipExo:BIDSExportFailed', ...
                'BIDS export failed for table row %d:\n%s', ...
                rowIndex, ...
                ME.message);

        end

    end

    exportAudit = [ ...
        exportAudit; ...
        table( ...
            rowIndex, ...
            originalSubjectID, ...
            subjectID, ...
            bidsSubject, ...
            bidsSubjectLabel, ...
            bidsSession, ...
            taskLabel, ...
            runNumber, ...
            string(xdfPath), ...
            sourceSignature, ...
            logical(success), ...
            message, ...
            string(detectedHeader), ...
            string(bidsRecordingSignature), ...
            logical(structureOK), ...
            string(exportedAt), ...
            'VariableNames', { ...
                'TableRow', ...
                'OriginalSubjectID', ...
                'SubjectID', ...
                'BidsSubject', ...
                'BidsSubjectLabel', ...
                'BidsSession', ...
                'Task', ...
                'RunNumber', ...
                'XdfPath', ...
                'SourceXDFSignature', ...
                'XDF2BIDSSuccess', ...
                'Message', ...
                'DetectedBIDSEEGHeader', ...
                'BIDSRecordingSignature', ...
                'BIDSStructureOK', ...
                'ExportedAt'}) ...
        ]; %#ok<AGROW>

    fclose all;

end

% Save BIDS export audit

writetable( ...
    exportAudit, ...
    P.bidsExportAuditFile);

% Update import table with BIDS provenance

for iAudit = 1:height(exportAudit)

    r = ...
        exportAudit.TableRow(iAudit);

    if ...
            exportAudit.XDF2BIDSSuccess(iAudit) && ...
            exportAudit.BIDSStructureOK(iAudit)

        importTable.BidsExportStatus(r) = ...
            "PASS";

    else

        importTable.BidsExportStatus(r) = ...
            "FAIL";

    end

    importTable.BidsExportMessage(r) = ...
        exportAudit.Message(iAudit);

    importTable.BidsEEGHeader(r) = ...
        exportAudit.DetectedBIDSEEGHeader(iAudit);

    importTable.BidsSourceSignature(r) = ...
        exportAudit.SourceXDFSignature(iAudit);

    importTable.BidsRecordingSignature(r) = ...
        exportAudit.BIDSRecordingSignature(iAudit);

    if ...
            exportAudit.XDF2BIDSSuccess(iAudit) && ...
            exportAudit.BIDSStructureOK(iAudit)

        importTable.BidsExportConfigSignature(r) = ...
            bidsExportConfigSignature;

    else

        importTable.BidsExportConfigSignature(r) = ...
            "";

    end

    importTable.BidsExportedAt(r) = ...
        exportAudit.ExportedAt(iAudit);

end

writetable( ...
    importTable, ...
    P.importTableFile);

% BIDS structure gate

if cfg.requireBidsStructureAuditPass

    failed = ...
        ~exportAudit.XDF2BIDSSuccess | ...
        ~exportAudit.BIDSStructureOK;

    if any(failed)

        disp( ...
            exportAudit( ...
                failed, ...
                { ...
                    'TableRow', ...
                    'OriginalSubjectID', ...
                    'SubjectID', ...
                    'BidsSession', ...
                    'Task', ...
                    'RunNumber', ...
                    'Message'}));

        error( ...
            ['One or more enabled recordings failed the BIDS export ' ...
             'gate. Fix them before BIDS -> EEGLAB conversion.']);

    end

end

% PART 2
% BIDS -> run-separated EEGLAB

bids2setLog = table();

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsEEGLABStatus');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsEEGLABMessage');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsEEGLABSet');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsEEGLABSignature');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsEEGLABConfigSignature');

importTable = ...
    ensure_string_column_local( ...
        importTable, ...
        'BidsEEGLABCreatedAt');

bidsEEGLABConfigSignature = ...
    bids_eeglab_config_signature_local(cfg);

nSetReused = 0;
nSetConverted = 0;

if cfg.createRunSeparatedEEGLAB

    successfulRows = ...
        exportAudit.XDF2BIDSSuccess & ...
        exportAudit.BIDSStructureOK;

    successfulAudit = ...
        exportAudit(successfulRows, :);

    for iRow = 1:height(successfulAudit)

        r = ...
            successfulAudit.TableRow(iRow);

        headerPath = ...
            char( ...
                successfulAudit.DetectedBIDSEEGHeader(iRow));

        subjectID = ...
            string( ...
                successfulAudit.SubjectID(iRow));

        originalSubjectID = ...
            string( ...
                successfulAudit.OriginalSubjectID(iRow));

        bidsSubjectLabel = ...
            string( ...
                successfulAudit.BidsSubjectLabel(iRow));

        bidsSession = ...
            string( ...
                successfulAudit.BidsSession(iRow));

        taskLabel = ...
            string( ...
                successfulAudit.Task(iRow));

        runNumber = ...
            successfulAudit.RunNumber(iRow);

        xdfPath = ...
            string( ...
                successfulAudit.XdfPath(iRow));

        sourceXDFSignature = ...
            string( ...
                successfulAudit.SourceXDFSignature(iRow));

        sourceBidsRecordingSignature = ...
            string( ...
                successfulAudit.BIDSRecordingSignature(iRow));

        success = false;
        message = "";

        setPath = ...
            expected_run_eeglab_set_path_local( ...
                headerPath, ...
                P.bidsRawEEGLABFolder, ...
                cfg, ...
                subjectID, ...
                bidsSession);

        setSignature = "";
        loaderName = "";
        completedAt = "";

        sampleCount = NaN;
        channelCount = NaN;
        samplingRate = NaN;

        try

            canReuse = ...
                can_reuse_run_eeglab_local( ...
                    importTable, ...
                    r, ...
                    setPath, ...
                    bidsEEGLABConfigSignature, ...
                    sourceBidsRecordingSignature, sourceXDFSignature);

            if canReuse

                setSignature = ...
                    hipexo.file_metadata_signature( ...
                        char(setPath));

                success = true;
                message = "REUSED";
                loaderName = "existing_run_separated_set";
                completedAt = ...
                    string(importTable.BidsEEGLABCreatedAt(r));

                nSetReused = nSetReused + 1;

            else

                fprintf( ...
                    '\nConverting BIDS -> run-separated EEGLAB: %s | ses-%s | run-%g\n', ...
                    subjectID, ...
                    bidsSession, ...
                    runNumber);

                [ ...
                    EEG, ...
                    setPath, ...
                    loaderName ...
                ] = ...
                    convert_one_bids_recording_local( ...
                        headerPath, ...
                        P.bidsRawEEGLABFolder, ...
                        cfg, ...
                        subjectID, ...
                        originalSubjectID, ...
                        bidsSubjectLabel, ...
                        bidsSession, ...
                        taskLabel, ...
                        runNumber, ...
                        xdfPath, ...
                        sourceXDFSignature, ...
                        sourceBidsRecordingSignature);

                sampleCount = ...
                    double(EEG.pnts);

                channelCount = ...
                    double(EEG.nbchan);

                samplingRate = ...
                    double(EEG.srate);

                setSignature = ...
                    hipexo.file_metadata_signature( ...
                        char(setPath));

                success = ...
                    true;

                message = ...
                    "OK";

                completedAt = ...
                    string(datetime( ...
                        'now', ...
                        'Format', ...
                        'yyyy-MM-dd HH:mm:ss'));

                nSetConverted = nSetConverted + 1;

            end

        catch ME

            message = ...
                string(ME.message);

            warning( ...
                'HipExo:BIDSRunEEGLABFailed', ...
                ['BIDS -> run-separated EEGLAB failed ' ...
                 'for row %d:\n%s'], ...
                r, ...
                ME.message);

        end

        bids2setLog = [ ...
            bids2setLog; ...
            table( ...
                r, ...
                subjectID, ...
                bidsSession, ...
                taskLabel, ...
                runNumber, ...
                string(headerPath), ...
                string(setPath), ...
                string(loaderName), ...
                logical(success), ...
                message, ...
                sampleCount, ...
                channelCount, ...
                samplingRate, ...
                string(setSignature), ...
                string(completedAt), ...
                'VariableNames', { ...
                    'TableRow', ...
                    'SubjectID', ...
                    'BidsSession', ...
                    'Task', ...
                    'RunNumber', ...
                    'BidsEEGHeader', ...
                    'BidsEEGLABSet', ...
                    'Loader', ...
                    'Success', ...
                    'Message', ...
                    'SampleCount', ...
                    'ChannelCount', ...
                    'SamplingRate', ...
                    'SetSignature', ...
                    'CompletedAt'}) ...
            ]; %#ok<AGROW>

        if success

            importTable.BidsEEGLABStatus(r) = ...
                "PASS";

            importTable.BidsEEGLABMessage(r) = ...
                message;

            importTable.BidsEEGLABSet(r) = ...
                string(setPath);

            importTable.BidsEEGLABSignature(r) = ...
                string(setSignature);

            importTable.BidsEEGLABConfigSignature(r) = ...
                bidsEEGLABConfigSignature;

            importTable.BidsEEGLABCreatedAt(r) = ...
                string(completedAt);

        else

            importTable.BidsEEGLABStatus(r) = ...
                "FAIL";

            importTable.BidsEEGLABMessage(r) = ...
                message;

            importTable.BidsEEGLABSet(r) = ...
                "";

            importTable.BidsEEGLABSignature(r) = ...
                "";

            importTable.BidsEEGLABConfigSignature(r) = ...
                "";

            importTable.BidsEEGLABCreatedAt(r) = ...
                "";

        end

        writetable( ...
            importTable, ...
            P.importTableFile);

        fclose all;

    end

    if ~isempty(bids2setLog)

        writetable( ...
            bids2setLog, ...
            P.bids2setLogFile);

    end

    if ...
            cfg.requireRunSeparatedEEGLABPass && ...
            any(~bids2setLog.Success)

        disp( ...
            bids2setLog( ...
                ~bids2setLog.Success, ...
                { ...
                    'TableRow', ...
                    'SubjectID', ...
                    'BidsSession', ...
                    'Task', ...
                    'RunNumber', ...
                    'Message'}));

        error( ...
            ['One or more BIDS recordings failed the canonical ' ...
             'BIDS -> EEGLAB gate. Step 03 is blocked.']);

    end

end

% Optional BeMoBIL merged reference mirror

if cfg.createBemobilMergedMirror

    create_bemobil_reference_mirror_local( ...
        P, ...
        cfg, ...
        importTable, ...
        rowsToExport);

end

% Final save

writetable( ...
    importTable, ...
    P.importTableFile);

fprintf('\nStep 02B complete.\n');

fprintf( ...
    'BIDS recordings ready: %d/%d (reused %d, exported %d)\n', ...
    sum( ...
        exportAudit.XDF2BIDSSuccess & ...
        exportAudit.BIDSStructureOK), ...
    height(exportAudit), ...
    nBidsReused, ...
    nBidsExported);

if cfg.createRunSeparatedEEGLAB

    fprintf( ...
        ['Canonical BIDS-derived EEGLAB recordings ready: %d/%d ' ...
         '(reused %d, converted %d)\n'], ...
        sum(bids2setLog.Success), ...
        height(bids2setLog), ...
        nSetReused, ...
        nSetConverted);

end

fprintf( ...
    'BIDS root:\n%s\n', ...
    P.bidsDataFolder);

fprintf( ...
    'Canonical EEG analysis input root:\n%s\n', ...
    P.bidsRawEEGLABFolder);

end

% LOCAL FUNCTIONS

function cleanedSubjects = clean_stale_subject_outputs_local(T, P)
cleanedSubjects = strings(0, 1);
labels = unique(string(T.BidsSubjectLabel), 'stable');
for k = 1:numel(labels)
    if ismissing(labels(k)) || strlength(labels(k)) == 0, continue; end
    enabled = string(T.BidsSubjectLabel) == labels(k) & T.DoBIDSImport == 1;
    sessions = "ses-" + unique(string(T.BidsSession(enabled)), 'stable');
    roots = {P.bidsDataFolder, P.bidsRawEEGLABFolder};
    cleaned = false;
    for j = 1:numel(roots)
        folder = fullfile(roots{j}, char("sub-" + labels(k)));
        entries = dir(fullfile(folder, 'ses-*'));
        entries = entries([entries.isdir]);
        for n = 1:numel(entries)
            if ~ismember(string(entries(n).name), sessions)
                rmdir(fullfile(entries(n).folder, entries(n).name), 's');
                cleaned = true;
            end
        end
