function validate_identity_table_local(T, rows, cfg)

if ~all(isfinite(T.BidsSubject(rows)))

    error( ...
        'One or more enabled rows have invalid BidsSubject values.');

end

bidsLabels = ...
    cellstr( ...
        strtrim( ...
            string(T.BidsSubjectLabel)));

subjectIDs = ...
    cellstr( ...
        strtrim( ...
            string(T.SubjectID)));

originalIDs = ...
    cellstr( ...
        strtrim( ...
            string(T.OriginalSubjectID)));

for ii = 1:numel(rows)

    r = rows(ii);

    expectedLabel = ...
        sprintf( ...
            '%0*d', ...
            cfg.subjectLabelWidth, ...
            round(T.BidsSubject(r)));

    expectedSubjectID = ...
        ['sub-' expectedLabel];

    actualLabel = ...
        bidsLabels{r};

    actualSubjectID = ...
        subjectIDs{r};

    actualOriginalID = ...
        originalIDs{r};

    if ~strcmp(actualLabel, expectedLabel)

        error( ...
            ['BidsSubjectLabel mismatch at row %d. ' ...
             'Found "%s"; expected "%s".'], ...
            r, ...
            actualLabel, ...
            expectedLabel);

    end

    if ~strcmp( ...
            actualSubjectID, ...
            expectedSubjectID)

        error( ...
            ['SubjectID mismatch at row %d. ' ...
             'Found "%s"; expected "%s".'], ...
            r, ...
            actualSubjectID, ...
            expectedSubjectID);

    end

    if isempty(strtrim(actualOriginalID))

        error( ...
            'OriginalSubjectID is empty at row %d.', ...
            r);

    end

end

selectedSubjectIDs = ...
    subjectIDs(rows);

selectedOriginalIDs = ...
    originalIDs(rows);

selectedBidsSubjects = ...
    T.BidsSubject(rows);

uniqueCanonical = ...
    unique( ...
        selectedSubjectIDs, ...
        'stable');

for i = 1:numel(uniqueCanonical)

    sameCanonical = ...
        strcmp( ...
            selectedSubjectIDs, ...
            uniqueCanonical{i});

    originalsForCanonical = ...
        unique( ...
            selectedOriginalIDs(sameCanonical), ...
            'stable');

    if numel(originalsForCanonical) ~= 1

        error( ...
            ['Canonical participant collision: %s maps to multiple ' ...
             'original participants.'], ...
            uniqueCanonical{i});

    end

    numericIDsForCanonical = ...
        unique( ...
            selectedBidsSubjects(sameCanonical));

    if numel(numericIDsForCanonical) ~= 1

        error( ...
            ['Canonical participant %s maps to multiple numeric ' ...
             'BidsSubject values.'], ...
            uniqueCanonical{i});

    end

end

end

