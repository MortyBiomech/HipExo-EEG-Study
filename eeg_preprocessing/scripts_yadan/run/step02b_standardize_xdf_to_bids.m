function [ok, headerPath, message] = ...
    audit_one_bids_eeg_local( ...
        bidsRoot, ...
        bidsSubjectLabel, ...
        bidsSession, ...
        taskLabel, ...
        runNumber)

ok = false;
headerPath = "";
message = "";

if ~isfile( ...
        fullfile( ...
            bidsRoot, ...
            'dataset_description.json'))

    message = ...
        "dataset_description.json is missing";

    return;

end

eegFolder = ...
    fullfile( ...
        bidsRoot, ...
        ['sub-' char(bidsSubjectLabel)], ...
        ['ses-' char(bidsSession)], ...
        'eeg');

if ~isfolder(eegFolder)

    message = ...
        "expected sub/ses/eeg directory is missing";

    return;

end

headers = ...
    dir( ...
        fullfile( ...
            eegFolder, ...
            '*_eeg.vhdr'));

if isempty(headers)

    message = ...
        "no BrainVision *_eeg.vhdr was detected";

    return;

end

names = ...
    string({headers.name});

mask = ...
    contains( ...
        names, ...
        "_task-" + taskLabel + "_");

if isfinite(runNumber)

    runMatch = ...
        false(size(names));

    for iName = 1:numel(names)

        token = ...
            regexp( ...
                char(names(iName)), ...
                '_run-(?<run>\d+)_', ...
                'names', ...
                'once');

        if ~isempty(token)

            runMatch(iName) = ...
                str2double(token.run) == ...
                round(runNumber);

        end

    end

    mask = ...
        mask & runMatch;

end

matched = ...
    headers(mask);

if isempty(matched)

    message = ...
        "no EEG header matches expected task/run identity";

    return;

end

if numel(matched) ~= 1

    message = ...
        "more than one EEG header matches expected task/run identity";

    return;

end

headerPath = ...
    string( ...
        fullfile( ...
            matched.folder, ...
            matched.name));

ok = true;
message = "OK";

end

