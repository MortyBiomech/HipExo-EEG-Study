function finiteOK = ...
    check_data_finite_blockwise_local(data)

finiteOK = ...
    ~isempty(data);

if ~finiteOK
    return;
end

blockSize = 100000;
nSamples = size(data, 2);

for firstSample = 1:blockSize:nSamples

    lastSample = min( ...
        nSamples, ...
        firstSample + blockSize - 1);

    block = ...
        data(:, firstSample:lastSample);

    if any(~isfinite(block(:)))

        finiteOK = false;
        return;
    end
end

end

function tf = ...
    channel_has_valid_xyz_local(chanloc)

tf = true;

for name = {'X', 'Y', 'Z'}

    fieldName = name{1};

    if ~isfield(chanloc, fieldName) || ...
            isempty(chanloc.(fieldName)) || ...
            ~isnumeric(chanloc.(fieldName)) || ...
            ~isscalar(chanloc.(fieldName)) || ...
            ~isfinite(double(chanloc.(fieldName)))

        tf = false;
        return;
    end
end

end

function [count, ok] = ...
    check_interpolated_channel_count_local( ...
        EEG, ...
        maxFraction)

count = NaN;
ok = false;

if ~isfield(EEG, 'etc') || ...
        ~isfield(EEG.etc, 'interpolated_channels')

    return;
end

channels = ...
    EEG.etc.interpolated_channels;

if isempty(channels)

    count = 0;
    ok = true;
    return;
end

channels = ...
    double(channels(:));

if any(~isfinite(channels)) || ...
        any(channels < 1) || ...
        any(channels > EEG.nbchan) || ...
        any(abs(channels - round(channels)) > 1e-6)

    return;
end

count = ...
    numel(unique(channels));

ok = ...
    count <= ...
    floor(double(EEG.nbchan) * maxFraction);

end

function [rankValue, valid] = ...
    get_rank_metadata_local(EEG)

rankValue = NaN;
valid = false;

if ~isfield(EEG, 'etc') || ...
        ~isfield(EEG.etc, 'rank')

    return;
end

rankValue = ...
    scalar_number_local(EEG.etc.rank);

valid = ...
    isfinite(rankValue) && ...
    rankValue >= 1 && ...
    rankValue <= EEG.nbchan && ...
    abs(rankValue - round(rankValue)) < 1e-6;

end

function value = ...
    scalar_number_local(x)

value = NaN;

if (isnumeric(x) || islogical(x)) && ...
        isscalar(x)

    value = double(x);

elseif ischar(x) || isstring(x)

    parsed = ...
        str2double(strtrim(string(x)));

    if isscalar(parsed)
        value = parsed;
    end
end

end

function peakDb = ...
    estimate_line_noise_peak_db_local( ...
        data, ...
        srate, ...
        targetHz, settings)

peakDb = NaN;

if isempty(data) || ...
        ~isfinite(srate) || ...
        srate <= 0 || ...
        targetHz + settings.lineNoiseNeighborHz(2) >= srate / 2

    return;
end

data = ...
    reshape( ...
        data, ...
        size(data, 1), ...
        []);

nAvailable = size(data, 2);

nSamples = ...
    min( ...
        nAvailable, ...
        round(settings.lineNoiseWindowSec * srate));

if nAvailable < round(settings.lineNoiseMinimumDurationSec * srate) || ...
        nSamples < 4

    return;
end

firstSample = ...
    floor((nAvailable - nSamples) / 2) + 1;

data = double( ...
    data(:, ...
    firstSample:firstSample + nSamples - 1));

data = ...
    data - mean(data, 2);

window = ...
    0.5 - ...
    0.5 * cos( ...
        2 * pi * ...
        (0:nSamples-1) / ...
        (nSamples-1));

spectrum = ...
    fft(data .* window, [], 2);

powerSpectrum = ...
    mean(abs(spectrum).^2, 1);

frequency = ...
    (0:nSamples-1) * ...
    (srate / nSamples);

positive = ...
    frequency <= srate / 2;

frequency = ...
    frequency(positive);

powerSpectrum = ...
    powerSpectrum(positive);

targetMask = ...
    abs(frequency - targetHz) <= settings.lineNoiseHalfWidthHz;

neighborMask = ...
    (frequency >= targetHz - settings.lineNoiseNeighborHz(2) & ...
     frequency <= targetHz - settings.lineNoiseNeighborHz(1)) | ...
    (frequency >= targetHz + settings.lineNoiseNeighborHz(1) & ...
     frequency <= targetHz + settings.lineNoiseNeighborHz(2));

if ~any(targetMask) || ...
        ~any(neighborMask)

    return;
end

targetPower = ...
    mean(powerSpectrum(targetMask));

neighborPower = ...
    mean(powerSpectrum(neighborMask));

if targetPower > 0 && ...
        neighborPower > 0 && ...
        isfinite(targetPower) && ...
        isfinite(neighborPower)

    peakDb = ...
        10 * log10( ...
            targetPower / neighborPower);
end

end

function eventTypes = ...
    event_type_strings_local(events)

if isempty(events)

    eventTypes = strings(0, 1);
    return;
end

eventTypes = ...
    strings(numel(events), 1);

for k = 1:numel(events)

    raw = events(k).type;

    if iscell(raw) && isscalar(raw)
        raw = raw{1};
    end

    if isnumeric(raw) && ~isscalar(raw)

        eventTypes(k) = ...
            strjoin(string(raw(:)'), '_');

    else

        eventTypes(k) = string(raw);
    end
end

eventTypes = ...
    upper(strtrim(eventTypes));

end

function [ok, notes] = ...
    check_preprocessing_provenance_local( ...
        EEG, ...
        expectedSignature, ...
        expectedSubject, ...
        expectedSession, ...
        expectedCanonicalSubject)

problems = strings(0, 1);

if ~isfield(EEG, 'etc')

    ok = false;
    notes = "EEG_etc_missing";
    return;
end

if ~isfield(EEG.etc, 'preprocessing_input_signature') || ...
        strtrim(string( ...
        EEG.etc.preprocessing_input_signature)) ~= ...
        strtrim(string(expectedSignature))

    problems(end+1, 1) = ...
        "preprocessing_signature_mismatch";
end

if ~isfield(EEG.etc, 'real_bids_subject') || ...
        scalar_number_local( ...
        EEG.etc.real_bids_subject) ~= ...
        double(expectedSubject)

    problems(end+1, 1) = ...
        "stored_bids_subject_mismatch";
end

if ~isfield(EEG.etc, 'session_label') || ...
        ~strcmpi( ...
            strtrim(string(EEG.etc.session_label)), ...
            strtrim(string(expectedSession)))

    problems(end+1, 1) = ...
        "stored_session_label_mismatch";
end

storedCanonical = "";

if isfield(EEG.etc, 'canonical_subject_id')

    storedCanonical = ...
        normalize_subject_identity_local( ...
            EEG.etc.canonical_subject_id);

elseif isfield(EEG.etc, 'processing_subject_label')

    storedCanonical = ...
        normalize_subject_identity_local( ...
            EEG.etc.processing_subject_label);
end

if storedCanonical ~= ...
        normalize_subject_identity_local( ...
            expectedCanonicalSubject)

    problems(end+1, 1) = ...
        "stored_canonical_subject_mismatch";
end

problems = ...
    unique(problems, 'stable');

ok = ...
    isempty(problems);

if ok

    notes = "OK";

else

    notes = join(problems, "; ");
end

end

function canonicalID = ...
    normalize_subject_identity_local(value)

canonicalID = "";

if isnumeric(value) || ...
        islogical(value)

    numericValue = double(value);

else

    textValue = ...
        lower(strtrim(string(value)));

    textValue = ...
        regexprep( ...
            textValue, ...
            '^sub[-_]*', ...
            '');

    numericValue = ...
        str2double(textValue);

    if ~isfinite(numericValue)

        token = ...
            regexp( ...
                char(textValue), ...
                '\d+$', ...
                'match', ...
                'once');

        numericValue = ...
            str2double(string(token));
    end
end

if isscalar(numericValue) && ...
        isfinite(numericValue) && ...
        numericValue >= 0 && ...
        abs(numericValue - round(numericValue)) < 1e-9

    canonicalID = ...
        "sub-" + ...
        string(sprintf( ...
            '%02d', ...
            round(numericValue)));
end

end