% GOAL
%   Check the structural and quantitative quality of each subject-level
%   BeMoBIL preprocessed EEG dataset before AMICA.
%
% INPUT
%   Updated subject_level_EEG_table.csv from Step 05.
%   Preprocessed .set/.fdt datasets produced by Step 05.
%
% APPROACH
%   1. Select completed preprocessing rows enabled by DoQC.
%   2. Skip QC when preprocessed content and the actual QC settings match
%      an existing passed result.
%   3. Load only new or changed datasets.
%   4. Check data, channel locations, gait events, preprocessing metadata,
%      interpolation/rank consistency, provenance, and residual 50 Hz noise.
%   5. Save QC status and metrics to the subject-level processing table.
%   6. Set DoAMICA = AnalysisReady automatically.
%
% OUTPUT
%   Updated subject_level_EEG_table.csv.
%
% USED BY
%   step07_run_amica_dipfit_iclabel.m

clear;
clc;
close all;

set(0, 'DefaultFigureVisible', 'off');
set(groot, 'DefaultFigureVisible', 'off');

%  LOAD PATHS AND CONFIGURATION

thisFile = mfilename('fullpath');

if isempty(thisFile)
    error('Could not resolve the current Step 06 script path.');
end

scriptsRoot = fileparts(fileparts(thisFile));

addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();
bemobil_config = config_step05_09_eeg_preprocessing_ica(P);

mappingFile = P.subjectLevelEEGTableFile;

if ~isfile(mappingFile)
    error([ ...
        'Subject-level processing table not found:\n%s\n' ...
        'Run step05_preprocess_eeg.m first.'], ...
        mappingFile);
end

expectedChannels = ...
    bemobil_config.preprocessingQC.expectedChannels;

processingVersion = ...
    string(bemobil_config.preprocessingQC.processingVersion);

lineNoiseFrequencyHz = ...
    bemobil_config.preprocessingQC.lineNoiseFrequencyHz;

maxLineNoisePeakDb = ...
    bemobil_config.preprocessingQC.maxLineNoisePeakDb;

maxInterpolatedChannelFraction = ...
    bemobil_config.preprocessingQC.maxInterpolatedChannelFraction;

reset_DoQC_from_PreprocessingStatus = ...
    bemobil_config.preprocessingQC.reset_DoQC_from_PreprocessingStatus;

if isempty(bemobil_config.resample_freq)
    expectedSrate = 500;
else
    expectedSrate = double(bemobil_config.resample_freq);
end

% Record the parameters that determine the QC measurements and decisions.
qcSettings = struct( ...
    'expectedChannels', expectedChannels, 'expectedSrate', expectedSrate, ...
    'minimumDurationSec', 120, 'lineNoiseFrequencyHz', lineNoiseFrequencyHz, ...
    'maxLineNoisePeakDb', maxLineNoisePeakDb, ...
    'maxInterpolatedChannelFraction', maxInterpolatedChannelFraction, ...
    'lineNoiseWindowSec', 60, 'lineNoiseMinimumDurationSec', 10, ...
    'lineNoiseHalfWidthHz', 0.5, 'lineNoiseNeighborHz', [1 3]);
qcSettingsSignature = hipexo.content_signature(qcSettings);

%  INITIALIZE EEGLAB

if exist('pop_loadset', 'file') ~= 2
    eeglab nogui;
end

hipexo.hide_all_figures();

%  READ SUBJECT-LEVEL TABLE

optsImport = detectImportOptions( ...
    mappingFile, ...
    'FileType', 'text', ...
    'Delimiter', ',', ...
    'VariableNamingRule', 'preserve');

sourceMap = readtable(mappingFile, optsImport);

requiredColumns = { ...
    'BidsSubject', ...
    'BidsSession', ...
    'PreprocessingStatus', ...
    'PreprocessedSetPath', ...
    'PreprocessingInputSignature'};

for c = 1:numel(requiredColumns)

    if ~ismember(requiredColumns{c}, sourceMap.Properties.VariableNames)

        error([ ...
            'Subject-level processing table is missing required column: %s\n' ...
            'Run step05_preprocess_eeg.m first.'], ...
            requiredColumns{c});
    end
end

sourceMap = ensure_numeric_column_local( ...
    sourceMap, ...
    'BidsSubject');

textColumns = { ...
    'BidsSession', ...
    'PreprocessingStatus', ...
    'PreprocessedSetPath', ...
    'PreprocessingInputSignature'};

for c = 1:numel(textColumns)

    sourceMap = ensure_string_column_local( ...
        sourceMap, ...
        textColumns{c});
end

if ismember('DoImport', sourceMap.Properties.VariableNames)

    sourceMap = ensure_numeric_column_local( ...
        sourceMap, ...
        'DoImport');
end

%  PREPARE QC AND OUTPUT COLUMNS

completedMask = ...
    lower(strtrim(sourceMap.PreprocessingStatus)) == "completed";

if ~ismember('DoQC', sourceMap.Properties.VariableNames)

    sourceMap.DoQC = double(completedMask);

elseif reset_DoQC_from_PreprocessingStatus

    sourceMap.DoQC = double(completedMask);

else

    sourceMap = ensure_numeric_column_local( ...
        sourceMap, ...
        'DoQC');

    missingDoQC = ~isfinite(sourceMap.DoQC);

    sourceMap.DoQC(missingDoQC) = ...
        double(completedMask(missingDoQC));
end

sourceMap = ensure_numeric_optional_column_local( ...
    sourceMap, ...
    'AnalysisReady');

sourceMap = ensure_numeric_optional_column_local( ...
    sourceMap, ...
    'DoAMICA');

stringOutputColumns = { ...
    'ProcessingSubjectLabel', ...
    'ProcessingSubjectFolder', ...
    'GaitEventStatus', ...
    'PreprocessingQCInputSetSignature', ...
    'PreprocessingQCProcessingVersion', ...
    'PreprocessingQCSettingsSignature', ...
    'PreprocessingQCStatus', ...
    'PreprocessingQCDate', ...
    'PreprocessingQCSummaryPath', ...
    'PreprocessingQCFigurePath', ...
    'PreprocessingQCNotes'};

for c = 1:numel(stringOutputColumns)

    sourceMap = ensure_string_column_local( ...
        sourceMap, ...
        stringOutputColumns{c});
end

numericOutputColumns = { ...
    'PreprocessingQCEventCount', ...
    'PreprocessingQCDataFinite', ...
    'PreprocessingQCDurationOK', ...
    'PreprocessingQCLabelsUnique', ...
    'PreprocessingQCHasZaplineMetadata', ...
    'PreprocessingQCHasChannelRejectionMetadata', ...
    'PreprocessingQCHasInterpolationMetadata', ...
    'PreprocessingQCHasAverageReferenceMetadata', ...
    'PreprocessingQCLabelsNonempty', ...
    'PreprocessingQCProvenanceOK', ...
    'PreprocessingQCRankOK', ...
    'PreprocessingQCLineNoiseOK', ...
    'PreprocessingQCInterpolationCountOK', ...
    'PreprocessingQCRankMetadata', ...
    'PreprocessingQCExpectedRank', ...
    'PreprocessingQCRankEstimate', ...
    'PreprocessingQCLineNoisePeakDb', ...
    'PreprocessingQCInterpolatedChannelCount'};

for c = 1:numel(numericOutputColumns)

    sourceMap = ensure_numeric_optional_column_local( ...
        sourceMap, ...
        numericOutputColumns{c});
end

disabledRows = sourceMap.DoQC ~= 1 | ~completedMask;

sourceMap.AnalysisReady(disabledRows) = 0;
sourceMap.DoAMICA(disabledRows) = 0;

rowsToCheck = find( ...
    sourceMap.DoQC == 1 & completedMask);

rowsToCheck = rowsToCheck(hipexo.subject_is_selected(sourceMap.BidsSubject(rowsToCheck)));

if isempty(rowsToCheck)
    error('No completed rows with DoQC = 1 were found.');
end

%  QC LOOP

nSkipped = 0;
nChecked = 0;

for rr = 1:numel(rowsToCheck)

    EEG = [];
    hipexo.hide_all_figures();

    rowIdx = rowsToCheck(rr);

    sessionRows = ...
        hipexo.session_peer_rows( ...
            sourceMap, ...
            rowIdx);

    bidsSubject = ...
        double(sourceMap.BidsSubject(rowIdx));

    bidsSession = ...
        strtrim(sourceMap.BidsSession(rowIdx));

    if ~isfinite(bidsSubject) || ...
            bidsSubject < 1 || ...
            abs(bidsSubject - round(bidsSubject)) > 1e-9

        sourceMap = set_failed_qc_local( ...
            sourceMap, ...
            sessionRows, ...
            "failed_invalid_bids_subject", ...
            "BidsSubject is missing or invalid.", ...
            "", ...
            processingVersion);

        writetable(sourceMap, mappingFile);
        continue;
    end

    bidsSubject = round(bidsSubject);

    processingSubjectLabel = ...
        string(sprintf('%02d', bidsSubject));

    processingSubjectFolder = ...
        "sub-" + processingSubjectLabel;

    sourceMap.ProcessingSubjectLabel(sessionRows) = ...
        processingSubjectLabel;

    sourceMap.ProcessingSubjectFolder(sessionRows) = ...
        processingSubjectFolder;

    preprocessedSetPath = ...
        strtrim(sourceMap.PreprocessedSetPath(rowIdx));

    if strlength(preprocessedSetPath) == 0 || ...
            ~isfile(preprocessedSetPath)

        sourceMap = set_failed_qc_local( ...
            sourceMap, ...
            sessionRows, ...
            "failed_preprocessed_set_not_found", ...
            "Preprocessed .set file was not found.", ...
            "", ...
            processingVersion);

        writetable(sourceMap, mappingFile);
        continue;
    end

    currentInputSignature = ...
        hipexo.eeglab_dataset_signature( ...
            preprocessedSetPath);

    qcAlreadyCurrent = ...
        sourceMap.PreprocessingQCStatus(rowIdx) == ...
            "passed_basic_checks" && ...
        sourceMap.PreprocessingQCInputSetSignature(rowIdx) == ...
            currentInputSignature && ...
        sourceMap.PreprocessingQCSettingsSignature(rowIdx) == qcSettingsSignature;

    if qcAlreadyCurrent

        sourceMap.AnalysisReady(sessionRows) = 1;
        sourceMap.DoAMICA(sessionRows) = 1;

        writetable(sourceMap, mappingFile);

        nSkipped = nSkipped + 1;
        continue;
    end

    try

        [setFolder, setName, setExt] = ...
            fileparts(char(preprocessedSetPath));

        EEG = pop_loadset( ...
            'filename', ...
            [setName setExt], ...
            'filepath', ...
            setFolder);

        EEG = eeg_checkset(EEG);

        channelLabels = ...
            string({EEG.chanlocs.labels})';

        channelOK = ...
            EEG.nbchan == expectedChannels;

        srateOK = ...
            isfinite(EEG.srate) && ...
            abs(double(EEG.srate) - expectedSrate) < 0.001;

        dataFiniteOK = ...
            check_data_finite_blockwise_local( ...
                EEG.data);

        durationOK = ...
            EEG.pnts > 1 && ...
            isfinite(EEG.srate) && ...
            EEG.srate > 0 && ...
            (EEG.pnts - 1) / EEG.srate >= qcSettings.minimumDurationSec;

        labelsNonemptyOK = ...
            numel(channelLabels) == EEG.nbchan && ...
            all(strlength(strtrim(channelLabels)) > 0);

        labelsUniqueOK = ...
            labelsNonemptyOK && ...
            numel(unique(lower(strtrim(channelLabels)))) == ...
            EEG.nbchan;

        if isempty(EEG.chanlocs)

            locationOK = false;

        else

            hasLocation = arrayfun( ...
                @channel_has_valid_xyz_local, ...
                EEG.chanlocs);

            locationOK = ...
                numel(hasLocation) == EEG.nbchan && ...
                all(hasLocation);
        end

        [provenanceOK, provenanceNotes] = ...
            check_preprocessing_provenance_local( ...
                EEG, ...
                sourceMap.PreprocessingInputSignature(rowIdx), ...
                bidsSubject, ...
                bidsSession, ...
                processingSubjectFolder);

        hasZaplineMetadata = ...
            isfield(EEG, 'etc') && ...
            isfield(EEG.etc, 'zapline');

        hasChannelRejectionMetadata = ...
            isfield(EEG, 'etc') && ...
            isfield(EEG.etc, 'channel_rejection');

        hasInterpolationMetadata = ...
            isfield(EEG, 'etc') && ...
            isfield(EEG.etc, 'interpolated_channels');

        hasAverageReferenceMetadata = ...
            isfield(EEG, 'etc') && ...
            isfield(EEG.etc, 'bemobil_reref') && ...
            ~isempty(EEG.etc.bemobil_reref);

        [interpolatedChannelCount, interpolationCountOK] = ...
            check_interpolated_channel_count_local( ...
                EEG, ...
                maxInterpolatedChannelFraction);

        expectedRank = NaN;

        if isfinite(interpolatedChannelCount)

            expectedRank = ...
                EEG.nbchan - interpolatedChannelCount;
        end

        [rankMetadata, rankMetadataValid] = ...
            get_rank_metadata_local(EEG);

        rankOK = ...
            rankMetadataValid && ...
            isfinite(expectedRank) && ...
            abs(rankMetadata - expectedRank) < 0.5;

        lineNoisePeakDb = ...
            estimate_line_noise_peak_db_local( ...
                EEG.data, ...
                EEG.srate, ...
                lineNoiseFrequencyHz, qcSettings);

        lineNoiseOK = ...
            isfinite(lineNoisePeakDb) && ...
            lineNoisePeakDb <= maxLineNoisePeakDb;

        requiredGaitEventTypes = ...
            ["RHS", "RTO", "LHS", "LTO"];

        eventTypes = ...
            event_type_strings_local(EEG.event);

        gaitEventCounts = ...
            zeros(numel(requiredGaitEventTypes), 1);

        for iEvent = 1:numel(requiredGaitEventTypes)

            gaitEventCounts(iEvent) = ...
                sum(eventTypes == ...
                requiredGaitEventTypes(iEvent));
        end

        eventOK = ...
            all(gaitEventCounts > 0);

        metadataOK = ...
            hasZaplineMetadata && ...
            hasChannelRejectionMetadata && ...
            hasInterpolationMetadata && ...
            hasAverageReferenceMetadata;

        checkNames = [ ...
            "channel_count", ...
            "sampling_rate", ...
            "data_finite", ...
            "duration", ...
            "labels_nonempty", ...
            "labels_unique", ...
            "XYZ_locations", ...
            "preprocessing_provenance", ...
            "preprocessing_metadata", ...
            "interpolated_channel_count", ...
            "rank_metadata", ...
            "line_noise_residual", ...
            "gait_events"];

        checkValues = logical([ ...
            channelOK, ...
            srateOK, ...
            dataFiniteOK, ...
            durationOK, ...
            labelsNonemptyOK, ...
            labelsUniqueOK, ...
            locationOK, ...
            provenanceOK, ...
            metadataOK, ...
            interpolationCountOK, ...
            rankOK, ...
            lineNoiseOK, ...
            eventOK]);

        allPassed = ...
            all(checkValues);

        if allPassed

            qcStatus = ...
                "passed_basic_checks";

            qcNotes = ...
                "Basic preprocessing checks passed.";

        else

            qcStatus = ...
                "check_required";

            qcNotes = ...
                "Failed checks: " + ...
                join(checkNames(~checkValues), "; ") + ...
                ".";

            if ~provenanceOK

                qcNotes = ...
                    qcNotes + ...
                    " Provenance detail: " + ...
                    provenanceNotes + ...
                    ".";
            end
        end

        sourceMap.AnalysisReady(sessionRows) = ...
            double(allPassed);

        sourceMap.DoAMICA(sessionRows) = ...
            double(allPassed);

        if eventOK

            sourceMap.GaitEventStatus(sessionRows) = ...
                "required_gait_event_types_verified";

        else

            sourceMap.GaitEventStatus(sessionRows) = ...
                "events_missing_not_ready_for_gait_analysis";
        end

        sourceMap.PreprocessingQCEventCount(sessionRows) = ...
            numel(EEG.event);

        sourceMap.PreprocessingQCDataFinite(sessionRows) = ...
            double(dataFiniteOK);

        sourceMap.PreprocessingQCDurationOK(sessionRows) = ...
            double(durationOK);

        sourceMap.PreprocessingQCLabelsUnique(sessionRows) = ...
            double(labelsUniqueOK);

        sourceMap.PreprocessingQCLabelsNonempty(sessionRows) = ...
            double(labelsNonemptyOK);

        sourceMap.PreprocessingQCHasZaplineMetadata(sessionRows) = ...
            double(hasZaplineMetadata);

        sourceMap.PreprocessingQCHasChannelRejectionMetadata(sessionRows) = ...
            double(hasChannelRejectionMetadata);

        sourceMap.PreprocessingQCHasInterpolationMetadata(sessionRows) = ...
            double(hasInterpolationMetadata);

        sourceMap.PreprocessingQCHasAverageReferenceMetadata(sessionRows) = ...
            double(hasAverageReferenceMetadata);

        sourceMap.PreprocessingQCProvenanceOK(sessionRows) = ...
            double(provenanceOK);

        sourceMap.PreprocessingQCRankOK(sessionRows) = ...
            double(rankOK);

        sourceMap.PreprocessingQCLineNoiseOK(sessionRows) = ...
            double(lineNoiseOK);

        sourceMap.PreprocessingQCInterpolationCountOK(sessionRows) = ...
            double(interpolationCountOK);

        sourceMap.PreprocessingQCRankMetadata(sessionRows) = ...
            rankMetadata;

        sourceMap.PreprocessingQCExpectedRank(sessionRows) = ...
            expectedRank;

        % The AMICA rank gate uses BeMoBIL rank metadata and
        % interpolation count only.
        sourceMap.PreprocessingQCRankEstimate(sessionRows) = ...
            NaN;

        sourceMap.PreprocessingQCLineNoisePeakDb(sessionRows) = ...
            lineNoisePeakDb;

        sourceMap.PreprocessingQCInterpolatedChannelCount(sessionRows) = ...
            interpolatedChannelCount;

        sourceMap.PreprocessingQCSettingsSignature(sessionRows) = qcSettingsSignature;

        sourceMap.PreprocessingQCInputSetSignature(sessionRows) = ...
            currentInputSignature;

        sourceMap.PreprocessingQCProcessingVersion(sessionRows) = ...
            processingVersion;

        sourceMap.PreprocessingQCStatus(sessionRows) = ...
            qcStatus;

        sourceMap.PreprocessingQCNotes(sessionRows) = ...
            qcNotes;

        sourceMap.PreprocessingQCDate(sessionRows) = ...
            string(datetime( ...
                'now', ...
                'Format', ...
                'yyyy-MM-dd HH:mm:ss'));

        sourceMap.PreprocessingQCSummaryPath(sessionRows) = "";
        sourceMap.PreprocessingQCFigurePath(sessionRows) = "";

        writetable(sourceMap, mappingFile);

        nChecked = nChecked + 1;

    catch ME

        sourceMap = set_failed_qc_local( ...
            sourceMap, ...
            sessionRows, ...
            "failed_qc_exception", ...
            string(ME.message), ...
            currentInputSignature, ...
            processingVersion);

        writetable(sourceMap, mappingFile);

        warning( ...
            'QC failed for %s:\n%s', ...
            processingSubjectFolder, ...
            ME.message);
    end

    EEG = [];
    hipexo.hide_all_figures();
end

%  FINAL REPORT

finalStatus = ...
    strtrim(sourceMap.PreprocessingQCStatus);

