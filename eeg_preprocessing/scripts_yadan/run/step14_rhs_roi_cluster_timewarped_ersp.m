        size(bandRangesHz, 2) == 2, ...
        'Band names and frequency ranges are inconsistent.');
    assert(groupWarpMs(end) > 0, ...
        'The final RHS group-warp latency must be positive.');

    timesMs = double(timesMs(:));
    gaitCyclePercent = 100 .* timesMs ./ double(groupWarpMs(end));
    frequenciesHz = double(frequenciesHz(:));

    groupSummary = table();
    subjectSummary = table();

    for conditionIndex = 1:numel(conditionNames)

        groupMatrix = groupData{conditionIndex};
        perSubjectMatrix = subjectData{conditionIndex};

        if isempty(groupMatrix)
            groupMatrix = NaN(numel(frequenciesHz), numel(timesMs));
        end

        groupMatrix = double(groupMatrix);
        assert(isequal(size(groupMatrix), ...
            [numel(frequenciesHz), numel(timesMs)]), ...
            'Group ERSP matrix has an unexpected size for condition %s.', ...
            char(conditionNames(conditionIndex)));

        if isempty(perSubjectMatrix)
            perSubjectMatrix = NaN( ...
                numel(frequenciesHz), ...
                numel(timesMs), ...
                numel(subjectNames));
        end

        perSubjectMatrix = double(perSubjectMatrix);
        if ndims(perSubjectMatrix) == 2
            perSubjectMatrix = reshape( ...
                perSubjectMatrix, ...
                size(perSubjectMatrix, 1), ...
                size(perSubjectMatrix, 2), ...
                1);
        end

        assert(size(perSubjectMatrix, 1) == numel(frequenciesHz) && ...
            size(perSubjectMatrix, 2) == numel(timesMs) && ...
            size(perSubjectMatrix, 3) == numel(subjectNames), ...
            'Subject ERSP matrix has an unexpected size for condition %s.', ...
            char(conditionNames(conditionIndex)));

        for bandIndex = 1:numel(bandNames)

            bandLow = double(bandRangesHz(bandIndex, 1));
            bandHigh = double(bandRangesHz(bandIndex, 2));
            frequencyMask = ...
                frequenciesHz >= bandLow & ...
                frequenciesHz <= bandHigh;

            assert(any(frequencyMask), ...
                'No ERSP frequency samples fall within band %s.', ...
                char(bandNames(bandIndex)));

            groupTimecourse = mean( ...
                groupMatrix(frequencyMask, :), ...
                1, ...
                'omitnan')';

            nTime = numel(timesMs);
            groupRows = table( ...
                repmat(roiID, nTime, 1), ...
                repmat(originalClusterID, nTime, 1), ...
                repmat(roiName, nTime, 1), ...
                repmat(conditionNames(conditionIndex), nTime, 1), ...
                repmat(conditionDisplayNames(conditionIndex), nTime, 1), ...
                repmat(double(nSubjects(conditionIndex)), nTime, 1), ...
                repmat(bandNames(bandIndex), nTime, 1), ...
                repmat(bandLow, nTime, 1), ...
                repmat(bandHigh, nTime, 1), ...
                timesMs, ...
                gaitCyclePercent, ...
                groupTimecourse, ...
