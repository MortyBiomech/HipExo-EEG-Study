    subjectNames = string(subjectNames(:));
    gaitPhaseNames = string(gaitPhaseNames(:));
    gaitPhaseDisplayLabels = string(gaitPhaseDisplayLabels(:));
    bandNames = string(bandNames(:));

    assert(numel(groupData) == numel(conditionNames), ...
        'Group ERSP cells do not match the condition count.');
    assert(numel(subjectData) == numel(conditionNames), ...
        'Subject ERSP cells do not match the condition count.');
    assert(numel(conditionDisplayNames) == numel(conditionNames), ...
        'Condition display labels do not match the condition count.');
    assert(numel(nSubjects) == numel(conditionNames), ...
        'Subject-count vector does not match the condition count.');
    assert(numel(groupWarpMs) == numel(gaitPhaseNames) + 1, ...
        'Gait phase count does not match the time-warp landmarks.');
    assert(numel(gaitPhaseDisplayLabels) == numel(gaitPhaseNames), ...
        'Gait-phase display labels do not match gait-phase names.');
    assert(size(bandRangesHz, 1) == numel(bandNames) && ...
        size(bandRangesHz, 2) == 2, ...
        'Band names and frequency ranges are inconsistent.');

    groupSummary = table();
    subjectSummary = table();

    for conditionIndex = 1:numel(conditionNames)

        groupMatrix = groupData{conditionIndex};
        perSubjectMatrix = subjectData{conditionIndex};

        if isempty(groupMatrix)
            groupMatrix = NaN(numel(frequenciesHz), numel(timesMs));
        end

        groupMatrix = double(groupMatrix);
        assert(isequal(size(groupMatrix), ...
            [numel(frequenciesHz), numel(timesMs)]), ...
            'Group ERSP matrix has an unexpected size for condition %s.', ...
            char(conditionNames(conditionIndex)));

        if isempty(perSubjectMatrix)
            perSubjectMatrix = NaN( ...
                numel(frequenciesHz), ...
                numel(timesMs), ...
                numel(subjectNames));
