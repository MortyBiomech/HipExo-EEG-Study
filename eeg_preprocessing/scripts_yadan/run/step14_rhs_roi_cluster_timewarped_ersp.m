                    'SubjectCount', ...
                    'Band', ...
                    'BandLow_Hz', ...
                    'BandHigh_Hz', ...
                    'Time_ms', ...
                    'GaitCycle_pct', ...
                    'MeanERSP_dB'});

            if isempty(groupSummary)
                groupSummary = groupRows;
            else
                groupSummary = [groupSummary; groupRows]; %#ok<AGROW>
            end

            for subjectIndex = 1:numel(subjectNames)

                subjectMatrix = perSubjectMatrix( ...
                    frequencyMask, ...
                    :, ...
                    subjectIndex);

                subjectMatrix = reshape( ...
                    subjectMatrix, ...
                    nnz(frequencyMask), ...
                    numel(timesMs));

                if ~any(isfinite(subjectMatrix(:)))
                    continue;
                end

                subjectTimecourse = mean( ...
                    subjectMatrix, ...
                    1, ...
                    'omitnan')';

                subjectRows = table( ...
                    repmat(roiID, nTime, 1), ...
                    repmat(originalClusterID, nTime, 1), ...
                    repmat(roiName, nTime, 1), ...
                    repmat(subjectNames(subjectIndex), nTime, 1), ...
                    repmat(conditionNames(conditionIndex), nTime, 1), ...
                    repmat(conditionDisplayNames(conditionIndex), nTime, 1), ...
                    repmat(bandNames(bandIndex), nTime, 1), ...
                    repmat(bandLow, nTime, 1), ...
                    repmat(bandHigh, nTime, 1), ...
                    timesMs, ...
                    gaitCyclePercent, ...
                    subjectTimecourse, ...
                    'VariableNames', { ...
                        'ROIID', ...
                        'OriginalClusterID', ...
                        'ROIName', ...
                        'Subject', ...
                        'Condition', ...
                        'ConditionDisplay', ...
                        'Band', ...
                        'BandLow_Hz', ...
                        'BandHigh_Hz', ...
                        'Time_ms', ...
                        'GaitCycle_pct', ...
                        'MeanERSP_dB'});

                if isempty(subjectSummary)
                    subjectSummary = subjectRows;
                else
                    subjectSummary = [subjectSummary; subjectRows]; %#ok<AGROW>
                end
            end
        end
    end
end


function [groupSummary, subjectSummary] = summarize_band_phase_local( ...
        groupData, ...
        subjectData, ...
        subjectNames, ...
        nSubjects, ...
        conditionNames, ...
        conditionDisplayNames, ...
        timesMs, ...
        frequenciesHz, ...
        groupWarpMs, ...
        gaitPhaseNames, ...
        gaitPhaseDisplayLabels, ...
        bandNames, ...
        bandRangesHz, ...
