% GOAL
%   Compute descriptive time-warped gait-cycle ERSPs for ROI-specific
%   cluster representations that passed Step 13 cluster QC.
%
% INPUT
%   Step 13 RHS_ROI_cluster_QC_review.xlsx.
%   ROI-specific STUDYs from Step 12.
%   EEGLAB time-frequency measure files when available.
%
% APPROACH
%   1. Read fixed ROI rows whose ROI-specific cluster representation has
%      ClusterDecision=KEEP and all cluster QC fields PASS.
%   2. Define one common group-median RHS-LTO-LHS-RTO-nextRHS time warp.
%   3. Compute or reuse time-warped component TF caches. Existing TF
%      decompositions are reused when only the ERSP baseline changes.
%   4. Read cached TF power and apply the current EEGLAB common-baseline
%      normalization across all conditions in the design.
%   5. If one subject contributes multiple ICs to the cluster, keep only
%      the smallest numeric IC index for that subject.
%   6. Treat each retained IC as that subject's ERSP and average subjects equally.
%   7. Average configured frequency bands across frequency while preserving
%      the full normalized gait-cycle time axis for continuous band time courses.
%   8. Summarize group ERSP within configured frequency bands and the four
%      gait phases RHS-LTO, LTO-LHS, LHS-RTO, and RTO-nextRHS.
%   9. Save group-level and subject-level band time-course and band-by-phase
%      summaries.
%
% OUTPUT
%   04_timewarped_ERSP


