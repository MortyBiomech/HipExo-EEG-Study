function groupWarpMs = group_median_warp_local(ALLEEG)

    warpRows = NaN(numel(ALLEEG), 5);

    for datasetIndex = 1:numel(ALLEEG)
        assert(isfield(ALLEEG(datasetIndex), 'timewarp') && ...
            isfield(ALLEEG(datasetIndex).timewarp, 'warpto') && ...
            isfield(ALLEEG(datasetIndex).timewarp, 'latencies'), ...
            'Dataset %d has incomplete EEG.timewarp.', ...
            datasetIndex);

        warpto = double(ALLEEG(datasetIndex).timewarp.warpto(:)');
        assert(numel(warpto) == 5 && all(isfinite(warpto)), ...
            'Dataset %d does not contain five finite warpto values.', ...
            datasetIndex);
        assert(all(diff(warpto) > 0), ...
            'Dataset %d warpto values are not strictly ordered.', ...
            datasetIndex);

        latencies = double(ALLEEG(datasetIndex).timewarp.latencies);
        assert(size(latencies, 2) == 5 && ...
            size(latencies, 1) == ALLEEG(datasetIndex).trials && ...
            all(isfinite(latencies(:))), ...
            'Dataset %d timewarp latencies do not match its trials.', ...
            datasetIndex);

        warpRows(datasetIndex, :) = warpto;
    end

    groupWarpMs = median(warpRows, 1);
end


