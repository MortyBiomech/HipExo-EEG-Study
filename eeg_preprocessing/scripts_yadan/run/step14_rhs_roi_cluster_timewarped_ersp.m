function [subjects, componentICs] = ...
        cluster_member_identity_local(STUDY, clusterIndex)

    sets = double(STUDY.cluster(clusterIndex).sets);
    comps = double(STUDY.cluster(clusterIndex).comps);

    if isvector(sets)
        sets = reshape(sets, 1, []);
    end
    if isvector(comps)
        comps = reshape(comps, 1, []);
    end

    nMembers = max(size(sets, 2), size(comps, 2));
    assert(size(sets, 2) == nMembers && ...
        size(comps, 2) == nMembers, ...
        'Selected cluster sets/comps columns are inconsistent.');

    subjects = strings(nMembers, 1);
    componentICs = NaN(nMembers, 1);

    for memberIndex = 1:nMembers
        validSets = sets(:, memberIndex);
        validSets = validSets(isfinite(validSets) & ...
            validSets >= 1 & ...
            validSets <= numel(STUDY.datasetinfo));
        validSets = unique(round(validSets), 'stable');

        assert(~isempty(validSets), ...
            'Cluster member %d has no valid dataset index.', ...
            memberIndex);

        memberSubjects = unique(string( ...
            {STUDY.datasetinfo(validSets).subject}), ...
            'stable');
        memberSubjects = memberSubjects(strlength(memberSubjects) > 0);

        assert(numel(memberSubjects) == 1, ...
            'Cluster member %d maps to more than one subject.', ...
            memberIndex);

        validComps = comps(:, memberIndex);
        validComps = validComps(isfinite(validComps) & validComps >= 1);
        validComps = unique(round(validComps), 'stable');

        assert(numel(validComps) == 1, ...
            'Cluster member %d does not map to one ICA component.', ...
            memberIndex);

        subjects(memberIndex) = memberSubjects;
        componentICs(memberIndex) = validComps;
    end
end


function [STUDY, componentERSP, erspTimes, erspFreqs] = ...
        read_cluster_commonbaseline_ersp_local( ...
            STUDY, ...
            ALLEEG, ...
            clusterIndex, ...
            designIndex, ...
            timerangeMs, ...
            frequencyRangeHz, ...
            baselineValue, ...
            baselineNormalization, ...
            trialBaselineMode, ...
            conditionNames, ...
            nMembers)

    nConditions = numel(conditionNames);

    assert(nMembers >= 1, ...
        'Selected ROI cluster contains no members.');

    % Read one cluster member at a time. std_readdata otherwise concatenates
    % all available members within each condition, so conditions with missing
    % members can have different third-dimension sizes. EEGLAB common-baseline
    % subtraction requires matching sizes across the condition cells.
    % Processing one member at a time preserves the intended component-wise
    % common baseline while allowing missing subject-condition cells.
    componentERSP = cell(nConditions, 1);
    erspTimes = [];
    erspFreqs = [];
    referenceCacheParams = [];

    for memberIndex = 1:nMembers

        [STUDY, memberPower, memberTimes, memberFreqs, ~, cacheParams] = ...
            std_readdata( ...
                STUDY, ...
                ALLEEG, ...
                'clusters', ...
                clusterIndex, ...
                'component', ...
                memberIndex, ...
                'datatype', ...
                'ersp', ...
                'singletrials', ...
                'off', ...
                'timerange', ...
                timerangeMs, ...
                'freqrange', ...
                frequencyRangeHz, ...
                'design', ...
                designIndex);

        assert(iscell(memberPower), ...
            'std_readdata did not return ERSP power data as a cell array.');
        assert(size(memberPower, 2) == 1, ...
            ['Cluster %d member %d returned %d STUDY groups. This script ' ...
             'expects one group only.'], ...
            clusterIndex, ...
            memberIndex, ...
            size(memberPower, 2));
        assert(size(memberPower, 1) == nConditions, ...
            ['Cluster %d member %d returned %d condition rows, but the ' ...
             'selected design contains %d conditions.'], ...
            clusterIndex, ...
            memberIndex, ...
            size(memberPower, 1), ...
            nConditions);
        assert(isstruct(cacheParams), ...
            'The cached TF parameters could not be read.');

        if isempty(referenceCacheParams)
            referenceCacheParams = cacheParams;
        end

        if isfield(cacheParams, 'trialbase')
            assert(strcmpi(string(cacheParams.trialbase), string(trialBaselineMode)), ...
                ['Cached trialbase is %s but Step 14 requires %s. ' ...
                 'Set cfg.ersp.forceRecomputeERSP = true once to rebuild the cache.'], ...
                char(string(cacheParams.trialbase)), ...
                char(string(trialBaselineMode)));
        end

        if isfield(cacheParams, 'basenorm')
            assert(strcmpi(string(cacheParams.basenorm), string(baselineNormalization)), ...
                ['Cached basenorm is %s but Step 14 requires %s. ' ...
                 'Set cfg.ersp.forceRecomputeERSP = true once to rebuild the cache.'], ...
                char(string(cacheParams.basenorm)), ...
                char(string(baselineNormalization)));
        end

        memberTimes = double(memberTimes(:)');
        memberFreqs = double(memberFreqs(:)');

        assert(~isempty(memberTimes) && all(isfinite(memberTimes)), ...
            'std_readdata returned an invalid ERSP time vector.');
        assert(~isempty(memberFreqs) && all(isfinite(memberFreqs)), ...
            'std_readdata returned an invalid ERSP frequency vector.');

        if isempty(erspTimes)
            erspTimes = memberTimes;
            erspFreqs = memberFreqs;
            for conditionIndex = 1:nConditions
                componentERSP{conditionIndex, 1} = NaN( ...
                    numel(erspFreqs), ...
                    numel(erspTimes), ...
                    nMembers);
            end
        else
            assert(isequal(size(memberTimes), size(erspTimes)) && ...
                max(abs(memberTimes - erspTimes)) <= 1e-9, ...
                'Cached ERSP time vectors differ across cluster members.');
            assert(isequal(size(memberFreqs), size(erspFreqs)) && ...
                max(abs(memberFreqs - erspFreqs)) <= 1e-9, ...
                'Cached ERSP frequency vectors differ across cluster members.');
        end

        availableConditions = false(nConditions, 1);
        for conditionIndex = 1:nConditions
            data = memberPower{conditionIndex, 1};
            if isempty(data)
                continue;
            end

            data = double(data);
            if ndims(data) == 3 && size(data, 3) == 1
                data = data(:, :, 1);
            end

            assert(isequal(size(data), ...
                [numel(erspFreqs), numel(erspTimes)]), ...
                ['Cached power for cluster %d member %d, condition %s has ' ...
                 'size %s; expected [%d %d].'], ...
                clusterIndex, ...
                memberIndex, ...
                char(conditionNames(conditionIndex)), ...
                mat2str(size(data)), ...
                numel(erspFreqs), ...
                numel(erspTimes));

            memberPower{conditionIndex, 1} = data;
            availableConditions(conditionIndex) = any(isfinite(data(:)));
        end

        assert(any(availableConditions), ...
            'Cluster %d member %d has no finite ERSP power in any condition.', ...
            clusterIndex, ...
            memberIndex);

        % EEGLAB std_erspplot applies one common baseline separately for each
        % component across conditions. Do the same here for this member only.
        % Missing conditions are excluded rather than imputed.
        baselineParams = cacheParams;
        baselineParams.baseline = baselineValue;
        baselineParams.basenorm = baselineNormalization;
        baselineParams.trialbase = trialBaselineMode;
        baselineParams.singletrials = 'off';
        baselineParams.commonbase = 'on';
        baselineParams.verbose = 'off';

        availablePower = memberPower(availableConditions, 1);
        baselineCorrectedPower = newtimefbaseln( ...
            availablePower, ...
            erspTimes, ...
            baselineParams);

        availableIndices = find(availableConditions);
        for availableIndex = 1:numel(availableIndices)
            conditionIndex = availableIndices(availableIndex);
            data = double(baselineCorrectedPower{availableIndex});
            data = 10 .* log10(data);

            assert(isreal(data), ...
                'Common-baseline ERSP for condition %s is complex.', ...
                char(conditionNames(conditionIndex)));
            assert(isequal(size(data), ...
                [numel(erspFreqs), numel(erspTimes)]), ...
                ['Common-baseline ERSP for condition %s has size %s, but ' ...
                 'the frequency/time grid is [%d %d].'], ...
                char(conditionNames(conditionIndex)), ...
                mat2str(size(data)), ...
                numel(erspFreqs), ...
                numel(erspTimes));

            componentERSP{conditionIndex, 1}(:, :, memberIndex) = data;
        end
    end

    assert(~isempty(referenceCacheParams), ...
        'No cached TF parameters were read for the selected cluster.');
end


function [selectedERSP, selectedSubjects, selectedICs] = ...
        keep_lowest_ic_per_subject_local( ...
            componentERSP, ...
            componentSubjects, ...
            componentICs)

    componentSubjects = string(componentSubjects(:));
    componentICs = double(componentICs(:));

    assert(numel(componentSubjects) == numel(componentICs), ...
        'Cluster member subject/IC vectors have different lengths.');
    assert(all(strlength(componentSubjects) > 0), ...
        'One or more cluster members have an empty subject label.');
    assert(all(isfinite(componentICs) & ...
        componentICs >= 1 & ...
        componentICs == round(componentICs)), ...
        'One or more cluster members have an invalid IC index.');

    uniqueSubjects = unique(componentSubjects, 'stable');
    selectedIndices = NaN(numel(uniqueSubjects), 1);

    fprintf('Selecting one IC per subject using the smallest IC number:\n');

    for subjectIndex = 1:numel(uniqueSubjects)

        memberIndices = find(componentSubjects == uniqueSubjects(subjectIndex));
        subjectICs = componentICs(memberIndices);
        minimumIC = min(subjectICs);

        minimumMatches = memberIndices(subjectICs == minimumIC);
        selectedIndices(subjectIndex) = minimumMatches(1);

        if numel(memberIndices) > 1
            fprintf('  %s: ICs %s -> keep IC %d\n', ...
                char(uniqueSubjects(subjectIndex)), ...
                mat2str(subjectICs(:)'), ...
                minimumIC);
        else
            fprintf('  %s: keep IC %d\n', ...
                char(uniqueSubjects(subjectIndex)), ...
                minimumIC);
        end
    end

    selectedIndices = round(selectedIndices);
    selectedSubjects = componentSubjects(selectedIndices);
    selectedICs = componentICs(selectedIndices);

    assert(numel(unique(selectedSubjects)) == numel(selectedSubjects), ...
        'Lowest-IC selection did not produce exactly one entry per subject.');

    selectedERSP = componentERSP;

    for conditionIndex = 1:numel(componentERSP)

        data = componentERSP{conditionIndex};

        if isempty(data)
            selectedERSP{conditionIndex} = data;
            continue;
        end

        assert(size(data, 3) == numel(componentSubjects), ...
            ['Condition %d ERSP member count does not match the cluster ' ...
             'member identity list.'], ...
            conditionIndex);

        selectedERSP{conditionIndex} = data(:, :, selectedIndices);
    end
end


function [groupERSP, contributingSubjects] = ...
        average_one_ic_per_subject_local(subjectERSP)

    groupERSP = cell(size(subjectERSP));
    contributingSubjects = zeros(numel(subjectERSP), 1);

    for conditionIndex = 1:numel(subjectERSP)

        data = subjectERSP{conditionIndex};

        if isempty(data)
            groupERSP{conditionIndex} = [];
            continue;
        end

        nSubjects = size(data, 3);
        validSubjects = false(nSubjects, 1);

        for subjectIndex = 1:nSubjects
            subjectSlice = data(:, :, subjectIndex);
            validSubjects(subjectIndex) = any(isfinite(subjectSlice(:)));
        end

        contributingSubjects(conditionIndex) = nnz(validSubjects);

        if any(validSubjects)
            groupERSP{conditionIndex} = mean( ...
                data(:, :, validSubjects), ...
                3, ...
                'omitnan');
        else
            groupERSP{conditionIndex} = NaN( ...
                size(data, 1), ...
                size(data, 2));
        end
    end
end


function [names, subjectData, groupData, nSubjects] = ...
        reorder_conditions_local( ...
            names, ...
            subjectData, ...
            groupData, ...
            nSubjects, ...
            preferredOrder)

    order = [];

    for preferredIndex = 1:numel(preferredOrder)
        match = find(strcmpi(names, preferredOrder(preferredIndex)), 1);
        if ~isempty(match)
            order(end + 1) = match; %#ok<AGROW>
        end
    end

    remaining = setdiff(1:numel(names), order, 'stable');
    order = [order remaining];

    names = names(order);
    subjectData = subjectData(order, :);
    groupData = groupData(order, :);
    nSubjects = nSubjects(order);
end


