                    phaseEndPct, ...
                    bandNames(bandIndex), ...
                    bandLow, ...
                    bandHigh, ...
                    groupMean, ...
                    'VariableNames', { ...
                        'ROIID', ...
                        'OriginalClusterID', ...
                        'ROIName', ...
                        'Condition', ...
                        'ConditionDisplay', ...
                        'SubjectCount', ...
                        'GaitPhase', ...
                        'GaitPhaseDisplay', ...
                        'PhaseStart_ms', ...
                        'PhaseEnd_ms', ...
                        'PhaseStart_pct', ...
                        'PhaseEnd_pct', ...
                        'Band', ...
                        'BandLow_Hz', ...
                        'BandHigh_Hz', ...
                        'MeanERSP_dB'});

                if isempty(groupSummary)
                    groupSummary = newGroupRow;
                else
                    groupSummary = [groupSummary; newGroupRow]; %#ok<AGROW>
                end

                for subjectIndex = 1:numel(subjectNames)

                    subjectSlice = perSubjectMatrix( ...
                        frequencyMask, ...
                        timeMask, ...
                        subjectIndex);

                    if ~any(isfinite(subjectSlice(:)))
                        continue;
                    end

                    subjectMean = mean(subjectSlice(:), 'omitnan');

                    newSubjectRow = table( ...
                        roiID, ...
                        originalClusterID, ...
                        roiName, ...
                        subjectNames(subjectIndex), ...
                        conditionNames(conditionIndex), ...
                        conditionDisplayNames(conditionIndex), ...
                        gaitPhaseNames(phaseIndex), ...
                        gaitPhaseDisplayLabels(phaseIndex), ...
                        phaseStart, ...
                        phaseEnd, ...
                        phaseStartPct, ...
                        phaseEndPct, ...
                        bandNames(bandIndex), ...
                        bandLow, ...
                        bandHigh, ...
                        subjectMean, ...
                        'VariableNames', { ...
                            'ROIID', ...
                            'OriginalClusterID', ...
                            'ROIName', ...
                            'Subject', ...
                            'Condition', ...
                            'ConditionDisplay', ...
                            'GaitPhase', ...
                            'GaitPhaseDisplay', ...
                            'PhaseStart_ms', ...
                            'PhaseEnd_ms', ...
                            'PhaseStart_pct', ...
                            'PhaseEnd_pct', ...
                            'Band', ...
                            'BandLow_Hz', ...
                            'BandHigh_Hz', ...
                            'MeanERSP_dB'});

                    if isempty(subjectSummary)
                        subjectSummary = newSubjectRow;
                    else
                        subjectSummary = [subjectSummary; newSubjectRow]; %#ok<AGROW>
                    end
                end
            end
        end
    end
end



function plot_band_timecourse_local( ...
        groupSummary, ...
        conditionDisplayNames, ...
        bandNames, ...
        bandRangesHz, ...
        groupWarpMs, ...
        gaitEventNames, ...
        roiID, ...
        roiName, ...
        outputFile)

    conditionDisplayNames = string(conditionDisplayNames(:));
    bandNames = string(bandNames(:));
    gaitEventNames = string(gaitEventNames(:));

    assert(numel(groupWarpMs) == numel(gaitEventNames), ...
        'Gait-event names do not match the time-warp landmarks.');

    eventPercent = 100 .* double(groupWarpMs(:)') ./ double(groupWarpMs(end));

    figureHandle = figure( ...
        'Color', ...
        'w', ...
        'Visible', ...
        'off', ...
        'Position', ...
        [80 80 700 * numel(bandNames) 540]);

    layout = tiledlayout( ...
        figureHandle, ...
        1, ...
        numel(bandNames), ...
        'Padding', ...
        'compact', ...
        'TileSpacing', ...
        'compact');

    legendHandles = gobjects(0);
    legendLabels = strings(0, 1);

    for bandIndex = 1:numel(bandNames)

        axisHandle = nexttile(layout);
        hold(axisHandle, 'on');

        for conditionIndex = 1:numel(conditionDisplayNames)

            rowMask = ...
                string(groupSummary.ConditionDisplay) == ...
                    conditionDisplayNames(conditionIndex) & ...
                string(groupSummary.Band) == ...
                    bandNames(bandIndex);

            rows = find(rowMask);
            if isempty(rows)
                continue;
            end

            xValues = double(groupSummary.GaitCycle_pct(rows));
            yValues = double(groupSummary.MeanERSP_dB(rows));

            [xValues, sortOrder] = sort(xValues);
            yValues = yValues(sortOrder);

            lineHandle = plot( ...
                axisHandle, ...
                xValues, ...
                yValues, ...
                'LineWidth', ...
                1.3, ...
                'DisplayName', ...
                char(conditionDisplayNames(conditionIndex)));

            if bandIndex == 1
                legendHandles(end + 1, 1) = lineHandle; %#ok<AGROW>
                legendLabels(end + 1, 1) = conditionDisplayNames(conditionIndex); %#ok<AGROW>
            end
        end

        yline(axisHandle, 0, '--', ...
            'LineWidth', 0.8, ...
            'HandleVisibility', 'off');

        xlim(axisHandle, [0 100]);
        xticks(axisHandle, 0:20:100);
        xlabel(axisHandle, 'Time-warped gait cycle (%)');
        ylabel(axisHandle, 'Mean common-baseline ERSP (dB)');
        grid(axisHandle, 'on');
        set(axisHandle, 'Layer', 'top');

        for eventIndex = 1:numel(eventPercent)
            xline( ...
                axisHandle, ...
                eventPercent(eventIndex), ...
                '-', ...
                'Color', ...
                [0.35 0.35 0.35], ...
                'LineWidth', ...
                0.8, ...
                'HandleVisibility', ...
                'off');
        end

        yLimits = ylim(axisHandle);
        if diff(yLimits) <= 0
            yLimits = [-1 1];
            ylim(axisHandle, yLimits);
        end
        yText = yLimits(2) - 0.04 * diff(yLimits);

        for eventIndex = 1:numel(eventPercent)
            horizontalAlignment = 'center';
            if eventIndex == 1
                horizontalAlignment = 'left';
            elseif eventIndex == numel(eventPercent)
                horizontalAlignment = 'right';
            end

            text( ...
                axisHandle, ...
                eventPercent(eventIndex), ...
                yText, ...
                char(gaitEventNames(eventIndex)), ...
                'HorizontalAlignment', ...
                horizontalAlignment, ...
                'VerticalAlignment', ...
                'top', ...
                'FontSize', ...
                8, ...
                'Clipping', ...
                'on');
        end

        title(axisHandle, sprintf( ...
            '%s (%.0f-%.0f Hz)', ...
            char(bandNames(bandIndex)), ...
            bandRangesHz(bandIndex, 1), ...
            bandRangesHz(bandIndex, 2)), ...
            'Interpreter', ...
            'none');
    end

    if ~isempty(legendHandles)
        legend( ...
            legendHandles, ...
            cellstr(legendLabels), ...
            'Location', ...
            'southoutside', ...
            'Orientation', ...
            'horizontal', ...
            'NumColumns', ...
            min(4, numel(legendHandles)));
    end

    title(layout, sprintf( ...
        '%s | %s | one-IC-per-subject band ERSP time course', ...
        char(roiID), ...
        strrep(char(roiName), '_', ' ')), ...
        'Interpreter', ...
        'none', ...
        'FontWeight', ...
        'bold');

    if exist('exportgraphics', 'file') == 2
        exportgraphics( ...
            figureHandle, ...
            outputFile, ...
            'Resolution', ...
            200);
    else
        print(figureHandle, outputFile, '-dpng', '-r200');
    end

    close(figureHandle);
end


