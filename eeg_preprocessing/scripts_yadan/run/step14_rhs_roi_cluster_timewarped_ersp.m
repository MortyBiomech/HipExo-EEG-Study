            char(conditionNames(conditionIndex)));

        for phaseIndex = 1:numel(gaitPhaseNames)

            phaseStart = double(groupWarpMs(phaseIndex));
            phaseEnd = double(groupWarpMs(phaseIndex + 1));
            phaseStartPct = 100 * phaseStart / double(groupWarpMs(end));
            phaseEndPct = 100 * phaseEnd / double(groupWarpMs(end));

            if phaseIndex < numel(gaitPhaseNames)
                timeMask = timesMs >= phaseStart & timesMs < phaseEnd;
            else
                timeMask = timesMs >= phaseStart & timesMs <= phaseEnd;
            end

            assert(any(timeMask), ...
                'No ERSP time samples fall within gait phase %s.', ...
                char(gaitPhaseNames(phaseIndex)));

            for bandIndex = 1:numel(bandNames)

                bandLow = double(bandRangesHz(bandIndex, 1));
                bandHigh = double(bandRangesHz(bandIndex, 2));
                frequencyMask = ...
                    frequenciesHz >= bandLow & ...
                    frequenciesHz <= bandHigh;

                assert(any(frequencyMask), ...
                    'No ERSP frequency samples fall within band %s.', ...
                    char(bandNames(bandIndex)));

                groupSlice = groupMatrix(frequencyMask, timeMask);
                groupMean = mean(groupSlice(:), 'omitnan');

                newGroupRow = table( ...
                    roiID, ...
                    originalClusterID, ...
                    roiName, ...
                    conditionNames(conditionIndex), ...
                    conditionDisplayNames(conditionIndex), ...
                    double(nSubjects(conditionIndex)), ...
