function plot_roi_heatmaps_local( ...
        groupData, ...
        nSubjects, ...
        conditionNames, ...
        timesMs, ...
        frequenciesHz, ...
        groupWarpMs, ...
        gaitEventNames, ...
        roiID, ...
        roiName, ...
        outputFile)

    timesPercent = 100 .* double(timesMs(:)') ./ double(groupWarpMs(end));
    eventPercent = 100 .* double(groupWarpMs(:)') ./ double(groupWarpMs(end));

    finiteValues = [];

    for conditionIndex = 1:numel(groupData)
        if ~isempty(groupData{conditionIndex})
            values = double(groupData{conditionIndex});
            finiteValues = [finiteValues; ...
                values(isfinite(values))]; %#ok<AGROW>
        end
    end

    assert(~isempty(finiteValues), ...
        'No finite ERSP values were available for %s.', ...
        char(roiID));

    absoluteValues = sort(abs(finiteValues));
    percentileIndex = max(1, ceil(0.98 * numel(absoluteValues)));
    colorLimit = absoluteValues(percentileIndex);
    if ~isfinite(colorLimit) || colorLimit <= 0
        colorLimit = max(absoluteValues);
    end
    if ~isfinite(colorLimit) || colorLimit <= 0
        colorLimit = 1;
    end

    nConditions = numel(conditionNames);
    nColumns = min(4, nConditions);
    nRows = ceil(nConditions / nColumns);

    figureHandle = figure( ...
        'Color', ...
        'w', ...
        'Visible', ...
        'off', ...
        'Position', ...
        [80 80 420 * nColumns 330 * nRows]);

    layout = tiledlayout( ...
        figureHandle, ...
        nRows, ...
        nColumns, ...
        'Padding', ...
        'compact', ...
        'TileSpacing', ...
        'compact');

    for conditionIndex = 1:nConditions
        axisHandle = nexttile(layout);
        data = groupData{conditionIndex};

        if isempty(data)
            axis(axisHandle, 'off');
            text(axisHandle, 0.5, 0.5, 'No data', ...
                'HorizontalAlignment', 'center');
            title(axisHandle, char(conditionNames(conditionIndex)), ...
                'Interpreter', 'none');
            continue;
        end

        data = double(data);
        assert(isreal(data), ...
            'Plot data for %s, condition %s are complex.', ...
            char(roiID), ...
            char(conditionNames(conditionIndex)));
        assert(isequal(size(data), [numel(frequenciesHz) numel(timesMs)]), ...
            ['Plot data size for %s, condition %s is %s; expected [%d %d].'], ...
            char(roiID), ...
            char(conditionNames(conditionIndex)), ...
            mat2str(size(data)), ...
            numel(frequenciesHz), ...
            numel(timesMs));
        assert(any(isfinite(data(:))), ...
            'Plot data for %s, condition %s contain no finite values.', ...
            char(roiID), ...
            char(conditionNames(conditionIndex)));

        surface( ...
            axisHandle, ...
            timesPercent, ...
            frequenciesHz, ...
            zeros(size(data)), ...
            data, ...
            'EdgeColor', ...
            'none');
        view(axisHandle, 2);
        axis(axisHandle, 'tight');
        set(axisHandle, ...
            'YDir', ...
            'normal', ...
            'YScale', ...
            'log', ...
            'YTick', ...
            [3 4 6 8 10 13 20 30 45], ...
            'FontSize', ...
            9, ...
            'Layer', ...
            'top');
        xlim(axisHandle, [0 100]);
        xticks(axisHandle, 0:20:100);
        caxis(axisHandle, [-colorLimit colorLimit]);
        hold(axisHandle, 'on');

        for eventIndex = 1:numel(eventPercent)
            xline( ...
                axisHandle, ...
                eventPercent(eventIndex), ...
                '-', ...
                'Color', ...
                [0.15 0.15 0.15], ...
                'LineWidth', ...
                0.8, ...
                'HandleVisibility', ...
                'off');
        end

        yLimits = ylim(axisHandle);
        yText = exp( ...
            log(yLimits(2)) - ...
            0.05 * (log(yLimits(2)) - log(yLimits(1))));

        for eventIndex = 1:numel(eventPercent)

            labelHorizontalAlignment = 'center';
            if eventIndex == 1
                labelHorizontalAlignment = 'left';
            elseif eventIndex == numel(eventPercent)
                labelHorizontalAlignment = 'right';
            end

            text( ...
                axisHandle, ...
                eventPercent(eventIndex), ...
                yText, ...
                char(gaitEventNames(eventIndex)), ...
                'HorizontalAlignment', ...
                labelHorizontalAlignment, ...
                'VerticalAlignment', ...
                'top', ...
                'FontSize', ...
                8, ...
                'Clipping', ...
                'on');
        end

        title(axisHandle, sprintf('%s  (subjects n=%d)', ...
            char(conditionNames(conditionIndex)), ...
            nSubjects(conditionIndex)), ...
            'Interpreter', ...
            'none');
        xlabel(axisHandle, 'Time-warped gait cycle (%)');
        ylabel(axisHandle, 'Frequency (Hz)');
        colorbar(axisHandle);
    end

    % Classic gait-ERSP palette: blue -> cyan/green -> yellow -> red.
    colormap(figureHandle, jet(256));
    title(layout, sprintf( ...
        ['%s | %s | one-IC-per-subject gait ERSP ' ...
         '(EEGLAB common baseline across conditions; dB)'], ...
        char(roiID), ...
        strrep(char(roiName), '_', ' ')), ...
        'Interpreter', ...
        'none', ...
        'FontWeight', ...
        'bold');

    if exist('exportgraphics', 'file') == 2
        exportgraphics( ...
            figureHandle, ...
            outputFile, ...
            'Resolution', ...
            200);
    else
        print(figureHandle, outputFile, '-dpng', '-r200');
    end

    close(figureHandle);
end



function [changed, reason] = tf_cache_definition_changed_local( ...
        runInfoFile, ...
        groupWarpMs, ...
        frequencyRangeHz, ...
        waveletCycles, ...
        numberOfFrequencies, ...
        numberOfTimePoints, ...
        paddingRatio)

    changed = true;
    reason = "No previous Step 14 run-info file is available.";

    if exist(runInfoFile, 'file') ~= 2
        return;
    end

    loaded = load(runInfoFile, 'runInfo');
    if ~isfield(loaded, 'runInfo') || ~isstruct(loaded.runInfo)
        reason = "Previous run-info file does not contain a valid runInfo structure.";
        return;
    end

    previous = loaded.runInfo;

    % Only parameters that change the expensive complex TF decomposition
    % belong in this cache-definition check. Baseline, basenorm, and
    % trialbase are not used to decide whether the wavelet decomposition
    % must be repeated. Their cached values are checked later when the
    % .icatimef data are read for ERSP processing.
    requiredFields = { ...
        'group_timewarp_ms', ...
        'frequency_range_hz', ...
        'wavelet_cycles', ...
        'number_of_frequencies', ...
        'number_of_time_points', ...
        'padding_ratio'};

    for fieldIndex = 1:numel(requiredFields)
        if ~isfield(previous, requiredFields{fieldIndex})
            reason = "Previous run-info is missing field " + ...
                string(requiredFields{fieldIndex}) + ".";
            return;
        end
    end

    comparisons = { ...
        'group_timewarp_ms', double(previous.group_timewarp_ms(:)'), double(groupWarpMs(:)'); ...
        'frequency_range_hz', double(previous.frequency_range_hz(:)'), double(frequencyRangeHz(:)'); ...
        'wavelet_cycles', double(previous.wavelet_cycles(:)'), double(waveletCycles(:)'); ...
        'number_of_frequencies', double(previous.number_of_frequencies), double(numberOfFrequencies); ...
        'number_of_time_points', double(previous.number_of_time_points), double(numberOfTimePoints); ...
        'padding_ratio', double(previous.padding_ratio), double(paddingRatio)};

    for comparisonIndex = 1:size(comparisons, 1)
        fieldName = string(comparisons{comparisonIndex, 1});
        oldValue = comparisons{comparisonIndex, 2};
        newValue = comparisons{comparisonIndex, 3};

        sameSize = isequal(size(oldValue), size(newValue));
        sameValue = sameSize && ...
            all((oldValue(:) == newValue(:)) | ...
                (isnan(oldValue(:)) & isnan(newValue(:))) | ...
                abs(oldValue(:) - newValue(:)) <= 1e-9);

        if ~sameValue
            reason = "Time-frequency definition changed in " + fieldName + ".";
            return;
        end
    end

    changed = false;
    reason = [ ...
        "Complex TF definition matches the previous Step 14 run; " ...
        "baseline-related settings do not trigger wavelet recomputation."];
end


function signature = processing_signature_local( ...
        version, ...
        reviewSourcePath, ...
        implementationFile, ...
        selectedTable, ...
        STUDY, ...
        groupWarpMs, ...
        frequencyRangeHz, ...
        waveletCycles, ...
        numberOfFrequencies, ...
        numberOfTimePoints, ...
        paddingRatio, ...
        baselineValue, ...
        baselineNormalization, ...
        trialBaselineMode, ...
        summaryBandNames, ...
        summaryBandRangesHz, ...
        gaitPhaseNames)

    records = strings(0, 1);
    records(end + 1) = "version=" + string(version);
    records(end + 1) = "review=" + ...
        file_signature_local(reviewSourcePath);
    records(end + 1) = "implementation=" + ...
        file_signature_local(implementationFile);
    records(end + 1) = "implementation_version=" + string(version);
    records(end + 1) = "warp=" + mat2str(groupWarpMs, 12);
    records(end + 1) = "freq=" + mat2str(frequencyRangeHz, 12);
    records(end + 1) = "cycles=" + mat2str(waveletCycles, 12);
    records(end + 1) = "nfreqs=" + string(numberOfFrequencies);
    records(end + 1) = "ntimes=" + string(numberOfTimePoints);
    records(end + 1) = "padratio=" + string(paddingRatio);
    records(end + 1) = "baseline=" + string(mat2str(baselineValue, 12));
    records(end + 1) = "basenorm_cache=" + string(baselineNormalization);
    records(end + 1) = "trialbase_cache=" + string(trialBaselineMode);
    records(end + 1) = "final_ersp_method=EEGLAB_std_readdata_plus_newtimefbaseln_commonbaseline";
    records(end + 1) = "common_baseline=average_across_conditions_before_log_transform";
    records(end + 1) = "ic_selection=one_per_subject_lowest_numeric_ic";
    records(end + 1) = "final_ersp_units=dB";
    records(end + 1) = "summary_band_names=" + strjoin(string(summaryBandNames(:)'), ',');
    records(end + 1) = "summary_band_ranges_hz=" + mat2str(double(summaryBandRangesHz), 12);
    records(end + 1) = "gait_phase_names=" + strjoin(string(gaitPhaseNames(:)'), ',');

    for rowIndex = 1:height(selectedTable)
        records(end + 1) = strjoin([ ...
            "roi", ...
            string(selectedTable.ROIID(rowIndex)), ...
            string(selectedTable.SelectedClusterIndex(rowIndex)), ...
            file_signature_local(char( ...
                selectedTable.ROIStudyPath(rowIndex)))], '|');
    end

    for datasetIndex = 1:numel(STUDY.datasetinfo)
        info = STUDY.datasetinfo(datasetIndex);
        datasetPath = fullfile(info.filepath, info.filename);
        records(end + 1) = "set=" + ...
            file_signature_local(datasetPath);

        [datasetFolder, datasetStem] = fileparts(datasetPath);
        fdtPath = fullfile(datasetFolder, [datasetStem '.fdt']);
        if exist(fdtPath, 'file') == 2
            records(end + 1) = "fdt=" + ...
                file_signature_local(fdtPath);
        end
    end

    assert(~any(ismissing(records)), ...
        'Processing signature contains a missing string value.');
    signature = strjoin(records, newline);
end


function signature = file_signature_local(filePath)

    info = dir(filePath);
    assert(numel(info) == 1 && ~info.isdir, ...
        'Cannot create provenance signature for: %s', ...
        filePath);
    signature = strjoin([ ...
        string(info.folder), ...
        string(info.name), ...
        string(info.bytes), ...
        string(info.datenum)], '|');
end


%% ========================================================================
% STANDALONE TIME-WARPED COMPONENT ERSP PRECOMPUTE
% =========================================================================

function precompute_timewarped_component_ersp_local( ...
        STUDY, ...
        ALLEEG, ...
        designIndex, ...
        recomputeFlag, ...
        baseERSPParameters)

    assert(designIndex >= 1 && designIndex <= numel(STUDY.design), ...
        'Invalid STUDY design index for ERSP precompute.');
    assert(numel(STUDY.datasetinfo) == numel(ALLEEG), ...
        ['STUDY.datasetinfo and ALLEEG have different lengths. The ' ...
         'standalone precompute requires one ALLEEG entry per STUDY dataset.']);

    datasetIndices = double([STUDY.datasetinfo.index]);
    assert(isequal(datasetIndices, 1:numel(STUDY.datasetinfo)), ...
        ['STUDY.datasetinfo.index is not 1:N. Refusing to guess the ' ...
         'dataset-to-ALLEEG mapping.']);

    subjects = string({STUDY.datasetinfo.subject});
    sessions = strings(size(subjects));

    for datasetIndex = 1:numel(STUDY.datasetinfo)
        sessionValue = STUDY.datasetinfo(datasetIndex).session;
        if isempty(sessionValue)
            sessionValue = 1;
        end
        sessions(datasetIndex) = string(sessionValue);
    end

    assert(all(strlength(subjects) > 0), ...
        'One or more STUDY datasets have an empty subject label.');

    subjectSessionKeys = subjects + "|session=" + sessions;
    uniqueKeys = unique(subjectSessionKeys, 'stable');
    uniqueSessionValues = unique(sessions, 'stable');
    allTrialCounts = double([ALLEEG.trials]);

    fprintf('\nStandalone precompute groups: %d subject/session units.\n', ...
        numel(uniqueKeys));

    for keyIndex = 1:numel(uniqueKeys)

        infoIndices = find(subjectSessionKeys == uniqueKeys(keyIndex));
        eegIndices = datasetIndices(infoIndices);

        assert(~isempty(infoIndices), ...
            'Internal error: empty subject/session precompute group.');

        subjectName = subjects(infoIndices(1));
        sessionName = sessions(infoIndices(1));

        referenceComponents = double( ...
            STUDY.datasetinfo(infoIndices(1)).comps(:)');
        assert(~isempty(referenceComponents) && ...
            all(isfinite(referenceComponents)) && ...
            all(referenceComponents >= 1) && ...
            all(referenceComponents == round(referenceComponents)), ...
            '%s has an invalid STUDY.datasetinfo.comps list.', ...
            char(subjectName));

        latencyCells = cell(numel(eegIndices), 1);
        expectedTrialCount = 0;
        referencePoints = double(ALLEEG(eegIndices(1)).pnts);
        referenceRate = double(ALLEEG(eegIndices(1)).srate);
        referenceXMin = double(ALLEEG(eegIndices(1)).xmin);
        referenceXMax = double(ALLEEG(eegIndices(1)).xmax);

        for localIndex = 1:numel(eegIndices)
            eegIndex = eegIndices(localIndex);
            infoIndex = infoIndices(localIndex);

            thisComponents = double( ...
                STUDY.datasetinfo(infoIndex).comps(:)');
            assert(isequal(thisComponents, referenceComponents), ...
                ['The selected component list differs across runs for %s. ' ...
                 'Shared-ICA ERSP requires one identical list.'], ...
                char(subjectName));

            assert(isequaln( ...
                    ALLEEG(eegIndex).icaweights, ...
                    ALLEEG(eegIndices(1)).icaweights) && ...
                   isequaln( ...
                    ALLEEG(eegIndex).icasphere, ...
                    ALLEEG(eegIndices(1)).icasphere), ...
                ['ICA weights/sphere differ across runs for %s. Refusing ' ...
                 'to concatenate components from different decompositions.'], ...
                char(subjectName));

            assert(double(ALLEEG(eegIndex).pnts) == referencePoints && ...
                   double(ALLEEG(eegIndex).srate) == referenceRate && ...
                   double(ALLEEG(eegIndex).xmin) == referenceXMin && ...
                   double(ALLEEG(eegIndex).xmax) == referenceXMax, ...
                ['Epoch length, sampling rate, or epoch limits differ ' ...
                 'across runs for %s.'], ...
                char(subjectName));
            assert(ALLEEG(eegIndex).trials >= 1 && ...
                ALLEEG(eegIndex).trials == round(ALLEEG(eegIndex).trials), ...
                'Dataset %d has an invalid trial count.', ...
                eegIndex);

            assert(isfield(ALLEEG(eegIndex), 'timewarp') && ...
                isfield(ALLEEG(eegIndex).timewarp, 'latencies'), ...
                'Dataset %d has no EEG.timewarp.latencies.', ...
                eegIndex);

            latencies = double( ...
                ALLEEG(eegIndex).timewarp.latencies);
            assert(size(latencies, 1) == ALLEEG(eegIndex).trials && ...
                size(latencies, 2) == 5 && ...
                all(isfinite(latencies(:))) && ...
                all(all(diff(latencies, 1, 2) > 0)) && ...
                all(latencies(:) >= referenceXMin * 1000 - 1) && ...
                all(latencies(:) <= referenceXMax * 1000 + 1), ...
                ['Dataset %d timewarp latency matrix is invalid or does ' ...
                 'not follow RHS-LTO-LHS-RTO-RHS order.'], ...
                eegIndex);

            latencyCells{localIndex} = latencies;
            expectedTrialCount = expectedTrialCount + ...
                ALLEEG(eegIndex).trials;
        end

        % std_ersp concatenates trials from the EEG structure array in the
        % same dataset order. newtimef requires one numeric matrix with one
        % row per concatenated trial; a cell array is invalid in EEGLAB 2026.
        timewarpMatrix = vertcat(latencyCells{:});

        assert(size(timewarpMatrix, 1) == expectedTrialCount && ...
            size(timewarpMatrix, 2) == 5, ...
            ['Combined timewarp rows do not equal the combined trial count ' ...
             'for %s.'], ...
            char(subjectName));

        erspParameters = set_parameter_local( ...
            baseERSPParameters, ...
            'timewarp', ...
            timewarpMatrix);

        timewarpTarget = parameter_value_local( ...
            erspParameters, ...
            'timewarpms');
        assert(isnumeric(timewarpTarget) && ...
            isvector(timewarpTarget) && ...
            numel(timewarpTarget) == 5 && ...
            all(isfinite(timewarpTarget)) && ...
            all(diff(timewarpTarget) > 0), ...
            'The common timewarpms target is invalid.');

        trialInfo = std_combtrialinfo( ...
            STUDY.datasetinfo, ...
            infoIndices, ...
            allTrialCounts);

        firstInfo = STUDY.datasetinfo(infoIndices(1));
        if numel(uniqueSessionValues) == 1
            fileBase = fullfile( ...
                firstInfo.filepath, ...
                char(subjectName));
        else
            sessionText = char(sessionName);
            fileBase = fullfile( ...
                firstInfo.filepath, ...
                sprintf('%s_ses-%s', ...
                    char(subjectName), ...
                    sessionText));
        end

        fprintf('\nPrecomputing %s, session %s\n', ...
            char(subjectName), ...
            char(sessionName));
        fprintf('  datasets: %d\n', numel(eegIndices));
        fprintf('  trials: %d\n', expectedTrialCount);
        fprintf('  components: %s\n', mat2str(referenceComponents));
        fprintf('  timewarp matrix: %d x %d\n', ...
            size(timewarpMatrix, 1), ...
            size(timewarpMatrix, 2));
        fprintf('  output base: %s\n', fileBase);

        std_ersp( ...
            ALLEEG(eegIndices), ...
            'components', ...
            referenceComponents, ...
            'recompute', ...
            recomputeFlag, ...
            'fileout', ...
            fileBase, ...
            'trialinfo', ...
            trialInfo, ...
            erspParameters{:});
    end
end


function parameters = set_parameter_local(parameters, name, value)

    names = string(parameters(1:2:end));
    match = find(strcmpi(names, string(name)), 1);
    assert(~isempty(match), ...
        'ERSP parameter %s is missing.', ...
        name);
    valueIndex = 2 * match;
    parameters{valueIndex} = value;
end


function value = parameter_value_local(parameters, name)

    names = string(parameters(1:2:end));
    match = find(strcmpi(names, string(name)), 1);
    assert(~isempty(match), ...
        'ERSP parameter %s is missing.', ...
        name);
    value = parameters{2 * match};
end