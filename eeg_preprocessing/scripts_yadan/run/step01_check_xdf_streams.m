function step01_check_xdf_streams()
% GOAL
%   Scan XDF files and create structural EEG/GRF usability audits that
%   determine which recordings may enter the import-control table.
%
% INPUT
%   Raw XDF files below P.rawDataFolder.
%
% APPROACH
%   1. Find all XDF files.
%   2. Reuse saved audit rows when the XDF file and QC configuration are
%      unchanged.
%   3. Inspect only new or changed files with hipexo.inspect_xdf_file().
%   4. Recheck timing-failed EEG by continuous block and record retained
%      source sample ranges, times, rates and duration in the existing CSVs.
%   5. Evaluate EEG and GRF independently and save the current audit tables.
%
% OUTPUT
%   output_data/xdf_file_stream_summary.csv
%   output_data/xdf_stream_detail_table.csv
%   output_data/xdf_eeg_quality_audit.csv
%   output_data/xdf_grf_quality_audit.csv
%
% USED BY
%   step02_build_import_table.m

%% Load paths and Step 01-02 configuration

thisFile = mfilename('fullpath');

if isempty(thisFile)
    error('Could not resolve the current Step file path.');
end

scriptsRoot = fileparts(fileparts(thisFile));

addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();
cfg = config_step01_02_xdf_import();

if ~isfolder(P.outputFolder)
    mkdir(P.outputFolder);
end

%% Initialize FieldTrip/XDF reader

ft_defaults;

if isempty(which('load_xdf'))
    error( ...
        'load_xdf was not found. Check P.xdfLoaderFolder in project_paths.m.');
end

%% Find XDF files

files = dir(fullfile(P.rawDataFolder, '**', '*.xdf'));

fprintf('\nFound %d XDF files in:\n%s\n', ...
    numel(files), ...
    P.rawDataFolder);

if isempty(files)
    error( ...
        'No XDF files found below:\n%s', ...
        P.rawDataFolder);
end

%% Load reusable audit rows

scanConfigSignature = ...
    scan_config_signature_local(cfg);

previous = ...
    load_previous_audits_local(P);

fileSummaryTable = table();
streamDetailTable = table();
eegQualityTable = table();
grfQualityTable = table();

nReused = 0;
nScanned = 0;

%% Scan new or changed XDF files

for i = 1:numel(files)

    xdfPath = fullfile( ...
        files(i).folder, ...
        files(i).name);

    sourceSignature = ...
        hipexo.file_metadata_signature(xdfPath);

    [canReuse, reused] = ...
        get_reusable_rows_local( ...
            previous, ...
            xdfPath, ...
            sourceSignature, ...
            scanConfigSignature, ...
            i);

    if canReuse

        fileSummaryTable = ...
            [fileSummaryTable; reused.fileSummary]; %#ok<AGROW>

        if ~isempty(reused.streamDetail)

            streamDetailTable = ...
                [streamDetailTable; reused.streamDetail]; %#ok<AGROW>

        end

        if ~isempty(reused.eegQuality)

            eegQualityTable = ...
                [eegQualityTable; reused.eegQuality]; %#ok<AGROW>

        end

        if ~isempty(reused.grfQuality)

            grfQualityTable = ...
                [grfQualityTable; reused.grfQuality]; %#ok<AGROW>

        end

        nReused = nReused + 1;

    else

        fprintf( ...
            'Scanning %d/%d: %s\n', ...
            i, ...
            numel(files), ...
            files(i).name);

        result = hipexo.inspect_xdf_file( ...
            xdfPath, ...
            i, ...
            cfg);

        result = ...
            add_provenance_local( ...
                result, ...
                sourceSignature, ...
                scanConfigSignature);

        fileSummaryTable = ...
            [fileSummaryTable; result.fileSummary]; %#ok<AGROW>

        if ~isempty(result.streamDetail)

            streamDetailTable = ...
                [streamDetailTable; result.streamDetail]; %#ok<AGROW>

        end

        if ~isempty(result.eegQuality)

            eegQualityTable = ...
                [eegQualityTable; result.eegQuality]; %#ok<AGROW>

        end

        if ~isempty(result.grfQuality)

            grfQualityTable = ...
                [grfQualityTable; result.grfQuality]; %#ok<AGROW>

        end

        nScanned = nScanned + 1;

        if ~isempty(result.fileSummary) && ...
                result.fileSummary.FileEEGQualityStatus == "LOAD_ERROR"

            warning( ...
                'Could not load XDF:\n%s\nError:\n%s', ...
                xdfPath, ...
                result.fileSummary.FileEEGQualityReason);

        end

    end

    %% Autosave progress

    if mod(i, cfg.scan.saveEveryNFiles) == 0 && ...
            i < numel(files)

        save_audit_tables( ...
            fileSummaryTable, ...
            streamDetailTable, ...
            eegQualityTable, ...
            grfQualityTable, ...
            P);

    end

end

%% Final save and report

save_audit_tables( ...
    fileSummaryTable, ...
    streamDetailTable, ...
    eegQualityTable, ...
    grfQualityTable, ...
    P);

fprintf('\nEEG + GRF XDF scan finished.\n');

fprintf( ...
    'Reused unchanged XDF audits: %d\n', ...
    nReused);

fprintf( ...
    'New or changed XDF files scanned: %d\n', ...
    nScanned);

nRealEEGFiles = ...
    sum(fileSummaryTable.HasRealEEG);

nUsableEEGFiles = ...
    sum(fileSummaryTable.HasUsableEEG);

nGRFFiles = ...
    sum(fileSummaryTable.HasGRFStream);

nUsableGRFFiles = ...
    sum(fileSummaryTable.HasUsableGRF);

nCombinedUsableFiles = ...
    sum( ...
        fileSummaryTable.HasUsableEEG & ...
        fileSummaryTable.HasUsableGRF);

fprintf( ...
    '\nFiles in current audit: %d\n', ...
    height(fileSummaryTable));

fprintf( ...
    'Files with real EEG: %d\n', ...
    nRealEEGFiles);

fprintf( ...
    'Files with usable EEG: %d\n', ...
    nUsableEEGFiles);

fprintf( ...
    'Files with a GRF candidate: %d\n', ...
    nGRFFiles);

fprintf( ...
    'Files with usable GRF: %d\n', ...
    nUsableGRFFiles);

fprintf( ...
    'Files passing both EEG and GRF gates: %d\n', ...
    nCombinedUsableFiles);

print_quality_summary( ...
    eegQualityTable, ...
    'EEG', ...
    'EEGQualityStatus', ...
    'IsUsableEEG');

print_quality_summary( ...
    grfQualityTable, ...
    'GRF', ...
    'GRFQualityStatus', ...
    'IsUsableGRF');

missingGRFRows = ...
    fileSummaryTable.HasRealEEG & ...
    ~fileSummaryTable.HasUsableGRF;

fprintf( ...
    '\nReal-EEG files blocked by the GRF gate: %d\n', ...
    sum(missingGRFRows));

end

%% Local functions

function signature = scan_config_signature_local(cfg)

S = struct();

S.eeg = cfg.eeg;
S.grf = cfg.grf;
S.timestamp = cfg.timestamp;

inspectorFile = ...
    which('hipexo.inspect_xdf_file');

if isempty(inspectorFile)

    error( ...
        'Could not locate hipexo.inspect_xdf_file.');

end

segmentCheckFile = ...
    which('hipexo.check_eeg_segments');

if isempty(segmentCheckFile)

    error( ...
        'Could not locate hipexo.check_eeg_segments.');

end

S.inspectXDFSignature = ...
    hipexo.content_signature( ...
        fileread(inspectorFile));

S.segmentCheckSignature = ...
    hipexo.content_signature( ...
        fileread(segmentCheckFile));

signature = ...
    hipexo.struct_signature(S);

end

function previous = load_previous_audits_local(P)

previous = struct( ...
    'available', false, ...
    'fileSummary', table(), ...
    'streamDetail', table(), ...
    'eegQuality', table(), ...
    'grfQuality', table());

files = { ...
    P.summaryFile, ...
    P.detailFile, ...
    P.eegQualityFile, ...
    P.grfQualityFile};

if ~all(cellfun(@isfile, files))
    return;
end

try

    previous.fileSummary = ...
        hipexo.read_csv_with_string_text( ...
            P.summaryFile);

    previous.streamDetail = ...
        hipexo.read_csv_with_string_text( ...
            P.detailFile);

    previous.eegQuality = ...
        hipexo.read_csv_with_string_text( ...
            P.eegQualityFile);

    previous.grfQuality = ...
        hipexo.read_csv_with_string_text( ...
            P.grfQualityFile);

catch

    return;

end

basicRequired = { ...
    'FullPath'};

if ~all(ismember( ...
        basicRequired, ...
        previous.fileSummary.Properties.VariableNames)) || ...
        ~all(ismember( ...
        basicRequired, ...
        previous.streamDetail.Properties.VariableNames))

    return;

end

previous.fileSummary.FullPath = ...
    string(previous.fileSummary.FullPath);

previous.streamDetail.FullPath = ...
    string(previous.streamDetail.FullPath);

if ~isempty(previous.eegQuality)

    if ~ismember( ...
            'FullPath', ...
            previous.eegQuality.Properties.VariableNames)

        return;

    end

    previous.eegQuality.FullPath = ...
        string(previous.eegQuality.FullPath);

end

if ~isempty(previous.grfQuality)

    if ~ismember( ...
            'FullPath', ...
            previous.grfQuality.Properties.VariableNames)

        return;

    end

    previous.grfQuality.FullPath = ...
        string(previous.grfQuality.FullPath);

end

required = { ...
    'FullPath', ...
    'SourceXDFSignature', ...
    'ScanConfigSignature'};

fullSchemaOK = ...
    all(ismember( ...
        required, ...
        previous.fileSummary.Properties.VariableNames)) && ...
    all(ismember( ...
        required, ...
        previous.streamDetail.Properties.VariableNames)) && ...
    optional_audit_schema_ok_local( ...
        previous.eegQuality, ...
        required) && ...
    optional_audit_schema_ok_local( ...
        previous.grfQuality, ...
        required);

if ~fullSchemaOK
    return;
end

previous.fileSummary.SourceXDFSignature = ...
    string( ...
        previous.fileSummary.SourceXDFSignature);

previous.fileSummary.ScanConfigSignature = ...
    string( ...
        previous.fileSummary.ScanConfigSignature);

previous.streamDetail.SourceXDFSignature = ...
    string( ...
        previous.streamDetail.SourceXDFSignature);

previous.streamDetail.ScanConfigSignature = ...
    string( ...
        previous.streamDetail.ScanConfigSignature);

previous = ...
    normalize_optional_audit_local( ...
        previous, ...
        'eegQuality');

previous = ...
    normalize_optional_audit_local( ...
        previous, ...
        'grfQuality');

textColumns = { ...
    'FileName', ...
    'FullPath', ...
    'AllStreams', ...
    'StreamName', ...
    'StreamType', ...
    'NominalSrate', ...
    'ChannelCount', ...
    'EEGQualityStatus', ...
    'EEGQualityReason', ...
    'GRFQualityStatus', ...
    'GRFQualityReason', ...
    'FileEEGQualityStatus', ...
    'FileEEGQualityReason', ...
    'FileGRFQualityStatus', ...
    'FileGRFQualityReason', ...
    'EEGOriginalQualityStatus', ...
    'EEGSegmentCheck', ...
    'EEGRetainedSampleRanges', ...
    'EEGRetainedTimeRangesSec', ...
    'EEGRetainedRatesHz', ...
    'SourceXDFSignature', ...
    'ScanConfigSignature'};

fields = { ...
    'fileSummary', ...
    'streamDetail', ...
    'eegQuality', ...
    'grfQuality'};

for k = 1:numel(fields)

    T = previous.(fields{k});

    for j = 1:numel(textColumns)

        if ismember( ...
                textColumns{j}, ...
                T.Properties.VariableNames)

            T.(textColumns{j}) = ...
                string(T.(textColumns{j}));

            T.(textColumns{j})( ...
                ismissing(T.(textColumns{j}))) = "";

        end

    end

    previous.(fields{k}) = T;

end

previous.available = true;

end

function ok = optional_audit_schema_ok_local( ...
        T, ...
        required)

if isempty(T)

    ok = true;

else

    ok = all( ...
        ismember( ...
            required, ...
            T.Properties.VariableNames));

end

end

function previous = normalize_optional_audit_local( ...
        previous, ...
        fieldName)

T = previous.(fieldName);

if isempty(T)
    return;
end

T.FullPath = ...
    string(T.FullPath);

T.SourceXDFSignature = ...
    string(T.SourceXDFSignature);

T.ScanConfigSignature = ...
    string(T.ScanConfigSignature);

previous.(fieldName) = T;

end

function [canReuse, reused] = ...
    get_reusable_rows_local( ...
        previous, ...
        xdfPath, ...
        sourceSignature, ...
        scanConfigSignature, ...
        fileIndex)

canReuse = false;

reused = struct( ...
    'fileSummary', table(), ...
    'streamDetail', table(), ...
    'eegQuality', table(), ...
    'grfQuality', table());

if ~previous.available
    return;
end

xdfPath = ...
    string(xdfPath);

sourceSignature = ...
    string(sourceSignature);

scanConfigSignature = ...
    string(scanConfigSignature);

summaryMask = ...
    previous.fileSummary.FullPath == xdfPath & ...
    previous.fileSummary.SourceXDFSignature == sourceSignature & ...
    previous.fileSummary.ScanConfigSignature == scanConfigSignature;

if sum(summaryMask) ~= 1
    return;
end

reused.fileSummary = ...
    previous.fileSummary(summaryMask, :);

fields = { ...
    'streamDetail', ...
    'eegQuality', ...
    'grfQuality'};

for k = 1:numel(fields)

    reused.(fields{k}) = ...
        matching_rows_local( ...
            previous.(fields{k}), ...
            xdfPath, ...
            sourceSignature, ...
            scanConfigSignature);

end

if isempty(reused.streamDetail)
    return;
end

segmentColumns = { ...
    'EEGOriginalQualityStatus', ...
    'EEGSegmentCheck', ...
    'EEGRetainedSampleRanges', ...
    'EEGRetainedTimeRangesSec', ...
    'EEGRetainedRatesHz'};

if ~all(ismember( ...
        segmentColumns, ...
        reused.streamDetail.Properties.VariableNames))

    return;

end

if ismember( ...
        'IsRealEEG', ...
        reused.streamDetail.Properties.VariableNames)

    eegRows = ...
        logical(reused.streamDetail.IsRealEEG);

else

    eegRows = ...
        false(height(reused.streamDetail), 1);

    if ismember( ...
            'EEGOriginalQualityStatus', ...
            reused.streamDetail.Properties.VariableNames)

        eegRows = ...
            strlength( ...
                string( ...
                    reused.streamDetail.EEGOriginalQualityStatus)) > 0;

    end

end

if any(eegRows)

    originalStatus = ...
        string( ...
            reused.streamDetail.EEGOriginalQualityStatus);

    segmentStatus = ...
        string( ...
            reused.streamDetail.EEGSegmentCheck);

    badRateRows = ...
        eegRows & ...
        originalStatus == "BAD_effective_srate";

    if any(badRateRows)

        checked = ...
            strlength( ...
                strtrim( ...
                    segmentStatus(badRateRows))) > 0;

        if ~all(checked)
            return;
        end

    end

end

reused.fileSummary.FileIndex(:) = ...
    fileIndex;

if ~isempty(reused.streamDetail)

    reused.streamDetail.FileIndex(:) = ...
        fileIndex;

end

if ~isempty(reused.eegQuality)

    reused.eegQuality.FileIndex(:) = ...
        fileIndex;

end

if ~isempty(reused.grfQuality)

    reused.grfQuality.FileIndex(:) = ...
        fileIndex;

end

canReuse = true;

end

function rows = matching_rows_local( ...
        T, ...
        xdfPath, ...
        sourceSignature, ...
        scanConfigSignature)

if isempty(T)

    rows = T;
    return;

end

mask = ...
    T.FullPath == xdfPath & ...
    T.SourceXDFSignature == sourceSignature & ...
    T.ScanConfigSignature == scanConfigSignature;

rows = T(mask, :);

end

function result = add_provenance_local( ...
        result, ...
        sourceSignature, ...
        scanConfigSignature)

fields = { ...
    'fileSummary', ...
    'streamDetail', ...
    'eegQuality', ...
    'grfQuality'};

for i = 1:numel(fields)

    fieldName = fields{i};

    T = result.(fieldName);

    if isempty(T)
        continue;
    end

    T.SourceXDFSignature = ...
        repmat( ...
            string(sourceSignature), ...
            height(T), ...
            1);

    T.ScanConfigSignature = ...
        repmat( ...
            string(scanConfigSignature), ...
            height(T), ...
            1);

    result.(fieldName) = T;

end

end

function print_quality_summary( ...
        T, ...
        label, ...
        statusVariable, ...
        usableVariable) %#ok<INUSD>

fprintf( ...
    '\n%s quality status summary:\n', ...
    label);

if isempty(T)

    fprintf( ...
        '  No %s candidate streams found.\n', ...
        label);

    return;

end

uniqueStatus = ...
    unique( ...
        T.(statusVariable), ...
        'stable');

for k = 1:numel(uniqueStatus)

    thisStatus = ...
        uniqueStatus(k);

    n = ...
        sum( ...
            T.(statusVariable) == thisStatus);

    fprintf( ...
        '  %-40s %d\n', ...
        thisStatus, ...
        n);

end

end

function save_audit_tables( ...
        fileSummaryTable, ...
        streamDetailTable, ...
        eegQualityTable, ...
        grfQualityTable, ...
        P)

writetable( ...
    fileSummaryTable, ...
    P.summaryFile);

writetable( ...
    streamDetailTable, ...
    P.detailFile);

writetable( ...
    eegQualityTable, ...
    P.eegQualityFile);

writetable( ...
    grfQualityTable, ...
    P.grfQualityFile);

end