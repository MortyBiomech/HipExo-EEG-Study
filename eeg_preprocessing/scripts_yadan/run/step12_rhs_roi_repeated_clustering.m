% SHARED-ICA-AWARE ROI MULTIVARIATE EVALUATION

function [clusterData, dataPlot] = ...
        create_shared_ica_multivariate_data_local( ...
            STUDY, ...
            ALLEEG, ...
            solutions, ...
            roiMNI, ...
            repetitions, ...
            K)


    roiXYZ = [ ...
        double(roiMNI.x), ...
        double(roiMNI.y), ...
        double(roiMNI.z)];


    bestCluster = ...
        zeros(repetitions,1);

    bestDistance = ...
        inf(repetitions,1);

    bestXYZ = ...
        nan(repetitions,3);

    bestSpread = ...
        nan(repetitions,1);

    bestSubjectCount = ...
        nan(repetitions,1);

    bestICCount = ...
        nan(repetitions,1);

    bestNormalizedSpread = ...
        nan(repetitions,1);

    bestMeanRV = ...
        nan(repetitions,1);

    regularClusterIndices = ...
        cell(repetitions,1);


    for solutionIndex = 1:repetitions

        solutionField = ...
            sprintf( ...
                'solution_%d', ...
                solutionIndex);


        solutionClusters = ...
            solutions.(solutionField);


        regularIndices = ...
            regular_cluster_indices_local( ...
                solutionClusters, ...
                K, ...
                solutionField);


        regularClusterIndices{solutionIndex} = ...
            regularIndices;


        solutionStudy = ...
            STUDY;

        solutionStudy.cluster = ...
            solutionClusters;


        for regularIndex = 1:numel(regularIndices)

            clusterIndex = ...
                regularIndices(regularIndex);


            members = ...
                cluster_membership_table_local( ...
                    solutionStudy, ...
                    clusterIndex);


            uniqueMembers = ...
                unique_ica_component_members_local( ...
                    members);


            if isempty(uniqueMembers)

                error( ...
                    '%s cluster %d contains no valid ICA components.', ...
                    solutionField, ...
                    clusterIndex);

            end


            [centroid, meanRV, positions] = ...
                cluster_source_statistics_local( ...
                    solutionStudy, ...
                    ALLEEG, ...
                    uniqueMembers);


            offsets = ...
                positions - centroid;


            spread = ...
                sum( ...
                    offsets(:) .^ 2, ...
                    'omitnan');


            subjectCount = ...
                numel( ...
                    unique( ...
                        uniqueMembers.Subject));


            icCount = ...
                height(uniqueMembers);


            distance = ...
                norm(centroid - roiXYZ);


            if distance < bestDistance(solutionIndex)

                bestCluster(solutionIndex) = ...
                    clusterIndex;

                bestDistance(solutionIndex) = ...
