% CLUSTER SOURCE STATISTICS

function [centroid, meanRV, positions, rvValues] = ...
        cluster_source_statistics_local( ...
            STUDY, ...
            ALLEEG, ...
            uniqueMembers)


    numberOfComponents = ...
        height(uniqueMembers);


    positions = ...
        nan( ...
            numberOfComponents, ...
            3);


    rvValues = ...
        nan( ...
            numberOfComponents, ...
            1);


    for row = 1:numberOfComponents


        datasetIndex = ...
            uniqueMembers.DatasetIndex(row);


        component = ...
            uniqueMembers.IC(row);


        if datasetIndex < 1 || ...
                datasetIndex > numel(ALLEEG)

            error( ...
                'Invalid dataset index %d.', ...
                datasetIndex);

        end


        model = ...
            ALLEEG(datasetIndex).dipfit.model(component);


        positions(row,:) = ...
            primary_dipole_xyz_local( ...
                model);


        rvValues(row) = ...
            dipole_rv_local( ...
                model);

    end


    if any(~isfinite(positions), 'all')

        error( ...
            'Selected ROI cluster contains invalid dipole positions.');

    end


    centroid = ...
        mean( ...
            positions, ...
            1, ...
            'omitnan');


    meanRV = ...
        mean( ...
            rvValues, ...
            'omitnan');

end


% PRIMARY DIPOLE XYZ

function xyz = ...
        primary_dipole_xyz_local(model)


    xyz = ...
        [NaN NaN NaN];


    if ~isfield(model, 'posxyz') || ...
            isempty(model.posxyz)

        return;

    end


    position = ...
        double(model.posxyz);


    if size(position,2) ~= 3

        return;

    end


    if size(position,1) == 1

        xyz = ...
            position(1,:);

    else

        xyz = ...
            mean( ...
                position, ...
                1, ...
                'omitnan');

    end

end


% DIPOLE RV

function rv = ...
        dipole_rv_local(model)


    rv = NaN;


    if ~isfield(model, 'rv') || ...
            isempty(model.rv)

        return;

    end


    values = ...
        double(model.rv(:));


    values = ...
        values( ...
            isfinite(values));


    if ~isempty(values)

        rv = ...
            mean(values);

    end

end


% FLATTEN STUDY CLUSTER MEMBERSHIP

function [setVector, compVector] = ...
        flatten_members_local( ...
            setsValue, ...
            compsValue)


    setsMatrix = ...
        double(setsValue);


    compsArray = ...
        double(compsValue);


    % Shared ICA representation:
    % columns = unique ICA components
    % rows    = run-separated datasets sharing that ICA component
    % NaN padding is allowed.

    if isvector(compsArray) && ...
            size(setsMatrix,2) == numel(compsArray)


        compsRow = ...
            compsArray(:)';


        validMask = ...
            isfinite(setsMatrix) & ...
            setsMatrix > 0;


        [~, componentColumns] = ...
            find(validMask);


        setVector = ...
            setsMatrix(validMask);


        compVector = ...
            compsRow( ...
                componentColumns)';


    elseif numel(setsMatrix) == ...
            numel(compsArray)


        setVector = ...
            setsMatrix(:);


        compVector = ...
            compsArray(:);


        validMask = ...
            isfinite(setVector) & ...
            setVector > 0 & ...
            isfinite(compVector) & ...
            compVector > 0;


        setVector = ...
            setVector(validMask);


        compVector = ...
            compVector(validMask);


    else

        error( ...
            ['Unsupported STUDY.cluster sets/comps shape.\n' ...
             'sets: %s\n' ...
             'comps: %s'], ...
            mat2str(size(setsMatrix)), ...
            mat2str(size(compsArray)));

    end


    pairs = ...
        unique( ...
            [ ...
                setVector(:), ...
                compVector(:)], ...
            'rows', ...
            'stable');


    setVector = ...
        pairs(:,1);


    compVector = ...
        pairs(:,2);

end


