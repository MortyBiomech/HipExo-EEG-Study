% FILE SIGNATURE

function signature = ...
        file_signature_local(filePath)


    information = ...
        dir( ...
            filePath);


    if numel(information) ~= 1

        error( ...
            'Could not resolve file:\n%s', ...
            filePath);

    end


    signature = ...
        sprintf( ...
            '%s|bytes=%d|datenum=%.15f', ...
            filePath, ...
            information.bytes, ...
            information.datenum);


    [fileFolder, fileStem, fileExtension] = ...
        fileparts(filePath);


    if strcmpi(fileExtension, '.set')

        fdtPath = ...
            fullfile(fileFolder, [fileStem '.fdt']);


        if exist(fdtPath, 'file') == 2

            fdtInformation = ...
                dir(fdtPath);


            signature = ...
                sprintf( ...
                    '%s|fdt=%s|bytes=%d|datenum=%.15f', ...
                    signature, ...
                    fdtPath, ...
                    fdtInformation.bytes, ...
                    fdtInformation.datenum);


        else

            signature = ...
                sprintf('%s|fdt=embedded_or_absent', signature);


        end

    end

end


% VERIFY EVERY REPEATED-CLUSTERING SOLUTION

function assert_complete_solution_bank_local( ...
        solutions, repetitions, K)


    if ~isstruct(solutions) || ~isscalar(solutions)

        error('clustering_solutions must be a scalar structure.');

    end


    for solutionIndex = 1:repetitions

        solutionField = ...
            sprintf('solution_%d', solutionIndex);


        if ~isfield(solutions, solutionField)

            error( ...
                'Solution bank is missing %s.', ...
                solutionField);

        end


        solutionClusters = ...
            solutions.(solutionField);


        regularIndices = ...
            regular_cluster_indices_local( ...
                solutionClusters, ...
                K, ...
                solutionField);


        requiredClusterFields = {'sets', 'comps'};


        for regularIndex = 1:numel(regularIndices)

            clusterIndex = ...
                regularIndices(regularIndex);

            for fieldIndex = 1:numel(requiredClusterFields)

                if ~isfield( ...
                        solutionClusters(clusterIndex), ...
                        requiredClusterFields{fieldIndex})

                    error( ...
                        '%s cluster %d is missing %s.', ...
                        solutionField, ...
                        clusterIndex, ...
                        requiredClusterFields{fieldIndex});

                end

            end

        end

    end

end


% IDENTIFY THE K REGULAR CLUSTERS

function regularIndices = ...
        regular_cluster_indices_local( ...
            clusters, ...
            K, ...
            solutionLabel)


    if ~isstruct(clusters) || isempty(clusters)

        error( ...
            '%s does not contain a cluster structure.', ...
            solutionLabel);

    end


    numberOfEntries = ...
        numel(clusters);


    if numberOfEntries < K + 1 || ...
            numberOfEntries > K + 2

        error([ ...
            '%s contains %d cluster entries. Expected either %d ' ...
            '(Parent + K) or %d (Parent + Outlier + K).'], ...
            solutionLabel, ...
            numberOfEntries, ...
            K + 1, ...
            K + 2);

    end


    clusterNames = ...
        strings(1,numberOfEntries);


    for clusterIndex = 1:numberOfEntries

        if isfield(clusters(clusterIndex), 'name') && ...
                ~isempty(clusters(clusterIndex).name)

            clusterNames(clusterIndex) = ...
                string(clusters(clusterIndex).name);

        else

            clusterNames(clusterIndex) = ...
                "<unnamed>";

        end

    end


    outlierMask = ...
        false(1,numberOfEntries);


    for clusterIndex = 2:numberOfEntries

        normalizedName = ...
            lower( ...
                regexprep( ...
                    clusterNames(clusterIndex), ...
                    '[^a-zA-Z0-9]', ...
                    ''));


        outlierMask(clusterIndex) = ...
            contains(normalizedName, 'outlier') || ...
            contains(normalizedName, 'notclust');

    end


    if sum(outlierMask) > 1

        error( ...
            '%s contains more than one Outlier/Notclust entry.', ...
            solutionLabel);

    end


    regularMask = ...
        true(1,numberOfEntries);

    regularMask(1) = ...
        false;

    regularMask(outlierMask) = ...
        false;


    regularIndices = ...
        find(regularMask);


    if numel(regularIndices) ~= K

        error([ ...
            '%s contains %d regular clusters after excluding Parent and ' ...
            'named Outlier/Notclust entries; expected %d. Names: %s'], ...
            solutionLabel, ...
            numel(regularIndices), ...
            K, ...
            strjoin(cellstr(clusterNames), ', '));

    end

end

function textValue = subject_ic_count_text_local(subjectValues)

    subjectValues = string(subjectValues(:));
    subjectValues(ismissing(subjectValues)) = "";
    subjectValues = strtrim(subjectValues);
    subjectValues = subjectValues(strlength(subjectValues) > 0);

    if isempty(subjectValues)
        textValue = "";
        return;
    end

    subjects = unique(subjectValues, 'stable');
    parts = strings(numel(subjects), 1);

    for k = 1:numel(subjects)
        parts(k) = subjects(k) + ":" + string(sum(subjectValues == subjects(k)));
    end

    textValue = strjoin(parts, '|');

end

