% VERIFY BASE STUDY

function profile = verify_base_study_local(STUDY, ALLEEG, referenceProfile)

    if nargin < 3
        referenceProfile = [];
    end

    datasetCount = numel(STUDY.datasetinfo);

    if datasetCount < 1
        error('The RHS STUDY contains no datasets.');
    end

    if numel(ALLEEG) ~= datasetCount
        error('STUDY.datasetinfo and ALLEEG contain different dataset counts.');
    end

    allSubjects = string({STUDY.datasetinfo.subject});
    allSubjects(ismissing(allSubjects)) = "";
    allSubjects = strtrim(allSubjects);

    if any(strlength(allSubjects) == 0)
        error('At least one STUDY dataset has an empty subject label.');
    end

    uniqueSubjects = unique(allSubjects, 'stable');
    subjectCount = numel(uniqueSubjects);

    subjectNames = strings(subjectCount, 1);
    subjectDatasetCounts = zeros(subjectCount, 1);
    subjectYesICs = strings(subjectCount, 1);
    subjectYesICCounts = zeros(subjectCount, 1);

    for subjectIndex = 1:subjectCount

        subjectLabel = uniqueSubjects(subjectIndex);
        positions = find(allSubjects == subjectLabel);

        if isempty(positions)
            error('No datasets found for subject %s.', subjectLabel);
        end

        referenceICs = [];

        for studyPosition = positions

            info = STUDY.datasetinfo(studyPosition);

            if isempty(info.session) || ...
                    ~isfinite(double(info.session)) || ...
                    double(info.session) < 1 || ...
                    double(info.session) ~= round(double(info.session))
                error('Dataset %d has an invalid shared-ICA session.', studyPosition);
            end

            if ~isfield(info, 'run') || ...
                    isempty(info.run) || ...
                    ~isfinite(double(info.run)) || ...
                    double(info.run) < 1 || ...
                    double(info.run) ~= round(double(info.run))
                error('Dataset %d has an invalid physical run number.', studyPosition);
            end

            observedICs = double(info.comps(:)');

            if isempty(observedICs) || ...
                    any(~isfinite(observedICs)) || ...
                    any(observedICs < 1) || ...
                    any(observedICs ~= round(observedICs)) || ...
                    numel(unique(observedICs)) ~= numel(observedICs)
                error('Dataset %d has an invalid selected-IC list.', studyPosition);
            end

            if isempty(referenceICs)
                referenceICs = sort(observedICs);
            elseif ~isequal(sort(observedICs), referenceICs)
                error('%s does not use one shared Yes-IC list across datasets.', ...
                    subjectLabel);
            end

            eegIndex = double(info.index);

            if eegIndex < 1 || eegIndex > numel(ALLEEG) || ...
                    eegIndex ~= round(eegIndex)
                error('Invalid ALLEEG index %g.', eegIndex);
            end

            EEG = ALLEEG(eegIndex);

            if isempty(EEG.icaweights) || isempty(EEG.icasphere)
                error('Dataset %d has no ICA decomposition.', studyPosition);
            end

            if ~isfield(EEG, 'dipfit') || ...
                    ~isfield(EEG.dipfit, 'model')
                error('Dataset %d has no DIPFIT model.', studyPosition);
            end

            for ic = observedICs
                if ic > numel(EEG.dipfit.model)
                    error('Dataset %d IC %d has no DIPFIT entry.', ...
                        studyPosition, ic);
                end

                xyz = primary_dipole_xyz_local(EEG.dipfit.model(ic));

                if any(~isfinite(xyz))
                    error('Dataset %d IC %d has an invalid dipole position.', ...
                        studyPosition, ic);
                end
            end

            if ~isfield(EEG, 'timewarp') || ...
                    ~isfield(EEG.timewarp, 'latencies')
                error('Dataset %d has no timewarp information.', studyPosition);
            end

            if size(EEG.timewarp.latencies, 1) ~= EEG.trials
                error('Dataset %d timewarp count does not equal trials.', ...
                    studyPosition);
            end

        end

        subjectNames(subjectIndex) = subjectLabel;
        subjectDatasetCounts(subjectIndex) = numel(positions);
        subjectYesICs(subjectIndex) = strjoin(string(referenceICs), ' ');
        subjectYesICCounts(subjectIndex) = numel(referenceICs);

    end

    uniqueCount = count_unique_ica_ic_units_local(STUDY);
    countFromSubjects = sum(subjectYesICCounts);

    if uniqueCount ~= countFromSubjects
        error([ ...
            'Unique ICA+IC count (%d) does not match the sum of the ' ...
            'subject-level selected IC counts (%d).'], ...
            uniqueCount, countFromSubjects);
    end

    subjectTable = table( ...
        subjectNames, ...
        subjectDatasetCounts, ...
        subjectYesICs, ...
        subjectYesICCounts, ...
        'VariableNames', { ...
            'Subject', ...
            'DatasetCount', ...
            'YesICs', ...
            'YesICCount'});

    profile = struct();
    profile.DatasetCount = datasetCount;
    profile.SubjectCount = subjectCount;
    profile.UniqueICAICCount = uniqueCount;
    profile.SubjectTable = subjectTable;

    if ~isempty(referenceProfile)

        if profile.DatasetCount ~= referenceProfile.DatasetCount
            error('Reused STUDY dataset count does not match the source STUDY.');
        end

        if profile.SubjectCount ~= referenceProfile.SubjectCount
            error('Reused STUDY subject count does not match the source STUDY.');
        end

        if profile.UniqueICAICCount ~= referenceProfile.UniqueICAICCount
            error('Reused STUDY selected-IC count does not match the source STUDY.');
        end

        refTable = sortrows(referenceProfile.SubjectTable, 'Subject');
        thisTable = sortrows(profile.SubjectTable, 'Subject');

        if height(refTable) ~= height(thisTable) || ...
                any(refTable.Subject ~= thisTable.Subject) || ...
                any(refTable.DatasetCount ~= thisTable.DatasetCount) || ...
                any(refTable.YesICCount ~= thisTable.YesICCount) || ...
                any(refTable.YesICs ~= thisTable.YesICs)
            error('Reused STUDY subject structure does not match the source STUDY.');
        end

    end

end


