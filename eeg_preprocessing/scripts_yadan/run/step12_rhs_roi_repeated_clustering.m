% ROBUST SOLUTION RANKING

function [ranked, scores, mahalanobisDistance] = ...
        rank_solutions_robust_local( ...
            clusterData, ...
            weights)


    data = ...
        double( ...
            clusterData.data);


    if size(data,2) < 9

        error( ...
            'Unexpected ROI multivariate data dimensions.');

    end


    if numel(weights) ~= 6

        error( ...
            'Six quality weights are required.');

    end


    % Replace non-finite entries

    for column = 1:size(data,2)


        values = ...
            data(:,column);


        finiteValues = ...
            values( ...
                isfinite(values));


        if isempty(finiteValues)

            values(:) = 0;

        else

            values(~isfinite(values)) = ...
                median(finiteValues);

        end


        data(:,column) = ...
            values;

    end


    % Mahalanobis from median

    distributionMedian = ...
        median( ...
            data, ...
            1);


    centered = ...
        data - ...
        distributionMedian;


    covarianceMatrix = ...
        cov(data);


    inverseCovariance = ...
        pinv( ...
            covarianceMatrix);


    mahalanobisDistance = ...
        sum( ...
            (centered * inverseCovariance) .* ...
            centered, ...
            2);


    % Same quality dimensions used by BeMoBIL

    measures = [ ...
        data(:,1), ...
        data(:,3), ...
        data(:,4), ...
        data(:,5), ...
        data(:,9), ...
        mahalanobisDistance];


    % Normalize

    for column = 1:size(measures,2)


        values = ...
            measures(:,column);


        finiteValues = ...
            values(isfinite(values));


        if isempty(finiteValues)

            measures(:,column) = 0;

            continue;

        end


        values(~isfinite(values)) = ...
            median(finiteValues);


        denominator = ...
            max(abs(values));


        if denominator == 0

            denominator = 1;

        end


        measures(:,column) = ...
            values ./ ...
            denominator;

    end


    scores = ...
        measures * ...
        double(weights(:));


    [~, ranked] = ...
        sort( ...
            scores, ...
            'descend');

end


% CLUSTER MEMBERSHIP TABLE

function members = ...
        cluster_membership_table_local( ...
            STUDY, ...
            clusterIndex)


    [datasetIndices, components] = ...
        flatten_members_local( ...
            STUDY.cluster(clusterIndex).sets, ...
            STUDY.cluster(clusterIndex).comps);


    numberOfMembers = ...
        numel(datasetIndices);


    Subject = ...
        strings(numberOfMembers,1);


    ICASession = ...
        nan(numberOfMembers,1);


    PhysicalRun = ...
        nan(numberOfMembers,1);


    Condition = ...
        strings(numberOfMembers,1);


    ICAUnit = ...
        strings(numberOfMembers,1);


    ICAComponentUnit = ...
        strings(numberOfMembers,1);


    for memberIndex = 1:numberOfMembers


        datasetIndex = ...
            datasetIndices(memberIndex);


        infoPosition = ...
            find( ...
                [STUDY.datasetinfo.index] == ...
                datasetIndex, ...
                1, ...
                'first');


        if isempty(infoPosition)

            error( ...
                'Cluster contains unknown dataset index %d.', ...
                datasetIndex);

        end


        info = ...
            STUDY.datasetinfo( ...
                infoPosition);


        Subject(memberIndex) = ...
            string(info.subject);


        ICASession(memberIndex) = ...
            double(info.session);


        if isfield(info, 'run') && ...
                ~isempty(info.run)

            PhysicalRun(memberIndex) = ...
                double(info.run);

        end


        Condition(memberIndex) = ...
            string(info.condition);


        ICAUnit(memberIndex) = ...
            Subject(memberIndex) + ...
            "|session" + ...
            string(ICASession(memberIndex));


        ICAComponentUnit(memberIndex) = ...
            ICAUnit(memberIndex) + ...
            "|IC" + ...
            string(components(memberIndex));

    end


    DatasetIndex = ...
        datasetIndices(:);


    IC = ...
        components(:);


    members = ...
        table( ...
            DatasetIndex, ...
            Subject, ...
            ICASession, ...
            PhysicalRun, ...
            Condition, ...
            IC, ...
            ICAUnit, ...
            ICAComponentUnit);


    members = ...
        unique( ...
            members, ...
            'rows', ...
            'stable');


    members = ...
        sortrows( ...
            members, ...
            { ...
                'Subject', ...
                'ICASession', ...
                'PhysicalRun', ...
                'Condition', ...
                'IC'});

end


