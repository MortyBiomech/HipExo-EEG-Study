    combinedTable = ...
        currentTable;

    return;
end

referenceNames = ...
    string(combinedTable.Properties.VariableNames);

currentNames = ...
    string(currentTable.Properties.VariableNames);

missingNames = ...
    setdiff( ...
        referenceNames, ...
        currentNames, ...
        'stable');

extraNames = ...
    setdiff( ...
        currentNames, ...
        referenceNames, ...
        'stable');

if ~isempty(missingNames) || ...
        ~isempty(extraNames)

    error([ ...
        'Per-recording MAT table schemas are inconsistent.\n' ...
        'Source: %s\n' ...
        'Missing columns: %s\n' ...
        'Extra columns: %s\n' ...
        'Re-run the affected Step 03 stage with the current code.'], ...
        sourceDescription, ...
        strjoin(missingNames, ', '), ...
        strjoin(extraNames, ', '));
end

currentTable = ...
    currentTable(:, cellstr(referenceNames));

try

    combinedTable = ...
        [combinedTable; currentTable];

catch appendError

    error([ ...
        'Could not append a per-recording MAT table while rebuilding ' ...
        'the shared CSV.\nSource: %s\nReason: %s'], ...
        sourceDescription, ...
        appendError.message);
end

end

