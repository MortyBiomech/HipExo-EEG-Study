function values = numeric_column_local(values)
if isnumeric(values)
    values = double(values);
elseif islogical(values)
    values = double(values);
else
    textValues = lower(strtrim(string(values)));
    values = str2double(textValues);
    values(ismember(textValues,["true","yes"])) = 1;
    values(ismember(textValues,["false","no"])) = 0;
end
end

function T = read_import_table_local(importTableFile)

T = ...
    hipexo.read_csv_with_string_text(importTableFile);

end

function gaitGate = gait_analysis_gate_local(T)
% Accept the Step 02 gait-analysis gate columns.

if ismember('DoGaitAnalysis', T.Properties.VariableNames)

    gaitGate = ...
        numeric_column_local(T.DoGaitAnalysis);

elseif ismember('DoImport', T.Properties.VariableNames)

    gaitGate = ...
        numeric_column_local(T.DoImport);

else

    error([ ...
        'Import table contains neither DoGaitAnalysis nor DoImport. ' ...
        'Re-run Step 02.']);
end

end

function [firstLSLTime, ...
          lastLSLTime, ...
          grfFirstLSLTime, ...
          grfLastLSLTime] = ...
        read_true_eeg_grf_lsl_bounds_from_xdf(xdfPath)

[streams, ~] = load_xdf(char(xdfPath));

nStreams = numel(streams);

streamName = strings(nStreams, 1);
streamType = strings(nStreams, 1);
nominalSrate = nan(nStreams, 1);
channelCount = nan(nStreams, 1);
sampleCount = nan(nStreams, 1);

for iStream = 1:nStreams

    currentStream = streams{iStream};

    streamName(iStream) = ...
        batch_xdf_stream_text_field(currentStream, 'name');

    streamType(iStream) = ...
        batch_xdf_stream_text_field(currentStream, 'type');

    nominalSrate(iStream) = ...
        batch_xdf_stream_nominal_srate(currentStream);

    if isfield(currentStream, 'time_series') && ...
            isnumeric(currentStream.time_series) && ...
            isfield(currentStream, 'time_stamps')

        currentData = currentStream.time_series;
        currentTimestamps = currentStream.time_stamps;

        sampleCount(iStream) = numel(currentTimestamps);

        if size(currentData, 2) == sampleCount(iStream)
            channelCount(iStream) = size(currentData, 1);

        elseif size(currentData, 1) == sampleCount(iStream)
            channelCount(iStream) = size(currentData, 2);
        end
    end
end

candidateMask = ...
    strcmpi(streamName, "LiveAmpSN-102108-1139") & ...
    channelCount >= 64 & ...
    channelCount <= 80 & ...
    abs(nominalSrate - 500) <= 1;

candidateIndices = find(candidateMask);

if isempty(candidateIndices)

    candidateMask = ...
        channelCount >= 64 & ...
        channelCount <= 80 & ...
        abs(nominalSrate - 500) <= 1 & ...
        (contains(lower(streamType), 'eeg') | ...
         contains(lower(streamName), 'liveamp'));

    candidateIndices = find(candidateMask);
end

if numel(candidateIndices) ~= 1

    streamSummary = table( ...
        (1:nStreams)', ...
        streamName, ...
        streamType, ...
        nominalSrate, ...
        channelCount, ...
        sampleCount, ...
        'VariableNames', ...
        {'StreamIndex','Name','Type','NominalSrate', ...
         'ChannelCount','SampleCount'});

    error('Could not uniquely identify EEG stream:\n%s', xdfPath);
end

eegStream = streams{candidateIndices(1)};
eegTimestamps = double(eegStream.time_stamps(:));

if isempty(eegTimestamps) || ...
        any(~isfinite(eegTimestamps)) || ...
        any(diff(eegTimestamps) <= 0)

    error('Invalid EEG LSL timestamps:\n%s', xdfPath);
end

firstLSLTime = eegTimestamps(1);
lastLSLTime = eegTimestamps(end);

isMarkerStream = ...
    contains(upper(streamName), "MARKER") | ...
    contains(upper(streamType), "MARKER");

grfCandidateMask = ...
    (strcmpi(strtrim(streamName), "GRF") | ...
     contains(upper(streamType), "FORCE")) & ...
    ~isMarkerStream;

grfCandidateIndices = find(grfCandidateMask);

if numel(grfCandidateIndices) ~= 1

    streamSummary = table( ...
        (1:nStreams)', ...
        streamName, ...
        streamType, ...
        nominalSrate, ...
        channelCount, ...
        sampleCount, ...
        'VariableNames', ...
        {'StreamIndex','Name','Type','NominalSrate', ...
         'ChannelCount','SampleCount'});

    error('Could not uniquely identify GRF stream:\n%s', xdfPath);
end

grfStream = streams{grfCandidateIndices(1)};
grfTimestamps = double(grfStream.time_stamps(:));

if isempty(grfTimestamps) || ...
        any(~isfinite(grfTimestamps)) || ...
        any(diff(grfTimestamps) <= 0)

    error('Invalid GRF LSL timestamps:\n%s', xdfPath);
end

grfFirstLSLTime = grfTimestamps(1);
grfLastLSLTime = grfTimestamps(end);

end

function subjectID = resolve_subject_id_local(subjectSpec, importTableFile)

T = read_import_table_local(importTableFile);
if ~ismember('SubjectID',T.Properties.VariableNames)
    error('Import table is missing SubjectID. Re-run Step 02.');
end
T.SubjectID = string(T.SubjectID);
subjectSpec = strtrim(string(subjectSpec));

% Resolve a canonical subject label, e.g. sub-01.
if any(T.SubjectID == subjectSpec)
    subjectID = subjectSpec;
    return;
end

% Resolve a supplied subject directory through XdfPath.
if isfolder(subjectSpec)
    if ~ismember('XdfPath',T.Properties.VariableNames)
        error('Import table is missing XdfPath.');
    end
    normalizedSpec = normalize_path_text(subjectSpec);
    normalizedPaths = normalize_path_text(string(T.XdfPath));
    mask = normalizedPaths == normalizedSpec | ...
        startsWith(normalizedPaths, normalizedSpec + "/");
    ids = unique(T.SubjectID(mask));
    ids(ids == "" | ismissing(ids)) = [];
    if numel(ids) == 1
        subjectID = ids(1);
        return;
    end
end

error(['Could not resolve subject "' char(subjectSpec) '". Use the canonical ' ...
    'SubjectID from Step 02, for example sub-01.']);

end

function batchStatus = run_subject_grf_cycle_qc_local( ...
        batchStatus, subjectOutputFolder, cfg)

qcFolder = fullfile(subjectOutputFolder, 'grf_quality_check');

if ~isfolder(qcFolder)
    mkdir(qcFolder);
end

allCycleQC = table();
allSummary = table();
allEdgeEvents = table();

acceptedGaitStatus = ["completed", "reused_verified"];
batchStatus.GRFGaitReviewStatus = repmat("not_available", height(batchStatus), 1);

for iRow = 1:height(batchStatus)

    gaitStatus = lower(strtrim(string(batchStatus.GaitEventStatus(iRow))));
    eventFile = string(batchStatus.GaitEventFile(iRow));

    if ~ismember(gaitStatus, acceptedGaitStatus) || ...
            strlength(strtrim(eventFile)) == 0 || ...
            ~isfile(eventFile)

        if lower(strtrim(string(batchStatus.OverallStatus(iRow)))) == "failed"
            batchStatus.GRFGaitQCStatus(iRow) = "blocked_processing_failure";
        else
            batchStatus.GRFGaitQCStatus(iRow) = "not_available";
        end
        continue;
    end

    loaded = load(char(eventFile), 'allEventTable');

    if ~isfield(loaded, 'allEventTable') || ...
            ~istable(loaded.allEventTable)

        batchStatus.GRFGaitQCStatus(iRow) = "failed";
        batchStatus.OverallStatus(iRow) = "failed";
        batchStatus.ErrorMessage(iRow) = ...
            "gait_event_file_missing_allEventTable";
        continue;
    end

    eventTable = loaded.allEventTable;

    if isempty(eventTable)
        batchStatus.GRFGaitQCStatus(iRow) = ...
            "excluded_no_detected_gait_events";
        continue;
    end

    eventTable.Subject = repmat( ...
        string(batchStatus.Subject(iRow)), height(eventTable), 1);

    settings = struct( ...
        'ExcludeFirstAndLastCycle', cfg.cycleQC.excludeFirstAndLastCycle, ...
        'MinimumStrideSec', cfg.cycleQC.minimumStrideSec, ...
        'MaximumStrideSec', cfg.cycleQC.maximumStrideSec, ...
        'RobustOutlierZ', cfg.cycleQC.robustOutlierZ);

    try
        [cycleQC, segmentSummary, edgeEvents] = ...
            hipexo.validate_grf_gait_event_table( ...
                eventTable, char(eventFile), settings);

        allCycleQC = append_compatible_table_local( ...
            allCycleQC, cycleQC, char(eventFile));
        allSummary = append_compatible_table_local( ...
            allSummary, segmentSummary, char(eventFile));
        allEdgeEvents = append_compatible_table_local( ...
            allEdgeEvents, edgeEvents, char(eventFile));

        currentPath = normalize_path_text(batchStatus.XDFPath(iRow));

        if isempty(cycleQC)
            currentRows = false(0, 1);
        else
            currentRows = ...
                normalize_path_text(cycleQC.XDFPath) == currentPath;
        end

        nRecommended = sum(cycleQC.GRFRecommendedForEpoch(currentRows));
        batchStatus.GRFRecommendedCycleCount(iRow) = nRecommended;
        batchStatus.GRFGaitReviewStatus(iRow) = strjoin( ...
            unique(string(segmentSummary.SegmentStatus), 'stable'), ";");

        % This status reports available candidate cycles, not visual approval.
        if nRecommended > 0
            batchStatus.GRFGaitQCStatus(iRow) = "ready_for_step04";
        else
            batchStatus.GRFGaitQCStatus(iRow) = ...
                "excluded_no_recommended_GRF_cycle";
        end

    catch qcError

        batchStatus.GRFGaitQCStatus(iRow) = "failed";
        batchStatus.GRFGaitReviewStatus(iRow) = "failed";
        batchStatus.OverallStatus(iRow) = "failed";
        batchStatus.ErrorMessage(iRow) = ...
            sanitize_error_message_local(qcError.message);
    end
end

cycleFile = fullfile(qcFolder, 'grf_gait_cycle_qc_grf_only.csv');
summaryFile = fullfile(qcFolder, 'grf_gait_cycle_qc_summary_grf_only.csv');
edgeFile = fullfile(qcFolder, 'grf_gait_edge_events_qc_grf_only.csv');
recommendedFile = fullfile( ...
    qcFolder, ...
    'grf_RHS_timewarp_cycles_grf_recommended.csv');

writetable(allCycleQC, cycleFile);
writetable(allSummary, summaryFile);
writetable(allEdgeEvents, edgeFile);

save( ...
    fullfile(qcFolder, 'grf_gait_cycle_qc_grf_only.mat'), ...
    'allCycleQC', ...
    'allSummary', ...
    'allEdgeEvents');

if isempty(allCycleQC)
    grfRecommended = allCycleQC;
else
    grfRecommended = allCycleQC(allCycleQC.GRFRecommendedForEpoch, :);
end

writetable(grfRecommended, recommendedFile);

end

function message = sanitize_error_message_local(rawMessage)

message = string(rawMessage);
message = replace(message, newline, " | ");
message = replace(message, sprintf('\r'), " | ");
message = regexprep(message, '\s*\|\s*\|+\s*', ' | ');
message = strtrim(message);

end

