            strtrim(string(loaded.etc.canonical_subject_id)), ...
            strtrim(string(expectedCanonicalSubject))) || ...
            ~strcmpi( ...
            strtrim(string(loaded.etc.original_subject_id)), ...
            strtrim(string(expectedOriginalSubject)))

        reason = "mapping_output_subject_identity_changed";
        return;
    end

    if ~strcmpi( ...
            normalize_path_text(info.source_event_file), ...
            normalize_path_text(gaitFile)) || ...
            string(info.source_event_signature) ~= ...
            hipexo.file_metadata_signature(gaitFile)

        reason = "mapping_source_event_file_changed";
        return;
    end

    if ~strcmpi( ...
            normalize_path_text(info.source_xdf), ...
            normalize_path_text(sourceXDF)) || ...
            string(info.source_xdf_signature) ~= ...
            hipexo.file_metadata_signature(sourceXDF)

        reason = "mapping_source_XDF_changed";
        return;
    end

    if ~strcmpi( ...
            normalize_path_text(info.source_bids_eeg_set), ...
            normalize_path_text(sourceBidsEEGLABSet)) || ...
            string(info.source_bids_eeg_set_signature) ~= ...
            hipexo.eeglab_dataset_signature(sourceBidsEEGLABSet)

        reason = "mapping_source_BIDS_EEGLAB_changed";
        return;
    end

    if ~logical(info.sample_count_identity_verified) || ...
            logical(info.sample_values_resampled)

        reason = "mapping_sample_identity_policy_changed";
        return;
    end

    if abs( ...
            double(info.output_nominal_srate_hz) - ...
            double(cfg.mapping.targetEEGSrateHz)) > 1e-9

        reason = "mapping_output_rate_changed";
        return;
    end

    if abs( ...
            double(info.maximum_mapping_error_ms) - ...
            double(cfg.mapping.maximumMappingErrorMs)) > 1e-12

        reason = "mapping_error_limit_changed";
        return;
    end

    if abs( ...
            double(info.timestamp_gap_factor) - ...
            double(cfg.mapping.timestampGapFactor)) > 1e-12 || ...
            abs( ...
            double(info.minimum_timestamp_gap_sec) - ...
            double(cfg.mapping.minimumTimestampGapSec)) > 1e-12

        reason = "mapping_timestamp_gap_parameters_changed";
        return;
    end

    if ~isequaln(info.mapping_parameters, cfg.mapping)
        reason = "mapping_parameters_changed";
        return;
    end
    eegQC = config_step01_02_xdf_import();
    currentEEGQC = struct('eeg', eegQC.eeg, 'timestamp', eegQC.timestamp);
    if ~isequaln(info.eeg_qc_parameters, currentEEGQC) || ...
            string(info.eeg_segment_code_signature) ~= hipexo.content_signature( ...
                fileread(which('hipexo.check_eeg_segments')))
        reason = "EEG_segment_QC_changed";
        return;
    end

    canReuse = true;
    reason = "verified";

catch verificationError

    reason = ...
        "mapping_verification_error: " + ...
        sanitize_error_message_local(verificationError.message);
end

