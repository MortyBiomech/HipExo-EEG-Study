function verify_bids_export_gate_local(importTableFile, requestedSubject)

T = ...
    read_import_table_local(importTableFile);

required = { ...
    'SubjectID', ...
    'XdfPath', ...
    'BidsExportStatus', ...
    'BidsSourceSignature', ...
    'BidsEEGHeader', ...
    'BidsRecordingSignature', ...
    'BidsEEGLABStatus', ...
    'BidsEEGLABSet', ...
    'BidsEEGLABSignature'};

missing = ...
    required( ...
        ~ismember( ...
            required, ...
            T.Properties.VariableNames));

if ~isempty(missing)

    error([ ...
        'The import table does not contain the mandatory Step 02B BIDS ' ...
        'gate columns: %s\n' ...
        'Run step02b_standardize_xdf_to_bids.m first.'], ...
        strjoin(missing, ', '));
end

gaitGate = ...
    gait_analysis_gate_local(T);

if strlength(strtrim(string(requestedSubject))) > 0
    requestedID = resolve_subject_id_local(requestedSubject, importTableFile);
    selected = strcmpi(string(T.SubjectID), string(requestedID));
else
    selected = hipexo.subject_is_selected(T.SubjectID);
end
enabled = find(gaitGate == 1 & selected);

if isempty(enabled)

    error( ...
        'No rows have DoGaitAnalysis = 1 in the import table.');
end

status = ...
    upper(strtrim(string(T.BidsExportStatus)));

eeglabStatus = ...
    upper(strtrim(string(T.BidsEEGLABStatus)));

eeglabSet = ...
    string(T.BidsEEGLABSet);

eeglabSignature = ...
    string(T.BidsEEGLABSignature);

xdfPath = ...
    string(T.XdfPath);

storedSignature = ...
    string(T.BidsSourceSignature);

bidsHeader = ...
    string(T.BidsEEGHeader);

storedBidsRecordingSignature = ...
    string(T.BidsRecordingSignature);

failed = ...
    enabled( ...
        status(enabled) ~= "PASS" | ...
        eeglabStatus(enabled) ~= "PASS");

if ~isempty(failed)

    error([ ...
        'Step 02B BIDS/BIDS-to-EEGLAB gate failed for gait-analysis ' ...
        'rows: %s.\n' ...
        'Run step02b_standardize_xdf_to_bids.m and resolve all failures ' ...
        'before Step 03.'], ...
        strjoin(string(failed), ', '));
end

staleRows = [];

for i = 1:numel(enabled)

    r = ...
        enabled(i);

    if ~isfile(xdfPath(r))

        staleRows(end+1) = r; %#ok<AGROW>
        continue;
    end

    currentSignature = ...
        string( ...
            hipexo.file_metadata_signature( ...
                char(xdfPath(r))));

    if strlength(storedSignature(r)) == 0 || ...
            currentSignature ~= storedSignature(r)

        staleRows(end+1) = r; %#ok<AGROW>
        continue;
    end

    if strlength(strtrim(bidsHeader(r))) == 0 || ...
            ~isfile(bidsHeader(r)) || ...
            strlength(storedBidsRecordingSignature(r)) == 0 || ...
            string( ...
                hipexo.bids_recording_signature( ...
                    char(bidsHeader(r)))) ~= ...
            storedBidsRecordingSignature(r)

        staleRows(end+1) = r; %#ok<AGROW>
        continue;
    end

    if strlength(strtrim(eeglabSet(r))) == 0 || ...
            ~isfile(eeglabSet(r)) || ...
            strlength(eeglabSignature(r)) == 0 || ...
            string( ...
                hipexo.file_metadata_signature( ...
                    char(eeglabSet(r)))) ~= ...
            eeglabSignature(r)

        staleRows(end+1) = r; %#ok<AGROW>
    end
end

if ~isempty(staleRows)

    error([ ...
        'One or more gait-analysis source XDF files changed after their ' ...
        'BIDS export (or have no stored signature): rows %s.\n' ...
        'Rerun Step 02B so the standardized BIDS layer matches the ' ...
        'actual source data.'], ...
        strjoin(string(staleRows), ', '));
end

end

function [canReuse, reason] = verify_gait_reuse_local( ...
        gaitFile, grfFile, expectedVersion, cfg)

canReuse = false;
reason = "unverified_gait_output";

try

    loaded = load( ...
        gaitFile, ...
        'processingInfo', ...
        'allEventTable');

    if ~isfield(loaded, 'processingInfo') || ...
            ~isfield(loaded, 'allEventTable') || ...
            isempty(loaded.allEventTable)

        reason = "missing_or_empty_gait_provenance";
        return;
    end

    info = loaded.processingInfo;

    requiredFields = { ...
        'version', ...
        'source_grf_file', ...
        'source_grf_signature', ...
        'detection_settings', ...
        'threshold_selection', ...
        'review_status'};

    if ~all(isfield(info, requiredFields))

        reason = "incomplete_gait_provenance";
        return;
    end


    if ~strcmpi( ...
            normalize_path_text(info.source_grf_file), ...
            normalize_path_text(grfFile)) || ...
            string(info.source_grf_signature) ~= ...
            hipexo.file_metadata_signature(grfFile)

        reason = "gait_source_GRF_changed";
        return;
    end

    oldSettings = info.detection_settings;
    newSettings = cfg.detection;
    if isfield(oldSettings, 'qcZoomWindowSec'), oldSettings = rmfield(oldSettings, 'qcZoomWindowSec'); end
    if isfield(newSettings, 'qcZoomWindowSec'), newSettings = rmfield(newSettings, 'qcZoomWindowSec'); end
    if ~isequaln(oldSettings, newSettings)

        reason = "gait_detection_parameters_changed";
        return;
    end

    allowedReviewStatus = [ ...
        "VISUALLY_ACCEPTED", ...
        "AUTOMATED_QC_PASS_NOT_VISUALLY_REVIEWED", ...
        "AUTOMATED_DETECTION_NOT_VISUALLY_REVIEWED"];

    if ~ismember( ...
            string(info.review_status), ...
            allowedReviewStatus)

        reason = "gait_review_status_not_accepted";
        return;
    end

    canReuse = true;
    reason = "verified";

catch verificationError

    reason = ...
        "gait_verification_error: " + ...
        sanitize_error_message_local(verificationError.message);
end

end

