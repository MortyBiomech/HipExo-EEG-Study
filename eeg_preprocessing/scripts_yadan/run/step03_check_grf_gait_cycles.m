% GOAL
%   Check selected walking recordings at the GRF gait-cycle level.
%   Step 03 performs GRF extraction, gait-event detection, and GRF-only
%   gait-cycle QC. EEG mapping is deferred until Step 04.
%
% INPUT
%   output_data/bemobil_import_table.csv
%   Raw XDF recordings selected by DoGaitAnalysis.
%   Step 02B run-separated BIDS-derived EEGLAB paths are retained for Step 04.
%
% APPROACH
%   1. Select gait-analysis candidate recordings by canonical SubjectID.
%   2. Extract GRF and detect RHS/LTO/LHS/RTO events.
%   3. Build RHS -> LTO -> LHS -> RTO -> RHS cycles.
%   4. Apply the existing GRF gait-cycle QC before any EEG mapping.
%   5. Save GRF-only cycle QC and defer EEG overlap/boundary QC to Step 04.
%
% OUTPUT
%   GRF_segmentation_output/sub-*/GRF/*
%   GRF_segmentation_output/sub-*/grf_quality_check/*_grf_only.csv
%   Per-subject and all-subject batch-status CSV files.
%
% USED BY
%   step04_process_subject_grf_eeg.m, which maps GRF events to retained EEG,
%   applies the final gait-EEG gate, and performs subject concatenation.

function batchStatus = step03_check_grf_gait_cycles(subjectFolder, varargin)

if nargin < 1
    subjectFolder = "";
end

% Load Step 03 defaults before parsing optional overrides.
thisFile = mfilename('fullpath');
if isempty(thisFile)
    error('Could not resolve the current Step file path.');
end
scriptsRoot = fileparts(fileparts(thisFile));
internalFolder = fullfile(scriptsRoot, 'internal');

addpath(scriptsRoot, '-begin');
addpath(internalFolder, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();
cfg = config_step03_04_grf_processing();

parser = inputParser;

addOptional(parser, 'subjectFolder', subjectFolder, ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));

addParameter(parser, 'ForceReprocess', cfg.batch.forceReprocess, ...
    @(x) islogical(x) && isscalar(x));

% Stage-specific recomputation switches. Dependencies cascade forward:
% extraction -> gait detection -> GRF gait-cycle QC.
addParameter(parser, 'ForceGRFExtraction', cfg.batch.forceGRFExtraction, ...
    @(x) islogical(x) && isscalar(x));

addParameter(parser, 'ForceGaitDetection', cfg.batch.forceGaitDetection, ...
    @(x) islogical(x) && isscalar(x));





parse(parser, subjectFolder, varargin{:});

subjectFolder = char(string(parser.Results.subjectFolder));
forceReprocess = logical(parser.Results.ForceReprocess);
forceGRFExtraction = forceReprocess || ...
    logical(parser.Results.ForceGRFExtraction);
forceGaitDetection = forceReprocess || forceGRFExtraction || ...
    logical(parser.Results.ForceGaitDetection);

expectedGRFExtractionVersion = ...
    "GRF_extraction_v2_strict_markers";
expectedGaitEventVersion = ...
    "GRF_gait_events_lab_threshold_search_v1";

close all;

previousFigureVisibility = get(groot, 'DefaultFigureVisible');
set(groot, 'DefaultFigureVisible', 'off');

figureVisibilityCleanup = onCleanup( ...
    @() set(groot, 'DefaultFigureVisible', previousFigureVisibility)); %#ok<NASGU>

rawDataFolder = P.rawDataFolder;
outputFolder = P.outputFolder;
grfSegmentationFolder = P.grfSegmentationFolder;
importTableFile = P.importTableFile;

% Step 03 uses GRF extraction/detection plus the GRF-only cycle validator.
requiredFunctions = { ...
    'step03_extract_and_segment_grf_internal', ...
    'step03_detect_grf_gait_events_internal', ...
    'hipexo.validate_grf_gait_event_table', ...
    'hipexo.detect_walking_intervals', ...
    'hipexo.detect_grf_gait_events', ...
    'hipexo.optimize_grf_thresholds', ...
    'hipexo.file_metadata_signature'};

for iRequired = 1:numel(requiredFunctions)
    if isempty(which(requiredFunctions{iRequired}))
        error('Required function is not available: %s', ...
            requiredFunctions{iRequired});
    end
end

if ~isfolder(rawDataFolder)
    error('Raw-data folder does not exist:\n%s', rawDataFolder);
end

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

if ~isfolder(grfSegmentationFolder)
    mkdir(grfSegmentationFolder);
end

if ~isfile(importTableFile)
    error([ ...
        'The run-level import-control table does not exist:\n%s\n\n' ...
        'Run Step 01 and Step 02 first.'], ...
        importTableFile);
end

% Mandatory publication/reproducibility gate: every enabled source XDF must
% have a successful, current Step 02B BIDS export before analysis proceeds.
verify_bids_export_gate_local(importTableFile, subjectFolder);

%% Run all subjects if no subject specified

if isempty(strtrim(subjectFolder))

    subjectFolders = discover_subject_ids_from_import_table(importTableFile);
    subjectFolders = subjectFolders(hipexo.subject_is_selected(subjectFolders));

    if isempty(subjectFolders)
        error('No canonical SubjectID rows are enabled in the import table.');
    end

    batchStatus = table();

    for iSubject = 1:numel(subjectFolders)

        fprintf('\nSubject %d/%d: %s\n', ...
            iSubject, numel(subjectFolders), subjectFolders(iSubject));

        try
            currentStatus = step03_check_grf_gait_cycles( ...
                char(subjectFolders(iSubject)), ...
                'ForceReprocess', forceReprocess, ...
                'ForceGRFExtraction', forceGRFExtraction, ...
                'ForceGaitDetection', forceGaitDetection);

            if isempty(batchStatus)
                batchStatus = currentStatus;
            else
                batchStatus = [batchStatus; currentStatus]; %#ok<AGROW>
            end

        catch subjectError
            fprintf(2, ...
                '\nSubject failed:\n%s\nReason:\n%s\n', ...
                subjectFolders(iSubject), ...
                subjectError.message);

            failureRow = failed_subject_status_row_local( ...
                subjectFolders(iSubject), ...
                subjectError.message);

            if isempty(batchStatus)
                batchStatus = failureRow;
            else
                batchStatus = [batchStatus; failureRow]; %#ok<AGROW>
            end
        end
    end

    if isempty(batchStatus)
        error('No subject produced a valid batch-status table.');
    end

    masterBatchLog = fullfile( ...
        grfSegmentationFolder, ...
        'GRF_gait_all_subjects_batch_status.csv');

    if isfile(masterBatchLog) && ~isempty(config_processing_scope())
        previous = hipexo.read_csv_with_string_text(masterBatchLog);
        previous = previous(~hipexo.subject_is_selected(previous.Subject), :);
        if ~isempty(previous)
            assert(all(ismember(batchStatus.Properties.VariableNames, previous.Properties.VariableNames)), ...
                'Previous master GRF status has a different schema. Use subjects = [] once.');
            batchStatus = [previous(:, batchStatus.Properties.VariableNames); batchStatus];
        end
    end
    writetable(batchStatus, masterBatchLog);

    return;
end

%% Canonical subject and recording selection

subjectID = resolve_subject_id_local(subjectFolder, importTableFile);
selectedRecordings = select_subject_recordings_from_import_table( ...
    subjectID, importTableFile);

if isempty(selectedRecordings)
    error('No gait-analysis-enabled recordings remain for %s.', subjectID);
end

xdfPaths = string(selectedRecordings.XdfPath);

%% TRUE LSL ORDER (source XDF timestamps only)

[xdfPaths, ...
 eegFirstLSLTime, ...
 eegLastLSLTime, ...
 grfFirstLSLTime, ...
 grfLastLSLTime] = ...
    sort_xdf_by_true_eeg_lsl_time(xdfPaths);

% Reorder the manifest rows to exactly the same chronological XDF order.
normalizedSelected = normalize_path_text(string(selectedRecordings.XdfPath));
normalizedSorted = normalize_path_text(xdfPaths);
[found, order] = ismember(normalizedSorted, normalizedSelected);
if ~all(found) || numel(unique(order)) ~= height(selectedRecordings)
    error('Could not align selected manifest rows with chronological XDF order.');
end
selectedRecordings = selectedRecordings(order,:);

subjectOutputName = string(subjectID);
subjectOutputFolder = fullfile( ...
    grfSegmentationFolder, char(subjectOutputName));
subjectGRFOutputFolder = fullfile(subjectOutputFolder, 'GRF');
if ~isfolder(subjectOutputFolder), mkdir(subjectOutputFolder); end
if ~isfolder(subjectGRFOutputFolder), mkdir(subjectGRFOutputFolder); end

batchLogFile = fullfile( ...
    subjectOutputFolder, ...
    [char(subjectOutputName) '_GRF_gait_batch_status.csv']);

%% File/session information

sessionNames = string(selectedRecordings.BidsSession);
xdfNames = strings(numel(xdfPaths), 1);
bidsEEGLABSets = string(selectedRecordings.BidsEEGLABSet);
originalSubjectIDs = string(selectedRecordings.OriginalSubjectID);

for iFile = 1:numel(xdfPaths)
    [~, currentName, currentExtension] = fileparts(char(xdfPaths(iFile)));
    xdfNames(iFile) = string([currentName currentExtension]);
end

eegLSLDurationSec = eegLastLSLTime - eegFirstLSLTime;
grfLSLDurationSec = grfLastLSLTime - grfFirstLSLTime;

grfEEGLSLOverlapSec = max( ...
    0, ...
    min(eegLastLSLTime, grfLastLSLTime) - ...
    max(eegFirstLSLTime, grfFirstLSLTime));

%% Batch table

nFiles = numel(xdfPaths);

batchStatus = table( ...
    repmat(subjectOutputName, nFiles, 1), ...
    sessionNames, ...
    xdfPaths, ...
    bidsEEGLABSets, ...
    eegFirstLSLTime, ...
    eegLastLSLTime, ...
    eegLSLDurationSec, ...
    grfFirstLSLTime, ...
    grfLastLSLTime, ...
    grfLSLDurationSec, ...
    grfEEGLSLOverlapSec, ...
    repmat("pending", nFiles, 1), ...
    repmat("pending", nFiles, 1), ...
    repmat("pending", nFiles, 1), ...
    repmat("pending", nFiles, 1), ...
    strings(nFiles, 1), ...
    strings(nFiles, 1), ...
    strings(nFiles, 1), ...
    strings(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    nan(nFiles, 1), ...
    repmat("pending", nFiles, 1), ...
    strings(nFiles, 1), ...
    strings(nFiles, 1), ...
    strings(nFiles, 1), ...
    'VariableNames', { ...
        'Subject', ...
        'SessionFolder', ...
        'XDFPath', ...
        'BidsEEGLABSet', ...
        'EEG_LSL_Start', ...
        'EEG_LSL_End', ...
        'EEG_LSL_DurationSec', ...
        'GRF_LSL_Start', ...
        'GRF_LSL_End', ...
        'GRF_LSL_DurationSec', ...
        'GRF_EEG_LSL_OverlapSec', ...
        'OverallStatus', ...
        'GRFExtractionStatus', ...
        'GaitEventStatus', ...
        'EEGMappingStatus', ...
        'GRFStreamFile', ...
        'GaitEventFile', ...
        'EEGSetFile', ...
        'MappingCSVFile', ...
        'MappedEventCount', ...
        'ExcludedEventCount', ...
        'FirstGRFEventSample', ...
        'FirstGRFEventLSLTime', ...
        'FirstMappedEEGSample', ...
        'FirstMatchedEEGLSLTime', ...
        'LastGRFEventSample', ...
        'LastGRFEventLSLTime', ...
        'LastMappedEEGSample', ...
        'LastMatchedEEGLSLTime', ...
        'MedianAbsMappingErrorMs', ...
        'MaxAbsMappingErrorMs', ...
        'EEGBoundaryCount', ...
        'SubjectMergeStatus', ...
        'SubjectMergedSetFile', ...
        'CompletedAt', ...
        'ErrorMessage'});

batchStatus.GRFRecommendedCycleCount = zeros(nFiles, 1);
batchStatus.GRFGaitQCStatus = repmat("pending", nFiles, 1);

%% Process XDFs

for iFile = 1:nFiles

    currentXDF = char(xdfPaths(iFile));
    currentBidsEEGLABSet = char(bidsEEGLABSets(iFile));

    if ~isfile(currentBidsEEGLABSet)
        error('Canonical BIDS-derived EEGLAB input is missing:\n%s', ...
            currentBidsEEGLABSet);
    end

    [~, bidsRawBaseName] = fileparts(currentBidsEEGLABSet);
    outputStem = regexprep(bidsRawBaseName, '_desc-bidsraw_eeg$', '');

    grfStreamFile = fullfile( ...
        subjectGRFOutputFolder, ...
        [outputStem '_GRF_stream.mat']);

    gaitEventFile = fullfile( ...
        subjectGRFOutputFolder, ...
        [outputStem '_GRF_gait_events.mat']);

    batchStatus.GRFStreamFile(iFile) = string(grfStreamFile);
    batchStatus.GaitEventFile(iFile) = string(gaitEventFile);
    batchStatus.EEGSetFile(iFile) = "";
    batchStatus.MappingCSVFile(iFile) = "";

    try

        %% GRF extraction

        batchStatus.GRFExtractionStatus(iFile) = "running";

        reuseGRF = false;
        reuseGRFReason = "output_missing_or_forced";

        if isfile(grfStreamFile) && ~forceGRFExtraction
            [reuseGRF, reuseGRFReason] = ...
                verify_grf_reuse_local( ...
                    grfStreamFile, ...
                    currentXDF, ...
                    expectedGRFExtractionVersion, cfg);
        end

        if reuseGRF

            batchStatus.GRFExtractionStatus(iFile) = ...
                "reused_verified";

        else

            step03_extract_and_segment_grf_internal( ...
                currentXDF, ...
                subjectGRFOutputFolder, ...
                true, ...
                outputStem, ...
                subjectOutputName);

            if ~isfile(grfStreamFile)
                error('GRF stream was not created:\n%s', grfStreamFile);
            end

            batchStatus.GRFExtractionStatus(iFile) = "completed";
        end

        close all;

        %% Gait events

        batchStatus.GaitEventStatus(iFile) = "running";

        reuseGait = false;
        reuseGaitReason = "output_missing_or_forced";

        if isfile(gaitEventFile) && ~forceGaitDetection
            [reuseGait, reuseGaitReason] = ...
                verify_gait_reuse_local( ...
                    gaitEventFile, ...
                    grfStreamFile, ...
                    expectedGaitEventVersion, ...
                    cfg);
        end

        if reuseGait

            batchStatus.GaitEventStatus(iFile) = ...
                "reused_verified";

        else

            step03_detect_grf_gait_events_internal( ...
                grfStreamFile, ...
                subjectGRFOutputFolder, ...
                true);

            if ~isfile(gaitEventFile)
                error('Gait-event file was not created:\n%s', gaitEventFile);
            end

            batchStatus.GaitEventStatus(iFile) = "completed";
        end

        close all;

        %% Defer EEG mapping until after GRF gait-cycle QC

        batchStatus.EEGMappingStatus(iFile) = "deferred_to_step04";
        batchStatus.OverallStatus(iFile) = "grf_completed";
        batchStatus.CompletedAt(iFile) = current_time_text;
        batchStatus.ErrorMessage(iFile) = "";

    catch currentError

        if batchStatus.GRFExtractionStatus(iFile) == "running"
            batchStatus.GRFExtractionStatus(iFile) = "failed";
        end

        if batchStatus.GaitEventStatus(iFile) == "running"
            batchStatus.GaitEventStatus(iFile) = "failed";
        end

        batchStatus.EEGMappingStatus(iFile) = "not_run_step03_failed";
        batchStatus.OverallStatus(iFile) = "failed";
        batchStatus.CompletedAt(iFile) = current_time_text;
        batchStatus.ErrorMessage(iFile) = ...
            sanitize_error_message_local(currentError.message);

        fprintf(2, ...
            '\nBatch result: FAILED\n%s\n', ...
            currentError.message);
    end

    close all;

    writetable(batchStatus, batchLogFile);
end

%% Rebuild subject-level shared GRF tables

% The selected per-recording MAT files define the complete shared tables.
rebuild_subject_grf_shared_tables_local( ...
    batchStatus, ...
    subjectGRFOutputFolder);

%% GRF-only gait-cycle QC

batchStatus = run_subject_grf_cycle_qc_local( ...
    batchStatus, ...
    subjectOutputFolder, ...
    cfg);

batchStatus.SubjectMergeStatus(:) = "deferred_to_step04";
batchStatus.SubjectMergedSetFile(:) = "";

writetable(batchStatus, batchLogFile);

end

% STEP-03 ORCHESTRATION HELPERS

function nominalSrate = batch_xdf_stream_nominal_srate(stream)

nominalSrate = NaN;

if ~isfield(stream, 'info') || ...
        ~isfield(stream.info, 'nominal_srate')
    return;
end

rawValue = stream.info.nominal_srate;

while iscell(rawValue) && ~isempty(rawValue)
    rawValue = rawValue{1};
end

if isnumeric(rawValue)
    nominalSrate = double(rawValue(1));
else
    nominalSrate = str2double(string(rawValue));
end

end

function textValue = batch_xdf_stream_text_field(stream, fieldName)

textValue = "";

if ~isfield(stream, 'info') || ...
        ~isfield(stream.info, fieldName)
    return;
end

rawValue = stream.info.(fieldName);

while iscell(rawValue) && ~isempty(rawValue)
    rawValue = rawValue{1};
end

if isempty(rawValue)
    return;
end

textValue = string(rawValue);
textValue = textValue(1);

end

function value = current_time_text
value = string(datetime('now','TimeZone','local','Format','yyyy-MM-dd HH:mm:ss'));
end

function subjectIDs = discover_subject_ids_from_import_table(importTableFile)

T = read_import_table_local(importTableFile);

if ~ismember('SubjectID', T.Properties.VariableNames)

    error('Import table is missing SubjectID. Re-run Step 02.');
end

gaitGate = gait_analysis_gate_local(T);

subjectIDs = unique( ...
    strtrim(string(T.SubjectID(gaitGate == 1))), ...
    'stable');

subjectIDs(subjectIDs == "" | ismissing(subjectIDs)) = [];

subjectIDs = sort(subjectIDs);

end

