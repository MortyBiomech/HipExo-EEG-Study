function [ ...
        outputCells, ...
        separatorExcelRows ...
    ] = ...
        table_to_cells_with_subject_separators_local( ...
            T, ...
            canonicalColumns)

    % GOAL
    %   Insert a clearly labelled visual separator immediately before each
    %   new subject.
    % Example:
    %   sub-Pilot2_1 ... IC 58
    %   NEXT SUBJECT: sub-Pilot2_3
    %   sub-Pilot2_3 ... IC 1
    % The separator row is NOT a real IC row:
    %   Session      = blank
    %   Dataset/File = blank
    %   IC           = blank
    % Therefore it cannot enter downstream IC selection.

    T = ...
        T(:, canonicalColumns);


    if isempty(T)

        outputCells = ...
            cell( ...
                0, ...
                width(T));

        separatorExcelRows = ...
            zeros(0, 1);

        return;
    end


    subjectValues = ...
        string(T.Subject);

    subjectValues( ...
        ismissing(subjectValues)) = "";


    rawCells = ...
        table2cell(T);

    nRows = ...
        height(T);

    nColumns = ...
        width(T);


    subjectChange = ...
        false( ...
            nRows, ...
            1);

    if nRows > 1

        subjectChange(2:end) = ...
            subjectValues(2:end) ~= ...
            subjectValues(1:end-1);
    end


    nSeparators = ...
        sum(subjectChange);


    outputCells = ...
        cell( ...
            nRows + ...
            nSeparators, ...
            nColumns);


    separatorExcelRows = ...
        zeros( ...
            nSeparators, ...
            1);


    outputRow = 0;
    separatorCounter = 0;


    for row = 1:nRows

        if row > 1 && ...
                subjectChange(row)

            outputRow = ...
                outputRow + 1;

            separatorCounter = ...
                separatorCounter + 1;


            % Start with a completely empty separator row.
            outputCells( ...
                outputRow, ...
                :) = ...
                repmat( ...
                    {''}, ...
                    1, ...
                    nColumns);


            % Only the Subject column contains a readable visual label.
            outputCells{ ...
                outputRow, ...
                1} = ...
                char( ...
                    "NEXT SUBJECT: " + ...
                    subjectValues(row));


            % Excel row 1 contains the header, therefore +1 here.
            separatorExcelRows( ...
                separatorCounter) = ...
                outputRow + 1;

        end


        outputRow = ...
            outputRow + 1;


        outputCells( ...
            outputRow, ...
            :) = ...
            rawCells( ...
                row, ...
                :);

    end

end


function format_subject_separator_rows_local( ...
        workbookPath, ...
        sheetName, ...
        separatorExcelRows, ...
        nColumns)

    % GOAL
    %   Highlight the complete visual subject-separator rows.
    % Windows + Microsoft Excel:
    %   Uses Excel COM automation to apply a light-yellow fill and bold text.
    % Other environments / Excel unavailable:
    %   No processing failure. The textual "NEXT SUBJECT: ..." label remains
    %   visible, so the workbook is still fully usable.

    if isempty(separatorExcelRows)

        return;
    end


    if ~ispc

        warning([ ...
            'Excel colour formatting was skipped because COM automation ' ...
            'is only available on Windows. Subject separator text remains.']);

        return;
    end


    excel = [];
    workbook = [];


    try

        excel = ...
            actxserver( ...
                'Excel.Application');

        excel.Visible = false;
        excel.DisplayAlerts = false;


        workbook = ...
            excel.Workbooks.Open( ...
                char(workbookPath));


        worksheet = ...
            workbook.Worksheets.Item( ...
                char(sheetName));


        lastColumnLetter = ...
            excel_column_name_local( ...
                nColumns);


        for k = 1:numel(separatorExcelRows)

            rowNumber = ...
                separatorExcelRows(k);


            rangeText = ...
                sprintf( ...
                    'A%d:%s%d', ...
                    rowNumber, ...
                    lastColumnLetter, ...
                    rowNumber);


            rowRange = ...
                worksheet.Range(rangeText);


            % Excel ColorIndex 36 = light yellow.
            rowRange.Interior.ColorIndex = 36;

            rowRange.Font.Bold = true;

            rowRange.RowHeight = 22;


            % Add borders so the separator remains obvious even with
            % different Excel themes.
            try
                rowRange.Borders.LineStyle = 1;
            catch
            end

        end


        workbook.Save();

        workbook.Close(false);

        excel.Quit();

        delete(excel);


        fprintf( ...
            'Applied coloured formatting to %d subject separator row(s).\n', ...
            numel(separatorExcelRows));


    catch ME

        warning([ ...
            'Could not apply Excel colour formatting.\n' ...
            'The NEXT SUBJECT text separators were still written and the ' ...
            'workbook remains valid.\nReason: %s'], ...
            ME.message);


        try

            if ~isempty(workbook)

                workbook.Close(false);
            end

        catch
        end


        try

            if ~isempty(excel)

                excel.Quit();
            end

        catch
        end


        try

            if ~isempty(excel)

                delete(excel);
            end

        catch
        end

    end

end


function columnName = ...
        excel_column_name_local( ...
            columnNumber)

    % Convert:
    %   1  -> A
    %   26 -> Z
    %   27 -> AA
    % Current review table has 17 columns -> Q.

    if ~isscalar(columnNumber) || ...
            columnNumber < 1 || ...
            columnNumber ~= floor(columnNumber)

        error( ...
            'Invalid Excel column number.');
    end


    columnName = "";


    while columnNumber > 0

        remainder = ...
            mod( ...
                columnNumber - 1, ...
                26);

        columnName = ...
            string( ...
                char( ...
                    double('A') + ...
                    remainder)) + ...
            columnName;

        columnNumber = ...
            floor( ...
                ( ...
                    columnNumber - 1 ...
                ) / ...
                26);

    end


    columnName = ...
        char(columnName);

end