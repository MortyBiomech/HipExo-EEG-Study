            strtrim(T.Subject)) > 0 & ...
        strlength( ...
            strtrim(T.Session)) > 0 & ...
        strlength( ...
            strtrim(T.("Dataset/File"))) > 0 & ...
        isfinite(T.IC) & ...
        T.IC >= 1;

end


