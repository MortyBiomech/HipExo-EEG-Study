function step09_update_manual_ic_review()
% GOAL
%   Automatically create/update one manual cortical IC review workbook from
%   all Step-08-approved subject-level preprocessed_and_ICA datasets.
%
% INPUT
%   subject_level_EEG_table.csv from Steps 07/08.
%   PreprocessedICASetPath for every ICA-QC-approved subject.
%
% APPROACH
%   1. Restore MATLAB/EEGLAB figure visibility for interactive IC review.
%   2. Automatically load every Step-08-approved preprocessed_and_ICA.set.
%   3. Include every IC and record ICLabel probabilities, DIPFIT RV, and
%      representative dipole coordinates.
%   4. Preserve existing ManualReviewReason / ManualFinalDecision by the
%      Subject + Session + Dataset/File + IC + ICAIdentity key.
%   5. Rebuild the workbook from the currently approved datasets only.
%   6. Insert a clearly labelled separator row between subjects.
%   7. On Windows with Microsoft Excel available, colour the complete
%      separator row light yellow and make its label bold.
%
% OUTPUT
%   output_data/manual_IC_selection_final.xlsx
%
% USED BY
%   step11_create_rhs_epoched_study.m

clc;
%  RESTORE INTERACTIVE FIGURE BEHAVIOR
restore_interactive_figures_local();
%  PATHS / CONFIGURATION
thisFile = mfilename('fullpath');

if isempty(thisFile)
    error('Could not resolve the current Step file path.');
end

scriptsRoot = fileparts(fileparts(thisFile));

addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();

bemobil_config = ...
    config_step05_09_eeg_preprocessing_ica(P);

mappingFile = ...
    P.subjectLevelEEGTableFile;

outputFolder = ...
    P.outputFolder;

manualICWorkbook = ...
    string(fullfile( ...
        outputFolder, ...
        bemobil_config.manualICReview.workbookName));

manualICSheetName = ...
    bemobil_config.manualICReview.sheetName;
%  REVIEW TABLE SCHEMA
canonicalColumns = { ...
    'Subject', ...
    'Session', ...
    'Dataset/File', ...
    'IC', ...
    'BrainPercent', ...
    'RVPercent', ...
    'DipoleX', ...
    'DipoleY', ...
    'DipoleZ', ...
    'Top1Class', ...
    'Top1Percent', ...
    'Top2Class', ...
    'Top2Percent', ...
    'Top3Class', ...
    'Top3Percent', ...
    'ManualReviewReason', ...
    'ManualFinalDecision', ...
    'ICAIdentity' ...
};
%  INPUT CHECK
if exist(mappingFile, 'file') ~= 2

    error([ ...
        'Subject-level processing table not found:\n%s\n' ...
        'Run Step 08 successfully first.'], ...
        mappingFile);
end

if ~exist('pop_loadset', 'file')

    eeglab nogui;
    restore_interactive_figures_local();
end
%  READ SUBJECT-LEVEL TABLE
opts = ...
    detectImportOptions( ...
        mappingFile, ...
        'FileType', 'text', ...
        'Delimiter', ',', ...
        'VariableNamingRule', 'preserve');

sourceMap = ...
    readtable(mappingFile, opts);
%  CHECK REQUIRED COLUMNS
requiredColumns = { ...
    'BidsSubject', ...
    'BidsSession', ...
    'PreprocessedICASetPath', ...
    'ICAQCStatus' ...
};

for c = 1:numel(requiredColumns)

    if ~ismember( ...
            requiredColumns{c}, ...
            sourceMap.Properties.VariableNames)

        error( ...
            'Subject-level table is missing required column: %s', ...
            requiredColumns{c});
    end
end
%  NORMALIZE REQUIRED TABLE COLUMNS
if ~isnumeric(sourceMap.BidsSubject)

    sourceMap.BidsSubject = ...
        str2double(string(sourceMap.BidsSubject));
end

sourceMap.BidsSession = ...
    string(sourceMap.BidsSession);

sourceMap.PreprocessedICASetPath = ...
    string(sourceMap.PreprocessedICASetPath);

sourceMap.ICAQCStatus = ...
    string(sourceMap.ICAQCStatus);

sourceMap.BidsSession( ...
    ismissing(sourceMap.BidsSession)) = "";

sourceMap.PreprocessedICASetPath( ...
    ismissing(sourceMap.PreprocessedICASetPath)) = "";

sourceMap.ICAQCStatus( ...
    ismissing(sourceMap.ICAQCStatus)) = "";
%  SELECT STEP-08-APPROVED DATASETS
eligibleRows = ...
    find( ...
        sourceMap.ICAQCStatus == ...
            "passed_ica_quality_basic_checks" & ...
        strlength( ...
            strtrim( ...
                sourceMap.PreprocessedICASetPath)) > 0);

if isempty(eligibleRows)

    error([ ...
        'No Step-08-approved preprocessed_and_ICA dataset was found.\n' ...
        'Run step08_check_amica_quality.m successfully first.']);
end

% Avoid processing the same dataset twice.
eligiblePaths = ...
    sourceMap.PreprocessedICASetPath(eligibleRows);

[~, uniquePathIndex] = ...
    unique( ...
        eligiblePaths, ...
        'stable');

rowsToReview = ...
    eligibleRows(uniquePathIndex);

%  BUILD CURRENT IC REVIEW TABLE
currentTables = ...
    cell( ...
        numel(rowsToReview), ...
        1);

for d = 1:numel(rowsToReview)

    row = ...
        rowsToReview(d);

    setPath = ...
        strtrim( ...
            sourceMap.PreprocessedICASetPath(row));

    if exist(char(setPath), 'file') ~= 2

        error( ...
            'PreprocessedICASetPath does not exist:\n%s', ...
            setPath);
    end

    EEG_review = ...
        load_ica_header_local(setPath);

    [ ...
        subjectLabel, ...
        sessionLabel, ...
        datasetFile ...
    ] = ...
        resolve_identity_from_table_local( ...
            sourceMap, ...
            row, ...
            setPath);

    currentTables{d} = ...
        build_ic_table_local( ...
            EEG_review, ...
            subjectLabel, ...
            sessionLabel, ...
            datasetFile, ...
            canonicalColumns);

end

currentTable = ...
    vertcat(currentTables{:});

currentTable = ...
    normalize_review_table_local( ...
        currentTable, ...
        canonicalColumns);
%  CHECK CURRENT IC IDENTITY UNIQUENESS
currentKey = ...
    review_key_local(currentTable);

if numel(unique(currentKey)) ~= ...
        height(currentTable)

    error([ ...
        'Current IC table contains duplicate ' ...
        'Subject + Session + Dataset/File + IC + ICAIdentity rows.']);
end
%  PRESERVE EXISTING MANUAL REVIEW
% The current Step-08-approved datasets define the complete workbook.
% The previous workbook is used only to restore manual entries for ICs
% that still exist in the current datasets.

masterTable = ...
    currentTable;

backupFile = "";

if exist(manualICWorkbook, 'file') == 2

    existingTable = ...
        read_review_table_local( ...
            manualICWorkbook, ...
            manualICSheetName);

    identityColumns = { ...
        'Subject', ...
        'Session', ...
        'Dataset/File', ...
        'IC' ...
    };

    if all( ...
            ismember( ...
                identityColumns, ...
                existingTable.Properties.VariableNames))

        existingTable = ...
            normalize_review_table_local( ...
                existingTable, ...
                canonicalColumns);

        % Remove old visual separator rows.
        existingTable = ...
            existingTable( ...
                valid_ic_rows_local(existingTable), ...
                :);

        existingKey = ...
            review_key_local(existingTable);

        if numel(unique(existingKey)) ~= ...
                height(existingTable)

            error([ ...
                'Existing workbook contains duplicate ' ...
                'Subject + Session + Dataset/File + IC + ICAIdentity rows.']);
        end

        [ ...
            hasOldReview, ...
            oldLocation ...
        ] = ...
            ismember( ...
                currentKey, ...
                existingKey);

        oldReviewed = strlength(strtrim(existingTable.ManualFinalDecision)) > 0 | ...
            strlength(strtrim(existingTable.ManualReviewReason)) > 0;
        unmatchedReview = oldReviewed & ~ismember(existingKey, currentKey);
        if any(unmatchedReview)
            backupFile = backup_workbook_local(manualICWorkbook, 'unmatched_review');
            warning(['%d previous IC reviews do not match a current ICA identity. ' ...
                'They were retained in the backup and were not transferred.'], ...
                sum(unmatchedReview));
        end

        masterTable.ManualReviewReason(hasOldReview) = ...
            existingTable.ManualReviewReason( ...
                oldLocation(hasOldReview));

        masterTable.ManualFinalDecision(hasOldReview) = ...
            existingTable.ManualFinalDecision( ...
                oldLocation(hasOldReview));

    else

        backupFile = ...
            backup_workbook_local( ...
                manualICWorkbook, ...
                'incompatible_schema');

        warning([ ...
            'Existing workbook does not contain the required IC identity ' ...
            'columns. It was backed up and will be replaced.']);
    end
end
%  FINAL NORMALIZATION / SORTING
masterTable = ...
    normalize_review_table_local( ...
        masterTable, ...
        canonicalColumns);

masterTable = ...
    sortrows( ...
        masterTable, ...
        { ...
            'Subject', ...
            'Session', ...
            'Dataset/File', ...
            'IC' ...
        });

finalKey = ...
    review_key_local(masterTable);

if numel(unique(finalKey)) ~= ...
        height(masterTable)

    error( ...
        'Final manual IC workbook would contain duplicate IC identities.');
end
%  PREPARE OUTPUT FOLDER
if exist(outputFolder, 'dir') ~= 7
    mkdir(outputFolder);
end
%  TEMPORARY WORKBOOK
temporaryWorkbook = ...
    string(fullfile( ...
        outputFolder, ...
        [ ...
            'manual_IC_selection_writing_' ...
            char(datetime( ...
                'now', ...
                'Format', ...
                'yyyyMMdd_HHmmss_SSS')) ...
            '.xlsx' ...
        ]));
%  CONVERT TABLE TO CELLS WITH SUBJECT SEPARATORS
[ ...
    workbookCells, ...
    separatorExcelRows ...
] = ...
    table_to_cells_with_subject_separators_local( ...
        masterTable, ...
        canonicalColumns);
%  WRITE MANUAL REVIEW SHEET
writecell( ...
    [ ...
        canonicalColumns; ...
        workbookCells ...
    ], ...
    temporaryWorkbook, ...
    'Sheet', ...
    manualICSheetName, ...
    'Range', ...
    'A1');
%  FORMAT SUBJECT SEPARATOR ROWS
format_subject_separator_rows_local( ...
    temporaryWorkbook, ...
    manualICSheetName, ...
    separatorExcelRows, ...
    numel(canonicalColumns));
%  REPLACE FINAL WORKBOOK
[ ...
    moveSucceeded, ...
    moveMessage ...
] = ...
    movefile( ...
        temporaryWorkbook, ...
        manualICWorkbook, ...
        'f');

if ~moveSucceeded

    if exist(temporaryWorkbook, 'file') == 2
        delete(temporaryWorkbook);
    end

    error([ ...
        'Could not replace the manual IC workbook.\n' ...
        'Close the workbook in Excel and rerun Step 09.\n' ...
        'Reason: %s\n' ...
        'Target:\n%s'], ...
        moveMessage, ...
        manualICWorkbook);
end
%  REPORT

%  LEAVE MATLAB / EEGLAB IN INTERACTIVE MODE
restore_interactive_figures_local();
%% END OF STEP
end
% STEP-LOCAL FUNCTIONS
function T = ...
        build_ic_table_local( ...
            EEG, ...
            subjectLabel, ...
            sessionLabel, ...
            datasetFile, ...
            canonicalColumns)
    %  ICA
    if ~isfield(EEG, 'icaweights') || ...
            isempty(EEG.icaweights)

        error( ...
            'Dataset does not contain ICA weights: %s', ...
            datasetFile);
    end

    nIC = ...
        size(EEG.icaweights, 1);
    %  ICLABEL
    if ~isfield(EEG, 'etc') || ...
            ~isfield(EEG.etc, 'ic_classification') || ...
            ~isfield( ...
                EEG.etc.ic_classification, ...
                'ICLabel') || ...
            ~isfield( ...
                EEG.etc.ic_classification.ICLabel, ...
                'classifications')

        error( ...
            'Dataset does not contain ICLabel classifications: %s', ...
            datasetFile);
    end

    probs = ...
        double( ...
            EEG.etc.ic_classification.ICLabel.classifications);

    if size(probs, 1) ~= nIC || ...
            size(probs, 2) ~= 7

        error([ ...
            'ICLabel dimensions do not match ICA.\n' ...
            'Dataset: %s | ICs: %d | ICLabel: %d x %d'], ...
            datasetFile, ...
            nIC, ...
            size(probs, 1), ...
            size(probs, 2));
    end

    if any(~isfinite(probs(:)))

        error( ...
            'ICLabel contains NaN/Inf: %s', ...
            datasetFile);
    end

    classNames = ...
        resolve_iclabel_class_names_local( ...
            EEG.etc.ic_classification.ICLabel);

    [ ...
        sortedProbabilities, ...
        sortedClassIndices ...
    ] = ...
        sort( ...
            probs, ...
            2, ...
            'descend');

    Top1Class = ...
        reshape( ...
            classNames( ...
                sortedClassIndices(:, 1)), ...
            [], ...
            1);

    Top1Percent = ...
        100 * ...
        sortedProbabilities(:, 1);

    Top2Class = ...
        reshape( ...
            classNames( ...
                sortedClassIndices(:, 2)), ...
            [], ...
            1);

    Top2Percent = ...
        100 * ...
        sortedProbabilities(:, 2);

    Top3Class = ...
        reshape( ...
            classNames( ...
                sortedClassIndices(:, 3)), ...
            [], ...
            1);

    Top3Percent = ...
        100 * ...
        sortedProbabilities(:, 3);

    brainClassIndex = ...
        find( ...
            strcmpi( ...
                classNames, ...
                "Brain"), ...
            1, ...
            'first');

    if isempty(brainClassIndex)

        error( ...
            'ICLabel Brain class was not found: %s', ...
            datasetFile);
    end

    BrainPercent = ...
        100 * ...
        probs(:, brainClassIndex);
    %  DIPFIT
    if ~isfield(EEG, 'dipfit') || ...
            ~isfield(EEG.dipfit, 'model') || ...
            numel(EEG.dipfit.model) ~= nIC

        error( ...
            'DIPFIT model count does not match ICA: %s', ...
            datasetFile);
    end

    RVPercent = ...
        nan(nIC, 1);

    DipoleX = ...
        nan(nIC, 1);

    DipoleY = ...
        nan(nIC, 1);

    DipoleZ = ...
        nan(nIC, 1);

    for ic = 1:nIC

        model = ...
            EEG.dipfit.model(ic);

        if ~isfield(model, 'rv') || ...
                isempty(model.rv) || ...
                ~isnumeric(model.rv) || ...
                ~isfinite(double(model.rv(1)))

            error( ...
                'IC %d has no valid DIPFIT RV: %s', ...
                ic, ...
                datasetFile);
        end

        RVPercent(ic) = ...
            100 * ...
            double(model.rv(1));

        if ~isfield(model, 'posxyz') || ...
                isempty(model.posxyz) || ...
                ~isnumeric(model.posxyz) || ...
                any(~isfinite(double(model.posxyz(:))))

            error( ...
                'IC %d has no valid DIPFIT position: %s', ...
                ic, ...
                datasetFile);
        end

        xyz = ...
            hipexo.representative_dipole_xyz(model);

        if numel(xyz) ~= 3 || ...
                any(~isfinite(double(xyz(:))))

            error( ...
                'Could not resolve dipole coordinates for IC %d: %s', ...
                ic, ...
                datasetFile);
        end

        DipoleX(ic) = xyz(1);
        DipoleY(ic) = xyz(2);
        DipoleZ(ic) = xyz(3);
    end
    %  BUILD TABLE
    Subject = ...
        repmat( ...
            string(subjectLabel), ...
            nIC, ...
            1);

    Session = ...
        repmat( ...
            string(sessionLabel), ...
            nIC, ...
            1);

    DatasetFile = ...
        repmat( ...
            string(datasetFile), ...
            nIC, ...
            1);

    IC = ...
        (1:nIC)';

    ManualReviewReason = ...
        strings(nIC, 1);

    ManualFinalDecision = ...
        strings(nIC, 1);
    ICAIdentity = repmat(hipexo.ica_identity_signature(EEG), nIC, 1);

    T = ...
        table( ...
            Subject, ...
            Session, ...
            DatasetFile, ...
            IC, ...
            BrainPercent, ...
            RVPercent, ...
            DipoleX, ...
            DipoleY, ...
            DipoleZ, ...
            Top1Class, ...
            Top1Percent, ...
            Top2Class, ...
            Top2Percent, ...
            Top3Class, ...
            Top3Percent, ...
            ManualReviewReason, ...
            ManualFinalDecision, ...
            ICAIdentity, ...
            'VariableNames', ...
            canonicalColumns);

end

function EEG = ...
        load_ica_header_local( ...
            setPath)

    [ ...
        setFolder, ...
        setName, ...
        setExtension ...
    ] = ...
        fileparts( ...
            char(setPath));

    try

        EEG = ...
            pop_loadset( ...
                'filename', ...
                [setName setExtension], ...
                'filepath', ...
                setFolder, ...
                'loadmode', ...
                'info');

    catch firstLoadError

        warning([ ...
            'Header-only loading failed; retrying normal pop_loadset.\n' ...
            'Dataset: %s\n' ...
            'Reason: %s'], ...
            setPath, ...
            firstLoadError.message);

        EEG = ...
            pop_loadset( ...
                'filename', ...
                [setName setExtension], ...
                'filepath', ...
                setFolder);
    end

end

function [ ...
        subjectLabel, ...
        sessionLabel, ...
        datasetFile ...
    ] = ...
        resolve_identity_from_table_local( ...
            sourceMap, ...
            row, ...
            setPath)

    sessionLabel = ...
        strtrim( ...
            string( ...
                sourceMap.BidsSession(row)));

    [ ...
        ~, ...
        setName, ...
        setExtension ...
    ] = ...
        fileparts( ...
            char(setPath));

    datasetFile = ...
        string( ...
            [ ...
                setName ...
                setExtension ...
            ]);

    bidsSubject = ...
        sourceMap.BidsSubject(row);

    if ~isnumeric(bidsSubject)

        bidsSubject = ...
            str2double( ...
                string(bidsSubject));
    end

    if ~isscalar(bidsSubject) || ...
            ~isfinite(bidsSubject) || ...
            bidsSubject < 1 || ...
            abs(bidsSubject - round(bidsSubject)) > 1e-6

        error( ...
            'Invalid BidsSubject in table row %d.', ...
            row);
    end

    subjectLabel = ...
        "sub-" + ...
        compose( ...
            "%02d", ...
            round(bidsSubject));

    if strlength(sessionLabel) == 0 || ...
            strlength(datasetFile) == 0

        error([ ...
            'Could not resolve Subject / Session / Dataset identity.\n' ...
            'Table row: %d\n' ...
            'Set path: %s'], ...
            row, ...
            setPath);
    end

end

function classNames = ...
        resolve_iclabel_class_names_local( ...
            ICLabel)

    standardClassNames = [ ...
        "Brain", ...
        "Muscle", ...
        "Eye", ...
        "Heart", ...
        "Line Noise", ...
        "Channel Noise", ...
        "Other" ...
    ];

    classNames = ...
        standardClassNames;

    if isfield(ICLabel, 'classes') && ...
            ~isempty(ICLabel.classes)

        rawClassNames = ...
            ICLabel.classes;

        while iscell(rawClassNames) && ...
                isscalar(rawClassNames) && ...
                iscell(rawClassNames{1})

            rawClassNames = ...
                rawClassNames{1};
        end

        suppliedClassNames = ...
            reshape( ...
                string(rawClassNames), ...
                1, ...
                []);

        if numel(suppliedClassNames) == 7 && ...
                all( ...
                    strlength( ...
                        strtrim(suppliedClassNames)) > 0)

            classNames = ...
                suppliedClassNames;
        end
    end

    classNames = ...
        strtrim(classNames);

end

function T = ...
        normalize_review_table_local( ...
            T, ...
            canonicalColumns)

    stringColumns = { ...
        'Subject', ...
        'Session', ...
        'Dataset/File', ...
        'Top1Class', ...
        'Top2Class', ...
        'Top3Class', ...
        'ManualReviewReason', ...
        'ManualFinalDecision', ...
        'ICAIdentity' ...
    };

    numericColumns = ...
        setdiff( ...
            canonicalColumns, ...
            stringColumns, ...
            'stable');

    for c = 1:numel(canonicalColumns)

        name = ...
            canonicalColumns{c};

        if ismember( ...
                name, ...
                T.Properties.VariableNames)

            continue;
        end

        if ismember( ...
                name, ...
                stringColumns)

            T.(name) = ...
                strings( ...
                    height(T), ...
                    1);

        else

            T.(name) = ...
                nan( ...
                    height(T), ...
                    1);
        end
    end

    T = ...
        T(:, canonicalColumns);

    for c = 1:numel(stringColumns)

        name = ...
            stringColumns{c};

        T.(name) = ...
            string(T.(name));

        T.(name)( ...
            ismissing(T.(name))) = "";

        blankLike = ...
            strcmpi( ...
                strtrim(T.(name)), ...
                "NaN") | ...
            strcmpi( ...
                strtrim(T.(name)), ...
                "<missing>") | ...
            strcmpi( ...
                strtrim(T.(name)), ...
                "missing");

        T.(name)(blankLike) = "";
    end

    for c = 1:numel(numericColumns)

        name = ...
            numericColumns{c};

        if isnumeric(T.(name)) || ...
                islogical(T.(name))

            T.(name) = ...
                double(T.(name));

        else

            T.(name) = ...
                str2double( ...
                    string(T.(name)));
        end
    end

end

function T = ...
        read_review_table_local( ...
            workbookPath, ...
            sheetName)

    cells = ...
        readcell( ...
            workbookPath, ...
            'Sheet', ...
            sheetName);

    if isempty(cells)

        error( ...
            'Existing manual IC workbook sheet is empty.');
    end

    headers = ...
        string(cells(1, :));

    headers( ...
        ismissing(headers)) = "";

    headers = ...
        strtrim(headers);

    validHeader = ...
        strlength(headers) > 0 & ...
        ~strcmpi(headers, "NaN") & ...
        ~strcmpi(headers, "<missing>");

    if ~any(validHeader)

        error( ...
            'Existing manual IC workbook has no usable headers.');
    end

    retainedHeaders = ...
        headers(validHeader);

    if numel(unique(lower(retainedHeaders))) ~= ...
            numel(retainedHeaders)

        error( ...
            'Existing manual IC workbook has duplicate headers.');
    end

    if size(cells, 1) == 1

        dataCells = ...
            cell( ...
                0, ...
                sum(validHeader));

    else

        dataCells = ...
            cells( ...
                2:end, ...
                validHeader);
    end

    T = ...
        cell2table( ...
            dataCells, ...
            'VariableNames', ...
            cellstr(retainedHeaders));

end

function key = ...
        review_key_local(T)

    key = ...
        lower( ...
            strtrim(T.Subject)) + "|" + ...
        lower( ...
            strtrim(T.Session)) + "|" + ...
        lower( ...
            strtrim(T.("Dataset/File"))) + "|" + ...
        string(T.IC) + "|ica=" + strtrim(T.ICAIdentity);

end

function validRows = ...
        valid_ic_rows_local(T)

    validRows = ...
        strlength( ...
            strtrim(T.Subject)) > 0 & ...
        strlength( ...
            strtrim(T.Session)) > 0 & ...
        strlength( ...
            strtrim(T.("Dataset/File"))) > 0 & ...
        isfinite(T.IC) & ...
        T.IC >= 1 & ...
        abs(T.IC - round(T.IC)) < 1e-6;

end

function [ ...
        outputCells, ...
        separatorExcelRows ...
    ] = ...
        table_to_cells_with_subject_separators_local( ...
            T, ...
            canonicalColumns)

    T = ...
        T(:, canonicalColumns);

    if isempty(T)

        outputCells = ...
            cell( ...
                0, ...
                width(T));

        separatorExcelRows = ...
            zeros(0, 1);

        return;
    end

    subjectValues = ...
        string(T.Subject);

    subjectValues( ...
        ismissing(subjectValues)) = "";

    rawCells = ...
        table2cell(T);

    nRows = ...
        height(T);

    nColumns = ...
        width(T);

    subjectChange = ...
        false( ...
            nRows, ...
            1);

    if nRows > 1

        subjectChange(2:end) = ...
            subjectValues(2:end) ~= ...
            subjectValues(1:end-1);
    end

    nSeparators = ...
        sum(subjectChange);

    outputCells = ...
        cell( ...
            nRows + nSeparators, ...
            nColumns);

    separatorExcelRows = ...
        zeros( ...
            nSeparators, ...
            1);

    outputRow = 0;
    separatorCounter = 0;

    for row = 1:nRows

        if row > 1 && ...
                subjectChange(row)

            outputRow = ...
                outputRow + 1;

            separatorCounter = ...
                separatorCounter + 1;

            outputCells( ...
                outputRow, ...
                :) = ...
                repmat( ...
                    {''}, ...
                    1, ...
                    nColumns);

            outputCells{ ...
                outputRow, ...
                1} = ...
                char( ...
                    "NEXT SUBJECT: " + ...
                    subjectValues(row));

            % Excel row 1 is the header.
            separatorExcelRows( ...
                separatorCounter) = ...
                outputRow + 1;
        end

        outputRow = ...
            outputRow + 1;

        outputCells( ...
            outputRow, ...
            :) = ...
            rawCells( ...
                row, ...
                :);
    end

end

function format_subject_separator_rows_local( ...
        workbookPath, ...
        sheetName, ...
        separatorExcelRows, ...
        nColumns)

    if isempty(separatorExcelRows)
        return;
    end

    if ~ispc

        warning([ ...
            'Excel colour formatting was skipped because COM automation ' ...
            'is only available on Windows. Subject separator text remains.']);

        return;
    end

    excel = [];
    workbook = [];

    try

        excel = ...
            actxserver( ...
                'Excel.Application');

        excel.Visible = false;
        excel.DisplayAlerts = false;

        workbook = ...
            excel.Workbooks.Open( ...
                char(workbookPath));

        worksheet = ...
            workbook.Worksheets.Item( ...
                char(sheetName));

        lastColumnLetter = ...
            excel_column_name_local( ...
                nColumns);

        for k = 1:numel(separatorExcelRows)

            rowNumber = ...
                separatorExcelRows(k);

            rangeText = ...
                sprintf( ...
                    'A%d:%s%d', ...
                    rowNumber, ...
                    lastColumnLetter, ...
                    rowNumber);

            rowRange = ...
                worksheet.Range(rangeText);

            % Excel ColorIndex 36 = light yellow.
            rowRange.Interior.ColorIndex = 36;

            rowRange.Font.Bold = true;

            rowRange.RowHeight = 22;

            try
                rowRange.Borders.LineStyle = 1;
            catch
            end
        end

        workbook.Save();
        workbook.Close(false);

        excel.Quit();
        delete(excel);

    catch ME

        warning([ ...
            'Could not apply Excel colour formatting.\n' ...
            'The NEXT SUBJECT separator rows were still written.\n' ...
            'Reason: %s'], ...
            ME.message);

        try
            if ~isempty(workbook)
                workbook.Close(false);
            end
        catch
        end

        try
            if ~isempty(excel)
                excel.Quit();
            end
        catch
        end

        try
            if ~isempty(excel)
                delete(excel);
            end
        catch
        end
    end

end

function columnName = ...
        excel_column_name_local( ...
            columnNumber)

    if ~isscalar(columnNumber) || ...
            columnNumber < 1 || ...
            columnNumber ~= floor(columnNumber)

        error( ...
            'Invalid Excel column number.');
    end

    columnName = "";

    while columnNumber > 0

        remainder = ...
            mod( ...
                columnNumber - 1, ...
                26);

        columnName = ...
            string( ...
                char( ...
                    double('A') + ...
                    remainder)) + ...
            columnName;

        columnNumber = ...
            floor( ...
                (columnNumber - 1) / ...
                26);
    end

    columnName = ...
        char(columnName);

end

function backupFile = ...
        backup_workbook_local( ...
            workbookPath, ...
            backupTag)

    [ ...
        folder, ...
        base, ...
        extension ...
    ] = ...
        fileparts( ...
            char(workbookPath));

    stamp = ...
        char( ...
            datetime( ...
                'now', ...
                'Format', ...
                'yyyyMMdd_HHmmss_SSS'));

    backupFile = ...
        string(fullfile( ...
            folder, ...
            [ ...
                base ...
                '_' ...
                char(backupTag) ...
                '_backup_' ...
                stamp ...
                extension ...
            ]));

    [ ...
        ok, ...
        message ...
    ] = ...
        copyfile( ...
            workbookPath, ...
            backupFile, ...
            'f');

    if ~ok

        error([ ...
            'Could not back up existing manual IC workbook.\n' ...
            'Reason: %s'], ...
            message);
    end

end

