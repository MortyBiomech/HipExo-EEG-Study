% GOAL
%   Automatically create/update one manual cortical IC review workbook from
%   all Step-08-approved subject-level preprocessed_and_ICA datasets.
% INPUT
%   subject_level_EEG_table.csv from Steps 07/08.
%   PreprocessedICASetPath for every ICA-QC-approved subject.
% APPROACH
%   1. Restore MATLAB/EEGLAB figure visibility for interactive IC review.
%   2. Automatically load every Step-08-approved preprocessed_and_ICA.set.
%   3. Include every IC and record ICLabel probabilities, DIPFIT RV, and
%      representative dipole coordinates.
%   4. Preserve existing ManualReviewReason / ManualFinalDecision by the
%      stable Subject + Session + Dataset/File + IC key.
%   5. Write one combined review workbook for all subjects.
%   6. Insert a clearly labelled separator row between subjects.
%   7. On Windows with Microsoft Excel available, colour the complete
%      separator row light yellow and make its label bold.
% OUTPUT
%   output_data/manual_IC_selection_final.xlsx
% USED BY
%   step10_apply_manual_ic_selection.m

clc;

%  RESTORE INTERACTIVE FIGURE BEHAVIOR

restore_interactive_figures_local();

%  PATHS / CONFIGURATION

runFolder = ...
    fileparts(mfilename('fullpath'));

scriptsRoot = ...
    fileparts(runFolder);

addpath( ...
    scriptsRoot, ...
    '-begin');

addpath( ...
    fullfile( ...
        scriptsRoot, ...
        'config'), ...
    '-begin');

P = ...
    project_paths();

bemobil_config = ...
    config_step05_09_eeg_preprocessing_ica(P);

mappingFile = ...
    P.subjectLevelEEGTableFile;

outputFolder = ...
    P.outputFolder;

manualICWorkbook = ...
    string( ...
        fullfile( ...
            outputFolder, ...
            bemobil_config.manualICReview.workbookName));

manualICSheetName = ...
    bemobil_config.manualICReview.sheetName;


%  REVIEW TABLE SCHEMA

canonicalColumns = { ...
    'Subject', ...
    'Session', ...
    'Dataset/File', ...
    'IC', ...
    'BrainPercent', ...
    'RVPercent', ...
    'DipoleX', ...
    'DipoleY', ...
    'DipoleZ', ...
    'Top1Class', ...
    'Top1Percent', ...
    'Top2Class', ...
    'Top2Percent', ...
    'Top3Class', ...
    'Top3Percent', ...
    'ManualReviewReason', ...
    'ManualFinalDecision' ...
};


%  INPUT CHECK

if exist( ...
        mappingFile, ...
        'file') ~= 2

    error([ ...
        'Subject-level processing table not found:\n%s\n' ...
        'Run Step 08 successfully first.'], ...
        mappingFile);
end

if ~exist( ...
        'pop_loadset', ...
        'file')

    eeglab nogui;

    restore_interactive_figures_local();
end


%  READ SUBJECT-LEVEL TABLE

opts = ...
    detectImportOptions( ...
        mappingFile, ...
        'FileType', ...
        'text', ...
        'Delimiter', ...
        ',', ...
        'VariableNamingRule', ...
        'preserve');

sourceMap = ...
    readtable( ...
        mappingFile, ...
        opts);


%  CHECK REQUIRED COLUMNS

requiredColumns = { ...
    'BidsSubject', ...
    'BidsSession', ...
    'PreprocessedICASetPath', ...
    'ICAQCStatus' ...
};

for c = 1:numel(requiredColumns)

    if ~ismember( ...
            requiredColumns{c}, ...
            sourceMap.Properties.VariableNames)

        error( ...
            'Subject-level table is missing required column: %s', ...
            requiredColumns{c});
    end
end


%  NORMALIZE TABLE COLUMNS

sourceMap.BidsSession = ...
    string(sourceMap.BidsSession);

sourceMap.PreprocessedICASetPath = ...
    string(sourceMap.PreprocessedICASetPath);

sourceMap.ICAQCStatus = ...
    string(sourceMap.ICAQCStatus);

sourceMap.BidsSession( ...
    ismissing(sourceMap.BidsSession)) = "";

sourceMap.PreprocessedICASetPath( ...
    ismissing(sourceMap.PreprocessedICASetPath)) = "";

sourceMap.ICAQCStatus( ...
    ismissing(sourceMap.ICAQCStatus)) = "";


%  SELECT STEP-08-APPROVED DATASETS

acceptedICAQCStatuses = ...
    "passed_ica_quality_basic_checks";

eligibleRows = ...
    find( ...
        ismember( ...
            sourceMap.ICAQCStatus, ...
            acceptedICAQCStatuses) & ...
        strlength( ...
            strtrim( ...
                sourceMap.PreprocessedICASetPath)) > 0);

if isempty(eligibleRows)

    error([ ...
        'No Step-08-approved preprocessed_and_ICA dataset was found.\n' ...
        'Run step08_check_amica_quality.m successfully first.']);
end


%  REMOVE DUPLICATE DATASET PATHS

eligiblePaths = ...
    sourceMap.PreprocessedICASetPath(eligibleRows);

[~, uniquePathIndex] = ...
    unique( ...
        eligiblePaths, ...
        'stable');

rowsToReview = ...
    eligibleRows(uniquePathIndex);

fprintf( ...
    '\nApproved datasets found: %d\n', ...
    numel(rowsToReview));

disp( ...
    sourceMap( ...
        rowsToReview, ...
        { ...
            'BidsSubject', ...
            'BidsSession', ...
            'ICAQCStatus', ...
            'PreprocessedICASetPath' ...
        }));


%  LOAD ALL DATASETS AND BUILD CURRENT IC TABLE

currentTables = ...
    cell( ...
        numel(rowsToReview), ...
        1);

for d = 1:numel(rowsToReview)

    row = ...
        rowsToReview(d);

    setPath = ...
        strtrim( ...
            sourceMap.PreprocessedICASetPath(row));

    if exist( ...
            char(setPath), ...
            'file') ~= 2

        error( ...
            'PreprocessedICASetPath does not exist:\n%s', ...
            setPath);
    end

    fprintf('\n------------------------------------------------------------\n');

    fprintf( ...
        'Loading dataset %d / %d\n', ...
        d, ...
        numel(rowsToReview));

    fprintf( ...
        '%s\n', ...
        setPath);


    %  LOAD ICA / ICLABEL / DIPFIT INFORMATION

    EEG_review = ...
        load_ica_header_local(setPath);


    %  RESOLVE DATASET IDENTITY

    [ ...
        subjectLabel, ...
        sessionLabel, ...
        datasetFile ...
    ] = ...
        resolve_identity_from_table_local( ...
            sourceMap, ...
            row, ...
            setPath);


    %  BUILD IC TABLE

    currentTables{d} = ...
        build_ic_table_local( ...
            EEG_review, ...
            subjectLabel, ...
            sessionLabel, ...
            datasetFile, ...
            canonicalColumns);

    fprintf( ...
        'Subject: %s\n', ...
        subjectLabel);

    fprintf( ...
        'Session: %s\n', ...
        sessionLabel);

    fprintf( ...
        'Dataset/File: %s\n', ...
        datasetFile);

    fprintf( ...
        'ICs added: %d\n', ...
        height(currentTables{d}));
end


%  MERGE CURRENT DATASETS

currentTable = ...
    vertcat(currentTables{:});

currentTable = ...
    normalize_review_table_local( ...
        currentTable, ...
        canonicalColumns);

currentTable = ...
    currentTable( ...
        valid_ic_rows_local(currentTable), ...
        :);


%  CHECK CURRENT IC IDENTITY UNIQUENESS

currentKey = ...
    review_key_local(currentTable);

if numel(unique(currentKey)) ~= height(currentTable)

    error([ ...
        'Current automatically generated IC table contains duplicate ' ...
        'Subject + Session + Dataset/File + IC rows.']);
end


%  PRESERVE EXISTING MANUAL REVIEW DECISIONS

masterTable = ...
    currentTable;

backupFile = "";

if exist( ...
        manualICWorkbook, ...
        'file') == 2

    existingTable = ...
        read_review_table_local( ...
            manualICWorkbook, ...
            manualICSheetName);

    identityColumns = { ...
        'Subject', ...
        'Session', ...
        'Dataset/File', ...
        'IC' ...
    };

    if all( ...
            ismember( ...
                identityColumns, ...
                existingTable.Properties.VariableNames))

        if ~all( ...
                ismember( ...
                    canonicalColumns, ...
                    existingTable.Properties.VariableNames))

            backupFile = ...
                backup_workbook_local( ...
                    manualICWorkbook, ...
                    'before_auto_all_dataset_schema');
        end

        existingTable = ...
            normalize_review_table_local( ...
                existingTable, ...
                canonicalColumns);

        % Removes the visual subject separator rows automatically.
        existingTable = ...
            existingTable( ...
                valid_ic_rows_local(existingTable), ...
                :);

        existingKey = ...
            review_key_local(existingTable);

        if numel(unique(existingKey)) ~= height(existingTable)

            error([ ...
                'Existing workbook contains duplicate ' ...
                'Subject + Session + Dataset/File + IC rows.']);
        end


        %  PRESERVE PREVIOUS MANUAL REVIEW

        [ ...
            hasOldReview, ...
            oldLocation ...
        ] = ...
            ismember( ...
                currentKey, ...
                existingKey);

        currentTable.ManualReviewReason(hasOldReview) = ...
            existingTable.ManualReviewReason( ...
                oldLocation(hasOldReview));

        currentTable.ManualFinalDecision(hasOldReview) = ...
            existingTable.ManualFinalDecision( ...
                oldLocation(hasOldReview));


        %  REPLACE DATASETS REGENERATED THIS RUN

        currentDatasetKey = ...
            lower(strtrim(currentTable.Subject)) + "|" + ...
            lower(strtrim(currentTable.Session));

        existingDatasetKey = ...
            lower(strtrim(existingTable.Subject)) + "|" + ...
            lower(strtrim(existingTable.Session));

        replaceDatasetKeys = ...
            unique(currentDatasetKey);

        keepExisting = ...
            ~ismember( ...
                existingDatasetKey, ...
                replaceDatasetKeys);

        masterTable = [ ...
            existingTable( ...
                keepExisting, ...
                canonicalColumns); ...
            currentTable ...
        ];

    else

        backupFile = ...
            backup_workbook_local( ...
                manualICWorkbook, ...
                'incompatible_schema');

        warning([ ...
            'Existing workbook does not contain the required IC identity ' ...
            'columns. It was backed up and replaced.']);

        masterTable = ...
            currentTable;
    end
end


%  FINAL NORMALIZATION / SORTING

masterTable = ...
    normalize_review_table_local( ...
        masterTable, ...
        canonicalColumns);

masterTable = ...
    masterTable( ...
        valid_ic_rows_local(masterTable), ...
        :);

masterTable = ...
    sortrows( ...
        masterTable, ...
        { ...
            'Subject', ...
            'Session', ...
            'Dataset/File', ...
            'IC' ...
        });


%  FINAL DUPLICATE CHECK

finalKey = ...
    review_key_local(masterTable);

if numel(unique(finalKey)) ~= height(masterTable)

    error( ...
        'Final manual IC workbook would contain duplicate IC identities.');
end


%  PREPARE OUTPUT FOLDER

if exist( ...
        outputFolder, ...
        'dir') ~= 7

    mkdir(outputFolder);
end


%  TEMPORARY WORKBOOK

temporaryWorkbook = ...
    string( ...
        fullfile( ...
            outputFolder, ...
            [ ...
                'manual_IC_selection_writing_' ...
                char( ...
                    datetime( ...
                        'now', ...
                        'Format', ...
                        'yyyyMMdd_HHmmss_SSS')) ...
                '.xlsx' ...
            ]));


%  CONVERT TABLE TO EXCEL CELLS WITH COLORED SUBJECT SEPARATORS

[ ...
    workbookCells, ...
    separatorExcelRows ...
] = ...
    table_to_cells_with_subject_separators_local( ...
        masterTable, ...
        canonicalColumns);


%  WRITE MANUAL REVIEW SHEET

headerCells = ...
    canonicalColumns;

writecell( ...
    [ ...
        headerCells; ...
        workbookCells ...
    ], ...
    temporaryWorkbook, ...
    'Sheet', ...
    manualICSheetName, ...
    'Range', ...
    'A1');


%  WRITE README SHEET

instructionCells = { ...
    'Field', ...
    'Meaning'; ...

    'Rows included', ...
    'Every IC from every Step-08-approved preprocessed_and_ICA dataset'; ...

    'Subject separators', ...
    'A labelled light-yellow row is inserted between subjects for readability only'; ...

    'Automatic selection', ...
    'None. BrainPercent and RVPercent are reference values only'; ...

    'ManualReviewReason', ...
    'Free-text notes completed manually by the reviewer'; ...

    'ManualFinalDecision', ...
    'Manual decision: Yes / Review / No'; ...

    'Downstream use', ...
    'Only exact ManualFinalDecision = Yes enters Step 10'; ...

    'Separator rows', ...
    'Separator rows have empty Session and IC values and are ignored downstream'; ...

    'Safety', ...
    'This workbook does not delete or alter ICA components' ...
};

writecell( ...
    instructionCells, ...
    temporaryWorkbook, ...
    'Sheet', ...
    'README', ...
    'Range', ...
    'A1');


%  APPLY EXCEL FORMATTING TO SUBJECT SEPARATOR ROWS

format_subject_separator_rows_local( ...
    temporaryWorkbook, ...
    manualICSheetName, ...
    separatorExcelRows, ...
    numel(canonicalColumns));


%  REPLACE FINAL WORKBOOK

[ ...
    moveSucceeded, ...
    moveMessage ...
] = ...
    movefile( ...
        temporaryWorkbook, ...
        manualICWorkbook, ...
        'f');

if ~moveSucceeded

    if exist( ...
            temporaryWorkbook, ...
            'file') == 2

        delete(temporaryWorkbook);
    end

    error([ ...
        'Could not replace the manual IC workbook.\n' ...
        'Close the workbook in Excel and rerun Step 09.\n' ...
        'Reason: %s\n' ...
        'Target:\n%s'], ...
        moveMessage, ...
        manualICWorkbook);
end


%  REPORT

fprintf('Manual IC review workbook updated: %s\n', manualICWorkbook);
fprintf('Datasets: %d | IC rows: %d\n', ...
    numel(unique(currentTable.Subject + "|" + currentTable.Session + "|" + currentTable.("Dataset/File"))), ...
    height(masterTable));


%  LEAVE MATLAB / EEGLAB IN INTERACTIVE MODE

restore_interactive_figures_local();



%  LOCAL FUNCTIONS


function restore_interactive_figures_local()

    try
        set( ...
            0, ...
            'DefaultFigureVisible', ...
            'on');
    catch
    end

    try
        set( ...
            groot, ...
            'DefaultFigureVisible', ...
            'on');
    catch
    end

    try

        figures = ...
            findall( ...
                groot, ...
                'Type', ...
                'figure');

        if ~isempty(figures)

            set( ...
                figures, ...
                'Visible', ...
                'on');
        end

    catch
    end

end


function EEG = ...
        load_ica_header_local( ...
            setPath)

    [ ...
        setFolder, ...
        setName, ...
        setExtension ...
    ] = ...
        fileparts( ...
            char(setPath));

    try

        EEG = ...
            pop_loadset( ...
                'filename', ...
                [setName setExtension], ...
                'filepath', ...
                setFolder, ...
                'loadmode', ...
                'info');

    catch firstLoadError

        warning([ ...
            'Header-only loading failed; retrying normal pop_loadset.\n' ...
            'Dataset: %s\n' ...
            'Reason: %s'], ...
            setPath, ...
            firstLoadError.message);

        EEG = ...
            pop_loadset( ...
                'filename', ...
                [setName setExtension], ...
                'filepath', ...
                setFolder);
    end

end


function [ ...
        subjectLabel, ...
        sessionLabel, ...
        datasetFile ...
    ] = ...
        resolve_identity_from_table_local( ...
            sourceMap, ...
            row, ...
            setPath)

    sessionLabel = ...
        strtrim( ...
            string( ...
                sourceMap.BidsSession(row)));

    [ ...
        ~, ...
        setName, ...
        setExtension ...
    ] = ...
        fileparts( ...
            char(setPath));

    datasetFile = ...
        string( ...
            [ ...
                setName ...
                setExtension ...
            ]);

    subjectLabel = "";


    if ismember( ...
            'SubjectLabel', ...
            sourceMap.Properties.VariableNames)

        candidate = ...
            strtrim( ...
                string( ...
                    sourceMap.SubjectLabel(row)));

        if ~ismissing(candidate) && ...
                strlength(candidate) > 0

            subjectLabel = ...
                candidate;
        end
    end


    if strlength(subjectLabel) == 0

        token = ...
            regexp( ...
                char(sessionLabel), ...
                '^Pilot2p([0-9]+)AllSessions$', ...
                'tokens', ...
                'once');

        if ~isempty(token)

            subjectLabel = ...
                "sub-Pilot2_" + ...
                string(token{1});
        end
    end


    if strlength(subjectLabel) == 0

        bidsSubject = ...
            sourceMap.BidsSubject(row);

        if ~isnumeric(bidsSubject)

            bidsSubject = ...
                str2double( ...
                    string(bidsSubject));
        end

        if isscalar(bidsSubject) && ...
                isfinite(bidsSubject)

            subjectLabel = ...
                "sub-Pilot2_" + ...
                string(round(bidsSubject));
        end
    end


    if strlength(subjectLabel) == 0 || ...
            strlength(sessionLabel) == 0 || ...
            strlength(datasetFile) == 0

        error([ ...
            'Could not resolve Subject / Session / Dataset identity.\n' ...
            'Table row: %d\n' ...
            'Set path: %s'], ...
            row, ...
            setPath);
    end

end


function T = ...
        build_ic_table_local( ...
            EEG, ...
            subjectLabel, ...
            sessionLabel, ...
            datasetFile, ...
            canonicalColumns)

    if isempty(EEG.icaweights)

        error( ...
            'Dataset does not contain ICA weights: %s', ...
            datasetFile);
    end


    if ~isfield( ...
            EEG, ...
            'etc') || ...
            ~isfield( ...
                EEG.etc, ...
                'ic_classification') || ...
            ~isfield( ...
                EEG.etc.ic_classification, ...
                'ICLabel') || ...
            ~isfield( ...
                EEG.etc.ic_classification.ICLabel, ...
                'classifications')

        error( ...
            'Dataset does not contain ICLabel classifications: %s', ...
            datasetFile);
    end


    probs = ...
        double( ...
            EEG.etc.ic_classification.ICLabel.classifications);

    nIC = ...
        size( ...
            EEG.icaweights, ...
            1);


    if size(probs, 1) ~= nIC || ...
            size(probs, 2) < 3

        error([ ...
            'ICLabel dimensions do not match ICA.\n' ...
            'Dataset: %s | ICs: %d | ICLabel: %d x %d'], ...
            datasetFile, ...
            nIC, ...
            size(probs, 1), ...
            size(probs, 2));
    end


    if any(~isfinite(probs(:)))

        error( ...
            'ICLabel contains NaN/Inf: %s', ...
            datasetFile);
    end


    classNames = ...
        resolve_iclabel_class_names_local( ...
            EEG.etc.ic_classification.ICLabel, ...
            size(probs, 2));


    [ ...
        sortedProbabilities, ...
        sortedClassIndices ...
    ] = ...
        sort( ...
            probs, ...
            2, ...
            'descend');


    Top1Class = ...
        reshape( ...
            classNames( ...
                sortedClassIndices(:, 1)), ...
            [], ...
            1);

    Top1Percent = ...
        100 * ...
        sortedProbabilities(:, 1);


    Top2Class = ...
        reshape( ...
            classNames( ...
                sortedClassIndices(:, 2)), ...
            [], ...
            1);

    Top2Percent = ...
        100 * ...
        sortedProbabilities(:, 2);


    Top3Class = ...
        reshape( ...
            classNames( ...
                sortedClassIndices(:, 3)), ...
            [], ...
            1);

    Top3Percent = ...
        100 * ...
        sortedProbabilities(:, 3);


    RVPercent = ...
        nan(nIC, 1);

    DipoleX = ...
        nan(nIC, 1);

    DipoleY = ...
        nan(nIC, 1);

    DipoleZ = ...
        nan(nIC, 1);


    for ic = 1:nIC

        if ~isfield( ...
                EEG, ...
                'dipfit') || ...
                ~isfield( ...
                    EEG.dipfit, ...
                    'model') || ...
                numel( ...
                    EEG.dipfit.model) < ic

            continue;
        end

        model = ...
            EEG.dipfit.model(ic);

        if isfield( ...
                model, ...
                'rv') && ...
                ~isempty(model.rv)

            RVPercent(ic) = ...
                100 * ...
                double(model.rv);
        end


        if isfield( ...
                model, ...
                'posxyz') && ...
                ~isempty(model.posxyz)

            xyz = ...
                hipexo.representative_dipole_xyz(model);

            DipoleX(ic) = ...
                xyz(1);

            DipoleY(ic) = ...
                xyz(2);

            DipoleZ(ic) = ...
                xyz(3);
        end

    end


    brainClassIndex = ...
        find( ...
            strcmpi( ...
                classNames, ...
                "Brain"), ...
            1, ...
            'first');


    if isempty(brainClassIndex)

        BrainPercent = ...
            nan(nIC, 1);

    else

        BrainPercent = ...
            100 * ...
            probs(:, brainClassIndex);
    end


    Subject = ...
        repmat( ...
            string(subjectLabel), ...
            nIC, ...
            1);

    Session = ...
        repmat( ...
            string(sessionLabel), ...
            nIC, ...
            1);

    DatasetFile = ...
        repmat( ...
            string(datasetFile), ...
            nIC, ...
            1);

    IC = ...
        (1:nIC)';


    ManualReviewReason = ...
        strings(nIC, 1);

    ManualFinalDecision = ...
        strings(nIC, 1);


    T = ...
        table( ...
            Subject, ...
            Session, ...
            DatasetFile, ...
            IC, ...
            BrainPercent, ...
            RVPercent, ...
            DipoleX, ...
            DipoleY, ...
            DipoleZ, ...
            Top1Class, ...
            Top1Percent, ...
            Top2Class, ...
            Top2Percent, ...
            Top3Class, ...
            Top3Percent, ...
            ManualReviewReason, ...
            ManualFinalDecision, ...
            'VariableNames', ...
            canonicalColumns);

end


function classNames = ...
        resolve_iclabel_class_names_local( ...
            ICLabel, ...
            nClasses)

    standardClassNames = [ ...
        "Brain", ...
        "Muscle", ...
        "Eye", ...
        "Heart", ...
        "Line Noise", ...
        "Channel Noise", ...
        "Other" ...
    ];

    classNames = ...
        "Class" + ...
        string(1:nClasses);

    nStandard = ...
        min( ...
            nClasses, ...
            numel(standardClassNames));

    classNames(1:nStandard) = ...
        standardClassNames(1:nStandard);


    if isfield( ...
            ICLabel, ...
            'classes') && ...
            ~isempty(ICLabel.classes)

        rawClassNames = ...
            ICLabel.classes;

        while iscell(rawClassNames) && ...
                isscalar(rawClassNames) && ...
                iscell(rawClassNames{1})

            rawClassNames = ...
                rawClassNames{1};
        end

        suppliedClassNames = ...
            reshape( ...
                string(rawClassNames), ...
                1, ...
                []);

        if numel(suppliedClassNames) == nClasses

            classNames = ...
                suppliedClassNames;
        end

    end


    classNames = ...
        strtrim(classNames);

    classNames( ...
        ismissing(classNames)) = "";


    for c = 1:nClasses

        if strlength(classNames(c)) == 0

            classNames(c) = ...
                "Class" + ...
                string(c);
        end

    end

end


function T = ...
        read_review_table_local( ...
            workbookPath, ...
            sheetName)

    cells = ...
        readcell( ...
            workbookPath, ...
            'Sheet', ...
            sheetName);


    if isempty(cells)

        error( ...
            'Existing manual IC workbook sheet is empty.');
    end


    headers = ...
        string(cells(1, :));

    headers( ...
        ismissing(headers)) = "";

    headers = ...
        strtrim(headers);


    validHeader = ...
        strlength(headers) > 0 & ...
        ~strcmpi(headers, "NaN") & ...
        ~strcmpi(headers, "<missing>");


    if ~any(validHeader)

        error( ...
            'Existing manual IC workbook has no usable headers.');
    end


    retainedHeaders = ...
        headers(validHeader);


    if numel(unique(lower(retainedHeaders))) ~= ...
            numel(retainedHeaders)

        error( ...
            'Existing manual IC workbook has duplicate headers.');
    end


    if size(cells, 1) == 1

        dataCells = ...
            cell( ...
                0, ...
                sum(validHeader));

    else

        dataCells = ...
            cells( ...
                2:end, ...
                validHeader);
    end


    T = ...
        cell2table( ...
            dataCells, ...
            'VariableNames', ...
            cellstr(retainedHeaders));

end


function T = ...
        normalize_review_table_local( ...
            T, ...
            canonicalColumns)

    stringColumns = { ...
        'Subject', ...
        'Session', ...
        'Dataset/File', ...
        'Top1Class', ...
        'Top2Class', ...
        'Top3Class', ...
        'ManualReviewReason', ...
        'ManualFinalDecision' ...
    };


    numericColumns = ...
        setdiff( ...
            canonicalColumns, ...
            stringColumns, ...
            'stable');


    for c = 1:numel(canonicalColumns)

        name = ...
            canonicalColumns{c};

        if ismember( ...
                name, ...
                T.Properties.VariableNames)

            continue;
        end


        if ismember( ...
                name, ...
                stringColumns)

            T.(name) = ...
                strings( ...
                    height(T), ...
                    1);

        else

            T.(name) = ...
                nan( ...
                    height(T), ...
                    1);
        end

    end


    T = ...
        T(:, canonicalColumns);


    for c = 1:numel(stringColumns)

        name = ...
            stringColumns{c};

        T.(name) = ...
            string(T.(name));

        T.(name)( ...
            ismissing(T.(name))) = "";


        blankLike = ...
            strcmpi( ...
                strtrim(T.(name)), ...
                "NaN") | ...
            strcmpi( ...
                strtrim(T.(name)), ...
                "<missing>") | ...
            strcmpi( ...
                strtrim(T.(name)), ...
                "missing");

        T.(name)(blankLike) = "";

    end


    for c = 1:numel(numericColumns)

        name = ...
            numericColumns{c};

        if isnumeric(T.(name)) || ...
                islogical(T.(name))

            T.(name) = ...
                double(T.(name));

        else

            T.(name) = ...
                str2double( ...
                    string(T.(name)));
        end

    end

end


