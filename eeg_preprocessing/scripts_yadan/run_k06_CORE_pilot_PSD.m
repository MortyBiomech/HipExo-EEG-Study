    datasetIndex = datasetClusterKeys(rowIndex, 1);
    clusterIndex = datasetClusterKeys(rowIndex, 2);

    memberMask = ...
        double(membership.DatasetIndex) == datasetIndex & ...
        double(membership.ClusterIndex) == clusterIndex;

    sourceRows = find(memberMask);

    aggregatedPsd = mean( ...
        icPsdLinear(memberMask, :), ...
        1, ...
        'omitnan');

    datasetClusterPsdLinear(rowIndex, :) = aggregatedPsd;

    metrics = compute_band_metrics_local( ...
        frequencyHz, ...
        aggregatedPsd, ...
        relativePowerReferenceHz, ...
        thetaBandHz, ...
        muBandHz, ...
        betaBandHz, ...
        lowBetaBandHz, ...
        highBetaBandHz);

    datasetClusterBandRows(rowIndex, :) = { ...
        clusterIndex, ...
        membership.ClusterName(sourceRows(1)), ...
        datasetIndex, ...
        membership.Subject(sourceRows(1)), ...
        membership.Condition(sourceRows(1)), ...
        double(membership.Session(sourceRows(1))), ...
        membership.DatasetFilename(sourceRows(1)), ...
        numel(sourceRows), ...
        strjoin(string(sort(double(membership.IC(sourceRows)))), ', '), ...
        mean(icAnalyzedDurationSec(sourceRows), 'omitnan'), ...
        sum(icWelchWindows(sourceRows)), ...
        metrics.ThetaPowerDb, ...
        metrics.MuPowerDb, ...
        metrics.BetaPowerDb, ...
        metrics.LowBetaPowerDb, ...
        metrics.HighBetaPowerDb, ...
        metrics.ThetaRelativePct, ...
        metrics.MuRelativePct, ...
        metrics.BetaRelativePct, ...
        metrics.LowBetaRelativePct, ...
        metrics.HighBetaRelativePct, ...
        metrics.MuPeakFrequencyHz, ...
        metrics.MuPeakPsdDb, ...
        "Average of IC PSDs in linear power", ...
        "Original session label; no experimental mapping applied", ...
        "Pilot QC only" ...
    };
end

