        datasetClusterBandpowerTable.Subject(firstRow), ...
        sum(sourceMask), ...
        strjoin( ...
            string(datasetClusterBandpowerTable.OriginalCondition(sourceRows)), ...
            ' | '), ...
        metrics.ThetaPowerDb, ...
        metrics.MuPowerDb, ...
        metrics.BetaPowerDb, ...
        metrics.LowBetaPowerDb, ...
        metrics.HighBetaPowerDb, ...
        metrics.ThetaRelativePct, ...
        metrics.MuRelativePct, ...
        metrics.BetaRelativePct, ...
        metrics.LowBetaRelativePct, ...
        metrics.HighBetaRelativePct, ...
