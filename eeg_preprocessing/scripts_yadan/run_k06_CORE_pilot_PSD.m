%  LOAD CORE STUDY AND MEMBERSHIP
%  ========================================================================

[STUDY, ALLEEG] = pop_loadstudy( ...
    'filename', coreStudyFilename, ...
    'filepath', coreStudyFolder);

membership = readtable( ...
    coreMembershipPath, ...
    'TextType', 'string', ...
    'VariableNamingRule', 'preserve');

requiredColumns = [ ...
    "ClusterIndex", ...
    "ClusterName", ...
    "DatasetIndex", ...
    "Subject", ...
    "Condition", ...
    "Session", ...
    "DatasetFilename", ...
    "IC", ...
    "ReviewerDecision"];

missingColumns = setdiff( ...
    requiredColumns, ...
    string(membership.Properties.VariableNames));

if ~isempty(missingColumns)
    error('Membership table is missing columns: %s', ...
        strjoin(missingColumns, ', '));
end

membership.ReviewerDecision = ...
    strtrim(string(membership.ReviewerDecision));

if any(membership.ReviewerDecision ~= "Keep")
    error([ ...
        'The CORE membership file contains a row whose ' ...
        'ReviewerDecision is not Keep.']);
end

membership = sortrows( ...
    membership, ...
    {'DatasetIndex', 'ClusterIndex', 'IC'});

