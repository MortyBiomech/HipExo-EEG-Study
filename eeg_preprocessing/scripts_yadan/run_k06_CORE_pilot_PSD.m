nMembers = height(membership);

fprintf('Verified CORE membership: %d ICs.\n', nMembers);
fprintf('Datasets represented: %d\n', ...
    numel(unique(membership.DatasetIndex)));
fprintf('Clusters represented: %d\n\n', ...
    numel(unique(membership.ClusterIndex)));

%% ========================================================================
%  COMPUTE IC-LEVEL PSD
%  ========================================================================

% The frequency vector is initialized using the first successfully analyzed
% IC. All datasets are expected to have the same post-processing sampling
% rate. If a minor difference occurs, PSD is interpolated to the first
% frequency grid.

frequencyHz = [];
icPsdLinear = [];
icWelchWindows = zeros(nMembers, 1);
icAnalyzedDurationSec = zeros(nMembers, 1);
icContinuousSegmentCount = zeros(nMembers, 1);
icSamplingRate = zeros(nMembers, 1);
icScalpMapRmsScale = nan(nMembers, 1);

% Band metrics at IC level.
icThetaPowerDb = nan(nMembers, 1);
icMuPowerDb = nan(nMembers, 1);
icBetaPowerDb = nan(nMembers, 1);
icLowBetaPowerDb = nan(nMembers, 1);
icHighBetaPowerDb = nan(nMembers, 1);

icThetaRelativePct = nan(nMembers, 1);
icMuRelativePct = nan(nMembers, 1);
icBetaRelativePct = nan(nMembers, 1);
icLowBetaRelativePct = nan(nMembers, 1);
icHighBetaRelativePct = nan(nMembers, 1);

icMuPeakFrequencyHz = nan(nMembers, 1);
icMuPeakPsdDb = nan(nMembers, 1);

currentDatasetIndex = NaN;
currentEEG = [];

for memberIndex = 1:nMembers

    datasetIndex = double(membership.DatasetIndex(memberIndex));
    componentIndex = double(membership.IC(memberIndex));

    if datasetIndex ~= currentDatasetIndex

        currentEEG = load_full_study_dataset_local( ...
            STUDY, ...
            ALLEEG, ...
            datasetIndex);

        currentDatasetIndex = datasetIndex;

        expectedFilename = ...
            string(membership.DatasetFilename(memberIndex));

        if string(currentEEG.filename) ~= expectedFilename
            error([ ...
                'Dataset filename mismatch for DatasetIndex %d.\n' ...
                'Membership: %s\nLoaded: %s'], ...
                datasetIndex, ...
                expectedFilename, ...
                string(currentEEG.filename));
        end

        fprintf('\nDataset %02d/%02d: %s\n', ...
            datasetIndex, ...
            numel(STUDY.datasetinfo), ...
            currentEEG.filename);
        fprintf('  Subject: %s | Condition: %s\n', ...
            membership.Subject(memberIndex), ...
            membership.Condition(memberIndex));
        fprintf('  Sampling rate: %.6f Hz | Samples: %d\n', ...
            currentEEG.srate, ...
            currentEEG.pnts);
    end

    if isempty(currentEEG.icaweights) || ...
            isempty(currentEEG.icasphere)
        error('Dataset %d has no ICA decomposition.', datasetIndex);
    end

    if componentIndex < 1 || ...
            componentIndex > size(currentEEG.icaweights, 1)
        error([ ...
            'Invalid IC %d for DatasetIndex %d. The dataset contains ' ...
            '%d ICA components.'], ...
            componentIndex, ...
            datasetIndex, ...
            size(currentEEG.icaweights, 1));
    end

    icActivation = compute_single_ic_activation_local( ...
        currentEEG, ...
        componentIndex);

    [ ...
        icActivation, ...
        scalpMapRmsScale ...
    ] = normalize_ic_activation_scale_local( ...
        currentEEG, ...
        componentIndex, ...
        icActivation);

    icScalpMapRmsScale(memberIndex) = scalpMapRmsScale;

    windowSamples = round(windowLengthSec * currentEEG.srate);

    continuousSegments = get_continuous_segments_local( ...
        currentEEG, ...
        edgeTrimSec, ...
        windowSamples, ...
        maxUsableDurationSec);

    [ ...
        memberPsdLinear, ...
        memberFrequencyHz, ...
        nWelchWindows, ...
        analyzedDurationSec ...
    ] = compute_welch_psd_across_segments_local( ...
        icActivation, ...
        continuousSegments, ...
        currentEEG.srate, ...
        windowLengthSec, ...
        overlapFraction);

    if nWelchWindows < minimumWelchWindows
        error([ ...
            'Dataset %d IC %d produced only %d valid Welch windows. ' ...
            'Minimum required: %d.'], ...
            datasetIndex, ...
            componentIndex, ...
            nWelchWindows, ...
            minimumWelchWindows);
    end

    if isempty(frequencyHz)

        exportMask = ...
            memberFrequencyHz >= exportFrequencyRangeHz(1) & ...
            memberFrequencyHz <= exportFrequencyRangeHz(2);

        frequencyHz = memberFrequencyHz(exportMask);
        icPsdLinear = nan(nMembers, numel(frequencyHz));

    else

        exportMask = ...
            memberFrequencyHz >= exportFrequencyRangeHz(1) & ...
            memberFrequencyHz <= exportFrequencyRangeHz(2);
    end

    memberFrequencyExport = memberFrequencyHz(exportMask);
    memberPsdExport = memberPsdLinear(exportMask);

    if numel(memberFrequencyExport) ~= numel(frequencyHz) || ...
            max(abs(memberFrequencyExport - frequencyHz)) > 1e-8

        memberPsdExport = interp1( ...
            memberFrequencyExport, ...
            memberPsdExport, ...
            frequencyHz, ...
            'linear', ...
            NaN);
    end

    icPsdLinear(memberIndex, :) = memberPsdExport;

    icWelchWindows(memberIndex) = nWelchWindows;
    icAnalyzedDurationSec(memberIndex) = analyzedDurationSec;
    icContinuousSegmentCount(memberIndex) = ...
        size(continuousSegments, 1);
    icSamplingRate(memberIndex) = currentEEG.srate;

    metrics = compute_band_metrics_local( ...
        frequencyHz, ...
        memberPsdExport, ...
        relativePowerReferenceHz, ...
        thetaBandHz, ...
        muBandHz, ...
        betaBandHz, ...
        lowBetaBandHz, ...
        highBetaBandHz);

    icThetaPowerDb(memberIndex) = metrics.ThetaPowerDb;
    icMuPowerDb(memberIndex) = metrics.MuPowerDb;
    icBetaPowerDb(memberIndex) = metrics.BetaPowerDb;
    icLowBetaPowerDb(memberIndex) = metrics.LowBetaPowerDb;
    icHighBetaPowerDb(memberIndex) = metrics.HighBetaPowerDb;

    icThetaRelativePct(memberIndex) = metrics.ThetaRelativePct;
    icMuRelativePct(memberIndex) = metrics.MuRelativePct;
    icBetaRelativePct(memberIndex) = metrics.BetaRelativePct;
    icLowBetaRelativePct(memberIndex) = ...
        metrics.LowBetaRelativePct;
    icHighBetaRelativePct(memberIndex) = ...
        metrics.HighBetaRelativePct;

    icMuPeakFrequencyHz(memberIndex) = metrics.MuPeakFrequencyHz;
    icMuPeakPsdDb(memberIndex) = metrics.MuPeakPsdDb;

    fprintf([ ...
        '  Cls %d | IC %d | %.1f s | %d windows | ' ...
        'theta %.2f dB | mu %.2f dB | beta %.2f dB\n'], ...
        double(membership.ClusterIndex(memberIndex)), ...
        componentIndex, ...
        analyzedDurationSec, ...
        nWelchWindows, ...
        metrics.ThetaPowerDb, ...
        metrics.MuPowerDb, ...
        metrics.BetaPowerDb);
end

