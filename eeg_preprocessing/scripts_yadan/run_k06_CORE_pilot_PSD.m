%% run_k06_CORE_pilot_PSD.m
%
% PURPOSE
% -------
% Compute a pilot continuous-EEG PSD prototype from the manually curated
% K=6 CORE STUDY.
%
% This script:
% 1. Loads the CORE STUDY and the 52-member CORE membership table.
% 2. Computes Welch PSD from each retained IC activation.
% 3. Resolves ICA scale indeterminacy by multiplying each activation by the
%    RMS of its scalp projection map before PSD estimation.
% 4. Never concatenates data across EEGLAB boundary events.
% 5. Averages multiple ICs in the same Dataset x Cluster in LINEAR power.
% 6. Exports theta, mu, beta, low-beta and high-beta band power.
% 7. Creates subject-level and cluster-level QC summaries and figures.
%
% IMPORTANT INTERPRETATION
% ------------------------
% This is a PILOT / METHOD-VALIDATION analysis only.
% - Original session labels are preserved.
% - No Assistive/Resistive/Transparent mapping is assumed.
% - No condition statistics are performed.
% - No gait-event alignment is performed.
% - Final PSD must be rerun after all participants and the final STUDY are
%   available.
%
% The script does NOT modify:
% - EEG.data
% - ICA decompositions
% - the CORE STUDY
% - cluster membership
%
% OUTPUT
% ------
% output_data/13_pilot-PSD-k06-CORE/
%   HipExo_k06_CORE_IC_level_bandpower.csv
%   HipExo_k06_CORE_dataset_cluster_bandpower.csv
%   HipExo_k06_CORE_dataset_cluster_PSD_long.csv
%   HipExo_k06_CORE_subject_cluster_bandpower_QC.csv
%   HipExo_k06_CORE_subject_cluster_PSD_long_QC.csv
%   HipExo_k06_CORE_cluster_PSD_QC_summary.csv
%   HipExo_k06_CORE_pilot_PSD_results.mat
%   HipExo_k06_CORE_pilot_PSD_settings.txt
%   figures/*.png

clear;
clc;
close all;

%% ========================================================================
%  PATHS
%  ========================================================================

projectFolder = ...
    '/Users/dydan/master_thesis/HipExo-EEG-Study/eeg_preprocessing';

eeglabFolder = ...
    '/Users/dydan/master_thesis/eeglab2026.0.0';

outputDataFolder = fullfile(projectFolder, 'output_data');

coreStudyFolder = fullfile( ...
    outputDataFolder, ...
    '11_curated-STUDY_k06');

coreStudyFilename = ...
    'HipExo_manual_IC_Yes_only_spatial_clustered_k06_CORE.study';

coreMembershipFilename = ...
    'HipExo_k06_CORE_membership.csv';

resultFolder = fullfile( ...
    outputDataFolder, ...
    '13_pilot-PSD-k06-CORE');

figureFolder = fullfile(resultFolder, 'figures');

if ~isfolder(resultFolder)
    mkdir(resultFolder);
end

if ~isfolder(figureFolder)
    mkdir(figureFolder);
end

coreStudyPath = fullfile(coreStudyFolder, coreStudyFilename);
coreMembershipPath = fullfile( ...
    coreStudyFolder, ...
    coreMembershipFilename);

if ~isfile(coreStudyPath)
    error('CORE STUDY was not found:\n%s', coreStudyPath);
end

if ~isfile(coreMembershipPath)
    error('CORE membership CSV was not found:\n%s', ...
        coreMembershipPath);
end

%% ========================================================================
%  PSD SETTINGS
%  ========================================================================

% Four-second windows provide approximately 0.25-Hz frequency resolution
% at 250 Hz when nfft = 1024.
windowLengthSec = 4.0;

% Consecutive Welch windows overlap by 50%.
overlapFraction = 0.50;

% Remove this amount from both sides of every continuous segment.
% This reduces edge effects around dataset boundaries and rejected portions.
edgeTrimSec = 2.0;

% Analyze all usable continuous data. Set a finite number such as 180 to
% use at most the first 180 usable seconds from each dataset.
maxUsableDurationSec = Inf;

% Minimum number of valid Welch windows required for an IC.
minimumWelchWindows = 20;

% Frequency range exported in the long-format PSD tables.
exportFrequencyRangeHz = [1 40];

% Frequency range used as the denominator for relative band power.
relativePowerReferenceHz = [3 30];

% Non-overlapping analysis bands:
% theta:     4 <= f < 8 Hz  (corresponds to nominal 4-7 Hz)
% mu:        8 <= f < 13 Hz
% beta:     13 <= f <= 30 Hz
% low beta: 13 <= f < 20 Hz
% high beta:20 <= f <= 30 Hz
thetaBandHz = [4 8];
muBandHz = [8 13];
betaBandHz = [13 30];
lowBetaBandHz = [13 20];
highBetaBandHz = [20 30];

%% ========================================================================
%  START EEGLAB
%  ========================================================================

addpath(eeglabFolder);

if isempty(which('eeglab'))
    error('EEGLAB was not found:\n%s', eeglabFolder);
end

[ALLEEG, EEG, CURRENTSET, ALLCOM] = eeglab('nogui'); %#ok<ASGLU>

fprintf('\n============================================================\n');
fprintf('K=6 CORE PILOT PSD ANALYSIS\n');
fprintf('============================================================\n');
fprintf('CORE STUDY:\n%s\n\n', coreStudyPath);
fprintf('CORE membership:\n%s\n\n', coreMembershipPath);
fprintf('Output folder:\n%s\n', resultFolder);
fprintf('============================================================\n\n');

