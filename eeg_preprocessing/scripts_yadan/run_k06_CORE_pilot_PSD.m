function verify_membership_against_study_local(STUDY, membership)

    memberKeys = ...
        string(membership.DatasetIndex) + "_" + ...
        string(membership.IC);

    if numel(unique(memberKeys)) ~= height(membership)
        error('Membership contains duplicate DatasetIndex-IC pairs.');
    end

    clusterIndices = unique( ...
        double(membership.ClusterIndex), ...
        'stable');

    for clusterIndex = reshape(clusterIndices, 1, [])

        rows = membership( ...
            double(membership.ClusterIndex) == clusterIndex, :);

        expectedPairs = sortrows( ...
            [ ...
                double(rows.DatasetIndex), ...
                double(rows.IC) ...
            ], ...
            [1 2]);

        actualPairs = sortrows( ...
            [ ...
                double(STUDY.cluster(clusterIndex).sets(:)), ...
                double(STUDY.cluster(clusterIndex).comps(:)) ...
            ], ...
            [1 2]);

        if ~isequal(expectedPairs, actualPairs)
            error([ ...
                'Membership CSV does not match CORE STUDY ' ...
                'cluster %d.'], ...
                clusterIndex);
        end
    end
end

function EEG = load_full_study_dataset_local( ...
        STUDY, ...
        ALLEEG, ...
        datasetIndex)

    expectedFilename = string( ...
        STUDY.datasetinfo(datasetIndex).filename);

    EEG = [];

    if datasetIndex <= numel(ALLEEG)

        candidate = ALLEEG(datasetIndex);

        if string(candidate.filename) == expectedFilename
            EEG = candidate;
        end
    end

    dataAreLoaded = ...
        ~isempty(EEG) && ...
        isnumeric(EEG.data) && ...
        ~isempty(EEG.data);

    if dataAreLoaded
        return;
    end

    datasetFilepath = string( ...
        STUDY.datasetinfo(datasetIndex).filepath);

    if datasetFilepath == ""
        error('Dataset %d has an empty filepath in STUDY.', ...
            datasetIndex);
    end

    fullDatasetPath = fullfile( ...
        datasetFilepath, ...
        expectedFilename);

    if ~isfile(fullDatasetPath)
        error('Dataset file was not found:\n%s', ...
            fullDatasetPath);
    end

    EEG = pop_loadset( ...
        'filename', char(expectedFilename), ...
        'filepath', char(datasetFilepath), ...
        'loadmode', 'all');

    EEG = eeg_checkset(EEG);
end

function activation = compute_single_ic_activation_local( ...
        EEG, ...
        componentIndex)

    data = double(reshape( ...
        EEG.data, ...
        EEG.nbchan, ...
        []));

    if isempty(EEG.icachansind)

        nIcaChannels = size(EEG.icasphere, 2);

        if nIcaChannels > size(data, 1)
            error('ICA channel count exceeds EEG channel count.');
        end

        icaChannelIndices = 1:nIcaChannels;

    else

        icaChannelIndices = double(EEG.icachansind(:))';
    end

    if any(icaChannelIndices < 1) || ...
            any(icaChannelIndices > size(data, 1))
        error('EEG.icachansind contains invalid channel indices.');
    end

    unmixingRow = ...
        double(EEG.icaweights(componentIndex, :)) * ...
        double(EEG.icasphere);

    activation = unmixingRow * ...
        data(icaChannelIndices, :);

    activation = double(activation(:)');
end

function [normalizedActivation, scalpMapRmsScale] = ...
        normalize_ic_activation_scale_local( ...
            EEG, ...
            componentIndex, ...
            activation)

    if isempty(EEG.icawinv)
        error('EEG.icawinv is empty; IC scale normalization is impossible.');
    end

    if componentIndex > size(EEG.icawinv, 2)
        error('IC %d exceeds EEG.icawinv column count.', componentIndex);
    end

    scalpMap = double(EEG.icawinv(:, componentIndex));

    validValues = scalpMap(isfinite(scalpMap));

    if isempty(validValues)
        error('IC %d scalp map contains no finite values.', componentIndex);
    end

    scalpMapRmsScale = sqrt(mean(validValues .^ 2));

    if ~isfinite(scalpMapRmsScale) || scalpMapRmsScale <= 0
        error('IC %d has an invalid scalp-map RMS scale.', componentIndex);
    end

    % ICA has an arbitrary component scaling: multiplying an activation by
    % c and dividing its scalp map by c leaves the sensor projection
    % unchanged. Multiplying the activation by RMS(icawinv(:,IC)) produces
    % a scale-invariant activation whose magnitude represents the RMS
    % sensor-space projection of that IC.
    normalizedActivation = ...
        double(activation) * scalpMapRmsScale;
end

function segments = get_continuous_segments_local( ...
        EEG, ...
        edgeTrimSec, ...
        minimumSegmentSamples, ...
        maxUsableDurationSec)

    nSamples = EEG.pnts * EEG.trials;

    boundaryLatencies = [];

    for eventIndex = 1:numel(EEG.event)

        eventType = EEG.event(eventIndex).type;

        while iscell(eventType) && numel(eventType) == 1
            eventType = eventType{1};
        end

        isBoundary = false;

        if ischar(eventType) || isstring(eventType)
            isBoundary = strcmpi( ...
                strtrim(string(eventType)), ...
                "boundary");
        end

        if ~isBoundary
            continue;
        end

        latency = double(EEG.event(eventIndex).latency);

        if isfinite(latency)
            boundaryLatencies(end+1) = latency; %#ok<AGROW>
        end
    end

    if isempty(boundaryLatencies)

        rawSegments = [1 nSamples];

    else

        splitSamples = unique( ...
            floor(boundaryLatencies));

        splitSamples = splitSamples( ...
            splitSamples >= 1 & ...
            splitSamples < nSamples);

        rawSegments = [ ...
            [1; splitSamples(:) + 1], ...
            [splitSamples(:); nSamples] ...
        ];
    end

    trimSamples = round(edgeTrimSec * EEG.srate);

    rawSegments(:, 1) = ...
        rawSegments(:, 1) + trimSamples;

    rawSegments(:, 2) = ...
        rawSegments(:, 2) - trimSamples;

    segmentLengths = ...
        rawSegments(:, 2) - ...
        rawSegments(:, 1) + 1;

    rawSegments = rawSegments( ...
        segmentLengths >= minimumSegmentSamples, :);

    if isempty(rawSegments)
        error([ ...
            'No continuous segment remains after boundary splitting ' ...
            'and edge trimming.']);
    end

    if isinf(maxUsableDurationSec)
        segments = rawSegments;
        return;
    end

    maximumSamples = round( ...
        maxUsableDurationSec * EEG.srate);

    segments = zeros(0, 2);
    usedSamples = 0;

    for segmentIndex = 1:size(rawSegments, 1)

        if usedSamples >= maximumSamples
            break;
        end

        startSample = rawSegments(segmentIndex, 1);
        endSample = rawSegments(segmentIndex, 2);

        availableSamples = ...
            endSample - startSample + 1;

        remainingSamples = ...
            maximumSamples - usedSamples;

        takeSamples = min( ...
            availableSamples, ...
            remainingSamples);

        if takeSamples < minimumSegmentSamples
            continue;
        end

        segments(end+1, :) = [ ... %#ok<AGROW>
            startSample, ...
            startSample + takeSamples - 1];

        usedSamples = usedSamples + takeSamples;
    end

    if isempty(segments)
        error('No segment satisfies maxUsableDurationSec.');
    end
end

function [ ...
        psdLinear, ...
        frequencyHz, ...
        numberOfWindows, ...
        analyzedDurationSec ...
    ] = compute_welch_psd_across_segments_local( ...
        signal, ...
        segments, ...
        samplingRate, ...
        windowLengthSec, ...
        overlapFraction)

    windowSamples = round( ...
        windowLengthSec * samplingRate);

    overlapSamples = round( ...
        overlapFraction * windowSamples);

    stepSamples = windowSamples - overlapSamples;

    if windowSamples < 4
        error('Welch window is too short.');
    end

    if stepSamples < 1
        error('Welch overlap leaves a non-positive step size.');
    end

    nfft = 2 ^ nextpow2(windowSamples);

    sampleIndex = (0:windowSamples-1)';

    if windowSamples == 1
        analysisWindow = 1;
    else
        analysisWindow = ...
            0.5 - ...
            0.5 * cos( ...
                2 * pi * sampleIndex / ...
                (windowSamples - 1));
    end

    windowEnergy = sum(analysisWindow .^ 2);

    positiveFrequencyCount = ...
        floor(nfft / 2) + 1;

    psdSum = zeros( ...
        positiveFrequencyCount, ...
        1);

    numberOfWindows = 0;
    analyzedSampleCount = 0;

    signal = double(signal(:));

    for segmentIndex = 1:size(segments, 1)

        startSample = segments(segmentIndex, 1);
        endSample = segments(segmentIndex, 2);

        segment = signal(startSample:endSample);
        segmentLength = numel(segment);

        frameStarts = ...
            1:stepSamples:(segmentLength - windowSamples + 1);

        for frameStart = frameStarts

            frame = segment( ...
                frameStart: ...
                frameStart + windowSamples - 1);

            if any(~isfinite(frame))
                continue;
            end

            frame = detrend(frame, 'linear');
            frame = frame .* analysisWindow;

            spectrum = fft(frame, nfft);

            twoSidedPsd = ...
                abs(spectrum) .^ 2 ./ ...
                (samplingRate * windowEnergy);

            oneSidedPsd = ...
                twoSidedPsd(1:positiveFrequencyCount);

            if rem(nfft, 2) == 0

                if numel(oneSidedPsd) > 2
                    oneSidedPsd(2:end-1) = ...
                        2 * oneSidedPsd(2:end-1);
                end

            else

                if numel(oneSidedPsd) > 1
                    oneSidedPsd(2:end) = ...
                        2 * oneSidedPsd(2:end);
                end
            end

            psdSum = psdSum + oneSidedPsd;
            numberOfWindows = numberOfWindows + 1;
        end

        analyzedSampleCount = ...
            analyzedSampleCount + segmentLength;
    end

    if numberOfWindows == 0
        error('No valid Welch windows were produced.');
    end

    psdLinear = ...
        psdSum ./ numberOfWindows;

    frequencyHz = ...
        (0:positiveFrequencyCount-1)' * ...
        samplingRate / nfft;

    analyzedDurationSec = ...
        analyzedSampleCount / samplingRate;
end

function metrics = compute_band_metrics_local( ...
        frequencyHz, ...
        psdLinear, ...
        referenceBandHz, ...
        thetaBandHz, ...
        muBandHz, ...
        betaBandHz, ...
        lowBetaBandHz, ...
        highBetaBandHz)

    frequencyHz = double(frequencyHz(:));
    psdLinear = double(psdLinear(:));

    referencePower = integrate_band_local( ...
        frequencyHz, ...
        psdLinear, ...
        referenceBandHz, ...
        true);

    thetaPower = integrate_band_local( ...
        frequencyHz, ...
        psdLinear, ...
        thetaBandHz, ...
        false);

    muPower = integrate_band_local( ...
        frequencyHz, ...
        psdLinear, ...
        muBandHz, ...
        false);

    betaPower = integrate_band_local( ...
        frequencyHz, ...
        psdLinear, ...
        betaBandHz, ...
        true);

    lowBetaPower = integrate_band_local( ...
        frequencyHz, ...
        psdLinear, ...
        lowBetaBandHz, ...
        false);

    highBetaPower = integrate_band_local( ...
        frequencyHz, ...
        psdLinear, ...
        highBetaBandHz, ...
        true);

    metrics = struct();

    metrics.ThetaPowerDb = safe_db_local(thetaPower);
    metrics.MuPowerDb = safe_db_local(muPower);
    metrics.BetaPowerDb = safe_db_local(betaPower);
    metrics.LowBetaPowerDb = safe_db_local(lowBetaPower);
    metrics.HighBetaPowerDb = safe_db_local(highBetaPower);

    metrics.ThetaRelativePct = ...
        safe_relative_percent_local( ...
            thetaPower, referencePower);

    metrics.MuRelativePct = ...
        safe_relative_percent_local( ...
            muPower, referencePower);

    metrics.BetaRelativePct = ...
        safe_relative_percent_local( ...
            betaPower, referencePower);

    metrics.LowBetaRelativePct = ...
        safe_relative_percent_local( ...
            lowBetaPower, referencePower);

    metrics.HighBetaRelativePct = ...
        safe_relative_percent_local( ...
            highBetaPower, referencePower);

    muMask = ...
        frequencyHz >= muBandHz(1) & ...
        frequencyHz < muBandHz(2) & ...
        isfinite(psdLinear);

    if any(muMask)

        muFrequencies = frequencyHz(muMask);
        muPsd = psdLinear(muMask);

        [peakPower, peakIndex] = max(muPsd);

        metrics.MuPeakFrequencyHz = ...
            muFrequencies(peakIndex);

        metrics.MuPeakPsdDb = ...
            safe_db_local(peakPower);

    else

        metrics.MuPeakFrequencyHz = NaN;
        metrics.MuPeakPsdDb = NaN;
    end
end

function bandPower = integrate_band_local( ...
        frequencyHz, ...
        psdLinear, ...
        bandHz, ...
        includeUpperBoundary)

    if includeUpperBoundary

        mask = ...
            frequencyHz >= bandHz(1) & ...
            frequencyHz <= bandHz(2);

    else

        mask = ...
            frequencyHz >= bandHz(1) & ...
            frequencyHz < bandHz(2);
    end

    mask = mask & ...
        isfinite(psdLinear);

    if sum(mask) < 2
        bandPower = NaN;
        return;
    end

    bandPower = trapz( ...
        frequencyHz(mask), ...
        psdLinear(mask));
end

function valueDb = safe_db_local(valueLinear)

    if ~isfinite(valueLinear) || ...
            valueLinear <= 0

        valueDb = NaN;

    else

        valueDb = 10 * log10(valueLinear);
    end
end

function relativePercent = safe_relative_percent_local( ...
        bandPower, ...
        referencePower)

    if ~isfinite(bandPower) || ...
            ~isfinite(referencePower) || ...
            referencePower <= 0

        relativePercent = NaN;

    else

        relativePercent = ...
            100 * bandPower / referencePower;
    end
end

function longTable = build_psd_long_table_local( ...
        metadataTable, ...
        frequencyHz, ...
        psdLinearMatrix)

    nRows = height(metadataTable);
    nFrequencies = numel(frequencyHz);

    repeatedMetadata = metadataTable( ...
        repelem((1:nRows)', nFrequencies), :);

    repeatedMetadata.Frequency_Hz = repmat( ...
        frequencyHz(:), ...
        nRows, ...
        1);

    repeatedMetadata.PSD_uV2_per_Hz = reshape( ...
        psdLinearMatrix', ...
        [], ...
        1);

    repeatedMetadata.PSD_dB_uV2_per_Hz = ...
        10 * log10( ...
            repeatedMetadata.PSD_uV2_per_Hz);

    longTable = repeatedMetadata;
end

