%% Detect real gaps in the EEG timestamp vector

eegTimestampDifferenceSec = ...
    diff(eegTimeStamps(:));

medianEEGSampleIntervalSec = ...
    median(eegTimestampDifferenceSec);

timestampGapThresholdSec = max( ...
    timestampGapFactor * medianEEGSampleIntervalSec, ...
    minimumTimestampGapSec);

gapBeforeSample = find( ...
    eegTimestampDifferenceSec > timestampGapThresholdSec);

gapAfterSample = ...
    gapBeforeSample + 1;

if isempty(gapBeforeSample)

    eegTimestampGapTable = table( ...
        'Size', ...
        [0 8], ...
        'VariableTypes', { ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double'}, ...
        'VariableNames', { ...
            'GapIndex', ...
            'SampleBeforeGap', ...
            'SampleAfterGap', ...
            'LSLBeforeGap', ...
            'LSLAfterGap', ...
            'TimestampJumpSec', ...
            'MissingDurationSec', ...
            'MissingSampleCount'});

else

    timestampJumpSec = ...
        eegTimestampDifferenceSec(gapBeforeSample);

    missingDurationSec = max( ...
        0, ...
        timestampJumpSec - medianEEGSampleIntervalSec);

    missingSampleCount = max( ...
        0, ...
        round(timestampJumpSec * targetEEGSrate) - 1);

    eegTimestampGapTable = table( ...
        (1:numel(gapBeforeSample))', ...
        double(gapBeforeSample(:)), ...
        double(gapAfterSample(:)), ...
        reshape( ...
            double(eegTimeStamps(gapBeforeSample)), ...
            [], ...
            1), ...
        reshape( ...
            double(eegTimeStamps(gapAfterSample)), ...
            [], ...
            1), ...
        double(timestampJumpSec(:)), ...
        double(missingDurationSec(:)), ...
        double(missingSampleCount(:)), ...
        'VariableNames', { ...
            'GapIndex', ...
            'SampleBeforeGap', ...
            'SampleAfterGap', ...
            'LSLBeforeGap', ...
            'LSLAfterGap', ...
            'TimestampJumpSec', ...
            'MissingDurationSec', ...
            'MissingSampleCount'});
end

fprintf('\nEEG timestamp-gap check:\n');

