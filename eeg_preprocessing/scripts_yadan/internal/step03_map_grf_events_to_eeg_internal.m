%% Map each GRF event to a real EEG sample

allEventTable = ...
    sortrows(allEventTable, 'LSLTime');

eventTypes = ...
    string(allEventTable.EventType);

grfEventLSLTime = ...
    double(allEventTable.LSLTime);

insideEEGRange = ...
    grfEventLSLTime >= eegTimeStamps(1) & ...
    grfEventLSLTime <= eegTimeStamps(end);

if any(~insideEEGRange)

    outsideRows = allEventTable( ...
        ~insideEEGRange, ...
        {'EventType', 'LSLTime'});

    disp(outsideRows);

    error([ ...
        '%d GRF events are outside the EEG timestamp range.\n' ...
        'No EEG file was saved. Check the walking interval and source XDF.'], ...
        sum(~insideEEGRange));
end

nearestEEGSample = interp1( ...
    eegTimeStamps, ...
    1:numel(eegTimeStamps), ...
    grfEventLSLTime, ...
    'nearest');

nearestEEGSample = ...
    round(nearestEEGSample(:));

if any(~isfinite(nearestEEGSample)) || ...
        any(nearestEEGSample < 1) || ...
        any(nearestEEGSample > numel(eegTimeStamps))

    error('One or more GRF events could not be mapped to an EEG sample.');
end

nearestEEGLSLTime = ...
    eegTimeStamps(nearestEEGSample);

nearestEEGLSLTime = ...
    nearestEEGLSLTime(:);

nearestMappingErrorMs = ...
    1000 * (nearestEEGLSLTime - grfEventLSLTime);

eventInsideTimestampGap = ...
    false(height(allEventTable), 1);

eventTimestampGapIndex = ...
    nan(height(allEventTable), 1);

for iGap = 1:height(eegTimestampGapTable)

    currentEventsInsideGap = ...
        grfEventLSLTime > ...
            eegTimestampGapTable.LSLBeforeGap(iGap) & ...
        grfEventLSLTime < ...
            eegTimestampGapTable.LSLAfterGap(iGap);

    eventInsideTimestampGap = ...
        eventInsideTimestampGap | ...
        currentEventsInsideGap;

    eventTimestampGapIndex(currentEventsInsideGap) = ...
        eegTimestampGapTable.GapIndex(iGap);
end

unexplainedBadMapping = ...
    abs(nearestMappingErrorMs) > maximumMappingErrorMs & ...
    ~eventInsideTimestampGap;

if any(unexplainedBadMapping)

    badRows = find(unexplainedBadMapping);

    disp(table( ...
        eventTypes(badRows), ...
        grfEventLSLTime(badRows), ...
        nearestEEGSample(badRows), ...
        nearestEEGLSLTime(badRows), ...
        nearestMappingErrorMs(badRows), ...
        'VariableNames', { ...
            'EventType', ...
            'GRFEventLSLTime', ...
            'NearestEEGSample', ...
            'NearestEEGLSLTime', ...
            'NearestMappingErrorMs'}));

    error([ ...
        '%d event mappings exceed %.3f ms and are not explained ' ...
        'by a detected EEG timestamp gap.\n' ...
        'No EEG file was saved.'], ...
        numel(badRows), ...
        maximumMappingErrorMs);
end

