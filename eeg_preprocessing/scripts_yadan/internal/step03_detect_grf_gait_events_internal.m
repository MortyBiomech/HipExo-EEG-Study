function set_zoom_y_limits( ...
        targetAxes, ...
        relativeTime, ...
        signals, ...
        zoomWindowSec, ...
        additionalValues)

visibleSamples = ...
    relativeTime >= zoomWindowSec(1) & ...
    relativeTime <= zoomWindowSec(2);

visibleValues = ...
    double(signals(visibleSamples, :));

visibleValues = ...
    visibleValues(isfinite(visibleValues));

additionalValues = ...
    double(additionalValues(:));

additionalValues = ...
    additionalValues(isfinite(additionalValues));

allValues = [ ...
    visibleValues(:); ...
    additionalValues];

if isempty(allValues)
    return;
end

lowerLimit = ...
    min(0, min(allValues));

upperLimit = ...
    max(allValues);

if upperLimit <= lowerLimit

    upperLimit = ...
        lowerLimit + 1;
end

padding = ...
    0.08 * (upperLimit - lowerLimit);

ylim( ...
    targetAxes, ...
    [ ...
        lowerLimit - 0.25 * padding, ...
        upperLimit + padding]);

end

function [alignedEvents, ...
          canMerge, ...
          structureChanged, ...
          changeDescription] = ...
        align_existing_event_table( ...
            existingEvents, ...
            templateEvents)

alignedEvents = ...
    existingEvents;

canMerge = true;
structureChanged = false;
changeMessages = strings(0, 1);

expectedNames = ...
    string(templateEvents.Properties.VariableNames);

existingNames = ...
    string(alignedEvents.Properties.VariableNames);

%% Normalize case-only differences in column names

for iExpected = 1:numel(expectedNames)

    exactMatch = find( ...
        existingNames == expectedNames(iExpected));

    if ~isempty(exactMatch)
        continue;
    end

    caseInsensitiveMatch = find( ...
        strcmpi( ...
            existingNames, ...
            expectedNames(iExpected)));

    if numel(caseInsensitiveMatch) == 1

        alignedEvents.Properties.VariableNames{ ...
            caseInsensitiveMatch} = ...
            char(expectedNames(iExpected));

        existingNames(caseInsensitiveMatch) = ...
            expectedNames(iExpected);

        structureChanged = true;
    end
end

existingNames = ...
    string(alignedEvents.Properties.VariableNames);

missingNames = setdiff( ...
    expectedNames, ...
    existingNames, ...
    'stable');

extraNames = setdiff( ...
    existingNames, ...
    expectedNames, ...
    'stable');

if ~isempty(missingNames)

    structureChanged = true;

    changeMessages(end + 1) = ...
        "added missing columns: " + ...
        strjoin(missingNames, ", "); %#ok<AGROW>
end

if ~isempty(extraNames)

    structureChanged = true;

    changeMessages(end + 1) = ...
        "removed obsolete columns: " + ...
        strjoin(extraNames, ", "); %#ok<AGROW>
end

if ~ismember("XDFPath", existingNames)

    canMerge = false;

    changeMessages(end + 1) = ...
        "old CSV had no XDFPath column"; %#ok<AGROW>

    changeDescription = ...
        char(strjoin(changeMessages, "; "));

    return;
end

nExistingRows = ...
    height(alignedEvents);

%% Add missing columns with compatible data types

for iMissing = 1:numel(missingNames)

    variableName = ...
        char(missingNames(iMissing));

    templateColumn = ...
        templateEvents.(variableName);

    if isstring(templateColumn)

        alignedEvents.(variableName) = ...
            strings(nExistingRows, 1);

    elseif isnumeric(templateColumn)

        alignedEvents.(variableName) = ...
            nan(nExistingRows, 1);

    elseif islogical(templateColumn)

        alignedEvents.(variableName) = ...
            false(nExistingRows, 1);

    else

        canMerge = false;

        changeMessages(end + 1) = ...
            "unsupported missing column type: " + ...
            string(variableName); %#ok<AGROW>

        changeDescription = ...
            char(strjoin(changeMessages, "; "));

        return;
    end
end

%% Convert existing columns to current data types

for iExpected = 1:numel(expectedNames)

    variableName = ...
        char(expectedNames(iExpected));

    templateColumn = ...
        templateEvents.(variableName);

    existingColumn = ...
        alignedEvents.(variableName);

    if isstring(templateColumn)

        if ~isstring(existingColumn)
            structureChanged = true;
        end

        alignedEvents.(variableName) = ...
            string(existingColumn);

    elseif isnumeric(templateColumn)

        if isnumeric(existingColumn)

            if ~isa(existingColumn, 'double')
                structureChanged = true;
            end

            alignedEvents.(variableName) = ...
                double(existingColumn);

        else

            structureChanged = true;

            alignedEvents.(variableName) = ...
                str2double(string(existingColumn));
        end

    elseif islogical(templateColumn)

        if ~islogical(existingColumn)
            structureChanged = true;
        end

        alignedEvents.(variableName) = ...
            logical(existingColumn);
    end
end

alignedEvents = ...
    alignedEvents(:, cellstr(expectedNames));

if structureChanged && isempty(changeMessages)

    changeMessages = ...
        "normalized column names or data types";
end

changeDescription = ...
    char(strjoin(changeMessages, "; "));

end

function backupFile = ...
        make_csv_backup_path(sharedCSVFile)

[csvFolder, csvBaseName, csvExtension] = ...
    fileparts(sharedCSVFile);

timeStamp = char(datetime( ...
    'now', ...
    'Format', ...
    'yyyyMMdd_HHmmss'));

backupFile = fullfile( ...
    csvFolder, ...
    sprintf( ...
        '%s_backup_%s%s', ...
        csvBaseName, ...
        timeStamp, ...
        csvExtension));

backupIndex = 1;

while isfile(backupFile)

    backupFile = fullfile( ...
        csvFolder, ...
        sprintf( ...
            '%s_backup_%s_%02d%s', ...
            csvBaseName, ...
            timeStamp, ...
            backupIndex, ...
            csvExtension));

    backupIndex = ...
        backupIndex + 1;
end

