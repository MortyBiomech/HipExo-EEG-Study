function conditions = canonical_condition_local(values)

values = string(values(:));
conditions = strings(size(values));

for valueIndex = 1:numel(values)

    key = lower(char(values(valueIndex)));
    key = regexprep(key, '[^a-z0-9]', '');

    if contains(key, 'noexo') && contains(key, 'pre')
        conditions(valueIndex) = "NoExoPre";

    elseif contains(key, 'noexo') && contains(key, 'post')
        conditions(valueIndex) = "NoExoPost";

    elseif contains(key, 'aquaplus') || contains(key, 'aquaextra')
        conditions(valueIndex) = "AquaPlus";

    elseif contains(key, 'transparent') || contains(key, 'exooff')
        conditions(valueIndex) = "Transparent";

    elseif contains(key, 'sport')
        conditions(valueIndex) = "Sport";

    elseif contains(key, 'boost')
        conditions(valueIndex) = "Boost";

    elseif contains(key, 'aqua')
        conditions(valueIndex) = "Aqua";

    elseif contains(key, 'eco') || strcmp(key, 'exo') || ...
            ~isempty(regexp(key, 'exo\d*(on)?$', 'once'))
        conditions(valueIndex) = "Exo";

    else
        error('Cannot canonicalize condition label: %s', ...
            char(values(valueIndex)));
    end
end

end

function key = subject_identity_key_local(value)

value = strtrim(string(value));

if ~isscalar(value) || ismissing(value) || strlength(value) == 0
    error('Participant identity must be one non-empty text value.');
end

key = lower(value);
key = regexprep(key, '^sub-', '');
key = regexprep(key, '^p(?=\d)', 'pilot');
key = regexprep(key, '[^a-z0-9]', '');

if strlength(key) == 0
    error('Participant identity cannot be normalized: %s', value);
end

end
