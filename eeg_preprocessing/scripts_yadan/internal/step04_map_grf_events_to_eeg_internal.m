function [selectedIndex, streamSummary] = ...
        find_real_eeg_stream( ...
            streams, ...
            expectedName, ...
            expectedChannels, ...
            targetSrate)

nStreams = numel(streams);

streamIndex = ...
    (1:nStreams)';

streamName = ...
    strings(nStreams, 1);

streamType = ...
    strings(nStreams, 1);

nominalSrate = ...
    nan(nStreams, 1);

channelCount = ...
    nan(nStreams, 1);

sampleCount = ...
    nan(nStreams, 1);

for iStream = 1:nStreams

    currentStream = ...
        streams{iStream};

    streamName(iStream) = ...
        get_stream_text_field( ...
            currentStream, ...
            'name');

    streamType(iStream) = ...
        get_stream_text_field( ...
            currentStream, ...
            'type');

    nominalSrate(iStream) = ...
        get_stream_nominal_srate( ...
            currentStream);

    if isfield(currentStream, 'time_series') && ...
            isnumeric(currentStream.time_series)

        currentData = ...
            currentStream.time_series;

        currentTimestamps = ...
            currentStream.time_stamps;

        sampleCount(iStream) = ...
            numel(currentTimestamps);

        if size(currentData, 2) == sampleCount(iStream)

            channelCount(iStream) = ...
                size(currentData, 1);

        elseif size(currentData, 1) == sampleCount(iStream)

            channelCount(iStream) = ...
                size(currentData, 2);
        end
    end
end

streamSummary = table( ...
    streamIndex, ...
    streamName, ...
    streamType, ...
    nominalSrate, ...
    channelCount, ...
    sampleCount, ...
    'VariableNames', { ...
        'StreamIndex', ...
        'Name', ...
        'Type', ...
        'NominalSrate', ...
        'ChannelCount', ...
        'SampleCount'});

exactNameMatch = ...
    strcmpi(streamName, expectedName) & ...
    channelCount >= expectedChannels & ...
    channelCount <= expectedChannels + 16 & ...
    abs(nominalSrate - targetSrate) <= 1;

candidateIndices = ...
    find(exactNameMatch);

if isempty(candidateIndices)

    fallbackMatch = ...
        channelCount >= expectedChannels & ...
        channelCount <= expectedChannels + 16 & ...
        abs(nominalSrate - targetSrate) <= 1 & ...
        (contains(lower(streamType), 'eeg') | ...
         contains(lower(streamName), 'liveamp'));

    candidateIndices = ...
        find(fallbackMatch);
end

if numel(candidateIndices) ~= 1

    disp(streamSummary);

    error([ ...
        'Could not identify exactly one real EEG stream near %.9g Hz.\n' ...
        'Number of candidates: %d'], ...
        targetSrate, ...
        numel(candidateIndices));
end

selectedIndex = ...
    candidateIndices(1);

end

function [selectedIndices, droppedIndices, selectionMethod] = ...
        select_project_eeg_channels( ...
            rawLabels, ...
            projectLabels, ...
            rawChannelCount, ...
            expectedChannelCount, ...
            expectedAuxiliaryLabels, ...
            expectedStreamName)

selectedIndices = [];
droppedIndices = [];
selectionMethod = "";

rawLabels = ...
    string(rawLabels(:));

projectLabels = ...
    string(projectLabels(:));

expectedAuxiliaryLabels = ...
    string(expectedAuxiliaryLabels(:));

if numel(rawLabels) ~= rawChannelCount || ...
        any(strlength(strtrim(rawLabels)) == 0)

    error([ ...
        'The BIDS-derived EEG recording does not provide a complete channel-label ' ...
        'list. The ACC channels cannot be removed safely by label.']);
end

normalizedRawLabels = ...
    rawLabels;

streamPrefix = ...
    string(expectedStreamName) + "_";

hasStreamPrefix = startsWith( ...
    normalizedRawLabels, ...
    streamPrefix, ...
    'IgnoreCase', ...
    true);

normalizedRawLabels(hasStreamPrefix) = extractAfter( ...
    normalizedRawLabels(hasStreamPrefix), ...
    strlength(streamPrefix));

if rawChannelCount == expectedChannelCount + ...
        numel(expectedAuxiliaryLabels)

    auxiliaryIndices = nan( ...
        numel(expectedAuxiliaryLabels), ...
        1);

    for iAuxiliary = 1:numel(expectedAuxiliaryLabels)

        currentMatch = find(strcmpi( ...
            strtrim(normalizedRawLabels), ...
            strtrim(expectedAuxiliaryLabels(iAuxiliary))));

        if numel(currentMatch) ~= 1

            error([ ...
                'Expected exactly one %s channel in the 67-channel ' ...
                'LiveAmp stream, but found %d.'], ...
                expectedAuxiliaryLabels(iAuxiliary), ...
                numel(currentMatch));
        end

        auxiliaryIndices(iAuxiliary) = ...
            currentMatch;
    end

    if numel(unique(auxiliaryIndices)) ~= ...
            numel(expectedAuxiliaryLabels)

        error('The ACC channel-label matches are not unique.');
    end

    droppedIndices = ...
        auxiliaryIndices;

elseif rawChannelCount == expectedChannelCount

    droppedIndices = ...
        zeros(0, 1);

else

    error([ ...
        'Expected either %d EEG channels or %d channels ' ...
        '(64 EEG + ACC_X/ACC_Y/ACC_Z), but found %d.'], ...
        expectedChannelCount, ...
        expectedChannelCount + numel(expectedAuxiliaryLabels), ...
        rawChannelCount);
end

remainingIndices = setdiff( ...
    (1:rawChannelCount)', ...
    droppedIndices, ...
    'stable');

if numel(remainingIndices) ~= expectedChannelCount

    error([ ...
        'Removing ACC_X/ACC_Y/ACC_Z did not leave exactly %d EEG ' ...
        'channels. Remaining channels: %d'], ...
        expectedChannelCount, ...
        numel(remainingIndices));
end

if numel(projectLabels) ~= expectedChannelCount || ...
        any(strlength(strtrim(projectLabels)) == 0)

    error('chanlocs.ced does not contain 64 valid channel labels.');
end

matchedIndices = ...
    nan(expectedChannelCount, 1);

for iChannel = 1:expectedChannelCount

    currentMatch = remainingIndices(strcmpi( ...
        strtrim(normalizedRawLabels(remainingIndices)), ...
        strtrim(projectLabels(iChannel))));

    if numel(currentMatch) ~= 1

        error([ ...
            'Could not match chanlocs.ced channel %s uniquely in the ' ...
            'BIDS-derived EEG recording. Number of matches: %d'], ...
            projectLabels(iChannel), ...
            numel(currentMatch));
    end

    matchedIndices(iChannel) = ...
        currentMatch;
end

if numel(unique(matchedIndices)) ~= expectedChannelCount

    error('The 64 EEG channel-label matches are not unique.');
end

selectedIndices = ...
    matchedIndices;

if isempty(droppedIndices)

    selectionMethod = ...
        "matched_64_EEG_channels_to_chanlocs_labels";

else

    selectionMethod = ...
        "removed_ACC_X_ACC_Y_ACC_Z_then_matched_chanlocs_labels";
end

end

function channelLabels = ...
        get_stream_channel_labels( ...
            stream, ...
            channelCount)

channelLabels = ...
    strings(channelCount, 1);

if ~isfield(stream, 'info') || ...
        ~isfield(stream.info, 'desc')

    return;
end

description = ...
    stream.info.desc;

while iscell(description) && ...
        numel(description) == 1

    description = ...
        description{1};
end

if ~isstruct(description) || ...
        ~isfield(description, 'channels')

    return;
end

channelsNode = ...
    description.channels;

while iscell(channelsNode) && ...
        numel(channelsNode) == 1

    channelsNode = ...
        channelsNode{1};
end

if ~isstruct(channelsNode) || ...
        ~isfield(channelsNode, 'channel')

    return;
end

channelEntries = ...
    channelsNode.channel;

if iscell(channelEntries)

    numberOfEntries = min( ...
        channelCount, ...
        numel(channelEntries));

    for iChannel = 1:numberOfEntries

        channelLabels(iChannel) = ...
            get_channel_entry_label( ...
                channelEntries{iChannel});
    end

elseif isstruct(channelEntries)

    numberOfEntries = min( ...
        channelCount, ...
        numel(channelEntries));

    for iChannel = 1:numberOfEntries

        channelLabels(iChannel) = ...
            get_channel_entry_label( ...
                channelEntries(iChannel));
    end
end

end

function channelLabel = ...
        get_channel_entry_label(channelEntry)

channelLabel = "";

while iscell(channelEntry) && ...
        numel(channelEntry) == 1

    channelEntry = ...
        channelEntry{1};
end

if ~isstruct(channelEntry) || ...
        ~isfield(channelEntry, 'label')

    return;
end

rawLabel = ...
    channelEntry.label;

while iscell(rawLabel) && ...
        ~isempty(rawLabel)

    rawLabel = ...
        rawLabel{1};
end

if isempty(rawLabel)

    return;
end

channelLabel = ...
    string(rawLabel);

channelLabel = ...
    channelLabel(1);

end

