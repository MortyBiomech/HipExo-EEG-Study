% GOAL
%   Map GRF-derived gait events onto the corresponding BIDS-derived EEGLAB
%   recording using the original XDF EEG timestamps as LSL timing provenance.
%
% INPUT
%   batchEventFile          Per-recording GRF gait-event MAT.
%   batchBidsEEGLABSet      Run-separated BIDS-derived EEGLAB dataset.
%   batchOutputStem         Canonical BIDS entity stem.
%   batchCanonicalSubject   Canonical SubjectID from Step 02 (sub-XX).
%   batchOriginalSubject    Original acquisition identity for provenance.
%   batchGRFOutputFolder    Subject GRF output folder.
%   batchEEGOutputFolder    Subject EEG-with-GRF-events output folder.
%
% APPROACH
%   1. Treat Step 02 SubjectID as the authoritative analysis identity.
%   2. Cross-check canonical/original identity across the event MAT, XDF,
%      import-table row, and BIDS-derived EEG before normalizing labels.
%   3. Verify source condition/run metadata and exact XDF/BIDS sample identity.
%   4. Map GRF event LSL times to real EEG samples without resampling.
%   5. Exclude events inside genuine EEG timestamp gaps and add boundaries.
%   6. Save the mapped EEG plus mapping/timestamp-gap audit tables.
%
% OUTPUT
%   *_desc-grfevents_eeg.set
%   *_desc-grfeventmapping_events.csv
%   *_desc-eegtimestampgaps_events.csv
%
% USED BY
%   step04_process_subject_grf_eeg.m

function step04_map_grf_events_to_eeg_internal( ...
        batchEventFile, batchBidsEEGLABSet, batchOutputStem, ...
        batchCanonicalSubject, batchOriginalSubject, ...
        batchGRFOutputFolder, batchEEGOutputFolder)
% GOAL
%   Map GRF-derived gait events onto one explicitly supplied run-separated
%   EEGLAB recording created FROM BIDS in Step 02B.
%
% INPUT
%   batchEventFile          GRF gait-event MAT for this recording.
%   batchBidsEEGLABSet      Canonical BIDS-derived, unresampled EEGLAB set.
%   batchOutputStem         Canonical BIDS entity stem for derivative names.
%   batchCanonicalSubject   Canonical participant identity, e.g. sub-01.
%   batchOriginalSubject    Original acquisition identity for provenance only.
%   batchGRFOutputFolder    GRF/event output folder.
%   batchEEGOutputFolder    Mapped EEG output folder.
%
% METHOD
%   BIDS-derived EEGLAB supplies all EEG amplitudes. Source XDF supplies only
%   the original LSL EEG timestamps required for GRF-to-EEG alignment. Paths
%   and identities are explicit function arguments; no environment-variable
%   worker state is used.

if nargin < 1, batchEventFile = ""; end
if nargin < 2, batchBidsEEGLABSet = ""; end
if nargin < 3, batchOutputStem = ""; end
if nargin < 4, batchCanonicalSubject = ""; end
if nargin < 5, batchOriginalSubject = ""; end
if nargin < 6, batchGRFOutputFolder = ""; end
if nargin < 7, batchEEGOutputFolder = ""; end

batchEventFile = char(strtrim(string(batchEventFile)));
batchBidsEEGLABSet = char(strtrim(string(batchBidsEEGLABSet)));
batchOutputStem = char(strtrim(string(batchOutputStem)));
batchCanonicalSubject = char(strtrim(string(batchCanonicalSubject)));
batchOriginalSubject = char(strtrim(string(batchOriginalSubject)));
batchGRFOutputFolder = char(strtrim(string(batchGRFOutputFolder)));
batchEEGOutputFolder = char(strtrim(string(batchEEGOutputFolder)));
batchModeRequested = ~isempty(batchEventFile) || ~isempty(batchBidsEEGLABSet) || ...
    ~isempty(batchGRFOutputFolder) || ~isempty(batchEEGOutputFolder);

processingVersion = ...
    "GRF_to_BIDS_EEGLAB_mapping_v6_retained_samples";

if ~batchModeRequested
    clc;
    close all;
end

%% Load project paths and Step 03 configuration

scriptsRoot = hipexo.project_root();
addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();
cfg = config_step03_04_grf_processing();
eegQC = config_step01_02_xdf_import();

grfSegmentationFolder = P.grfSegmentationFolder;
channelLocationFile = P.channelLocationFile;

if ~isempty(batchGRFOutputFolder)
    grfSegmentationFolder = batchGRFOutputFolder;
end

if ~isfolder(grfSegmentationFolder)
    error('The GRF output folder does not exist:\n%s', ...
        grfSegmentationFolder);
end

if ~isfile(channelLocationFile)
    error('Cannot find channel-location file:\n%s', ...
        channelLocationFile);
end

if isempty(batchBidsEEGLABSet) || ~isfile(batchBidsEEGLABSet)
    error(['Step 04 requires a valid run-separated BIDS-derived EEGLAB set.\n' ...
        'Input BIDS-derived EEGLAB set: %s'], batchBidsEEGLABSet);
end

sourceBidsEEGLABSet = string(batchBidsEEGLABSet);
sourceBidsEEGLABSignature = hipexo.eeglab_dataset_signature(char(sourceBidsEEGLABSet));

if isempty(batchOutputStem)
    [~, rawStem] = fileparts(batchBidsEEGLABSet);
    batchOutputStem = regexprep(rawStem, '_desc-bidsraw_eeg$', '');
end

if ~isempty(batchEEGOutputFolder)
    eegEventOutputFolder = batchEEGOutputFolder;
else
    eegEventOutputFolder = P.eegWithGRFEventsFolder;
end

if ~isfolder(eegEventOutputFolder)
    mkdir(eegEventOutputFolder);
end

%% Mapping settings

expectedEEGStreamName = cfg.mapping.expectedEEGStreamName;
expectedEEGChannels = cfg.mapping.expectedEEGChannels;
expectedAuxiliaryLabels = cfg.mapping.expectedAuxiliaryLabels;
targetEEGSrate = cfg.mapping.targetEEGSrateHz;
maximumMappingErrorMs = cfg.mapping.maximumMappingErrorMs;
timestampGapFactor = cfg.mapping.timestampGapFactor;
minimumTimestampGapSec = cfg.mapping.minimumTimestampGapSec;

%% Select one saved per-XDF GRF event file

if ~isempty(batchEventFile)

    sourceEventFile = batchEventFile;

else

    eventFileFilter = fullfile( ...
        grfSegmentationFolder, ...
        '*.mat');

    [selectedFile, selectedFolder] = uigetfile( ...
        eventFileFilter, ...
        'Select one GRF gait-event MAT file');

    if isequal(selectedFile, 0)
        error('No GRF gait-event file was selected.');
    end

    sourceEventFile = fullfile( ...
        selectedFolder, ...
        selectedFile);
end

if ~isfile(sourceEventFile)
    error('Cannot find the GRF gait-event MAT file:\n%s', ...
        sourceEventFile);
end

sourceEventSignature = hipexo.file_metadata_signature(sourceEventFile);

loadedEvents = load(sourceEventFile);

if ~isfield(loadedEvents, 'allEventTable')
    error([ ...
        'The selected MAT file does not contain allEventTable:\n%s'], ...
        sourceEventFile);
end

allEventTable = loadedEvents.allEventTable;

requiredEventVariables = { ...
    'Subject', ...
    'Condition', ...
    'EventType', ...
    'Side', ...
    'SegmentIndex', ...
    'LSLTime', ...
    'XDFPath'};

if ~all(ismember( ...
        requiredEventVariables, ...
        allEventTable.Properties.VariableNames))

    error([ ...
        'The event table is missing one or more required variables:\n%s'], ...
        strjoin(requiredEventVariables, ', '));
end

if isempty(allEventTable)
    error('The selected event table is empty.');
end

eventTypes = string(allEventTable.EventType);
validEventTypes = ["RHS", "RTO", "LHS", "LTO"];

if any(~ismember(eventTypes, validEventTypes))
    error('The event table contains an unexpected EventType.');
end

xdfPaths = unique(string(allEventTable.XDFPath));
xdfPaths(strlength(xdfPaths) == 0) = [];

if numel(xdfPaths) ~= 1
    error([ ...
        'The selected event MAT must contain events from exactly one XDF.\n' ...
        'Number of unique XDF paths found: %d'], ...
        numel(xdfPaths));
end

xdfFile = xdfPaths(1);

if ~isfile(xdfFile)
    error('Cannot find the source XDF:\n%s', xdfFile);
end

sourceXDFSignature = hipexo.file_metadata_signature(xdfFile);

sourceMetadata = ...
    parse_xdf_source_metadata(xdfFile);

canonicalSubject = ...
    strtrim(string(batchCanonicalSubject));

originalSubject = ...
    strtrim(string(batchOriginalSubject));

if ismissing(canonicalSubject) || ...
        strlength(canonicalSubject) == 0

    error('Canonical participant identity is missing for GRF-to-EEG mapping.');
end

if isempty(regexp( ...
        char(canonicalSubject), ...
        '^sub-[0-9]+$', ...
        'once'))

    error([ ...
        'Invalid canonical participant identity: %s\n' ...
        'Expected the Step 02 SubjectID format sub-XX.'], ...
        canonicalSubject);
end

if ismissing(originalSubject) || ...
        strlength(originalSubject) == 0

    error('Original participant identity is missing for GRF-to-EEG mapping.');
end

eventSubjectValues = ...
    unique(strtrim(string(allEventTable.Subject)));

eventSubjectValues( ...
    ismissing(eventSubjectValues) | ...
    strlength(eventSubjectValues) == 0) = [];

if numel(eventSubjectValues) ~= 1

    error([ ...
        'GRF event table must contain exactly one non-empty Subject label. ' ...
        'Found: %s'], ...
        strjoin(eventSubjectValues, ', '));
end

eventSubjectKey = ...
    subject_identity_key_local(eventSubjectValues(1));

if eventSubjectKey ~= subject_identity_key_local(canonicalSubject) && ...
        eventSubjectKey ~= subject_identity_key_local(originalSubject)

    error([ ...
        'GRF event-table Subject belongs to a different participant.\n' ...
        'Event table: %s | Canonical: %s | Original: %s'], ...
        eventSubjectValues(1), ...
        canonicalSubject, ...
        originalSubject);
end

% Step 02 is the authoritative participant-identity source. Older GRF
% event MAT files may contain the legacy raw-XDF label (for example
% Pilot2_3). Normalize the in-memory event table to the canonical sub-XX
% identity before mapping; the original XDF identity remains available
% separately in provenance metadata.
allEventTable.Subject(:) = canonicalSubject;

eventConditions = unique( ...
    canonical_condition_local(allEventTable.Condition));

expectedCondition = ...
    canonical_condition_local(sourceMetadata.ConditionLabel);

if numel(eventConditions) ~= 1 || ...
        eventConditions(1) ~= expectedCondition
    error([ ...
        'GRF event-table Condition does not match the source XDF filename.\n' ...
        'Event table: %s -> %s | XDF: %s -> %s'], ...
        strjoin(unique(string(allEventTable.Condition)), ', '), ...
        strjoin(eventConditions, ', '), ...
        sourceMetadata.ConditionLabel, ...
        expectedCondition);
end

if ~isfinite(sourceMetadata.RunNumber) || ...
        sourceMetadata.RunNumber < 1 || ...
        sourceMetadata.RunNumber ~= round(sourceMetadata.RunNumber)

    error([ ...
        'The source recording has an invalid run number.\n' ...
        'Resolved run number: %g\nSource XDF:\n%s'], ...
        sourceMetadata.RunNumber, ...
        xdfFile);
end

if sourceMetadata.IsOldVersion

    error('Old XDF versions are not accepted:\n%s', ...
        xdfFile);
end

canonicalRecordingLabel = ...
    string(batchOutputStem);

%% Load XDF and find the real EEG stream

fprintf('\n====================================================\n');
fprintf('MAP GRF EVENTS TO BIDS-DERIVED EEG\n');
fprintf('====================================================\n');
fprintf('Source event MAT:\n%s\n\n', sourceEventFile);
fprintf('Source XDF (timing provenance only):\n%s\n\n', xdfFile);
fprintf('Source BIDS-derived EEGLAB signal:\n%s\n\n', sourceBidsEEGLABSet);

[streams, ~] = load_xdf(char(xdfFile));

if isempty(streams)
    error('No streams were loaded from the XDF.');
end

[eegStreamIndex, streamSummary] = find_real_eeg_stream( ...
    streams, ...
    expectedEEGStreamName, ...
    expectedEEGChannels, ...
    targetEEGSrate);

disp(streamSummary);

EEGStream = streams{eegStreamIndex};
eegTimeStamps = double(EEGStream.time_stamps(:)');

if isempty(eegTimeStamps)
    error('The source XDF EEG stream has no LSL timestamps.');
end

% Do NOT use EEGStream.time_series for downstream EEG amplitudes. The XDF is
% retained here solely because it contains the original LSL clock needed to
% align the GRF events with the BIDS-derived recording.
xdfEEGSampleCount = numel(eegTimeStamps);

%% Load canonical BIDS-derived EEGLAB signal and select project EEG channels

if exist('eeglab', 'file') ~= 2
    error('Cannot find eeglab.m. Check eeglabFolder in project_paths.m.');
end

[ALLEEG, EEG, CURRENTSET, ALLCOM] = eeglab('nogui'); %#ok<ASGLU>

[sourceBidsFolder, sourceBidsFile, sourceBidsExt] = ...
    fileparts(char(sourceBidsEEGLABSet));
BIDS_EEG = pop_loadset('filename', [sourceBidsFile sourceBidsExt], ...
    'filepath', sourceBidsFolder);

if ~isfield(BIDS_EEG, 'etc') || ...
        ~isfield(BIDS_EEG.etc, 'hipexo_canonical_subject_id') || ...
        ~isfield(BIDS_EEG.etc, 'hipexo_original_subject_id')

    error([ ...
        'The BIDS-derived EEGLAB dataset lacks Step 02B participant ' ...
        'identity metadata. Re-run Step 02B for this recording.']);
end

bidsCanonicalSubject = ...
    strtrim(string(BIDS_EEG.etc.hipexo_canonical_subject_id));

bidsOriginalSubject = ...
    strtrim(string(BIDS_EEG.etc.hipexo_original_subject_id));

% Step 02 binds the current acquisition folder to a canonical participant.
% Filenames can retain an earlier acquisition label. Verify the exact XDF
% path and signature saved by Step 02B before accepting that binding.
if ~isfield(BIDS_EEG.etc, 'hipexo_source_xdf') || ...
        ~isfield(BIDS_EEG.etc, 'hipexo_source_xdf_signature_at_bids_export') || ...
        ~strcmpi(strrep(strtrim(string(BIDS_EEG.etc.hipexo_source_xdf)), '\', '/'), ...
            strrep(strtrim(string(xdfFile)), '\', '/')) || ...
        string(BIDS_EEG.etc.hipexo_source_xdf_signature_at_bids_export) ~= ...
            string(sourceXDFSignature)
    error('BIDS EEG and GRF events are not bound to the same current source XDF.');
end

if ~strcmpi(bidsCanonicalSubject, canonicalSubject) || ...
        subject_identity_key_local(bidsOriginalSubject) ~= ...
        subject_identity_key_local(originalSubject)

    error([ ...
        'BIDS-derived EEG participant identity does not match the ' ...
        'current import-table row.\n' ...
        'Expected: %s / %s | BIDS EEG: %s / %s'], ...
        canonicalSubject, ...
        originalSubject, ...
        bidsCanonicalSubject, ...
        bidsOriginalSubject);
end

bidsDatasetSubject = "";

if isfield(BIDS_EEG, 'subject')
    bidsDatasetSubject = strtrim(string(BIDS_EEG.subject));
end

if ~isscalar(bidsDatasetSubject) || ...
        ~strcmpi(bidsDatasetSubject, canonicalSubject)

    error([ ...
        'BIDS-derived EEG.subject does not match canonical SubjectID.\n' ...
        'Expected: %s | BIDS EEG.subject: %s'], ...
        canonicalSubject, ...
        strjoin(bidsDatasetSubject, ', '));
end

if double(BIDS_EEG.pnts) ~= xdfEEGSampleCount || ...
        size(BIDS_EEG.data, 2) ~= xdfEEGSampleCount

    error([ ...
        'BIDS-derived EEG and XDF LSL timestamp vectors differ in sample count.\n' ...
        'BIDS-derived EEG.pnts: %d\n' ...
        'BIDS-derived data samples: %d\n' ...
        'XDF EEG timestamps: %d\n' ...
        'No mapping is allowed because sample identity is not one-to-one.'], ...
        double(BIDS_EEG.pnts), ...
        size(BIDS_EEG.data, 2), ...
        xdfEEGSampleCount);
end

% IMPORTANT:
% The BrainVision header written during BIDS conversion may contain an
% effective sampling rate inferred from the XDF timing (for example
% 499.9x Hz) even though the LiveAmp stream is nominally 500 Hz. That is
% NOT evidence that samples were resampled. The scientifically relevant
% no-resampling gate here is one-to-one sample identity, verified above.
bidsHeaderSrate = double(BIDS_EEG.srate);

if ~isscalar(bidsHeaderSrate) || ...
        ~isfinite(bidsHeaderSrate) || ...
        bidsHeaderSrate <= 0

    error('The BIDS-derived EEGLAB dataset has an invalid sampling rate.');
end

if isfield(BIDS_EEG, 'etc') && ...
        isfield(BIDS_EEG.etc, 'hipexo_bids_to_eeglab_no_resampling') && ...
        ~logical(BIDS_EEG.etc.hipexo_bids_to_eeglab_no_resampling)

    error([ ...
        'Step 02B provenance reports that the BIDS-derived EEGLAB ' ...
        'recording was resampled. Step 03 requires sample identity ' ...
        'with the source XDF.']);
end

projectChanlocs = readlocs(channelLocationFile);
if numel(projectChanlocs) ~= expectedEEGChannels
    error('Expected %d project channel locations, found %d.', ...
        expectedEEGChannels, numel(projectChanlocs));
end
projectChannelLabels = string({projectChanlocs.labels})';

rawEEGChannelCount = double(BIDS_EEG.nbchan);
if isempty(BIDS_EEG.chanlocs) || numel(BIDS_EEG.chanlocs) ~= rawEEGChannelCount
    error('BIDS-derived EEGLAB dataset lacks a complete channel-label list.');
end
rawEEGChannelLabels = string({BIDS_EEG.chanlocs.labels})';

[selectedEEGChannelIndices, droppedEEGChannelIndices, channelSelectionMethod] = ...
    select_project_eeg_channels( ...
        rawEEGChannelLabels, projectChannelLabels, rawEEGChannelCount, ...
        expectedEEGChannels, expectedAuxiliaryLabels, expectedEEGStreamName);

% Recheck the same source sample ranges as Step 01 before slicing amplitudes.
[retainedRanges, segmentAudit, checkedTimeStamps] = ...
    hipexo.check_eeg_segments(EEGStream, eegQC, xdfFile);
if isempty(retainedRanges)
    error('No continuous EEG segment passes the current Step 01 QC: %s', ...
        segmentAudit.status);
end
retainedIndex = cell(size(retainedRanges, 1), 1);
for k = 1:size(retainedRanges, 1)
    retainedIndex{k} = retainedRanges(k, 1):retainedRanges(k, 2);
end
retainedIndex = [retainedIndex{:}];
eegTimeStamps = checkedTimeStamps(retainedIndex);
eegData = double(BIDS_EEG.data(selectedEEGChannelIndices, retainedIndex));
retainedJoinSamples = cumsum(retainedRanges(:, 2) - retainedRanges(:, 1) + 1);
retainedJoinSamples = retainedJoinSamples(1:end-1);
retainedJoinSamples = retainedJoinSamples(:);
selectedEEGChannelLabels = rawEEGChannelLabels(selectedEEGChannelIndices);
droppedEEGChannelLabels = rawEEGChannelLabels(droppedEEGChannelIndices);
originalBidsEvents = BIDS_EEG.event;

if any(~isfinite(eegTimeStamps)) || ...
        any(diff(eegTimeStamps) <= 0)

    error('EEG timestamps must be finite and strictly increasing.');
end

measuredEEGSrate = 1 / median(diff(eegTimeStamps));
nominalEEGSrate = get_stream_nominal_srate(EEGStream);

if ~isfinite(nominalEEGSrate) || ...
        abs(nominalEEGSrate - targetEEGSrate) > 1

    error([ ...
        'The selected EEG stream does not match the configured nominal rate.\n' ...
        'Configured rate: %.9g Hz\n' ...
        'XDF nominal rate: %.9g Hz'], ...
        targetEEGSrate, ...
        nominalEEGSrate);
end

fprintf('XDF timing stream: %s\n', ...
    get_stream_text_field(EEGStream, 'name'));
fprintf('EEG amplitude source: BIDS-derived EEGLAB set\n');

fprintf('BIDS-derived raw channels: %d\n', ...
    rawEEGChannelCount);

fprintf('Selected EEG channels: %d\n', ...
    size(eegData, 1));

fprintf('Channel-selection method: %s\n', ...
    channelSelectionMethod);

if ~isempty(droppedEEGChannelIndices)

    fprintf('Dropped auxiliary channel indices: %s\n', ...
        mat2str(droppedEEGChannelIndices'));

    if any(strlength(droppedEEGChannelLabels) > 0)

        fprintf('Dropped auxiliary channel labels: %s\n', ...
            strjoin(droppedEEGChannelLabels, ', '));
    end
end

fprintf('EEG samples: %d\n', ...
    size(eegData, 2));

fprintf('Nominal XDF EEG rate: %.6f Hz\n', ...
    nominalEEGSrate);

fprintf('Measured XDF timestamp rate: %.6f Hz\n', ...
    measuredEEGSrate);

fprintf('BIDS/BrainVision header rate: %.6f Hz\n', ...
    bidsHeaderSrate);

fprintf([ ...
    'Output EEGLAB nominal rate: %.6f Hz ' ...
    '(sample data are not resampled)\n'], ...
    targetEEGSrate);

fprintf('EEG LSL range: %.6f to %.6f s\n', ...
    eegTimeStamps(1), ...
    eegTimeStamps(end));

%% Detect real gaps in the EEG timestamp vector

eegTimestampDifferenceSec = ...
    diff(eegTimeStamps(:));

medianEEGSampleIntervalSec = ...
    median(eegTimestampDifferenceSec);

timestampGapThresholdSec = max( ...
    timestampGapFactor * medianEEGSampleIntervalSec, ...
    minimumTimestampGapSec);

gapBeforeSample = unique([find( ...
    eegTimestampDifferenceSec > timestampGapThresholdSec); retainedJoinSamples]);

gapAfterSample = ...
    gapBeforeSample + 1;

if isempty(gapBeforeSample)

    eegTimestampGapTable = table( ...
        'Size', ...
        [0 8], ...
        'VariableTypes', { ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double', ...
            'double'}, ...
        'VariableNames', { ...
            'GapIndex', ...
            'SampleBeforeGap', ...
            'SampleAfterGap', ...
            'LSLBeforeGap', ...
            'LSLAfterGap', ...
            'TimestampJumpSec', ...
            'MissingDurationSec', ...
            'MissingSampleCount'});

else

    timestampJumpSec = ...
        eegTimestampDifferenceSec(gapBeforeSample);

    missingDurationSec = max( ...
        0, ...
        timestampJumpSec - medianEEGSampleIntervalSec);

    missingSampleCount = max( ...
        0, ...
        round(timestampJumpSec * targetEEGSrate) - 1);

    eegTimestampGapTable = table( ...
        (1:numel(gapBeforeSample))', ...
        double(gapBeforeSample(:)), ...
        double(gapAfterSample(:)), ...
        reshape( ...
            double(eegTimeStamps(gapBeforeSample)), ...
            [], ...
            1), ...
        reshape( ...
            double(eegTimeStamps(gapAfterSample)), ...
            [], ...
            1), ...
        double(timestampJumpSec(:)), ...
        double(missingDurationSec(:)), ...
        double(missingSampleCount(:)), ...
        'VariableNames', { ...
            'GapIndex', ...
            'SampleBeforeGap', ...
            'SampleAfterGap', ...
            'LSLBeforeGap', ...
            'LSLAfterGap', ...
            'TimestampJumpSec', ...
            'MissingDurationSec', ...
            'MissingSampleCount'});
end

fprintf('\nEEG timestamp-gap check:\n');

fprintf('Gap threshold: %.6f s\n', ...
    timestampGapThresholdSec);

fprintf('Detected gaps: %d\n', ...
    height(eegTimestampGapTable));

if ~isempty(eegTimestampGapTable)
    disp(eegTimestampGapTable);
end

%% Map each GRF event to a real EEG sample

allEventTable = ...
    sortrows(allEventTable, 'LSLTime');

eventTypes = ...
    string(allEventTable.EventType);

grfEventLSLTime = ...
    double(allEventTable.LSLTime);

insideEEGRange = ...
    grfEventLSLTime >= eegTimeStamps(1) & ...
    grfEventLSLTime <= eegTimeStamps(end);

% GRF may start earlier or finish later than retained EEG. Such events
% stay in the mapping audit with no EEG latency and cannot enter analysis.
nearestEEGSample = nan(height(allEventTable), 1);
nearestEEGSample(insideEEGRange) = round(interp1( ...
    eegTimeStamps, 1:numel(eegTimeStamps), ...
    grfEventLSLTime(insideEEGRange), 'nearest'));
if any(~isfinite(nearestEEGSample(insideEEGRange)))
    error('A GRF event inside the EEG range could not be mapped.');
end
nearestEEGLSLTime = nan(height(allEventTable), 1);
nearestEEGLSLTime(insideEEGRange) = eegTimeStamps(nearestEEGSample(insideEEGRange));

nearestMappingErrorMs = ...
    1000 * (nearestEEGLSLTime - grfEventLSLTime);

eventInsideTimestampGap = ...
    false(height(allEventTable), 1);

eventTimestampGapIndex = ...
    nan(height(allEventTable), 1);

for iGap = 1:height(eegTimestampGapTable)

    currentEventsInsideGap = ...
        grfEventLSLTime > ...
            eegTimestampGapTable.LSLBeforeGap(iGap) & ...
        grfEventLSLTime < ...
            eegTimestampGapTable.LSLAfterGap(iGap);

    eventInsideTimestampGap = ...
        eventInsideTimestampGap | ...
        currentEventsInsideGap;

    eventTimestampGapIndex(currentEventsInsideGap) = ...
        eegTimestampGapTable.GapIndex(iGap);
end

unexplainedBadMapping = ...
    abs(nearestMappingErrorMs) > maximumMappingErrorMs & ...
    ~eventInsideTimestampGap & insideEEGRange;

if any(unexplainedBadMapping)

    badRows = find(unexplainedBadMapping);

    disp(table( ...
        eventTypes(badRows), ...
        grfEventLSLTime(badRows), ...
        nearestEEGSample(badRows), ...
        nearestEEGLSLTime(badRows), ...
        nearestMappingErrorMs(badRows), ...
        'VariableNames', { ...
            'EventType', ...
            'GRFEventLSLTime', ...
            'NearestEEGSample', ...
            'NearestEEGLSLTime', ...
            'NearestMappingErrorMs'}));

    error([ ...
        '%d event mappings exceed %.3f ms and are not explained ' ...
        'by a detected EEG timestamp gap.\n' ...
        'No EEG file was saved.'], ...
        numel(badRows), ...
        maximumMappingErrorMs);
end

mappingStatus = repmat( ...
    "mapped", ...
    height(allEventTable), ...
    1);

mappingStatus(eventInsideTimestampGap) = ...
    "excluded_no_EEG_sample_in_timestamp_gap";
mappingStatus(~insideEEGRange) = "excluded_outside_retained_EEG_range";

