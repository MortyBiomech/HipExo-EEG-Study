function value = get_info_text(stream, fieldName)

value = "";

if ~isfield(stream, 'info') || ...
        ~isfield(stream.info, fieldName)
    return;
end

rawValue = stream.info.(fieldName);

while iscell(rawValue) && ...
        numel(rawValue) == 1

    rawValue = rawValue{1};
end

try
    value = string(rawValue);
    value = value(1);
catch
    value = "";
end
end

function labels = marker_to_string(timeSeries)

if isempty(timeSeries)
    labels = strings(0, 1);
    return;
end

rawValues = timeSeries(:);
labels = strings(numel(rawValues), 1);

for iValue = 1:numel(rawValues)

    if iscell(rawValues)
        currentValue = rawValues{iValue};
    else
        currentValue = rawValues(iValue);
    end

    while iscell(currentValue) && ...
            numel(currentValue) == 1

        currentValue = currentValue{1};
    end

    try
        convertedValue = string(currentValue);
        labels(iValue) = convertedValue(1);
    catch
        labels(iValue) = "";
    end
end

labels = strtrim(labels);
end

