function [startSec, endSec, conditions, ...
    startLabels, endLabels] = pair_markers( ...
        markerLabels, ...
        markerTimeSec, ...
        excludedWords)

markerLabels = string(markerLabels(:));
markerTimeSec = double(markerTimeSec(:));

upperLabels = upper(strtrim(markerLabels));

isStart = ...
    startsWith(upperLabels, "START_") | ...
    strcmp(upperLabels, "START");

isEnd = ...
    startsWith(upperLabels, "END_") | ...
    strcmp(upperLabels, "END");

usedEnd = false(numel(markerLabels), 1);

startSec = zeros(0, 1);
endSec = zeros(0, 1);
conditions = strings(0, 1);

startLabels = strings(0, 1);
endLabels = strings(0, 1);

startIndices = find(isStart);

for iStart = 1:numel(startIndices)

    startIndex = startIndices(iStart);

    condition = regexprep( ...
        markerLabels(startIndex), ...
        '(?i)^START_?', ...
        '');

    condition = strtrim(condition);

    if strlength(condition) == 0
        condition = "Unspecified";
    end

    excludeCondition = false;

    for iWord = 1:numel(excludedWords)

        if contains( ...
                upper(condition), ...
                upper(excludedWords(iWord)))

            excludeCondition = true;
            break;
        end
    end

    if excludeCondition
        continue;
    end

    endConditions = regexprep( ...
        markerLabels, ...
        '(?i)^END_?', ...
        '');

    sameCondition = strcmpi( ...
        strtrim(endConditions), ...
        condition);

    if condition == "Unspecified"
        sameCondition = ...
            strlength(strtrim(endConditions)) == 0;
    end

    matchingEnd = find( ...
        isEnd & ...
        sameCondition & ...
        ~usedEnd & ...
        markerTimeSec > markerTimeSec(startIndex), ...
        1, ...
        'first');

    if isempty(matchingEnd)

        warning( ...
            ['No condition-matched END marker found for %s. ' ...
            'This START marker is not used.'], ...
            markerLabels(startIndex));

        continue;
    end

    usedEnd(matchingEnd) = true;

    startSec(end + 1, 1) = ...
        markerTimeSec(startIndex); %#ok<AGROW>

    endSec(end + 1, 1) = ...
        markerTimeSec(matchingEnd); %#ok<AGROW>

    conditions(end + 1, 1) = ...
        condition; %#ok<AGROW>

    startLabels(end + 1, 1) = ...
        markerLabels(startIndex); %#ok<AGROW>

    endLabels(end + 1, 1) = ...
        markerLabels(matchingEnd); %#ok<AGROW>
end

validIntervals = ...
    isfinite(startSec) & ...
    isfinite(endSec) & ...
    endSec > startSec;

startSec = startSec(validIntervals);
endSec = endSec(validIntervals);

conditions = conditions(validIntervals);
startLabels = startLabels(validIntervals);
endLabels = endLabels(validIntervals);

[startSec, sortOrder] = sort(startSec);

endSec = endSec(sortOrder);
conditions = conditions(sortOrder);
startLabels = startLabels(sortOrder);
endLabels = endLabels(sortOrder);

if numel(startSec) > 1 && ...
        any(startSec(2:end) < endSec(1:end-1))
    error([ ...
        'Condition-matched marker intervals overlap. ' ...
        'Do not accept these marker boundaries automatically.']);
end
end

