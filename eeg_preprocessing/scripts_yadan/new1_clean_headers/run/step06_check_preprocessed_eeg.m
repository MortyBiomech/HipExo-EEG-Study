                        chanloc.(name)))

            tf = false;
            return;
        end
    end

end


function [ok, notes] = ...
        check_preprocessing_provenance( ...
            EEG, ...
            expectedSignature, ...
            expectedSubject, ...
            expectedSession, ...
            expectedProcessingLabel)

    problems = ...
        strings(0, 1);

    expectedSignature = ...
        string(expectedSignature);

    if strlength( ...
            strtrim( ...
                expectedSignature)) == 0

        problems(end + 1, 1) = ...
            "table_preprocessing_signature_missing";

    elseif ~isfield( ...
            EEG, ...
            'etc') || ...
            ~isfield( ...
                EEG.etc, ...
                'preprocessing_input_signature') || ...
            string( ...
                EEG.etc.preprocessing_input_signature) ~= ...
                expectedSignature

        problems(end + 1, 1) = ...
            "preprocessing_signature_mismatch";
    end

    if ~isfield( ...
            EEG, ...
            'etc') || ...
            ~isfield( ...
                EEG.etc, ...
                'real_bids_subject')

        problems(end + 1, 1) = ...
            "stored_bids_subject_missing";

    else

        storedSubject = ...
            scalar_number( ...
                EEG.etc.real_bids_subject);

        if isnan(storedSubject) || ...
                storedSubject ~= ...
                double(expectedSubject)

            problems(end + 1, 1) = ...
                "stored_bids_subject_mismatch";
        end
    end

    if ~isfield( ...
            EEG, ...
            'etc') || ...
            ~isfield( ...
                EEG.etc, ...
                'session_label') || ...
            string( ...
                EEG.etc.session_label) ~= ...
                string(expectedSession)

        problems(end + 1, 1) = ...
            "stored_session_label_mismatch";
    end

    if ~isfield( ...
            EEG, ...
            'etc') || ...
            ~isfield( ...
                EEG.etc, ...
                'processing_subject_label') || ...
            string( ...
                EEG.etc.processing_subject_label) ~= ...
                string(expectedProcessingLabel)

        problems(end + 1, 1) = ...
            "stored_processing_label_mismatch";
    end

    ok = ...
        isempty(problems);

    if ok

        notes = ...
            "OK";

    else

        notes = ...
            join( ...
                problems, ...
                "; ");
    end

end


function value = scalar_number(x)

    value = NaN;

    try

        if isnumeric(x) || ...
                islogical(x)

            if isscalar(x)

                value = ...
                    double(x);
            end

        else

            parsed = ...
                str2double( ...
                    string(x));

            if isscalar(parsed)

                value = ...
                    parsed;
            end
        end

    catch

        value = NaN;
    end

end


