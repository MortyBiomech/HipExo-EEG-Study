% GOAL
%   Check the structural and quantitative quality of each subject-level
%   BeMoBIL preprocessed EEG dataset before AMICA.
%
% INPUT
%   Updated subject_level_EEG_processing_table.csv from Step 05.
%   Preprocessed .set/.fdt datasets produced by Step 05.
%
% APPROACH
%   1. Select rows enabled by DoQC.
%   2. Verify preprocessing provenance and expected dataset structure.
%   3. Check finite data, sampling rate, rank metadata, channel locations,
%      interpolated-channel count, ZapLine metadata, and residual 50 Hz noise.
%   4. Save QC status/metrics back to the subject-level processing table.
%
% OUTPUT
%   Updated subject_level_EEG_processing_table.csv
%   Per-subject preprocessing QC summary/figure outputs.
%
% USED BY
%   step07_run_amica_dipfit_iclabel.m

clear; clc; close all;

% Keep figures hidden during QC.
set(0, 'DefaultFigureVisible', 'off');
set(groot, 'DefaultFigureVisible', 'off');


%  LOAD PATHS, CONFIGURATION, AND QC SETTINGS

runFolder = fileparts(mfilename('fullpath'));
scriptsRoot = fileparts(runFolder);

addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();

assert(isstruct(P), ...
    'project_paths() did not return a struct.');

assert(isfield(P, 'outputFolder') && ...
       strlength(strtrim(string(P.outputFolder))) > 0, ...
    'project_paths() did not define P.outputFolder.');

assert(isfield(P, 'subjectLevelEEGTableFile') && ...
       strlength(strtrim(string(P.subjectLevelEEGTableFile))) > 0, ...
    'project_paths() did not define P.subjectLevelEEGTableFile.');

bemobil_config = ...
    config_step05_09_eeg_preprocessing_ica(P);

mappingFile = P.subjectLevelEEGTableFile;

if ~exist(mappingFile, 'file')
    error([ ...
        'Subject-level processing table not found:\n%s\n' ...
        'Run step05_preprocess_eeg.m first.'], ...
        mappingFile);
end

expectedChannels = ...
    bemobil_config.preprocessingQC.expectedChannels;

rankSampleLimit = ...
    bemobil_config.preprocessingQC.rankSampleLimit;

processingVersion = ...
    bemobil_config.preprocessingQC.processingVersion;

lineNoiseFrequencyHz = ...
    bemobil_config.preprocessingQC.lineNoiseFrequencyHz;

maxLineNoisePeakDb = ...
    bemobil_config.preprocessingQC.maxLineNoisePeakDb;

maxInterpolatedChannelFraction = ...
    bemobil_config.preprocessingQC.maxInterpolatedChannelFraction;

reset_DoQC_from_PreprocessingStatus = ...
    bemobil_config.preprocessingQC.reset_DoQC_from_PreprocessingStatus;

if isempty(bemobil_config.resample_freq)
    expectedSrate = 500;
else
    expectedSrate = double(bemobil_config.resample_freq);
end


%  INITIALIZE EEGLAB

if ~exist('pop_loadset', 'file')
    eeglab nogui;
end

hipexo.hide_all_figures();


%  READ IMPORT TABLE

optsImport = detectImportOptions(mappingFile, ...
    'FileType', 'text', ...
    'Delimiter', ',', ...
    'VariableNamingRule', 'preserve');

sourceMap = readtable(mappingFile, optsImport);

fprintf('\nLoaded import table:\n%s\n', mappingFile);
fprintf('Rows in import table: %d\n', height(sourceMap));


%  CHECK REQUIRED COLUMNS

requiredColumns = { ...
    'DoImport', ...
    'XdfPath', ...
    'FileName', ...
    'BidsSubject', ...
    'BidsSession', ...
    'PreprocessingStatus', ...
    'PreprocessedSetPath', ...
    'PreprocessingInputSignature' ...
};

for c = 1:length(requiredColumns)

    if ~ismember(requiredColumns{c}, sourceMap.Properties.VariableNames)

        error([ ...
            'Import table is missing required column: %s\n' ...
            'Please run step05_preprocess_eeg.m first.'], ...
            requiredColumns{c});
    end
end


%  NORMALIZE IMPORTANT COLUMNS

sourceMap = ensure_numeric_column(sourceMap, 'DoImport');
sourceMap = ensure_numeric_column(sourceMap, 'BidsSubject');

sourceMap.XdfPath = ...
    string(sourceMap.XdfPath);

sourceMap.FileName = ...
    string(sourceMap.FileName);

sourceMap.BidsSession = ...
    string(sourceMap.BidsSession);

sourceMap.PreprocessingStatus = ...
    string(sourceMap.PreprocessingStatus);

sourceMap.PreprocessedSetPath = ...
    string(sourceMap.PreprocessedSetPath);

sourceMap.PreprocessingInputSignature = ...
    string(sourceMap.PreprocessingInputSignature);

sourceMap.XdfPath(ismissing(sourceMap.XdfPath)) = "";
sourceMap.FileName(ismissing(sourceMap.FileName)) = "";
sourceMap.BidsSession(ismissing(sourceMap.BidsSession)) = "";

sourceMap.PreprocessingStatus( ...
    ismissing(sourceMap.PreprocessingStatus)) = "";

sourceMap.PreprocessedSetPath( ...
    ismissing(sourceMap.PreprocessedSetPath)) = "";

sourceMap.PreprocessingInputSignature( ...
    ismissing(sourceMap.PreprocessingInputSignature)) = "";

if ismember( ...
        'ProcessingSubjectLabel', ...
        sourceMap.Properties.VariableNames)

    sourceMap.ProcessingSubjectLabel = ...
        string(sourceMap.ProcessingSubjectLabel);

    sourceMap.ProcessingSubjectLabel( ...
        ismissing(sourceMap.ProcessingSubjectLabel)) = "";
end

if ismember( ...
        'ProcessingSubjectFolder', ...
        sourceMap.Properties.VariableNames)

    sourceMap.ProcessingSubjectFolder = ...
        string(sourceMap.ProcessingSubjectFolder);

    sourceMap.ProcessingSubjectFolder( ...
        ismissing(sourceMap.ProcessingSubjectFolder)) = "";
end

if ismember( ...
        'EEGStreamName', ...
        sourceMap.Properties.VariableNames)

    sourceMap.EEGStreamName = ...
        string(sourceMap.EEGStreamName);

    sourceMap.EEGStreamName( ...
        ismissing(sourceMap.EEGStreamName)) = "";
end

if ismember( ...
        'RawSetPath', ...
        sourceMap.Properties.VariableNames)

    sourceMap.RawSetPath = ...
        string(sourceMap.RawSetPath);

    sourceMap.RawSetPath( ...
        ismissing(sourceMap.RawSetPath)) = "";
end

if ismember( ...
        'RawSetStatus', ...
        sourceMap.Properties.VariableNames)

    sourceMap.RawSetStatus = ...
        string(sourceMap.RawSetStatus);

    sourceMap.RawSetStatus( ...
        ismissing(sourceMap.RawSetStatus)) = "";
end


%  CREATE OR RESET DOQC

if ~ismember( ...
        'DoQC', ...
        sourceMap.Properties.VariableNames)

    sourceMap.DoQC = ...
        zeros(height(sourceMap), 1);

    status = ...
        string(sourceMap.PreprocessingStatus);

    status(ismissing(status)) = "";

    sourceMap.DoQC( ...
        status == "completed") = 1;

    writetable( ...
        sourceMap, ...
        mappingFile);

    fprintf('\nDoQC column was not found.\n');

    fprintf([ ...
        'Created DoQC from PreprocessingStatus == "completed" ' ...
        'and saved it to:\n%s\n'], ...
        mappingFile);

    fprintf('You can manually edit DoQC later:\n');
    fprintf('  DoQC = 1 -> check this row\n');
    fprintf('  DoQC = 0 -> skip this row\n');

else

    sourceMap = ...
        ensure_numeric_column( ...
            sourceMap, ...
            'DoQC');

    status = ...
        string(sourceMap.PreprocessingStatus);

    status(ismissing(status)) = "";

    if reset_DoQC_from_PreprocessingStatus

        sourceMap.DoQC = ...
            zeros(height(sourceMap), 1);

        sourceMap.DoQC( ...
            status == "completed") = 1;

        writetable( ...
            sourceMap, ...
            mappingFile);

        fprintf('\nDoQC column already existed.\n');

        fprintf([ ...
            'Reset DoQC from PreprocessingStatus == "completed" ' ...
            'because reset_DoQC_from_PreprocessingStatus = true.\n']);

        fprintf( ...
            'Updated import table saved to:\n%s\n', ...
            mappingFile);

    else

        missingDoQC = ...
            isnan(sourceMap.DoQC);

        sourceMap.DoQC(missingDoQC) = 0;

        sourceMap.DoQC( ...
            missingDoQC & ...
            status == "completed") = 1;

        writetable( ...
            sourceMap, ...
            mappingFile);

        fprintf('\nDoQC column already existed.\n');

        fprintf([ ...
            'Preserved explicit DoQC values and filled only missing ' ...
            'values from PreprocessingStatus.\n']);
    end
end


%  SELECT ROWS TO CHECK

sourceMap = ...
    ensure_numeric_column( ...
        sourceMap, ...
        'DoQC');

candidateRows = ...
    find(sourceMap.DoQC == 1);

if isempty(candidateRows)

    error([ ...
        'No rows with DoQC = 1 found in the subject-level ' ...
        'processing table.']);
end

hasPreprocessedPath = ...
    strlength( ...
        strtrim( ...
            sourceMap.PreprocessedSetPath)) > 0;

completedRows = ...
    sourceMap.PreprocessingStatus == "completed";

validRows = ...
    candidateRows( ...
        hasPreprocessedPath(candidateRows) & ...
        completedRows(candidateRows));

if isempty(validRows)

    fprintf([ ...
        '\nRows with DoQC = 1 exist, but none have ' ...
        'PreprocessingStatus == completed and non-empty ' ...
        'PreprocessedSetPath.\n']);

    fprintf('Problem rows:\n');

    disp( ...
        sourceMap( ...
            candidateRows, ...
            { ...
                'FileName', ...
                'BidsSubject', ...
                'BidsSession', ...
                'DoImport', ...
                'DoQC', ...
                'PreprocessingStatus', ...
                'PreprocessedSetPath' ...
            }));

    error('No valid rows for preprocessing QC.');
end

% Safety: avoid checking the same preprocessed file more than once.
preprocessedPathsForValidRows = ...
    sourceMap.PreprocessedSetPath(validRows);

[~, uniqueIdx] = ...
    unique( ...
        preprocessedPathsForValidRows, ...
        'stable');

rowsToCheck = ...
    validRows(uniqueIdx);

fprintf('\n============================================================\n');
fprintf('PREPROCESSED EEG QUALITY CHECK STARTED\n');
fprintf('============================================================\n');

fprintf('Selection mode: table-driven preprocessing-QC\n');

fprintf( ...
    'Rows with DoQC = 1: %d\n', ...
    length(candidateRows));

fprintf( ...
    ['Rows with completed preprocessing and ' ...
     'PreprocessedSetPath: %d\n'], ...
    length(validRows));

fprintf( ...
    'Unique preprocessed .set files to check: %d\n', ...
    length(rowsToCheck));

fprintf( ...
    'Import table:\n%s\n', ...
    mappingFile);

fprintf('============================================================\n\n');

fprintf('Rows selected for QC:\n');

disp( ...
    sourceMap( ...
        rowsToCheck, ...
        { ...
            'FileName', ...
            'BidsSubject', ...
            'BidsSession', ...
            'PreprocessingStatus', ...
            'PreprocessedSetPath' ...
        }));

hipexo.hide_all_figures();


%  CHECK LOOP

for rr = 1:length(rowsToCheck)

    hipexo.hide_all_figures();

    rowIdx = ...
        rowsToCheck(rr);

    sessionRows = ...
        hipexo.session_peer_rows( ...
            sourceMap, ...
            rowIdx);

    bidsSubject = ...
        sourceMap.BidsSubject(rowIdx);

    bidsSession = ...
        char(sourceMap.BidsSession(rowIdx));

    originalXDFName = ...
        char(sourceMap.FileName(rowIdx));

    originalXDFPath = ...
        char(sourceMap.XdfPath(rowIdx));

    if isnan(bidsSubject)

        warning( ...
            'Invalid BidsSubject in row %d. Skipping this row.', ...
            rowIdx);

        sourceMap = ...
            update_qc_status( ...
                sourceMap, ...
                rowIdx, ...
                "failed_invalid_bids_subject", ...
                "BidsSubject is NaN or invalid.", ...
                "", ...
                "");

        writetable( ...
            sourceMap, ...
            mappingFile);

        continue;
    end


    %% --------------------------------------------------------------------
    %  RESOLVE PROCESSING LABEL
    %  --------------------------------------------------------------------

    if ismember( ...
            'ProcessingSubjectLabel', ...
            sourceMap.Properties.VariableNames) && ...
            strlength( ...
                strtrim( ...
                    string( ...
                        sourceMap.ProcessingSubjectLabel(rowIdx)))) > 0

        processingSubjectLabel = ...
            char( ...
                sourceMap.ProcessingSubjectLabel(rowIdx));

    else

        processingSubjectLabel = ...
            char( ...
                make_bids_label( ...
                    string(bidsSession)));
    end

    if ismember( ...
            'ProcessingSubjectFolder', ...
            sourceMap.Properties.VariableNames) && ...
            strlength( ...
                strtrim( ...
                    string( ...
                        sourceMap.ProcessingSubjectFolder(rowIdx)))) > 0

        processingSubjectFolder = ...
            char( ...
                sourceMap.ProcessingSubjectFolder(rowIdx));

    else

        processingSubjectFolder = ...
            ['sub-' processingSubjectLabel];
    end


    %% --------------------------------------------------------------------
    %  RESOLVE PREPROCESSED .SET PATH
    %  --------------------------------------------------------------------

    preprocessedSetPath = ...
        string( ...
            sourceMap.PreprocessedSetPath(rowIdx));

    if strlength( ...
            strtrim( ...
                preprocessedSetPath)) == 0

        preprocessedSetPath = ...
            string( ...
                fullfile( ...
                    bemobil_config.study_folder, ...
                    bemobil_config.EEG_preprocessing_data_folder, ...
                    processingSubjectFolder, ...
                    [ ...
                        processingSubjectFolder ...
                        '_' ...
                        bemobil_config.preprocessed_filename ...
                    ]));
    end

    preprocessedSetPath = ...
        char(preprocessedSetPath);

    [ ...
        preprocFolder, ...
        setFilenameNoExt, ...
        setExt ...
    ] = ...
        fileparts(preprocessedSetPath);

    setFilename = ...
        [setFilenameNoExt setExt];

    fprintf('\n\n============================================================\n');

    fprintf( ...
        'CHECKING FILE %d / %d\n', ...
        rr, ...
        length(rowsToCheck));

    fprintf('============================================================\n');

    fprintf( ...
        'Table row: %d\n', ...
        rowIdx);

    fprintf( ...
        'Original XDF name:\n%s\n\n', ...
        originalXDFName);

    fprintf( ...
        'Original XDF path:\n%s\n\n', ...
        originalXDFPath);

    fprintf( ...
        'Imported BIDS subject:\nsub-%d\n', ...
        bidsSubject);

    fprintf( ...
        'Imported BIDS session:\n%s\n', ...
        bidsSession);

    fprintf( ...
        'Processing subject label:\n%s\n', ...
        processingSubjectLabel);

    fprintf( ...
        'Processing folder:\n%s\n', ...
        processingSubjectFolder);

    fprintf( ...
        'Preprocessed .set file:\n%s\n', ...
        preprocessedSetPath);

    fprintf('============================================================\n\n');

    if ~exist( ...
            preprocessedSetPath, ...
            'file')

        warning( ...
            ['Preprocessed .set file not found. ' ...
             'Skipping this row:\n%s'], ...
            preprocessedSetPath);

        sourceMap = ...
            update_qc_status( ...
                sourceMap, ...
                rowIdx, ...
                "failed_preprocessed_set_not_found", ...
                "Preprocessed .set file was not found.", ...
                preprocessedSetPath, ...
                "");

        writetable( ...
            sourceMap, ...
            mappingFile);

        continue;
    end

    % Compute the QC input signature only after the preprocessed path has
    % been resolved and its .set file has been confirmed to exist.
    currentPreprocessedSetSignature = ...
        eeg_dataset_signature_local( ...
            preprocessedSetPath);


    %% --------------------------------------------------------------------
    %  PREPARE QUALITY CHECK OUTPUT FOLDER
    %  --------------------------------------------------------------------

    checkOutputFolder = ...
        fullfile( ...
            P.outputFolder, ...
            'Processed_EEG_quality_check', ...
            processingSubjectFolder);

    if ~exist( ...
            checkOutputFolder, ...
            'dir')

        mkdir(checkOutputFolder);
    end

    summaryFile = ...
        fullfile( ...
            checkOutputFolder, ...
            [ ...
                processingSubjectFolder ...
                '_preprocessed_check_summary.txt' ...
            ]);

    locationFig = ...
        fullfile( ...
            checkOutputFolder, ...
            [ ...
                processingSubjectFolder ...
                '_channel_locations.png' ...
            ]);


    %% --------------------------------------------------------------------
    %  START DIARY LOG
    %  --------------------------------------------------------------------

    if exist( ...
            summaryFile, ...
            'file')

        delete(summaryFile);
    end

    diary(summaryFile);

    fprintf('============================================================\n');
    fprintf('Preprocessed EEG quality check\n');
    fprintf('============================================================\n\n');

    fprintf( ...
        'Table row: %d\n\n', ...
        rowIdx);

    fprintf( ...
        'Original XDF name:\n%s\n\n', ...
        originalXDFName);

    fprintf( ...
        'Original XDF path:\n%s\n\n', ...
        originalXDFPath);

    fprintf( ...
        'Imported BIDS subject:\nsub-%d\n', ...
        bidsSubject);

    fprintf( ...
        'Imported BIDS session:\n%s\n', ...
        bidsSession);

    fprintf( ...
        'Processing subject label:\n%s\n', ...
        processingSubjectLabel);

    fprintf( ...
        'Processing folder:\n%s\n\n', ...
        processingSubjectFolder);

    if ismember( ...
            'RawSetPath', ...
            sourceMap.Properties.VariableNames)

        fprintf( ...
            'RawSetPath:\n%s\n\n', ...
            char( ...
                sourceMap.RawSetPath(rowIdx)));
    end

    if ismember( ...
            'RawSetStatus', ...
            sourceMap.Properties.VariableNames)

        fprintf( ...
            'RawSetStatus:\n%s\n\n', ...
            char( ...
                sourceMap.RawSetStatus(rowIdx)));
    end

    fprintf( ...
        'Input preprocessed file:\n%s\n\n', ...
        preprocessedSetPath);

    fprintf( ...
        'Quality check output folder:\n%s\n\n', ...
        checkOutputFolder);


    %% --------------------------------------------------------------------
    %  LOAD EEG
    %  --------------------------------------------------------------------

    try

        hipexo.hide_all_figures();

        EEG = ...
            pop_loadset( ...
                'filename', ...
                setFilename, ...
                'filepath', ...
                preprocFolder);

        EEG = ...
            eeg_checkset(EEG);

        hipexo.hide_all_figures();

    catch ME

        fprintf( ...
            '\nERROR while loading EEG:\n%s\n', ...
            ME.message);

        diary off;

        sourceMap = ...
            update_qc_status( ...
                sourceMap, ...
                rowIdx, ...
                "failed_load_preprocessed_set", ...
                string(ME.message), ...
                summaryFile, ...
                "");

        writetable( ...
            sourceMap, ...
            mappingFile);

        continue;
    end


    %% --------------------------------------------------------------------
    %  BASIC INFORMATION
    %  --------------------------------------------------------------------

    fprintf('============================================================\n');
    fprintf('Basic EEG information\n');
    fprintf('============================================================\n');

    fprintf( ...
        'Channels: %d\n', ...
        EEG.nbchan);

    fprintf( ...
        'Sampling rate: %.2f Hz\n', ...
        EEG.srate);

    fprintf( ...
        'Samples: %d\n', ...
        EEG.pnts);

    fprintf( ...
        'Duration: %.2f seconds\n', ...
        EEG.pnts / EEG.srate);

    fprintf( ...
        'Events: %d\n', ...
        length(EEG.event));

    channelLabels = ...
        {EEG.chanlocs.labels}';

    dataFiniteOK = ...
        check_data_finite_blockwise( ...
            EEG.data);

    durationOK = ...
        EEG.pnts > 1 && ...
        (EEG.pnts - 1) / EEG.srate >= 120;

    labelsUniqueOK = ...
        numel(channelLabels) == ...
        numel( ...
            unique( ...
                string(channelLabels)));

    labelsNonemptyOK = ...
        all( ...
            strlength( ...
                strtrim( ...
                    string(channelLabels))) > 0);

    expectedPreprocessingSignature = ...
        sourceMap.PreprocessingInputSignature(rowIdx);

    [ ...
        provenanceOK, ...
        provenanceNotes ...
    ] = ...
        check_preprocessing_provenance( ...
            EEG, ...
            expectedPreprocessingSignature, ...
            bidsSubject, ...
            bidsSession, ...
            processingSubjectLabel);

    % BeMoBIL deliberately stores the ICA rank after channel
    % interpolation in EEG.etc.rank. Spherical interpolation makes every
    % reconstructed channel a linear combination of the retained channels,
    % so the expected rank is:
    %
    %   number of output EEG channels - number of interpolated channels
    %
    % A direct rank(double(single_precision_data')) call can incorrectly
    % return the full channel count because small single-precision
    % interpolation round-off errors are treated as independent dimensions.
    % Keep the sampled numerical estimate as a diagnostic only and validate
    % the rank metadata against BeMoBIL's interpolation bookkeeping.

    [ ...
        interpolatedChannelCount, ...
        interpolationCountOK ...
    ] = ...
        check_interpolated_channel_count( ...
            EEG, ...
            maxInterpolatedChannelFraction);

    expectedRankFromInterpolation = NaN;

    if isfinite( ...
            interpolatedChannelCount)

        expectedRankFromInterpolation = ...
            EEG.nbchan - ...
            interpolatedChannelCount;
    end

    rankEstimate = ...
        estimate_data_rank_sampled( ...
            EEG.data, ...
            rankSampleLimit);

    [ ...
        rankMetadataValue, ...
        rankMetadataValid ...
    ] = ...
        get_rank_metadata(EEG);

    rankMetadataMatchesInterpolation = ...
        rankMetadataValid && ...
        isfinite( ...
            expectedRankFromInterpolation) && ...
        abs( ...
            rankMetadataValue - ...
            expectedRankFromInterpolation) < 0.5;

    % The numerical estimate may be inflated by interpolation round-off,
    % but it must never be lower than the intended ICA rank.
    rankEstimateCompatible = ...
        ~isnan(rankEstimate) && ...
        rankEstimate + 0.5 >= rankMetadataValue && ...
        rankEstimate <= EEG.nbchan;

    rankOK = ...
        rankMetadataMatchesInterpolation && ...
        rankEstimateCompatible;

    lineNoisePeakDb = ...
        estimate_line_noise_peak_db( ...
            EEG.data, ...
            EEG.srate, ...
            lineNoiseFrequencyHz);

    lineNoiseOK = ...
        ~isnan(lineNoisePeakDb) && ...
        lineNoisePeakDb <= maxLineNoisePeakDb;

    hasZaplineMetadata = ...
        isfield(EEG, 'etc') && ...
        isfield(EEG.etc, 'zapline');

    hasChannelRejectionMetadata = ...
        isfield(EEG, 'etc') && ...
        isfield( ...
            EEG.etc, ...
            'channel_rejection');

    hasInterpolationMetadata = ...
        isfield(EEG, 'etc') && ...
        isfield( ...
            EEG.etc, ...
            'interpolated_channels');

    hasAverageReferenceMetadata = ...
        isfield(EEG, 'etc') && ...
        isfield( ...
            EEG.etc, ...
            'bemobil_reref') && ...
        ~isempty( ...
            EEG.etc.bemobil_reref);

    fprintf( ...
        '\nProvenance check: %d\n', ...
        provenanceOK);

    fprintf( ...
        'Provenance detail: %s\n', ...
        provenanceNotes);

    fprintf( ...
        'Stored rank metadata: %.6g\n', ...
        rankMetadataValue);

    fprintf( ...
        ['Expected rank from BeMoBIL interpolation ' ...
         'metadata: %.6g\n'], ...
        expectedRankFromInterpolation);

    fprintf( ...
        ['Estimated sampled numerical rank ' ...
         '(diagnostic only): %.6g\n'], ...
        rankEstimate);

    fprintf( ...
        ['Rank metadata consistent with BeMoBIL ' ...
         'interpolation: %d\n'], ...
        rankOK);

    if rankOK && ...
            rankEstimate > rankMetadataValue

        fprintf([ ...
            'Note: the larger sampled numerical rank is compatible ' ...
            'with single-precision interpolation round-off and is not ' ...
            'used as the AMICA PCA rank.\n']);
    end

    fprintf( ...
        ['Residual %.1f Hz peak relative to neighboring ' ...
         'bands: %.4f dB\n'], ...
        lineNoiseFrequencyHz, ...
        lineNoisePeakDb);

    fprintf( ...
        'Residual line-noise check <= %.2f dB: %d\n', ...
        maxLineNoisePeakDb, ...
        lineNoiseOK);

    fprintf( ...
        'Interpolated channels: %.0f\n', ...
        interpolatedChannelCount);

    fprintf( ...
        'Interpolated-channel fraction <= %.2f: %d\n', ...
        maxInterpolatedChannelFraction, ...
        interpolationCountOK);


    %% --------------------------------------------------------------------
    %  SOURCE INFORMATION CHECK
    %  --------------------------------------------------------------------

    fprintf('\n============================================================\n');
    fprintf('Source information stored in EEG.etc\n');
    fprintf('============================================================\n');

    if isfield(EEG, 'etc')

        if isfield( ...
                EEG.etc, ...
                'source_original_xdf_name')

            fprintf( ...
                'source_original_xdf_name:\n%s\n', ...
                EEG.etc.source_original_xdf_name);

        else

            fprintf([ ...
                'CHECK: EEG.etc.source_original_xdf_name ' ...
                'does not exist.\n']);
        end

        if isfield( ...
                EEG.etc, ...
                'source_original_xdf_path')

            fprintf( ...
                'source_original_xdf_path:\n%s\n', ...
                EEG.etc.source_original_xdf_path);

        else

            fprintf([ ...
                'CHECK: EEG.etc.source_original_xdf_path ' ...
                'does not exist.\n']);
        end

        if isfield( ...
                EEG.etc, ...
                'real_bids_subject')

            fprintf( ...
                'real_bids_subject:\n%d\n', ...
                EEG.etc.real_bids_subject);

        elseif isfield( ...
                EEG.etc, ...
                'real_subject_label')

            fprintf( ...
                'real_subject_label:\n%s\n', ...
                EEG.etc.real_subject_label);

        else

            fprintf([ ...
                'CHECK: neither EEG.etc.real_bids_subject nor ' ...
                'EEG.etc.real_subject_label exists.\n']);
        end

        if isfield( ...
                EEG.etc, ...
                'session_label')

            fprintf( ...
                'session_label:\n%s\n', ...
                EEG.etc.session_label);

        else

            fprintf([ ...
                'CHECK: EEG.etc.session_label ' ...
                'does not exist.\n']);
        end

        if isfield( ...
