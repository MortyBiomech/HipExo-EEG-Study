function finiteOK = check_data_finite_blockwise(data)

    finiteOK = ...
        ~isempty(data);

    if ~finiteOK
        return;
    end

    blockSize = ...
        100000;

    nSamples = ...
        size(data, 2);

    for firstSample = ...
            1:blockSize:nSamples

        lastSample = ...
            min( ...
                nSamples, ...
                firstSample + ...
                blockSize - 1);

        block = ...
            double( ...
                data( ...
                    :, ...
                    firstSample:lastSample));

        if any( ...
                ~isfinite( ...
                    block(:)))

            finiteOK = false;
            return;
        end
    end

end


