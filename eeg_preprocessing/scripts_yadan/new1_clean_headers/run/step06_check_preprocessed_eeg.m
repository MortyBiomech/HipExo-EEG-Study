function [count, ok] = ...
        check_interpolated_channel_count( ...
            EEG, ...
            maxFraction)

    count = NaN;
    ok = false;

    if ~isfield( ...
            EEG, ...
            'etc') || ...
            ~isfield( ...
                EEG.etc, ...
                'interpolated_channels')

        return;
    end

    channels = ...
        EEG.etc.interpolated_channels;

    if isempty(channels)

        count = 0;
        ok = true;
        return;
    end

    if ~isnumeric(channels) || ...
            any( ...
                ~isfinite( ...
                    double( ...
                        channels(:)))) || ...
            any( ...
                channels(:) < 1) || ...
            any( ...
                channels(:) > EEG.nbchan) || ...
            any( ...
                abs( ...
                    double( ...
                        channels(:)) - ...
                    round( ...
                        double( ...
                            channels(:)))) > 1e-6)

        return;
    end

    count = ...
        numel( ...
            unique( ...
                double( ...
                    channels(:))));

    ok = ...
        count <= ...
        floor( ...
            double(EEG.nbchan) * ...
            maxFraction);

end


function rankEstimate = ...
        estimate_data_rank_sampled( ...
            data, ...
            sampleLimit)

    rankEstimate = NaN;

    try

        data = ...
            reshape( ...
                data, ...
                size(data, 1), ...
                []);

        nSamples = ...
            size(data, 2);

        if nSamples < 2 || ...
                isempty(data)

            return;
        end

        if nSamples > sampleLimit

            sampleIdx = ...
                unique( ...
                    round( ...
                        linspace( ...
                            1, ...
                            nSamples, ...
                            sampleLimit)));

            data = ...
                data( ...
                    :, ...
                    sampleIdx);
        end

        rankEstimate = ...
            rank( ...
                double( ...
                    data'));

    catch

        rankEstimate = NaN;
    end

end


function peakDb = ...
        estimate_line_noise_peak_db( ...
            data, ...
            srate, ...
            targetHz)

    peakDb = NaN;

    try

        if isempty(data) || ...
                ~isfinite(srate) || ...
                srate <= 0 || ...
                targetHz + 3 >= srate / 2

            return;
        end

        data = ...
            reshape( ...
                data, ...
                size(data, 1), ...
                []);

        nAvailable = ...
            size(data, 2);

        nSamples = ...
            min( ...
                nAvailable, ...
                max( ...
                    round(10 * srate), ...
                    round(60 * srate)));

        if nAvailable < ...
                round(10 * srate) || ...
                nSamples < 4

            return;
        end

        firstSample = ...
            floor( ...
                (nAvailable - nSamples) / 2) + 1;

        data = ...
            double( ...
                data( ...
                    :, ...
                    firstSample: ...
                    firstSample + ...
                    nSamples - 1));

        data = ...
            data - ...
            mean( ...
                data, ...
                2);

        window = ...
            0.5 - ...
            0.5 * ...
            cos( ...
                2 * pi * ...
                (0:nSamples - 1) / ...
                (nSamples - 1));

        spectrum = ...
            fft( ...
                data .* window, ...
                [], ...
                2);

        powerSpectrum = ...
            mean( ...
                abs(spectrum) .^ 2, ...
                1);

        frequency = ...
            (0:nSamples - 1) * ...
            (srate / nSamples);

        positive = ...
            frequency <= srate / 2;

        frequency = ...
            frequency(positive);

        powerSpectrum = ...
            powerSpectrum(positive);

        targetMask = ...
            abs( ...
                frequency - ...
                targetHz) <= 0.5;

        neighborMask = ...
            ( ...
                frequency >= targetHz - 3 & ...
                frequency <= targetHz - 1 ...
            ) | ...
            ( ...
                frequency >= targetHz + 1 & ...
                frequency <= targetHz + 3 ...
            );

        if ~any(targetMask) || ...
                ~any(neighborMask)

            return;
        end

        targetPower = ...
            mean( ...
                powerSpectrum(targetMask));

        neighborPower = ...
            mean( ...
                powerSpectrum(neighborMask));

        if targetPower <= 0 || ...
                neighborPower <= 0 || ...
                ~isfinite(targetPower) || ...
                ~isfinite(neighborPower)

            return;
        end

        peakDb = ...
            10 * ...
            log10( ...
                targetPower / ...
                neighborPower);

    catch

        peakDb = NaN;
    end

end


function signature = ...
        eeg_dataset_signature_local(setPath)

    setInfo = ...
        dir(setPath);

    if numel(setInfo) ~= 1

        error( ...
            'Cannot create a dataset signature for:\n%s', ...
            setPath);
    end

    [ ...
        setFolder, ...
        setStem ...
    ] = ...
        fileparts(setPath);

    fdtPath = ...
        fullfile( ...
            setFolder, ...
            [setStem '.fdt']);

    signature = ...
        string( ...
            sprintf( ...
                'set=%s|bytes=%d|datenum=%.15f', ...
                setPath, ...
                setInfo.bytes, ...
                setInfo.datenum));

    if isfile(fdtPath)

        fdtInfo = ...
            dir(fdtPath);

        signature = ...
            string( ...
                sprintf( ...
                    '%s|fdt=%s|bytes=%d|datenum=%.15f', ...
                    signature, ...
                    fdtPath, ...
                    fdtInfo.bytes, ...
                    fdtInfo.datenum));

    else

        signature = ...
            signature + ...
            "|fdt=embedded_or_absent";
    end

end