% GOAL
%   Scan new or changed XDF recordings and create structural EEG/GRF
%   usability audits that determine which recordings may enter the
%   import-control table.
%
% INPUT
%   Raw XDF files below P.rawDataFolder.
%   Existing Step 01 audit tables, when available.
%
% APPROACH
%   1. Find all XDF files.
%   2. Reuse existing QC results for unchanged XDF files.
%   3. Inspect only new or changed files with hipexo.inspect_xdf_file().
%   4. Evaluate EEG and GRF independently.
%   5. Autosave audit tables while scanning.
%
% OUTPUT
%   output_data/xdf_file_stream_summary.csv
%   output_data/xdf_stream_detail_table.csv
%   output_data/xdf_eeg_quality_audit.csv
%   output_data/xdf_grf_quality_audit.csv
%
% USED BY
%   step02_build_import_table.m

clear;
clc;

%% Load paths and Step 01-02 configuration

scriptsRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();
cfg = config_step01_02_xdf_import();

cacheVersion = "STEP01_CACHE_V2";

if ~isfolder(P.outputFolder)
    mkdir(P.outputFolder);
end

%% Initialize FieldTrip/XDF reader

ft_defaults;

if isempty(which('load_xdf'))
    error( ...
        'load_xdf was not found. Check P.xdfLoaderFolder in project_paths.m.');
end

%% Find XDF files

files = dir(fullfile(P.rawDataFolder, '**', '*.xdf'));

if isempty(files)
    error( ...
        'No XDF files found below:\n%s', ...
        P.rawDataFolder);
end

fprintf('\nFound %d XDF files.\n', numel(files));

%% Load existing audit cache

[cache, cacheReady] = ...
    load_audit_cache( ...
        P, ...
        cacheVersion);

fileSummaryTable = table();
streamDetailTable = table();

nReused = 0;
nScanned = 0;

%% Process XDF files

for i = 1:numel(files)

    xdfPath = fullfile( ...
        files(i).folder, ...
        files(i).name);

    sourceSignature = ...
        hipexo.file_signature(xdfPath);

    [reuseResult, result] = ...
        get_cached_result( ...
            cache, ...
            cacheReady, ...
            xdfPath, ...
            sourceSignature, ...
            i);

    if reuseResult

        nReused = nReused + 1;

    else

        nScanned = nScanned + 1;

        fprintf( ...
            'Scanning %d/%d: %s\n', ...
            i, ...
            numel(files), ...
            files(i).name);

        result = ...
            hipexo.inspect_xdf_file( ...
                xdfPath, ...
                i, ...
                cfg);

        if ~isempty(result.fileSummary)

            result.fileSummary.SourceFileSignature = ...
                repmat( ...
                    sourceSignature, ...
                    height(result.fileSummary), ...
                    1);

            result.fileSummary.CacheVersion = ...
                repmat( ...
                    cacheVersion, ...
                    height(result.fileSummary), ...
                    1);

        end

        if ~isempty(result.fileSummary) && ...
                result.fileSummary.FileEEGQualityStatus == "LOAD_ERROR"

            warning( ...
                'Could not load XDF:\n%s\nError:\n%s', ...
                xdfPath, ...
                result.fileSummary.FileEEGQualityReason);

        end

    end

    fileSummaryTable = ...
        [fileSummaryTable; result.fileSummary]; %#ok<AGROW>

    streamDetailTable = ...
        [streamDetailTable; result.streamDetail]; %#ok<AGROW>

    %% Autosave progress

    if mod(i, cfg.scan.saveEveryNFiles) == 0 || ...
            i == numel(files)

        save_audit_tables( ...
            fileSummaryTable, ...
            streamDetailTable, ...
            P);

    end

end

%% Final report

fprintf('\n============================================================\n');
fprintf('EEG + GRF XDF SCAN FINISHED\n');
fprintf('============================================================\n');

fprintf('Files found:               %d\n', ...
    numel(files));

fprintf('Unchanged files reused:    %d\n', ...
    nReused);

fprintf('New/changed files scanned: %d\n', ...
    nScanned);

fprintf('\nFiles with real EEG:       %d\n', ...
    sum(fileSummaryTable.HasRealEEG));

fprintf('Files with usable EEG:     %d\n', ...
    sum(fileSummaryTable.HasUsableEEG));

fprintf('Files with a GRF stream:   %d\n', ...
    sum(fileSummaryTable.HasGRFStream));

fprintf('Files with usable GRF:     %d\n', ...
    sum(fileSummaryTable.HasUsableGRF));

fprintf('EEG + GRF PASS:            %d\n', ...
    sum( ...
        fileSummaryTable.HasUsableEEG & ...
        fileSummaryTable.HasUsableGRF));

print_failed_files(fileSummaryTable);

fprintf( ...
    '\nDone. Run step02_build_import_table.m next when needed.\n');

%% Local cache helpers

function [cache, cacheReady] = ...
        load_audit_cache( ...
            P, ...
            expectedCacheVersion)

cache = struct( ...
    'fileSummary', table(), ...
    'streamDetail', table());

cacheReady = false;

if ~isfile(P.summaryFile) || ...
        ~isfile(P.detailFile)

    return;

end

try

    %% Read summary as strings first

    summaryOpts = ...
        detectImportOptions( ...
            P.summaryFile, ...
            'FileType', 'text', ...
            'Delimiter', ',', ...
            'VariableNamingRule', 'preserve');

    summaryOpts = ...
        setvartype( ...
            summaryOpts, ...
            summaryOpts.VariableNames, ...
            'string');

    fileSummary = ...
        readtable( ...
            P.summaryFile, ...
            summaryOpts);

    %% Read stream details as strings first

    detailOpts = ...
        detectImportOptions( ...
            P.detailFile, ...
            'FileType', 'text', ...
            'Delimiter', ',', ...
            'VariableNamingRule', 'preserve');

    detailOpts = ...
        setvartype( ...
            detailOpts, ...
            detailOpts.VariableNames, ...
            'string');

    streamDetail = ...
        readtable( ...
            P.detailFile, ...
            detailOpts);

catch
    return;
end

%% Check cache schema and version

requiredSummaryColumns = { ...
    'FileIndex', ...
    'FileName', ...
    'FullPath', ...
    'AllStreams', ...
    'HasRealEEG', ...
    'HasUsableEEG', ...
    'FileEEGQualityStatus', ...
    'FileEEGQualityReason', ...
    'HasGRFStream', ...
    'HasUsableGRF', ...
    'FileGRFQualityStatus', ...
    'FileGRFQualityReason', ...
    'SourceFileSignature', ...
    'CacheVersion'};

requiredDetailColumns = { ...
    'FileIndex', ...
    'FileName', ...
    'FullPath', ...
    'StreamIndex', ...
    'StreamName', ...
    'StreamType', ...
    'NominalSrate', ...
    'ChannelCount', ...
    'IsRealEEG', ...
    'IsUsableEEG', ...
    'IsGRFCandidate', ...
    'IsUsableGRF', ...
    'NDataSamples', ...
    'NTimeStamps', ...
    'DurationSec', ...
    'EffectiveSrate', ...
    'MedianDtSec', ...
    'MinDtSec', ...
    'MaxDtSec', ...
    'SrateAbsDiff', ...
    'SrateRelDiff', ...
    'SampleTimestampMatch', ...
    'TimestampsFinite', ...
    'TimestampsStrictlyIncreasing', ...
    'DataFiniteSampled', ...
    'RobustGapLimitSec', ...
    'EEGQualityStatus', ...
    'EEGQualityReason', ...
    'GRFQualityStatus', ...
    'GRFQualityReason'};

if ~all(ismember( ...
        requiredSummaryColumns, ...
        fileSummary.Properties.VariableNames))

    return;

end

if ~all(ismember( ...
        requiredDetailColumns, ...
        streamDetail.Properties.VariableNames))

    return;

end

if isempty(fileSummary) || ...
        any(fileSummary.CacheVersion ~= expectedCacheVersion)

    return;

end

%% Restore summary data types

fileSummary.FileIndex = ...
    to_numeric_column( ...
        fileSummary.FileIndex);

fileSummary.HasRealEEG = ...
    to_logical_column( ...
        fileSummary.HasRealEEG);

fileSummary.HasUsableEEG = ...
    to_logical_column( ...
        fileSummary.HasUsableEEG);

fileSummary.HasGRFStream = ...
    to_logical_column( ...
        fileSummary.HasGRFStream);

fileSummary.HasUsableGRF = ...
    to_logical_column( ...
        fileSummary.HasUsableGRF);

%% Restore stream-detail data types

numericDetailColumns = { ...
    'FileIndex', ...
    'StreamIndex', ...
    'NDataSamples', ...
    'NTimeStamps', ...
    'DurationSec', ...
    'EffectiveSrate', ...
    'MedianDtSec', ...
    'MinDtSec', ...
    'MaxDtSec', ...
    'SrateAbsDiff', ...
    'SrateRelDiff', ...
    'RobustGapLimitSec'};

for k = 1:numel(numericDetailColumns)

    name = numericDetailColumns{k};

    streamDetail.(name) = ...
        to_numeric_column( ...
            streamDetail.(name));

end

logicalDetailColumns = { ...
    'IsRealEEG', ...
    'IsUsableEEG', ...
    'IsGRFCandidate', ...
    'IsUsableGRF', ...
    'SampleTimestampMatch', ...
    'TimestampsFinite', ...
    'TimestampsStrictlyIncreasing', ...
    'DataFiniteSampled'};

for k = 1:numel(logicalDetailColumns)

    name = logicalDetailColumns{k};

    streamDetail.(name) = ...
        to_logical_column( ...
            streamDetail.(name));

end

cache.fileSummary = ...
    fileSummary(:, requiredSummaryColumns);

cache.streamDetail = ...
    streamDetail(:, requiredDetailColumns);

cacheReady = true;

end

function [reuseResult, result] = ...
        get_cached_result( ...
            cache, ...
            cacheReady, ...
            xdfPath, ...
            sourceSignature, ...
            currentFileIndex)

reuseResult = false;

result = struct( ...
    'fileSummary', table(), ...
    'streamDetail', table());

if ~cacheReady
    return;
end

summaryMask = ...
    matching_path_rows( ...
        cache.fileSummary, ...
        xdfPath);

summaryIndex = ...
    find(summaryMask);

if numel(summaryIndex) ~= 1
    return;
end

summaryRow = ...
    cache.fileSummary(summaryIndex, :);

if summaryRow.SourceFileSignature ~= sourceSignature
    return;
end

% Retry files that previously failed to load.

if summaryRow.FileEEGQualityStatus == "LOAD_ERROR" || ...
        summaryRow.FileGRFQualityStatus == "LOAD_ERROR"

    return;

end

detailRows = ...
    cache.streamDetail( ...
        matching_path_rows( ...
            cache.streamDetail, ...
            xdfPath), ...
        :);

if isempty(detailRows)
    return;
end

summaryRow.FileIndex(:) = ...
    currentFileIndex;

detailRows.FileIndex(:) = ...
    currentFileIndex;

result.fileSummary = ...
    summaryRow;

result.streamDetail = ...
    detailRows;

reuseResult = true;

end

function mask = ...
        matching_path_rows( ...
            T, ...
            xdfPath)

if isempty(T) || ...
        ~ismember( ...
            'FullPath', ...
            T.Properties.VariableNames)

    mask = false(height(T), 1);
    return;

end

storedPaths = ...
    normalize_paths( ...
        string(T.FullPath));

targetPath = ...
    normalize_paths( ...
        string(xdfPath));

mask = ...
    storedPaths == targetPath;

end

function paths = normalize_paths(paths)

paths = ...
    strtrim( ...
        string(paths));

paths = ...
    replace( ...
        paths, ...
        "\", ...
        "/");

if ispc
    paths = lower(paths);
end

end

function y = to_numeric_column(x)

if isnumeric(x)

    y = double(x);

elseif islogical(x)

    y = double(x);

else

    y = ...
        str2double( ...
            string(x));

end

end

function y = to_logical_column(x)

if islogical(x)

    y = x;
    return;

end

if isnumeric(x)

    y = x ~= 0;
    return;

end

x = ...
    lower( ...
        strtrim( ...
            string(x)));

y = ...
    x == "true" | ...
    x == "1" | ...
    x == "yes";

end

%% Local output helpers

function save_audit_tables( ...
        fileSummaryTable, ...
        streamDetailTable, ...
        P)

writetable( ...
    fileSummaryTable, ...
    P.summaryFile);

writetable( ...
    streamDetailTable, ...
    P.detailFile);

if isempty(streamDetailTable)

    eegQualityTable = table();
    grfQualityTable = table();

else

    eegQualityTable = ...
        streamDetailTable( ...
            streamDetailTable.IsRealEEG, ...
            :);

    grfQualityTable = ...
        streamDetailTable( ...
            streamDetailTable.IsGRFCandidate, ...
            :);

end

writetable( ...
    eegQualityTable, ...
    P.eegQualityFile);

writetable( ...
    grfQualityTable, ...
    P.grfQualityFile);

end

function print_failed_files(fileSummaryTable)

failedRows = ...
    (fileSummaryTable.HasRealEEG & ...
     (~fileSummaryTable.HasUsableEEG | ...
      ~fileSummaryTable.HasUsableGRF)) | ...
    fileSummaryTable.FileEEGQualityStatus == "LOAD_ERROR" | ...
    fileSummaryTable.FileGRFQualityStatus == "LOAD_ERROR";

if ~any(failedRows)

    fprintf( ...
        '\nNo real-EEG XDF files failed the EEG/GRF gates.\n');

    return;

end

fprintf('\nFiles requiring review:\n');

disp(fileSummaryTable( ...
    failedRows, ...
    { ...
        'FileName', ...
        'FileEEGQualityStatus', ...
        'FileEEGQualityReason', ...
        'FileGRFQualityStatus', ...
        'FileGRFQualityReason'}));

end