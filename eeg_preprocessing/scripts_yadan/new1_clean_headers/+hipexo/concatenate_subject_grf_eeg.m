    'FileType','text', ...
    'Delimiter',',', ...
    'VariableNamingRule','preserve');

textVariables = ...
    options.VariableNames( ...
    ismember( ...
    options.VariableTypes, ...
    {'char','categorical'}));

if ~isempty(textVariables)

    options = setvartype( ...
        options, ...
        textVariables, ...
        'string');
end

outputTable = readtable(csvFile,options);

end

function values = numeric_column_local(values)

if isnumeric(values)

    values = double(values);

elseif islogical(values)

    values = double(values);

else

    textValues = ...
        lower(strtrim(string(values)));

    values = str2double(textValues);

    values(ismember( ...
        textValues, ...
        ["true","yes"])) = 1;

    values(ismember( ...
        textValues, ...
        ["false","no"])) = 0;
end

end

function value = current_time_text

value = string(datetime( ...
    'now', ...
    'TimeZone','local', ...
    'Format','yyyy-MM-dd HH:mm:ss'));

end
