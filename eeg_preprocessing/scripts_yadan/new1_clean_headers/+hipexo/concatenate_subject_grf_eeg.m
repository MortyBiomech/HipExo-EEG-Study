for iFile = 1:numel(sourceSetPaths)

    setPath = string(sourceSetPaths(iFile));
    setInfo = dir(setPath);

    if isempty(setInfo)
        error('Source SET missing:\n%s',setPath);
    end

    [setFolder,setBase,~] = ...
        fileparts(char(setPath));

    fdtPath = fullfile( ...
        setFolder, ...
        [setBase '.fdt']);

    fdtPart = "";

    if isfile(fdtPath)

        fdtInfo = dir(fdtPath);

        fdtPart = compose( ...
            "|fdt=%d@%.12f", ...
            fdtInfo.bytes, ...
            fdtInfo.datenum);
    end

    parts(iFile) = ...
        string(setPath) + ...
        compose( ...
        "|set=%d@%.12f", ...
        setInfo.bytes, ...
        setInfo.datenum) + ...
        fdtPart;
end

signature = ...
    "raw_xdf_eeg_lsl_chronological_merge_v5||" + ...
    strjoin(parts,"||");

end

function signature = ...
        build_continuous_input_signature(sourceManifest, EEG)

% This signature answers a different question from
% SubjectInputSignature. SubjectInputSignature changes whenever a mapped
% source .set is regenerated, including an event-only update. The
% continuous signature changes only when the source XDF identity/order,
% sample layout, sampling rate, or channel layout changes.

nSources = height(sourceManifest);
parts = strings(nSources, 1);

for iSource = 1:nSources

    xdfPath = string(sourceManifest.XDFPath(iSource));
    xdfInfo = dir(xdfPath);

    if isempty(xdfInfo)
        error(['Cannot build the continuous-input signature because ' ...
            'the source XDF is missing:\n%s'], xdfPath);
    end

    parts(iSource) = compose( ...
        ['%d|%s|xdf=%d@%.12f|start=%d|end=%d|samples=%d|' ...
         'condition=%s|run=%g'], ...
        double(sourceManifest.SourceIndex(iSource)), ...
        xdfPath, ...
        xdfInfo.bytes, ...
        xdfInfo.datenum, ...
        double(sourceManifest.StartSampleInMergedEEG(iSource)), ...
        double(sourceManifest.EndSampleInMergedEEG(iSource)), ...
        double(sourceManifest.SampleCount(iSource)), ...
        string(sourceManifest.ConditionLabel(iSource)), ...
        double(sourceManifest.RunNumber(iSource)));
end

channelLabels = strjoin(string({EEG.chanlocs.labels}), '|');

signature = ...
    "continuous_xdf_chronological_layout_v1" + ...
    "||nbchan=" + string(double(EEG.nbchan)) + ...
    "||srate=" + compose('%.15g', double(EEG.srate)) + ...
    "||pnts=" + string(double(EEG.pnts)) + ...
    "||channels=" + channelLabels + ...
    "||" + strjoin(parts, "||");

end

