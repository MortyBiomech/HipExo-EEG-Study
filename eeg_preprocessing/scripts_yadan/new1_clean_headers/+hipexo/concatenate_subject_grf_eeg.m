function validate_merged_subject_eeg( ...
        EEG,expectedSourceCount)

if EEG.trials ~= 1 || ...
        EEG.nbchan ~= 64 || ...
        abs(double(EEG.srate)-500) > 1e-6

    error('Merged EEG failed basic structure QC.');
end

if ~channel_locations_complete(EEG.chanlocs)
    error('Merged EEG channel locations incomplete.');
end

if any(~isfinite(double(EEG.data(:))))
    error('Merged EEG contains NaN/Inf.');
end

eventTypes = event_type_strings(EEG.event);

requiredGaitEventTypes = ...
    ["RHS","RTO","LHS","LTO"];

missingGaitEventTypes = ...
    requiredGaitEventTypes( ...
    ~ismember( ...
    requiredGaitEventTypes, ...
    eventTypes));

if ~isempty(missingGaitEventTypes)
    error('Merged EEG missing gait event types.');
end

recordingStartCount = ...
    sum(eventTypes=="recording_start");

if recordingStartCount ~= expectedSourceCount
    error('Incorrect number of recording_start events.');
end

recordingStartIndices = ...
    event_numeric_field_values( ...
    EEG.event(eventTypes=="recording_start"), ...
    'source_recording_index');

if numel(recordingStartIndices) ~= expectedSourceCount || ...
        ~isequal( ...
        sort(recordingStartIndices(:))', ...
        1:expectedSourceCount)

    error('recording_start indices invalid.');
end

gaitEventSourceIndices = ...
    event_numeric_field_values( ...
    EEG.event(ismember( ...
    eventTypes, ...
    requiredGaitEventTypes)), ...
    'source_recording_index');

if any(~isfinite(gaitEventSourceIndices)) || ...
        any(gaitEventSourceIndices < 1) || ...
        any(gaitEventSourceIndices > expectedSourceCount)

    error('Gait event source index invalid.');
end

expectedJoinBoundaries = ...
    max(0,expectedSourceCount-1);

boundarySources = ...
    event_text_field_values( ...
    EEG.event(eventTypes=="boundary"), ...
    'source_recording');

joinBoundaryCount = ...
    sum(boundarySources=="dataset_join_boundary");

if joinBoundaryCount ~= expectedJoinBoundaries
    error('Incorrect dataset-join boundary count.');
end

end

