function EEG = ...
        normalize_merged_event_metadata( ...
            EEG,sourceManifest)

requiredTextFields = { ...
    'subject_label', ...
    'day_label', ...
    'session_label', ...
    'condition_label', ...
    'task_label', ...
    'source_xdf', ...
    'source_recording'};

for iEvent = 1:numel(EEG.event)

    for iField = 1:numel(requiredTextFields)

        fieldName = requiredTextFields{iField};

        if ~isfield(EEG.event,fieldName) || ...
                ~has_nonempty_event_text_value( ...
                EEG.event(iEvent).(fieldName))

            EEG.event(iEvent).(fieldName) = '';
        end
    end

    if ~isfield(EEG.event,'run_number') || ...
            isempty(EEG.event(iEvent).run_number)

        EEG.event(iEvent).run_number = NaN;
    end

    if ~isfield(EEG.event,'source_recording_index') || ...
            isempty(EEG.event(iEvent).source_recording_index)

        EEG.event(iEvent).source_recording_index = NaN;
    end

    currentType = ...
        event_type_strings(EEG.event(iEvent));

    if currentType == "boundary" && ...
            ~has_nonempty_event_text_value( ...
            EEG.event(iEvent).source_recording)

        EEG.event(iEvent).source_recording = ...
            'dataset_join_boundary';
    end
end

expectedJoinLatencies = ...
    double( ...
    sourceManifest.EndSampleInMergedEEG(1:end-1)) + 0.5;

allEventTypes = ...
    event_type_strings(EEG.event);

allEventLatencies = ...
    double([EEG.event.latency])';

for iJoin = 1:numel(expectedJoinLatencies)

    matchingBoundary = find( ...
        allEventTypes == "boundary" & ...
        abs( ...
        allEventLatencies - ...
        expectedJoinLatencies(iJoin)) <= 1e-6);

    if numel(matchingBoundary) ~= 1

        error( ...
            'Expected one join boundary at latency %.9g.', ...
            expectedJoinLatencies(iJoin));
    end

    eventIndex = matchingBoundary(1);

    EEG.event(eventIndex).source_recording = ...
        'dataset_join_boundary';

    EEG.event(eventIndex).source_recording_index = ...
        NaN;

    if isfield(EEG.event,'mapping_status')

        EEG.event(eventIndex).mapping_status = ...
            'dataset_join_boundary';
    end
end

end

