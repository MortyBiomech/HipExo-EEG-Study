%% ------------------------------------------------------------
function validate_source_eeg( ...
        EEG, ...
        metadata, ...
        referenceSrate, ...
        referenceChannelLabels, ...
        referenceChannelXYZ)

if EEG.trials ~= 1
    error('Source EEG must be continuous.');
end

if EEG.nbchan ~= 64
    error('Expected 64 EEG channels.');
end

if abs(double(EEG.srate)-500) > 1e-6
    error('Expected 500 Hz EEG.');
end

if isfinite(referenceSrate) && ...
        abs(double(EEG.srate)-referenceSrate) > 1e-6
    error('Sampling-rate mismatch.');
end

currentChannelLabels = ...
    string({EEG.chanlocs.labels})';

if numel(unique(lower(strtrim(currentChannelLabels)))) ~= EEG.nbchan
    error('Channel labels are not unique.');
end

if ~isempty(referenceChannelLabels) && ...
        ~isequal( ...
        lower(strtrim(currentChannelLabels)), ...
        lower(strtrim(referenceChannelLabels)))

    error('Channel labels/order differ.');
end

if ~channel_locations_complete(EEG.chanlocs)
    error('Channel locations incomplete.');
end

currentChannelXYZ = ...
    channel_xyz_matrix(EEG.chanlocs);

if ~isempty(referenceChannelXYZ) && ...
        (size(currentChannelXYZ,1) ~= size(referenceChannelXYZ,1) || ...
         any(abs( ...
         currentChannelXYZ(:)-referenceChannelXYZ(:)) > 1e-9))

    error('Channel coordinates differ.');
end

if any(~isfinite(double(EEG.data(:))))
    error('EEG contains NaN/Inf.');
end

if isempty(EEG.event)
    error('Source EEG contains no events.');
end

end

function tf = channel_locations_complete(chanlocs)

tf = ~isempty(chanlocs);

if ~tf
    return;
end

requiredFields = {'X','Y','Z'};

for iField = 1:numel(requiredFields)

    fieldName = requiredFields{iField};

    if ~isfield(chanlocs,fieldName)
        tf = false;
        return;
    end

    for iChannel = 1:numel(chanlocs)

        value = chanlocs(iChannel).(fieldName);

        if isempty(value) || ...
                ~isnumeric(value) || ...
                ~isfinite(double(value(1)))

            tf = false;
            return;
        end
    end
end

end

function xyz = channel_xyz_matrix(chanlocs)

xyz = nan(numel(chanlocs),3);

for iChannel = 1:numel(chanlocs)

    xyz(iChannel,:) = [ ...
        double(chanlocs(iChannel).X), ...
        double(chanlocs(iChannel).Y), ...
        double(chanlocs(iChannel).Z)];
end

end

%% Read actual EEG LSL timestamps directly from original XDF

function [firstLSLTime,lastLSLTime] = ...
        source_xdf_eeg_lsl_bounds(xdfPath)

if exist('load_xdf','file') ~= 2
    error('load_xdf is not available.');
end

[streams,~] = load_xdf(char(xdfPath));

nStreams = numel(streams);

streamName = strings(nStreams,1);
streamType = strings(nStreams,1);
nominalSrate = nan(nStreams,1);
channelCount = nan(nStreams,1);
sampleCount = nan(nStreams,1);

for iStream = 1:nStreams

    currentStream = streams{iStream};

    streamName(iStream) = ...
        xdf_stream_text_field(currentStream,'name');

    streamType(iStream) = ...
        xdf_stream_text_field(currentStream,'type');

    nominalSrate(iStream) = ...
        xdf_stream_nominal_srate(currentStream);

    if isfield(currentStream,'time_stamps')

        currentTimestamps = ...
            currentStream.time_stamps;

        sampleCount(iStream) = ...
            numel(currentTimestamps);

        if isfield(currentStream,'time_series') && ...
                isnumeric(currentStream.time_series)

            currentData = ...
                currentStream.time_series;

            if size(currentData,2) == sampleCount(iStream)

                channelCount(iStream) = ...
                    size(currentData,1);

            elseif size(currentData,1) == sampleCount(iStream)

                channelCount(iStream) = ...
                    size(currentData,2);
            end
        end
    end
end

candidateMask = ...
    strcmpi(streamName,"LiveAmpSN-102108-1139") & ...
    channelCount >= 64 & ...
    channelCount <= 80 & ...
    abs(nominalSrate-500) <= 1;

candidateIndices = find(candidateMask);

if isempty(candidateIndices)

    candidateMask = ...
        channelCount >= 64 & ...
        channelCount <= 80 & ...
        abs(nominalSrate-500) <= 1 & ...
        (contains(lower(streamType),'eeg') | ...
         contains(lower(streamName),'liveamp'));

    candidateIndices = find(candidateMask);
end

if numel(candidateIndices) ~= 1

    streamSummary = table( ...
        (1:nStreams)', ...
        streamName, ...
        streamType, ...
        nominalSrate, ...
        channelCount, ...
        sampleCount, ...
        'VariableNames', ...
        {'StreamIndex','Name','Type','NominalSrate', ...
         'ChannelCount','SampleCount'});

    disp(streamSummary);

    error('Could not uniquely identify EEG stream:\n%s', ...
        xdfPath);
end

eegStream = streams{candidateIndices(1)};
eegTimestamps = double(eegStream.time_stamps(:));

if isempty(eegTimestamps) || ...
        any(~isfinite(eegTimestamps)) || ...
        any(diff(eegTimestamps)<=0)

    error('Invalid EEG LSL timestamps:\n%s', xdfPath);
end

firstLSLTime = eegTimestamps(1);
lastLSLTime = eegTimestamps(end);

end

function textValue = ...
        xdf_stream_text_field(stream,fieldName)

textValue = "";

if ~isfield(stream,'info') || ...
        ~isfield(stream.info,fieldName)
    return;
end

rawValue = stream.info.(fieldName);

while iscell(rawValue) && ~isempty(rawValue)
    rawValue = rawValue{1};
end

if isempty(rawValue)
    return;
