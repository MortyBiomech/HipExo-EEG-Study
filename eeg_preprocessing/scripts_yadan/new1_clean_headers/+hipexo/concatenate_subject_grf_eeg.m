function update_subject_processing_table(newRow,tableFile)

baseVariables = newRow.Properties.VariableNames;

if ~isfile(tableFile)
    writetable(newRow,tableFile);
    return;
end

oldTable = read_csv_with_string_text(tableFile);

if ~ismember( ...
        'SubjectLabel', ...
        oldTable.Properties.VariableNames)

    backupFile = char( ...
        string(tableFile) + ...
        ".incompatible_backup_" + ...
        string(datetime( ...
        'now', ...
        'Format','yyyyMMdd_HHmmss')) + ...
        ".csv");

    copyfile(tableFile,backupFile);

    writetable(newRow,tableFile);

    return;
end

oldTable.SubjectLabel = ...
    string(oldTable.SubjectLabel);

if ismember( ...
        'SubjectInputSignature', ...
        oldTable.Properties.VariableNames)

    oldTable.SubjectInputSignature = ...
        string(oldTable.SubjectInputSignature);
end

matchingRows = ...
    find(oldTable.SubjectLabel == newRow.SubjectLabel);

if numel(matchingRows) > 1
    error(['The subject-level processing table contains duplicate rows ' ...
        'for %s. Resolve the duplicate rows before concatenation.'], ...
        newRow.SubjectLabel);
end

% Keep a recoverable copy before replacing an existing participant row.
% This is intentionally done before any downstream-state decision.
if ~isempty(matchingRows)
    backupFile = char( ...
        string(tableFile) + ...
        ".before_subject_update_" + ...
        string(datetime('now', 'Format','yyyyMMdd_HHmmss_SSS')) + ...
        ".csv");
    copyfile(tableFile, backupFile);
end

oldVariableNames = ...
    oldTable.Properties.VariableNames;

for iVariable = 1:numel(baseVariables)

    variableName = baseVariables{iVariable};

    if ~ismember(variableName,oldVariableNames)

        oldTable.(variableName) = ...
            make_missing_column_like( ...
            newRow.(variableName), ...
            height(oldTable));
    end
end

oldVariableNames = ...
    oldTable.Properties.VariableNames;

for iVariable = 1:numel(oldVariableNames)

    variableName = oldVariableNames{iVariable};

    if ~ismember( ...
            variableName, ...
            newRow.Properties.VariableNames)

        newRow.(variableName) = ...
            make_missing_column_like( ...
            oldTable.(variableName), ...
            1);
    end
end

newRow = ...
    newRow(:,oldTable.Properties.VariableNames);

if ~isempty(matchingRows)

    previousRow = matchingRows(1);

    signatureUnchanged = false;

    if ismember('SubjectInputSignature', ...
            oldTable.Properties.VariableNames)
        signatureUnchanged = ...
            string(oldTable.SubjectInputSignature(previousRow)) == ...
            string(newRow.SubjectInputSignature);
    end

    continuousLayoutCompatible = ...
        continuous_layout_compatible_local( ...
            oldTable, newRow, previousRow);

    preserveDownstream = ...
        signatureUnchanged || continuousLayoutCompatible;

    if signatureUnchanged
        newRow.EventUpdateCompatibility(1) = ...
            "identical_source_signature_downstream_preserved";
    elseif continuousLayoutCompatible
        newRow.EventUpdateCompatibility(1) = ...
            "event_only_compatible_downstream_preserved";
    else
        newRow.EventUpdateCompatibility(1) = ...
            "continuous_layout_changed_downstream_reset";
    end

    if preserveDownstream

        columnsToPreserve = setdiff( ...
            oldTable.Properties.VariableNames, ...
            baseVariables, ...
            'stable');

        if ismember('DoPreprocess',baseVariables)
            columnsToPreserve = ...
                [{'DoPreprocess'},columnsToPreserve];
        end

        for iColumn = 1:numel(columnsToPreserve)

            columnName = ...
                columnsToPreserve{iColumn};

            newRow.(columnName)(1,:) = ...
                oldTable.(columnName)(previousRow,:);
        end
    end
else
    newRow.EventUpdateCompatibility(1) = ...
        "new_subject_no_previous_downstream_state";
end

oldTable(matchingRows,:) = [];

updatedTable = [oldTable;newRow];

if ismember( ...
        'BidsSubject', ...
        updatedTable.Properties.VariableNames)

    updatedTable = ...
        sortrows(updatedTable,'BidsSubject');
end

writetable(updatedTable,tableFile);

end

function compatible = continuous_layout_compatible_local( ...
        oldTable, newRow, previousRow)

compatible = false;

% This signature depends on source XDF identity/order, sample layout, sampling
% rate, and channels, but deliberately not on gait-event latencies/counts.
if ismember('ContinuousInputSignature', ...
        oldTable.Properties.VariableNames) && ...
        ismember('ContinuousInputSignature', ...
        newRow.Properties.VariableNames)

    oldSignature = strtrim(string( ...
        oldTable.ContinuousInputSignature(previousRow)));
    newSignature = strtrim(string( ...
        newRow.ContinuousInputSignature(1)));

    if strlength(oldSignature) > 0 && strlength(newSignature) > 0
        compatible = oldSignature == newSignature;
        return;
    end
end

% These fields together establish that the same recordings remain in the same merged
% continuous sample layout. MappedGaitEventCount is intentionally absent.
requiredStringFields = {'SubjectLabel','BidsSession','XdfPath'};
requiredNumericFields = { ...
    'SourceRecordingCount', ...
    'BoundaryEventCount', ...
    'ChannelCount', ...
    'SamplingRate', ...
    'DurationSec'};

if ~all(ismember(requiredStringFields, ...
        oldTable.Properties.VariableNames)) || ...
        ~all(ismember(requiredStringFields, ...
        newRow.Properties.VariableNames)) || ...
        ~all(ismember(requiredNumericFields, ...
        oldTable.Properties.VariableNames)) || ...
        ~all(ismember(requiredNumericFields, ...
        newRow.Properties.VariableNames))
    return;
end

for k = 1:numel(requiredStringFields)
    fieldName = requiredStringFields{k};
    oldValue = strtrim(string(oldTable.(fieldName)(previousRow)));
    newValue = strtrim(string(newRow.(fieldName)(1)));

    if strlength(oldValue) == 0 || strlength(newValue) == 0 || ...
            ~strcmpi(oldValue, newValue)
        return;
    end
end

for k = 1:numel(requiredNumericFields)
    fieldName = requiredNumericFields{k};
    oldValue = numeric_column_local( ...
        oldTable.(fieldName)(previousRow));
    newValue = numeric_column_local(newRow.(fieldName)(1));

    if ~isscalar(oldValue) || ~isscalar(newValue) || ...
            ~isfinite(oldValue) || ~isfinite(newValue)
        return;
    end

    tolerance = max(1e-9, abs(newValue) * 1e-9);
    if abs(oldValue - newValue) > tolerance
        return;
    end
end

compatible = true;

end

function column = ...
        make_missing_column_like(example,numberOfRows)

if isstring(example)

    column = strings( ...
        numberOfRows,size(example,2));

elseif islogical(example)

    column = false( ...
        numberOfRows,size(example,2));

elseif isnumeric(example)

    column = nan( ...
        numberOfRows,size(example,2));

elseif isdatetime(example)

    column = NaT( ...
        numberOfRows,size(example,2));

elseif iscell(example)

    column = cell( ...
        numberOfRows,size(example,2));

elseif iscategorical(example)

    column = repmat( ...
        categorical(missing), ...
        numberOfRows, ...
        size(example,2));

else

    column = strings( ...
        numberOfRows,size(example,2));
end

end

