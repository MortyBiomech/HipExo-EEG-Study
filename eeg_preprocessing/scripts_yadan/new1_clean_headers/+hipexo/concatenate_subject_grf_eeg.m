    % chronology is independently read from the original XDF here.
    [eegFirstLSLTime(iSource), ...
     eegLastLSLTime(iSource)] = ...
        source_xdf_eeg_lsl_bounds( ...
        sourceTable.XDFPath(iSource));

    loadedEEG{iSource} = currentEEG;
    sourceMetadata{iSource} = currentMetadata;
end

