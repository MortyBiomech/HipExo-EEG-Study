%% build_k06_curated_STUDY.m
%
% Goal:
% 1. Load the original K=6 spatially clustered Yes-only STUDY.
% 2. Read the completed member-level QC table.
% 3. Create a conservative CORE STUDY containing ReviewerDecision = Keep.
% 4. Create an INCLUSIVE STUDY containing Keep + NeedsDiscussion.
% 5. Verify every cluster membership against the QC table.
% 6. Export membership and coverage reports.
% 7. Support Keep, NeedsDiscussion, Reassign, and ClusterOutlier decisions.
%
% This script does NOT:
% - rerun ICA;
% - rerun preclustering;
% - rerun k-means;
% - modify the original .set datasets;
% - overwrite the original K=6 STUDY.

