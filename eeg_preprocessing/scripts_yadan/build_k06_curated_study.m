%% Local functions

function verify_qc_against_source_study_local( ...
    STUDY, qc, expectedChildClusterIndices, expectedMemberCount)

    actualChildClusterIndices = 2:numel(STUDY.cluster);

    if ~isequal(actualChildClusterIndices, expectedChildClusterIndices)
        error(['Source STUDY child cluster indices do not match the frozen ' ...
            'K=6 definition. Expected %s, found %s.'], ...
            mat2str(expectedChildClusterIndices), ...
            mat2str(actualChildClusterIndices));
    end

    if height(qc) ~= expectedMemberCount
        error('Expected %d source QC members, but found %d.', ...
            expectedMemberCount, height(qc));
    end

    clusterIndices = unique(double(qc.ClusterIndex(:)))';

    if ~isequal(clusterIndices, expectedChildClusterIndices)
        error(['QC table must contain every source child cluster exactly. ' ...
            'Expected %s, found %s.'], ...
            mat2str(expectedChildClusterIndices), ...
            mat2str(clusterIndices));
    end

    allKeys = string(qc.DatasetIndex) + "_" + string(qc.IC);

    if numel(unique(allKeys)) ~= numel(allKeys)
        duplicateKeys = allKeys( ...
            duplicated_rows_local(allKeys));

        error( ...
            'The QC table contains duplicate DatasetIndex-IC pairs: %s', ...
            strjoin(unique(duplicateKeys), ', '));
    end

    for rowIndex = 1:height(qc)

        datasetIndex = double(qc.DatasetIndex(rowIndex));
        icIndex = double(qc.IC(rowIndex));
        clusterIndex = double(qc.ClusterIndex(rowIndex));

        if datasetIndex < 1 || ...
                datasetIndex > numel(STUDY.datasetinfo)

            error( ...
                'Invalid DatasetIndex %d in QC row %d.', ...
                datasetIndex, rowIndex);
        end

        expectedFilename = string( ...
            STUDY.datasetinfo(datasetIndex).filename);

        qcFilename = string(qc.DatasetFilename(rowIndex));

        if expectedFilename ~= qcFilename
            error([ ...
                'Dataset filename mismatch in QC row %d.\n' ...
                'STUDY: %s\nQC: %s'], ...
                rowIndex, expectedFilename, qcFilename);
        end

        expectedSubject = string( ...
            STUDY.datasetinfo(datasetIndex).subject);
        expectedCondition = string( ...
            STUDY.datasetinfo(datasetIndex).condition);

        if expectedSubject ~= string(qc.Subject(rowIndex)) || ...
                expectedCondition ~= string(qc.Condition(rowIndex))

            error(['Subject/condition mismatch in QC row %d for dataset %d.'], ...
                rowIndex, datasetIndex);
        end

        expectedClusterName = string(STUDY.cluster(clusterIndex).name);

        if expectedClusterName ~= string(qc.ClusterName(rowIndex))
            error(['Cluster name mismatch in QC row %d. STUDY: %s; QC: %s'], ...
                rowIndex, expectedClusterName, ...
                string(qc.ClusterName(rowIndex)));
        end

        [clusterSets, clusterComps] = flatten_cluster_members_local( ...
            STUDY.cluster(clusterIndex).sets, ...
            STUDY.cluster(clusterIndex).comps);

        isMember = any( ...
            clusterSets == datasetIndex & ...
            clusterComps == icIndex);

        if ~isMember
            error([ ...
                'QC row %d is not present in source cluster %d: ' ...
                'Dataset %d, IC %d.'], ...
                rowIndex, ...
                clusterIndex, ...
                datasetIndex, ...
                icIndex);
        end
    end

    sourceUnion = zeros(0, 2);

    for clusterIndex = expectedChildClusterIndices

        qcRows = qc(double(qc.ClusterIndex) == clusterIndex, :);

        expectedPairs = sortrows( ...
            [double(qcRows.DatasetIndex), double(qcRows.IC)], ...
            [1 2]);

        [actualSets, actualComps] = flatten_cluster_members_local( ...
            STUDY.cluster(clusterIndex).sets, ...
            STUDY.cluster(clusterIndex).comps);

        actualPairs = sortrows( ...
            [actualSets, actualComps], [1 2]);

        if ~isequal(expectedPairs, actualPairs)
            error( ...
                'QC membership does not exactly match source cluster %d.', ...
                clusterIndex);
        end


        sourceUnion = [sourceUnion; actualPairs]; %#ok<AGROW>
    end

    sourceUnion = sortrows(sourceUnion, [1 2]);

    if size(unique(sourceUnion, 'rows'), 1) ~= size(sourceUnion, 1)
        error(['The source STUDY assigns at least one DatasetIndex-IC pair ' ...
            'to more than one child cluster.']);
    end

    [parentSets, parentComps] = flatten_cluster_members_local( ...
        STUDY.cluster(1).sets, STUDY.cluster(1).comps);
    parentPairs = sortrows([parentSets, parentComps], [1 2]);

    if ~isequal(sourceUnion, parentPairs)
        error(['Source ParentCluster membership is not exactly the union ' ...
            'of child clusters %s.'], ...
            mat2str(expectedChildClusterIndices));
    end
end

function resolvedQC = resolve_review_decisions_local( ...
    qc, STUDY, expectedChildClusterIndices)

    resolvedQC = qc;
    resolvedQC.OriginalClusterIndex = double(qc.ClusterIndex);
    resolvedQC.OriginalClusterName = string(qc.ClusterName);

    targetClusters = normalize_numeric_local(qc.TargetCluster);
    resolvedQC.ResolvedClusterIndex = double(qc.ClusterIndex);
    resolvedQC.ResolutionNote = strings(height(qc), 1);

    for rowIndex = 1:height(qc)
        decision = string(qc.ReviewerDecision(rowIndex));
        originalCluster = double(qc.ClusterIndex(rowIndex));

        if decision == "Reassign"
            targetCluster = targetClusters(rowIndex);

            if ~isfinite(targetCluster) || ...
                    targetCluster ~= round(targetCluster) || ...
                    ~ismember(targetCluster, expectedChildClusterIndices)

                error(['QC row %d is Reassign but TargetCluster is not a ' ...
                    'valid child cluster in %s.'], ...
                    rowIndex, mat2str(expectedChildClusterIndices));
            end

            if targetCluster == originalCluster
                error(['QC row %d is Reassign, but TargetCluster equals the ' ...
                    'original cluster %d. Use Keep instead.'], ...
                    rowIndex, originalCluster);
            end

            resolvedQC.ClusterIndex(rowIndex) = targetCluster;
            resolvedQC.ClusterName(rowIndex) = ...
                string(STUDY.cluster(targetCluster).name);
            resolvedQC.ResolvedClusterIndex(rowIndex) = targetCluster;
            resolvedQC.ResolutionNote(rowIndex) = ...
                "Reassigned from cluster " + string(originalCluster) + ...
                " to cluster " + string(targetCluster);

        else
            if isfinite(targetClusters(rowIndex))
                error(['QC row %d has ReviewerDecision=%s but also contains ' ...
                    'TargetCluster=%g. Clear TargetCluster or use Reassign.'], ...
                    rowIndex, decision, targetClusters(rowIndex));
            end

            if decision == "ClusterOutlier"
                resolvedQC.ResolutionNote(rowIndex) = ...
                    "Excluded from CORE and INCLUSIVE";
            else
                resolvedQC.ResolutionNote(rowIndex) = ...
                    "Original automatic cluster retained";
            end
        end
    end

end

function STUDY = create_curated_study_local( ...
        STUDY_SOURCE, ...
        members, ...
        versionName, ...
        qcFilename, ...
        outputFilename, ...
        outputFolder, ...
        expectedChildClusterIndices, ...
        qcSignature)

    STUDY = STUDY_SOURCE;

    clusterIndices = unique(double(members.ClusterIndex(:)))';

    if any(~ismember(clusterIndices, expectedChildClusterIndices))
        error('Curated members contain an unexpected child cluster index.');
    end

    % Remove cached cluster-level measure fields whose membership-dependent
    % values may no longer be valid.
    staleFields = { ...
        'erptimes', ...
        'erpdata', ...
        'specfreqs', ...
        'specdata', ...
        'erspdata', ...
        'ersptimes', ...
        'erspfreqs', ...
        'erspdatatrials', ...
        'erspsubjinds', ...
        'erspbase', ...
        'ersptrialinfo', ...
        'itcdata', ...
        'itcfreqs', ...
        'itctimes', ...
        'erpimdata', ...
        'erpimevents', ...
        'erpimtrials', ...
        'erpimtimes'};

    for fieldIndex = 1:numel(staleFields)
        if isfield(STUDY.cluster, staleFields{fieldIndex})
            STUDY.cluster = rmfield( ...
                STUDY.cluster, ...
                staleFields{fieldIndex});
        end
    end

    % Clear every expected child cluster first. This prevents an omitted
    % cluster from silently retaining automatic K-means members.
    for clusterIndex = expectedChildClusterIndices

        STUDY.cluster(clusterIndex).sets = [];
        STUDY.cluster(clusterIndex).comps = [];

        if isfield(STUDY.cluster, 'preclust')
            STUDY.cluster(clusterIndex).preclust = [];
        end
    end

    % Rebuild every child cluster from the resolved review table.
    for clusterIndex = expectedChildClusterIndices

        clusterRows = members( ...
            double(members.ClusterIndex) == clusterIndex, :);

        STUDY.cluster(clusterIndex).sets = ...
            double(clusterRows.DatasetIndex(:))';

        STUDY.cluster(clusterIndex).comps = ...
            double(clusterRows.IC(:))';

    end

    % Update ParentCluster 1 to contain exactly the union of curated members.
    parentRows = sortrows( ...
        members, ...
        {'DatasetIndex', 'IC'});

    STUDY.cluster(1).sets = ...
        double(parentRows.DatasetIndex(:))';

    STUDY.cluster(1).comps = ...
        double(parentRows.IC(:))';

    if isfield(STUDY.cluster, 'preclust')
        STUDY.cluster(1).preclust = [];
    end

    if ~isfield(STUDY, 'etc') || ~isstruct(STUDY.etc)
        STUDY.etc = struct();
    end

    STUDY.etc.manual_cluster_qc = struct();
    STUDY.etc.manual_cluster_qc.version = char(versionName);
    STUDY.etc.manual_cluster_qc.source_qc_csv = qcFilename;
    STUDY.etc.manual_cluster_qc.source_qc_signature = char(qcSignature);
    STUDY.etc.manual_cluster_qc.created = ...
        datestr(now, 30);
    STUDY.etc.manual_cluster_qc.member_count = ...
        height(members);
    STUDY.etc.manual_cluster_qc.cluster_indices = ...
        expectedChildClusterIndices;
    STUDY.etc.manual_cluster_qc.reassigned_member_count = ...
        sum(string(members.ReviewerDecision) == "Reassign");

    STUDY.name = sprintf( ...
        '%s | K=6 %s', ...
        STUDY_SOURCE.name, ...
        versionName);

    STUDY.notes = sprintf([ ...
        '%s\n\n' ...
        'Manual K=6 member-level QC version: %s\n' ...
        'Source QC table: %s\n' ...
        'Included members: %d\n' ...
        'Original datasets were not modified.\n'], ...
        char(string(STUDY_SOURCE.notes)), ...
        versionName, ...
        qcFilename, ...
        height(members));

    STUDY.filename = outputFilename;
    STUDY.filepath = outputFolder;
    STUDY.saved = 'no';
end

function verify_curated_study_local( ...
    STUDY, members, label, expectedChildClusterIndices)

    memberKeys = ...
        string(members.DatasetIndex) + "_" + string(members.IC);

    if numel(unique(memberKeys)) ~= height(members)
        error( ...
            '%s contains duplicate DatasetIndex-IC membership rows.', ...
            label);
    end

    clusterIndices = unique(double(members.ClusterIndex(:)))';

    if any(~ismember(clusterIndices, expectedChildClusterIndices))
        error('%s contains an unexpected child cluster index.', label);
    end

    actualChildClusterIndices = 2:numel(STUDY.cluster);

    if ~isequal(actualChildClusterIndices, expectedChildClusterIndices)
        error('%s has unexpected STUDY child cluster indices.', label);
    end

    totalChildMembers = 0;
    childUnion = zeros(0, 2);

    for clusterIndex = expectedChildClusterIndices

        rows = members( ...
            double(members.ClusterIndex) == clusterIndex, :);

        expectedPairs = sortrows( ...
            [double(rows.DatasetIndex), double(rows.IC)], ...
            [1 2]);

        [actualSets, actualComps] = flatten_cluster_members_local( ...
            STUDY.cluster(clusterIndex).sets, ...
            STUDY.cluster(clusterIndex).comps);

        actualPairs = sortrows( ...
            [actualSets, actualComps], [1 2]);

        if ~isequal(expectedPairs, actualPairs)
            error( ...
                '%s verification failed for cluster %d.', ...
                label, clusterIndex);
        end

        totalChildMembers = totalChildMembers + size(actualPairs, 1);
        childUnion = [childUnion; actualPairs]; %#ok<AGROW>
    end

    childUnion = sortrows(childUnion, [1 2]);

    if size(unique(childUnion, 'rows'), 1) ~= size(childUnion, 1)
        error('%s assigns a DatasetIndex-IC pair to multiple clusters.', ...
            label);
    end

    parentExpected = sortrows( ...
        [double(members.DatasetIndex), double(members.IC)], ...
        [1 2]);

    [parentSets, parentComps] = flatten_cluster_members_local( ...
        STUDY.cluster(1).sets, STUDY.cluster(1).comps);
    parentActual = sortrows([parentSets, parentComps], [1 2]);

    if ~isequal(parentExpected, parentActual)
        error( ...
            '%s ParentCluster membership verification failed.', ...
            label);
    end

    if totalChildMembers ~= height(members)
        error( ...
            '%s child-cluster member count is inconsistent.', ...
            label);
    end

    if ~isequal(childUnion, parentActual)
        error('%s child-cluster union does not equal ParentCluster.', label);
    end

    fprintf( ...
        ['%s verification passed: %d members; every cluster %s was ' ...
        'checked, including empty clusters.\n'], ...
        label, ...
        height(members), ...
        mat2str(expectedChildClusterIndices));
end

function [ ...
        clusterSummary, ...
        subjectCoverage, ...
        conditionCoverage, ...
        subjectConditionCoverage, ...
        duplicateDatasetMembers ...
    ] = build_coverage_tables_local(members)

    clusterIndices = unique(double(members.ClusterIndex(:)))';

    clusterSummary = table();
    subjectCoverage = table();
    conditionCoverage = table();
    subjectConditionCoverage = table();
    duplicateDatasetMembers = table();

    for clusterIndex = clusterIndices

        clusterRows = members( ...
            double(members.ClusterIndex) == clusterIndex, :);

        clusterName = string(clusterRows.ClusterName(1));

        subjectValues = unique( ...
            string(clusterRows.Subject), ...
            'stable');

        conditionValues = unique( ...
            string(clusterRows.Condition), ...
            'stable');

        subjectCountParts = strings(numel(subjectValues), 1);

        for subjectIndex = 1:numel(subjectValues)

            currentSubject = subjectValues(subjectIndex);

            subjectRows = clusterRows( ...
                string(clusterRows.Subject) == currentSubject, :);

            subjectCountParts(subjectIndex) = sprintf( ...
                '%s:%d', ...
                char(currentSubject), ...
                height(subjectRows));

            newSubjectRow = table( ...
                clusterIndex, ...
                clusterName, ...
                currentSubject, ...
                height(subjectRows), ...
                numel(unique(subjectRows.DatasetIndex)), ...
                numel(unique(string(subjectRows.Condition))), ...
                'VariableNames', { ...
                    'ClusterIndex', ...
                    'ClusterName', ...
                    'Subject', ...
                    'N_IC', ...
                    'N_Datasets', ...
                    'N_Conditions'});

            if isempty(subjectCoverage)
                subjectCoverage = newSubjectRow;
            else
                subjectCoverage = [ ...
                    subjectCoverage; ...
                    newSubjectRow]; %#ok<AGROW>
            end
        end

        conditionCountParts = strings(numel(conditionValues), 1);

        for conditionIndex = 1:numel(conditionValues)

            currentCondition = conditionValues(conditionIndex);

            conditionRows = clusterRows( ...
                string(clusterRows.Condition) == currentCondition, :);

            conditionCountParts(conditionIndex) = sprintf( ...
                '%s:%d', ...
                char(currentCondition), ...
                height(conditionRows));

            newConditionRow = table( ...
                clusterIndex, ...
                clusterName, ...
                currentCondition, ...
                height(conditionRows), ...
                numel(unique(conditionRows.DatasetIndex)), ...
                numel(unique(string(conditionRows.Subject))), ...
                'VariableNames', { ...
                    'ClusterIndex', ...
                    'ClusterName', ...
                    'Condition', ...
                    'N_IC', ...
                    'N_Datasets', ...
                    'N_Subjects'});

            if isempty(conditionCoverage)
                conditionCoverage = newConditionRow;
            else
                conditionCoverage = [ ...
                    conditionCoverage; ...
                    newConditionRow]; %#ok<AGROW>
            end
        end

        for subjectIndex = 1:numel(subjectValues)

            currentSubject = subjectValues(subjectIndex);

            for conditionIndex = 1:numel(conditionValues)

                currentCondition = conditionValues(conditionIndex);

                rows = clusterRows( ...
                    string(clusterRows.Subject) == currentSubject & ...
                    string(clusterRows.Condition) == currentCondition, :);

                if isempty(rows)
                    continue;
                end

                newSubjectConditionRow = table( ...
                    clusterIndex, ...
                    clusterName, ...
                    currentSubject, ...
                    currentCondition, ...
                    height(rows), ...
                    numel(unique(rows.DatasetIndex)), ...
                    'VariableNames', { ...
                        'ClusterIndex', ...
                        'ClusterName', ...
                        'Subject', ...
                        'Condition', ...
                        'N_IC', ...
                        'N_Datasets'});

                if isempty(subjectConditionCoverage)
                    subjectConditionCoverage = newSubjectConditionRow;
                else
                    subjectConditionCoverage = [ ...
                        subjectConditionCoverage; ...
                        newSubjectConditionRow]; %#ok<AGROW>
                end
            end
        end

        uniqueDatasets = unique(clusterRows.DatasetIndex);

        for datasetIndex = reshape(uniqueDatasets, 1, [])

            datasetRows = clusterRows( ...
                clusterRows.DatasetIndex == datasetIndex, :);

            if height(datasetRows) <= 1
                continue;
            end

            icList = strjoin( ...
                string(sort(double(datasetRows.IC))), ...
                ', ');

            newDuplicateRow = table( ...
                clusterIndex, ...
                clusterName, ...
                double(datasetIndex), ...
                string(datasetRows.Subject(1)), ...
                string(datasetRows.Condition(1)), ...
                double(datasetRows.Session(1)), ...
                height(datasetRows), ...
                icList, ...
                'VariableNames', { ...
                    'ClusterIndex', ...
                    'ClusterName', ...
                    'DatasetIndex', ...
                    'Subject', ...
                    'Condition', ...
                    'Session', ...
                    'N_IC', ...
                    'IC_List'});

            if isempty(duplicateDatasetMembers)
                duplicateDatasetMembers = newDuplicateRow;
            else
                duplicateDatasetMembers = [ ...
                    duplicateDatasetMembers; ...
                    newDuplicateRow]; %#ok<AGROW>
            end
        end

        newClusterSummaryRow = table( ...
            clusterIndex, ...
            clusterName, ...
            height(clusterRows), ...
            numel(unique(clusterRows.DatasetIndex)), ...
            numel(subjectValues), ...
            numel(conditionValues), ...
            sum(clusterRows.ReviewerDecision == "Keep"), ...
            sum(clusterRows.ReviewerDecision == "NeedsDiscussion"), ...
            sum(clusterRows.ReviewerDecision == "Reassign"), ...
            strjoin(subjectCountParts, '; '), ...
            strjoin(conditionCountParts, '; '), ...
            'VariableNames', { ...
                'ClusterIndex', ...
                'ClusterName', ...
                'N_IC', ...
                'N_Datasets', ...
                'N_Subjects', ...
                'N_Conditions', ...
                'N_Keep', ...
                'N_NeedsDiscussion', ...
                'N_Reassign', ...
                'SubjectCounts', ...
                'ConditionCounts'});

        if isempty(clusterSummary)
            clusterSummary = newClusterSummaryRow;
        else
            clusterSummary = [ ...
                clusterSummary; ...
                newClusterSummaryRow]; %#ok<AGROW>
        end
    end
end

function duplicateMask = duplicated_rows_local(values)

    [~, firstIndex] = unique(values, 'stable');

    duplicateMask = true(size(values));
    duplicateMask(firstIndex) = false;
end

function [setVector, compVector] = ...
        flatten_cluster_members_local(setsValue, compsValue)

    setVector = zeros(0, 1);
    compVector = zeros(0, 1);

    if isnumeric(setsValue) && isnumeric(compsValue)
        setsFlat = double(setsValue(:));
        compsFlat = double(compsValue(:));
        n = min(numel(setsFlat), numel(compsFlat));
        setsFlat = setsFlat(1:n);
        compsFlat = compsFlat(1:n);

        valid = isfinite(setsFlat) & setsFlat > 0 & ...
            isfinite(compsFlat) & compsFlat > 0;

        setVector = setsFlat(valid);
        compVector = compsFlat(valid);
        return;
    end

    if iscell(setsValue) && iscell(compsValue)
        nCells = min(numel(setsValue), numel(compsValue));

        for cellIndex = 1:nCells
            currentSets = double(setsValue{cellIndex}(:));
            currentComps = double(compsValue{cellIndex}(:));

            if isempty(currentSets) || isempty(currentComps)
                continue;
            end

            if isscalar(currentSets) && numel(currentComps) > 1
                currentSets = repmat(currentSets, size(currentComps));
            elseif isscalar(currentComps) && numel(currentSets) > 1
                currentComps = repmat(currentComps, size(currentSets));
            end

            n = min(numel(currentSets), numel(currentComps));
            currentSets = currentSets(1:n);
            currentComps = currentComps(1:n);

            valid = isfinite(currentSets) & currentSets > 0 & ...
                isfinite(currentComps) & currentComps > 0;

            setVector = [setVector; currentSets(valid)]; %#ok<AGROW>
            compVector = [compVector; currentComps(valid)]; %#ok<AGROW>
        end
        return;
    end

    if isempty(setsValue) && isempty(compsValue)
        return;
    end

    error('Unsupported STUDY cluster sets/comps representation.');
end

function values = normalize_numeric_local(values)

    if isnumeric(values)
        values = double(values);
    elseif islogical(values)
        values = double(values);
    else
        textValues = strtrim(string(values));
        textValues(ismissing(textValues)) = "";
        values = str2double(textValues);
    end

    values = double(values(:));
end

function signature = file_signature_local(filePath)

    filePath = string(filePath);

    if exist(filePath, 'file') ~= 2
        error('Cannot create a signature for a missing file: %s', filePath);
    end

    info = dir(filePath);
    signature = string(info.bytes) + "|" + ...
        compose('%.15g', info.datenum);
end
