    eegRetainedSourceSampleRanges;

sourceManifest.EEGSampleSelectionSignature = ...
    eegSampleSelectionSignature;

% Merge

if numel(ALLEEG) == 1
    EEG = ALLEEG(1);
else
    EEG = pop_mergeset( ...
        ALLEEG, ...
        1:numel(ALLEEG), ...
        0);
end

EEG = eeg_checkset(EEG);

EEG = ...
    normalize_merged_event_metadata( ...
        EEG, ...
        sourceManifest);

EEG = eeg_checkset( ...
    EEG, ...
    'eventconsistency');

EEG.setname = ...
    char(erase( ...
        string(mergedSetName), ...
        ".set"));

EEG.subject = ...
    char(subjectLabel);

EEG.condition = ...
    'AllSessions';

% pop_mergeset may leave EEG.etc empty/non-struct.
if ~isfield(EEG,'etc') || ...
        ~isstruct(EEG.etc)

    EEG.etc = struct();
end

EEG.etc.subject_level_concatenation = ...
    true;

EEG.etc.subject_merge_input_signature = ...
    char(sourceInputSignature);

EEG.etc.subject_merge_source_manifest = ...
    sourceManifest;

EEG.etc.subject_merge_source_set_paths = ...
    sourceSetPath;

EEG.etc.subject_merge_source_xdf_paths = ...
    xdfPath;

EEG.etc.subject_merge_source_recording_count = ...
    nSources;

EEG.etc.subject_merge_created_at = ...
    char(current_time_text);

validate_merged_subject_eeg( ...
    EEG, ...
    nSources);

% Save

writetable( ...
    sourceManifest, ...
    manifestFile);

EEG = pop_saveset( ...
    EEG, ...
    'filename', mergedSetName, ...
    'filepath', subjectDestinationFolder, ...
    'savemode', 'twofiles');

if ~isfile(mergedSetPath)
    error('Merged EEG was not created:\n%s', ...
        mergedSetPath);
end

subjectSummary = ...
    build_subject_summary( ...
        subjectLabel, ...
        mergedSetPath, ...
        manifestFile, ...
        sourceManifest, ...
        EEG, ...
        sourceInputSignature, ...
        "completed");

update_subject_processing_table( ...
    subjectSummary, ...
    subjectLevelEEGTableFile);

fprintf('\nSUBJECT-LEVEL EEG CONCATENATION COMPLETED\n');
fprintf('Subject: %s\n',subjectLabel);
fprintf('Sources: %d\n',nSources);
fprintf('Merged EEG:\n%s\n',mergedSetPath);
fprintf('Source manifest:\n%s\n',manifestFile);

end


function validate_source_eeg( ...
        EEG, ...
        metadata, ...
        referenceSrate, ...
        referenceChannelLabels, ...
        referenceChannelXYZ) %#ok<INUSD>

if EEG.trials ~= 1
    error('Source EEG must be continuous.');
end

if EEG.nbchan ~= 64
    error('Expected 64 EEG channels.');
end

if abs(double(EEG.srate)-500) > 1e-6
    error('Expected 500 Hz EEG.');
end

if isfinite(referenceSrate) && ...
        abs(double(EEG.srate)-referenceSrate) > 1e-6

    error('Sampling-rate mismatch.');
end

currentChannelLabels = ...
    string({EEG.chanlocs.labels})';

if numel(unique( ...
        lower(strtrim(currentChannelLabels)))) ~= EEG.nbchan

    error('Channel labels are not unique.');
end

if ~isempty(referenceChannelLabels) && ...
        ~isequal( ...
            lower(strtrim(currentChannelLabels)), ...
            lower(strtrim(referenceChannelLabels)))

    error('Channel labels/order differ.');
end

if ~channel_locations_complete(EEG.chanlocs)
    error('Channel locations incomplete.');
end

currentChannelXYZ = ...
    channel_xyz_matrix( ...
        EEG.chanlocs);

if ~isempty(referenceChannelXYZ) && ...
        (size(currentChannelXYZ,1) ~= ...
            size(referenceChannelXYZ,1) || ...
        any(abs( ...
            currentChannelXYZ(:) - ...
            referenceChannelXYZ(:)) > 1e-9))

    error('Channel coordinates differ.');
end

if any(~isfinite(double(EEG.data(:))))
    error('EEG contains NaN/Inf.');
end

if isempty(EEG.event)
    error('Source EEG contains no events.');
end

end


function tf = ...
        channel_locations_complete(chanlocs)

tf = ~isempty(chanlocs);

if ~tf
    return;
end

requiredFields = {'X','Y','Z'};

for iField = 1:numel(requiredFields)

    fieldName = ...
        requiredFields{iField};

    if ~isfield(chanlocs,fieldName)
        tf = false;
        return;
    end

