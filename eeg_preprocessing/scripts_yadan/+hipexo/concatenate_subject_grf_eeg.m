% GOAL
%   Concatenate all Step 04-eligible run-separated EEG recordings for one
%   participant after GRF-derived gait events and project channel locations
%   are present.
%
% APPROACH
%   1. Read the Step 04-updated subject batch-status CSV.
%   2. Use only recordings that passed final gait-EEG QC.
%   3. Verify source EEG structure, channel layout, sampling rate, and events.
%   4. Sort recordings by true source-XDF EEG LSL acquisition time.
%   5. Preserve retained-EEG sample-selection identity.
%   6. Concatenate recordings while preserving source/run event metadata.
%   7. Save the subject-level continuous EEG and source manifest.
%
% USED BY
%   step04_process_subject_grf_eeg.m

function [mergedSetPath, subjectSummary] = ...
        concatenate_subject_grf_eeg(subjectOutputFolder, varargin)

if nargin < 1
    subjectOutputFolder = "";
end

parser = inputParser;

addOptional(parser, 'subjectOutputFolder', subjectOutputFolder, ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));

addParameter(parser, 'ForceReprocess', false, ...
    @(x) islogical(x) && isscalar(x));

addParameter(parser, 'AllowPartialSubject', false, ...
    @(x) islogical(x) && isscalar(x));

parse(parser, subjectOutputFolder, varargin{:});

subjectOutputFolder = ...
    char(string(parser.Results.subjectOutputFolder));

forceReprocess = ...
    logical(parser.Results.ForceReprocess);

allowPartialSubject = ...
    logical(parser.Results.AllowPartialSubject);

packageFolder = fileparts(mfilename('fullpath'));
scriptsRoot = fileparts(packageFolder);

addpath(scriptsRoot, '-begin');
addpath(fullfile(scriptsRoot, 'config'), '-begin');

P = project_paths();

grfSegmentationFolder = P.grfSegmentationFolder;
subjectLevelEEGFolder = P.subjectLevelEEGFolder;
subjectLevelEEGTableFile = P.subjectLevelEEGTableFile;

if ~isfolder(subjectLevelEEGFolder)
    mkdir(subjectLevelEEGFolder);
end

% All subjects mode

if isempty(strtrim(subjectOutputFolder))

    subjectDirectories = dir(fullfile( ...
        grfSegmentationFolder, ...
        'sub-*'));

    subjectDirectories = ...
        subjectDirectories([subjectDirectories.isdir]);

    if isempty(subjectDirectories)
        error('No subject GRF/EEG output folders found below:\n%s', ...
            grfSegmentationFolder);
    end

    mergedSetPath = strings(0,1);
    subjectSummary = table();

    for iSubject = 1:numel(subjectDirectories)

        currentSubjectFolder = fullfile( ...
            subjectDirectories(iSubject).folder, ...
            subjectDirectories(iSubject).name);

        try

            [currentMergedPath, currentSummary] = ...
                hipexo.concatenate_subject_grf_eeg( ...
                    currentSubjectFolder, ...
                    'ForceReprocess', forceReprocess, ...
                    'AllowPartialSubject', allowPartialSubject);

            mergedSetPath(end+1,1) = ...
                string(currentMergedPath); %#ok<AGROW>

            if isempty(subjectSummary)
                subjectSummary = currentSummary;
            else
                subjectSummary = ...
                    [subjectSummary; currentSummary]; %#ok<AGROW>
            end

        catch currentError

            fprintf(2, ...
                '\nSubject concatenation failed:\n%s\n%s\n', ...
                currentSubjectFolder, ...
                getReport(currentError, ...
                    'extended', ...
                    'hyperlinks', ...
                    'off'));
        end
    end

    if isempty(subjectSummary)
        error('No subject-level EEG dataset was created.');
    end

    return;
end

% Batch status

if ~isfolder(subjectOutputFolder)
    error('Subject output folder does not exist:\n%s', ...
        subjectOutputFolder);
end

batchLogs = dir(fullfile( ...
    subjectOutputFolder, ...
    '*_GRF_EEG_batch_status.csv'));

if numel(batchLogs) ~= 1
    error('Expected exactly one subject batch-status CSV below:\n%s', ...
        subjectOutputFolder);
end

batchLogFile = fullfile( ...
    batchLogs(1).folder, ...
    batchLogs(1).name);

batchStatus = ...
    hipexo.read_csv_with_string_text(batchLogFile);

requiredBatchVariables = { ...
    'Subject', ...
    'SessionFolder', ...
    'XDFPath', ...
    'EEG_LSL_Start', ...
    'EEG_LSL_End', ...
    'EEG_LSL_DurationSec', ...
    'GRF_LSL_Start', ...
    'GRF_LSL_End', ...
    'GRF_LSL_DurationSec', ...
    'GRF_EEG_LSL_OverlapSec', ...
    'OverallStatus', ...
    'GRFGaitQCStatus', ...
    'EEGMappingStatus', ...
    'EEGSetFile', ...
    'MappedEventCount', ...
    'FinalRecommendedCycleCount', ...
    'FinalGaitEEGStatus', ...
    'FirstGRFEventSample', ...
    'FirstGRFEventLSLTime', ...
    'FirstMappedEEGSample', ...
    'FirstMatchedEEGLSLTime', ...
    'LastGRFEventSample', ...
    'LastGRFEventLSLTime', ...
    'LastMappedEEGSample', ...
    'LastMatchedEEGLSLTime', ...
    'MedianAbsMappingErrorMs', ...
    'MaxAbsMappingErrorMs'};

for iVariable = 1:numel(requiredBatchVariables)

    variableName = requiredBatchVariables{iVariable};

    if ~ismember(variableName, ...
            batchStatus.Properties.VariableNames)

        error('Batch-status CSV missing "%s":\n%s', ...
            variableName, ...
            batchLogFile);
    end
end

numericBatchVariables = { ...
    'EEG_LSL_Start', ...
    'EEG_LSL_End', ...
    'EEG_LSL_DurationSec', ...
    'GRF_LSL_Start', ...
    'GRF_LSL_End', ...
    'GRF_LSL_DurationSec', ...
    'GRF_EEG_LSL_OverlapSec', ...
    'MappedEventCount', ...
    'FinalRecommendedCycleCount', ...
    'FirstGRFEventSample', ...
    'FirstGRFEventLSLTime', ...
    'FirstMappedEEGSample', ...
    'FirstMatchedEEGLSLTime', ...
    'LastGRFEventSample', ...
    'LastGRFEventLSLTime', ...
    'LastMappedEEGSample', ...
    'LastMatchedEEGLSLTime', ...
    'MedianAbsMappingErrorMs', ...
    'MaxAbsMappingErrorMs'};

for iVariable = 1:numel(numericBatchVariables)

    variableName = numericBatchVariables{iVariable};

    batchStatus.(variableName) = ...
        numeric_column_local( ...
            batchStatus.(variableName));
end

batchStatus.Subject = string(batchStatus.Subject);
batchStatus.SessionFolder = string(batchStatus.SessionFolder);
batchStatus.XDFPath = string(batchStatus.XDFPath);
batchStatus.OverallStatus = string(batchStatus.OverallStatus);
batchStatus.GRFGaitQCStatus = string(batchStatus.GRFGaitQCStatus);
batchStatus.EEGMappingStatus = string(batchStatus.EEGMappingStatus);
batchStatus.EEGSetFile = string(batchStatus.EEGSetFile);
batchStatus.FinalGaitEEGStatus = ...
    string(batchStatus.FinalGaitEEGStatus);

% GRF/QC exclusion is not a technical subject failure.
% Only a GRF-qualified run whose Step 04 EEG mapping actually failed
% blocks subject concatenation when partial subjects are disallowed.

hardFailureRows = ...
    lower(strtrim(batchStatus.GRFGaitQCStatus)) == ...
        "ready_for_step04" & ...
    lower(strtrim(batchStatus.EEGMappingStatus)) == ...
        "failed";

if any(hardFailureRows) && ~allowPartialSubject

    error([ ...
        '%d GRF-qualified run(s) failed during Step 04 EEG mapping. ' ...
        'Subject concatenation blocked.'], ...
        sum(hardFailureRows));
end

% Only recordings surviving the final Step 04 gait-EEG gate are merged.

readyRows = ...
    lower(strtrim(batchStatus.OverallStatus)) == "completed" & ...
    lower(strtrim(batchStatus.FinalGaitEEGStatus)) == "included" & ...
    batchStatus.FinalRecommendedCycleCount > 0 & ...
    batchStatus.MappedEventCount > 0 & ...
    strlength(strtrim(batchStatus.EEGSetFile)) > 0;

if ~any(readyRows)
    error('No Step 04-eligible mapped EEG datasets are available.');
end

sourceTable = batchStatus(readyRows,:);

for iSource = 1:height(sourceTable)

    if ~isfile(sourceTable.EEGSetFile(iSource))
        error('Mapped EEG does not exist:\n%s', ...
            sourceTable.EEGSetFile(iSource));
    end
end

subjectLabels = unique(sourceTable.Subject);
subjectLabels(strlength(strtrim(subjectLabels)) == 0) = [];

if numel(subjectLabels) ~= 1
    error('Rows do not resolve to exactly one subject.');
end

subjectLabel = subjectLabels(1);

% Output

subjectDestinationFolder = fullfile( ...
    subjectLevelEEGFolder, ...
    char(subjectLabel));

if ~isfolder(subjectDestinationFolder)
    mkdir(subjectDestinationFolder);
end

mergedSetName = char( ...
    subjectLabel + ...
    "_desc-continuousGRF_eeg.set");

mergedSetPath = fullfile( ...
    subjectDestinationFolder, ...
    mergedSetName);

manifestFile = fullfile( ...
    subjectDestinationFolder, ...
    char(subjectLabel + ...
    "_desc-continuousGRF_sources.csv"));

sourceInputSignature = ...
    build_source_input_signature( ...
        sourceTable.EEGSetFile, sourceTable.XDFPath);

% EEGLAB

if exist('pop_loadset','file') ~= 2
    eeglab nogui;
end

try
    pop_editoptions( ...
        'option_saveversion6', 0, ...
        'option_single', 0, ...
        'option_memmapdata', 0, ...
        'option_savetwofiles', 1, ...
        'option_storedisk', 0);
catch
    warning('Could not set every EEGLAB save option.');
end

% Reuse validation

if isfile(mergedSetPath) && ...
        isfile(manifestFile) && ...
        ~forceReprocess

    existingEEG = [];
    storedSignature = "";

    try
        existingEEG = pop_loadset( ...
            'filename', mergedSetName, ...
            'filepath', subjectDestinationFolder);
    catch reuseLoadError
        fprintf( ...
            '\nExisting merged EEG could not be loaded: %s\n', ...
            reuseLoadError.message);
    end

    if ~isempty(existingEEG) && ...
            isfield(existingEEG,'etc') && ...
            isstruct(existingEEG.etc) && ...
            isfield(existingEEG.etc, ...
                'subject_merge_input_signature')

        storedSignature = string( ...
            existingEEG.etc.subject_merge_input_signature);
    end

    if storedSignature == sourceInputSignature

        try

            sourceManifest = ...
                hipexo.read_csv_with_string_text( ...
                    manifestFile);

            validate_merged_subject_eeg( ...
                existingEEG, ...
                height(sourceManifest));

            subjectSummary = ...
                build_subject_summary( ...
                    subjectLabel, ...
                    mergedSetPath, ...
                    manifestFile, ...
                    sourceManifest, ...
                    existingEEG, ...
                    sourceInputSignature, ...
                    "reused_existing");

            update_subject_processing_table( ...
                subjectSummary, ...
                subjectLevelEEGTableFile);

            fprintf('\nReusing subject-level EEG:\n%s\n', ...
                mergedSetPath);

            return;

        catch
            % Rebuild below if reuse validation fails.
        end
    end
end

% Load source EEGs and read source-XDF EEG LSL timestamps

nSources = height(sourceTable);

loadedEEG = cell(nSources,1);
sourceMetadata = cell(nSources,1);

eegFirstLSLTime = nan(nSources,1);
eegLastLSLTime = nan(nSources,1);

referenceSrate = NaN;
referenceChannelLabels = strings(0,1);
referenceChannelXYZ = [];

for iSource = 1:nSources

    currentSetPath = ...
        char(sourceTable.EEGSetFile(iSource));

    [currentSetFolder, ...
     currentSetBase, ...
     currentSetExtension] = ...
        fileparts(currentSetPath);

    currentEEG = pop_loadset( ...
        'filename', ...
        [currentSetBase currentSetExtension], ...
        'filepath', ...
        currentSetFolder);

    currentEEG = eeg_checkset(currentEEG);

    currentMetadata = ...
        resolve_source_metadata( ...
            currentEEG, ...
            sourceTable.XDFPath(iSource));

    if currentMetadata.SubjectLabel ~= subjectLabel
        error([ ...
            'Source EEG subject mismatch. Expected %s, found %s.'], ...
            subjectLabel, ...
            currentMetadata.SubjectLabel);
    end

    validate_source_eeg( ...
        currentEEG, ...
        currentMetadata, ...
        referenceSrate, ...
        referenceChannelLabels, ...
        referenceChannelXYZ);

    if iSource == 1

        referenceSrate = ...
            double(currentEEG.srate);

        referenceChannelLabels = ...
            string({currentEEG.chanlocs.labels})';

        referenceChannelXYZ = ...
            channel_xyz_matrix( ...
                currentEEG.chanlocs);
    end

    [eegFirstLSLTime(iSource), ...
     eegLastLSLTime(iSource)] = ...
        source_xdf_eeg_lsl_bounds( ...
            sourceTable.XDFPath(iSource));

    loadedEEG{iSource} = currentEEG;
    sourceMetadata{iSource} = currentMetadata;
end

if numel(unique(eegFirstLSLTime)) ~= nSources
    error('Duplicate EEG first LSL timestamps detected.');
end

% Chronological order

[~, chronologicalOrder] = ...
    sort(eegFirstLSLTime, 'ascend');

sourceTable = ...
    sourceTable(chronologicalOrder,:);

loadedEEG = ...
    loadedEEG(chronologicalOrder);

sourceMetadata = ...
    sourceMetadata(chronologicalOrder);

eegFirstLSLTime = ...
    eegFirstLSLTime(chronologicalOrder);

eegLastLSLTime = ...
    eegLastLSLTime(chronologicalOrder);

fprintf('\nTRUE EEG LSL ACQUISITION ORDER\n');

for iSource = 1:nSources

    currentMetadata = sourceMetadata{iSource};

    fprintf( ...
        '%02d %s run-%03d Start=%.6f End=%.6f\n', ...
        iSource, ...
        currentMetadata.SessionLabel, ...
        currentMetadata.RunNumber, ...
        eegFirstLSLTime(iSource), ...
        eegLastLSLTime(iSource));
end

% Build chronologically sorted recordings

ALLEEG = [];
CURRENTSET = 0;

sourceIndex = (1:nSources)';

eegLSLDurationSec = ...
    eegLastLSLTime - eegFirstLSLTime;

grfFirstLSLTime = ...
    sourceTable.GRF_LSL_Start;

grfLastLSLTime = ...
    sourceTable.GRF_LSL_End;

grfLSLDurationSec = ...
    sourceTable.GRF_LSL_DurationSec;

grfEEGLSLOverlapSec = ...
    sourceTable.GRF_EEG_LSL_OverlapSec;

firstGRFEventSample = ...
    sourceTable.FirstGRFEventSample;

firstGRFEventLSLTime = ...
    sourceTable.FirstGRFEventLSLTime;

firstMappedEEGSample = ...
    sourceTable.FirstMappedEEGSample;

firstMatchedEEGLSLTime = ...
    sourceTable.FirstMatchedEEGLSLTime;

lastGRFEventSample = ...
    sourceTable.LastGRFEventSample;

lastGRFEventLSLTime = ...
    sourceTable.LastGRFEventLSLTime;

lastMappedEEGSample = ...
    sourceTable.LastMappedEEGSample;

lastMatchedEEGLSLTime = ...
    sourceTable.LastMatchedEEGLSLTime;

medianAbsMappingErrorMs = ...
    sourceTable.MedianAbsMappingErrorMs;

maxAbsMappingErrorMs = ...
    sourceTable.MaxAbsMappingErrorMs;

manifestSubject = ...
    repmat(subjectLabel,nSources,1);

sessionLabel = strings(nSources,1);
conditionLabel = strings(nSources,1);
taskLabel = strings(nSources,1);
runNumber = nan(nSources,1);

xdfPath = sourceTable.XDFPath;
sourceSetPath = sourceTable.EEGSetFile;

startSample = nan(nSources,1);
endSample = nan(nSources,1);
sampleCount = nan(nSources,1);
durationSec = nan(nSources,1);
gaitEventCount = nan(nSources,1);
internalBoundaryCount = nan(nSources,1);

% These two values must be collected BEFORE loadedEEG is cleared.
eegRetainedSourceSampleRanges = ...
    strings(nSources,1);

eegSampleSelectionSignature = ...
    strings(nSources,1);

cumulativeSamples = 0;

validGaitEventTypes = ...
    ["RHS","RTO","LHS","LTO"];

for iSource = 1:nSources

    currentEEG = loadedEEG{iSource};
    currentMetadata = sourceMetadata{iSource};

    currentEEG = ...
        add_source_metadata_to_events( ...
            currentEEG, ...
            currentMetadata, ...
            iSource);

    currentEEG = ...
        add_recording_start_event( ...
            currentEEG, ...
            currentMetadata, ...
            iSource);

    currentEEG = eeg_checkset( ...
        currentEEG, ...
        'eventconsistency');

    currentEventTypes = ...
        event_type_strings( ...
            currentEEG.event);

    currentGaitEventCount = ...
        sum(ismember( ...
            currentEventTypes, ...
            validGaitEventTypes));

    missingGaitEventTypes = ...
        validGaitEventTypes( ...
            ~ismember( ...
                validGaitEventTypes, ...
                currentEventTypes));

    if ~isempty(missingGaitEventTypes)

        error('Required gait events missing from %s: %s', ...
            sourceSetPath(iSource), ...
            strjoin(missingGaitEventTypes, ', '));
    end

    sessionLabel(iSource) = ...
        currentMetadata.SessionLabel;

    conditionLabel(iSource) = ...
        currentMetadata.ConditionLabel;

    taskLabel(iSource) = ...
        currentMetadata.TaskLabel;

    runNumber(iSource) = ...
        currentMetadata.RunNumber;

    startSample(iSource) = ...
        cumulativeSamples + 1;

    endSample(iSource) = ...
        cumulativeSamples + currentEEG.pnts;

    sampleCount(iSource) = ...
        currentEEG.pnts;

    durationSec(iSource) = ...
        currentEEG.pnts / currentEEG.srate;

    gaitEventCount(iSource) = ...
        currentGaitEventCount;

    internalBoundaryCount(iSource) = ...
        sum(currentEventTypes == "boundary");

    % Preserve the identity of the EEG samples retained from the original
    % BIDS-derived source before currentEEG is released from memory.

    sourceRanges = ...
        [1 double(currentEEG.pnts)];

    sourceCount = ...
        double(currentEEG.pnts);

    if isfield(currentEEG,'etc') && ...
            isstruct(currentEEG.etc)

        if isfield(currentEEG.etc, ...
                'eeg_retained_source_sample_ranges') && ...
                ~isempty(currentEEG.etc.eeg_retained_source_sample_ranges)

            sourceRanges = ...
                currentEEG.etc.eeg_retained_source_sample_ranges;
        end

        if isfield(currentEEG.etc, ...
                'eeg_source_sample_count') && ...
                ~isempty(currentEEG.etc.eeg_source_sample_count)

            sourceCount = ...
                double(currentEEG.etc.eeg_source_sample_count);
        end
    end

    eegRetainedSourceSampleRanges(iSource) = ...
        string(jsonencode(sourceRanges));

    boundarySamples = ...
        double([ ...
        currentEEG.event( ...
            currentEventTypes == "boundary").latency]);

    if ~isequal(sourceRanges,[1 sourceCount]) || ...
            ~isempty(boundarySamples)

        eegSampleSelectionSignature(iSource) = ...
            hipexo.content_signature( ...
                struct( ...
                    'ranges', ...
                    sourceRanges, ...
                    'boundary_samples', ...
                    boundarySamples));
    end

    cumulativeSamples = ...
        endSample(iSource);

    [ALLEEG,currentEEG,CURRENTSET] = ...
        eeg_store( ...
            ALLEEG, ...
            currentEEG, ...
            0);

    % Safe now: everything required from currentEEG has already been
    % transferred into ALLEEG or stored in the manifest variables.
    loadedEEG{iSource} = [];
end

% Source manifest

sourceManifest = table( ...
    sourceIndex, ...
    manifestSubject, ...
    sessionLabel, ...
    conditionLabel, ...
    taskLabel, ...
    runNumber, ...
    xdfPath, ...
    eegFirstLSLTime, ...
    eegLastLSLTime, ...
    eegLSLDurationSec, ...
    grfFirstLSLTime, ...
    grfLastLSLTime, ...
    grfLSLDurationSec, ...
    grfEEGLSLOverlapSec, ...
    firstGRFEventSample, ...
    firstGRFEventLSLTime, ...
    firstMappedEEGSample, ...
    firstMatchedEEGLSLTime, ...
    lastGRFEventSample, ...
    lastGRFEventLSLTime, ...
    lastMappedEEGSample, ...
    lastMatchedEEGLSLTime, ...
    medianAbsMappingErrorMs, ...
    maxAbsMappingErrorMs, ...
    sourceSetPath, ...
    startSample, ...
    endSample, ...
    sampleCount, ...
    durationSec, ...
    gaitEventCount, ...
    internalBoundaryCount, ...
    'VariableNames', { ...
        'SourceIndex', ...
        'SubjectLabel', ...
        'SessionLabel', ...
        'ConditionLabel', ...
        'TaskLabel', ...
        'RunNumber', ...
        'XDFPath', ...
        'EEG_LSL_Start', ...
        'EEG_LSL_End', ...
        'EEG_LSL_DurationSec', ...
        'GRF_LSL_Start', ...
        'GRF_LSL_End', ...
        'GRF_LSL_DurationSec', ...
        'GRF_EEG_LSL_OverlapSec', ...
        'FirstGRFEventSample', ...
        'FirstGRFEventLSLTime', ...
        'FirstMappedEEGSample', ...
        'FirstMatchedEEGLSLTime', ...
        'LastGRFEventSample', ...
        'LastGRFEventLSLTime', ...
