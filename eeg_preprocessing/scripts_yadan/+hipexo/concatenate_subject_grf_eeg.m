function update_subject_processing_table( ...
        newRow,tableFile)

baseVariables = ...
    newRow.Properties.VariableNames;

if ~isfile(tableFile)

    writetable(newRow,tableFile);
    return;
end

oldTable = ...
    hipexo.read_csv_with_string_text( ...
        tableFile);

if ~ismember( ...
        'SubjectLabel', ...
        oldTable.Properties.VariableNames)

    backupFile = char( ...
        string(tableFile) + ...
        ".incompatible_backup_" + ...
        string(datetime( ...
            'now', ...
            'Format','yyyyMMdd_HHmmss')) + ...
        ".csv");

    copyfile(tableFile,backupFile);
    writetable(newRow,tableFile);

    return;
end

oldTable.SubjectLabel = ...
    string(oldTable.SubjectLabel);

if ismember( ...
        'SubjectInputSignature', ...
        oldTable.Properties.VariableNames)

    oldTable.SubjectInputSignature = ...
        string( ...
            oldTable.SubjectInputSignature);
end

matchingRows = ...
    find( ...
        oldTable.SubjectLabel == ...
        newRow.SubjectLabel);

if numel(matchingRows) > 1

    error([ ...
        'The subject-level processing table contains duplicate rows ' ...
        'for %s.'], ...
        newRow.SubjectLabel);
end

if ~isempty(matchingRows)

    backupFile = char( ...
        string(tableFile) + ...
        ".before_subject_update_" + ...
        string(datetime( ...
            'now', ...
            'Format','yyyyMMdd_HHmmss_SSS')) + ...
        ".csv");

    copyfile(tableFile,backupFile);
end

oldVariableNames = ...
    oldTable.Properties.VariableNames;

for iVariable = 1:numel(baseVariables)

    variableName = ...
        baseVariables{iVariable};

    if ~ismember( ...
            variableName, ...
            oldVariableNames)

        oldTable.(variableName) = ...
            make_missing_column_like( ...
                newRow.(variableName), ...
                height(oldTable));
    end
end

oldVariableNames = ...
    oldTable.Properties.VariableNames;

for iVariable = 1:numel(oldVariableNames)

    variableName = ...
        oldVariableNames{iVariable};

    if ~ismember( ...
            variableName, ...
            newRow.Properties.VariableNames)

        newRow.(variableName) = ...
            make_missing_column_like( ...
                oldTable.(variableName), ...
                1);
    end
end

newRow = ...
    newRow(:, ...
        oldTable.Properties.VariableNames);

if ~isempty(matchingRows)

    previousRow = ...
        matchingRows(1);

    signatureUnchanged = false;

    if ismember( ...
            'SubjectInputSignature', ...
            oldTable.Properties.VariableNames)

        signatureUnchanged = ...
            string( ...
                oldTable.SubjectInputSignature(previousRow)) == ...
            string( ...
                newRow.SubjectInputSignature);
    end

    continuousLayoutCompatible = ...
        continuous_layout_compatible_local( ...
            oldTable, ...
            newRow, ...
            previousRow);

    preserveDownstream = ...
        signatureUnchanged || ...
        continuousLayoutCompatible;

    if signatureUnchanged

        newRow.EventUpdateCompatibility(1) = ...
            "identical_source_signature_downstream_preserved";

    elseif continuousLayoutCompatible

        newRow.EventUpdateCompatibility(1) = ...
            "event_only_compatible_downstream_preserved";

    else

        newRow.EventUpdateCompatibility(1) = ...
            "continuous_layout_changed_downstream_reset";
    end

    if preserveDownstream

        columnsToPreserve = ...
            setdiff( ...
                oldTable.Properties.VariableNames, ...
                baseVariables, ...
                'stable');

        if ismember( ...
                'DoPreprocess', ...
                baseVariables)

            columnsToPreserve = ...
                [{'DoPreprocess'}, ...
                 columnsToPreserve];
        end

        for iColumn = 1:numel(columnsToPreserve)

            columnName = ...
                columnsToPreserve{iColumn};

            newRow.(columnName)(1,:) = ...
                oldTable.(columnName)( ...
                    previousRow,:);
        end
    end

else

    newRow.EventUpdateCompatibility(1) = ...
        "new_subject_no_previous_downstream_state";
end

oldTable(matchingRows,:) = [];

updatedTable = ...
    [oldTable;newRow];

if ismember( ...
        'BidsSubject', ...
        updatedTable.Properties.VariableNames)

    updatedTable = ...
        sortrows( ...
            updatedTable, ...
            'BidsSubject');
end

writetable( ...
    updatedTable, ...
    tableFile);

end


function compatible = continuous_layout_compatible_local(oldTable, newRow, previousRow)
compatible = false;
field = 'ContinuousInputSignature';
if ~ismember(field, oldTable.Properties.VariableNames) || ...
        ~ismember(field, newRow.Properties.VariableNames)
    return;
end
oldSignature = string(oldTable.(field)(previousRow));
newSignature = string(newRow.(field)(1));
% Missing legacy fingerprints cannot establish sample equality.
compatible = startsWith(oldSignature, "content-sha256:") && ...
    oldSignature == newSignature;
end

function column = ...
        make_missing_column_like( ...
            example,numberOfRows)

if isstring(example)

    column = ...
        strings( ...
            numberOfRows, ...
            size(example,2));

elseif islogical(example)

    column = ...
        false( ...
            numberOfRows, ...
            size(example,2));

elseif isnumeric(example)

    column = ...
        nan( ...
            numberOfRows, ...
            size(example,2));

elseif isdatetime(example)

    column = ...
        NaT( ...
            numberOfRows, ...
            size(example,2));

elseif iscell(example)

    column = ...
        cell( ...
            numberOfRows, ...
            size(example,2));

elseif iscategorical(example)

    column = ...
        repmat( ...
            categorical(missing), ...
            numberOfRows, ...
            size(example,2));

else

    column = ...
        strings( ...
            numberOfRows, ...
            size(example,2));
end

end


