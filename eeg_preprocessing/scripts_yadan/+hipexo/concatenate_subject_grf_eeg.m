function values = ...
        numeric_column_local(values)

if isnumeric(values)

    values = double(values);

elseif islogical(values)

    values = double(values);

else

    textValues = ...
        lower(strtrim(string(values)));

    values = ...
        str2double(textValues);

    values(ismember( ...
        textValues, ...
        ["true","yes"])) = 1;

    values(ismember( ...
        textValues, ...
        ["false","no"])) = 0;
end

